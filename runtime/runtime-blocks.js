// ── $$if ─────────────────────────────────────────────────────────────────
// select() returns the active branch index or -1.

export function $$if(cursor, select, branches, changed) {
  let anchor;
  let index = -1;
  let current = null;
  const show = (next) => {
    index = next;
    current = next >= 0 ? mountFragment(branches[next], undefined, anchor, cursor.ctx) : null;
  };
  if (cursor.hydrating) {
    // The range state is the branch the server rendered (X-7.1).
    const token = cursor.open();
    index = select();
    cursor.expect(token === (index >= 0 ? String(index) : 'x'), `#if renders branch ${index >= 0 ? index : 'x'}, the server rendered ${token}`);
    if (index >= 0) current = cursor.mount(branches[index]);
    anchor = cursor.close();
  } else {
    anchor = cursor.comment();
    show(select());
  }
  const block = {
    p(dirty) {
      if (block.isDone()) return;
      if (!changed || changed(dirty)) {
        const next = select();
        if (next !== index) {
          unmount(current);
          show(next);
          return;
        }
      }
      updateMounted(current, dirty, false);
    },
    move(before) {
      if (current) moveRange(current.range, before);
      before.parentNode.insertBefore(anchor, before);
    },
  };
  return registerBlock(cursor, block, anchor, (removeDom) => {
    if (!current) return;
    if (removeDom) unmount(current);
    else current.owner.release();
  });
}

// ── $$key ────────────────────────────────────────────────────────────────

export function $$key(cursor, value, body, changed) {
  let anchor;
  let key = value();
  let current;
  if (cursor.hydrating) {
    cursor.open();
    current = cursor.mount(body);
    anchor = cursor.close();
  } else {
    anchor = cursor.comment();
    current = mountFragment(body, undefined, anchor, cursor.ctx);
  }
  const block = {
    p(dirty) {
      if (block.isDone()) return;
      if (!changed || changed(dirty)) {
        const next = value();
        if (next !== key) {
          key = next;
          unmount(current);
          current = mountFragment(body, undefined, anchor, cursor.ctx);
          return;
        }
      }
      updateMounted(current, dirty, false);
    },
    move(before) {
      moveRange(current.range, before);
      before.parentNode.insertBefore(anchor, before);
    },
  };
  return registerBlock(cursor, block, anchor, (removeDom) => {
    if (removeDom) unmount(current);
    else current.owner.release();
  });
}

// ── $$each ───────────────────────────────────────────────────────────────
// collection() returns the iterable; key(item, index) returns the row key or
// is null for an unkeyed list. A row fragment receives the scope
// { item, index } and is updated in place with scopeChanged = true.
// dirtyRows(), when given, returns the indexes of rows changed only by
// in-place mutation of a deep collection (or null): those rows update
// without a reconciliation, as long as the row count is unchanged.

export function $$each(cursor, collection, key, row, fallback, changed, dirtyRows) {
  let anchor;
  let rows = [];
  let byKey = key ? new Map() : null;
  let empty = null;

  const mountRow = (item, index, before) => mountFragment(row, { item, index }, before, cursor.ctx);

  const reconcile = (dirty, initial) => {
    const items = Array.from(collection() || []);
    if (items.length === 0) {
      for (const mounted of rows) unmount(mounted);
      rows = [];
      if (byKey) byKey.clear();
      if (fallback && !empty) empty = mountFragment(fallback, undefined, anchor, cursor.ctx);
      else updateMounted(empty, dirty, false);
      return;
    }
    if (empty) {
      unmount(empty);
      empty = null;
    }
    if (!byKey) {
      // Unkeyed: rows are positional and update in place.
      for (let i = 0; i < items.length; i++) {
        if (i < rows.length) {
          rows[i].scope.item = items[i];
          rows[i].scope.index = i;
          updateMounted(rows[i], dirty, true);
        } else {
          rows.push(mountRow(items[i], i, anchor));
        }
      }
      for (const mounted of rows.splice(items.length)) unmount(mounted);
      return;
    }
    // Keyed: retain, move, create and remove rows by key; keep focus inside a
    // retained row that moves.
    const focused = initial ? null : document.activeElement;
    const restoreFocus = focused && focused !== document.body &&
      rows.some((mounted) => rangeContains(mounted.range, focused));
    const next = [];
    const nextKeys = new Map();
    for (let i = 0; i < items.length; i++) {
      const rowKey = key(items[i], i);
      nextKeys.set(rowKey, i);
      let mounted = byKey.get(rowKey);
      if (mounted) {
        mounted.scope.item = items[i];
        mounted.scope.index = i;
        updateMounted(mounted, dirty, true);
      } else {
        mounted = mountRow(items[i], i, anchor);
        byKey.set(rowKey, mounted);
      }
      mounted.key = rowKey;
      next.push(mounted);
    }
    for (const [rowKey, mounted] of byKey) {
      if (!nextKeys.has(rowKey)) {
        unmount(mounted);
        byKey.delete(rowKey);
      }
    }
    // Place rows in order, moving only those not already in position.
    let before = anchor;
    for (let i = next.length - 1; i >= 0; i--) {
      const mounted = next[i];
      if (mounted.range.end.nextSibling !== before) moveRange(mounted.range, before);
      before = mounted.range.start;
    }
    rows = next;
    if (restoreFocus && focused.isConnected && typeof focused.focus === 'function' &&
        document.activeElement !== focused) {
      focused.focus();
    }
  };

  if (cursor.hydrating) {
    // Rows are adopted in order; keys come from the restored collection
    // (S-6.10). A different row count leaves a row marker or the end
    // marker unconsumed, which the cursor reports (X-7.1).
    const token = cursor.open();
    const items = Array.from(collection() || []);
    if (items.length === 0) {
      cursor.expect(token === (fallback ? 'e' : ''), `#each is empty, the server rendered ${token === 'e' ? 'the fallback' : 'rows'}`);
      if (fallback) empty = cursor.mount(fallback);
    } else {
      cursor.expect(token === '', `#each has ${items.length} rows, the server rendered the fallback`);
      for (let i = 0; i < items.length; i++) {
        const mounted = cursor.mountRow(row, { item: items[i], index: i });
        if (byKey) {
          mounted.key = key(items[i], i);
          byKey.set(mounted.key, mounted);
        }
        rows.push(mounted);
      }
    }
    anchor = cursor.close();
  } else {
    anchor = cursor.comment();
    reconcile(undefined, true);
  }
  const block = {
    p(dirty) {
      if (block.isDone()) return;
      if (!changed || changed(dirty)) {
        const indexes = dirtyRows ? dirtyRows() : null;
        const items = indexes ? Array.from(collection() || []) : null;
        if (indexes && items.length === rows.length) {
          const updated = new Set(indexes);
          for (let i = 0; i < rows.length; i++) {
            if (updated.has(i)) {
              rows[i].scope.item = items[i];
              rows[i].scope.index = i;
              updateMounted(rows[i], dirty, true);
            } else {
              updateMounted(rows[i], dirty, false);
            }
          }
          return;
        }
        reconcile(dirty, false);
        return;
      }
      for (const mounted of rows) updateMounted(mounted, dirty, false);
      updateMounted(empty, dirty, false);
    },
    move(before) {
      for (const mounted of rows) moveRange(mounted.range, before);
      if (empty) moveRange(empty.range, before);
      before.parentNode.insertBefore(anchor, before);
    },
  };
  return registerBlock(cursor, block, anchor, (removeDom) => {
    for (const mounted of rows) {
      if (removeDom) unmount(mounted);
      else mounted.owner.release();
    }
    if (empty) {
      if (removeDom) unmount(empty);
      else empty.owner.release();
    }
  });
}

// ── $$await ──────────────────────────────────────────────────────────────
// Branch fragments receive { value } or { error }. A settlement of a promise
// that is no longer current is ignored.

// reviveError rebuilds an error object the server wrote in its payload
// form: kind, own message, own enumerable properties.
const errorKinds = { Error, TypeError, RangeError };
function reviveError(form) {
  const error = new (errorKinds[form.kind] || Error)();
  if ('message' in form) {
    Object.defineProperty(error, 'message', { value: form.message, writable: true, configurable: true });
  }
  return Object.assign(error, form.props);
}

export function $$await(cursor, operand, pending, then, catcher, changed) {
  let anchor;
  let promise = null;
  let current = null;
  let state = -1;

  const show = (nextState, scope) => {
    unmount(current);
    current = null;
    state = nextState;
    const fragment = nextState === 0 ? pending : nextState === 1 ? then : catcher;
    if (fragment) current = mountFragment(fragment, scope, anchor, cursor.ctx);
  };

  // drive evaluates the operand; adopted keeps the adopted pending branch.
  const drive = (adopted) => {
    const next = Promise.resolve(operand());
    if (next === promise) return false;
    promise = next;
    if (!adopted) show(0, undefined);
    // A branch that fails to mount after the promise settled goes to the
    // enclosing {#boundary} (task 091).
    next.then(
      (value) => {
        if (promise !== next || block.isDone()) return;
        guarded(cursor.ctx, () => show(1, { value }));
      },
      (error) => {
        if (promise !== next || block.isDone()) return;
        guarded(cursor.ctx, () => show(2, { error }));
      },
    );
    return true;
  };

  const block = {
    p(dirty) {
      if (block.isDone()) return;
      if ((!changed || changed(dirty)) && drive()) return;
      updateMounted(current, dirty, false);
    },
    move(before) {
      if (current) moveRange(current.range, before);
      before.parentNode.insertBefore(anchor, before);
    },
    state: () => state,
  };
  if (cursor.hydrating) {
    // The "a" entry holds the branch the server rendered (S-6.11).
    const token = cursor.open();
    const entry = cursor.entry('a') || {};
    cursor.expect(entry.state === token, `#await entry is ${entry.state}, the server range is ${token}`);
    if (token === 't') {
      state = 1;
      if (then) current = cursor.mount(then, { value: entry.value });
    } else if (token === 'c') {
      state = 2;
      const error = entry.errorObject ? reviveError(entry.error) : entry.error;
      if (catcher) current = cursor.mount(catcher, { error });
    } else {
      state = 0;
      if (pending) current = cursor.mount(pending);
      cursor.afterCommit(() => {
        if (!block.isDone()) drive(true);
      });
    }
    anchor = cursor.close();
  } else {
    anchor = cursor.comment();
  }
  registerBlock(cursor, block, anchor, (removeDom) => {
    promise = null;
    if (!current) return;
    if (removeDom) unmount(current);
    else current.owner.release();
  });
  if (!cursor.hydrating) drive();
  return block;
}

// ── $$component ──────────────────────────────────────────────────────────
// Mounts a child through its public factory before an anchor, whichever DOM
// engine compiled it. props() returns the current prop object; events maps
// component event names to handlers attached to the child's root element;
// scope is the parent's CSS scope attribute, set on the child's root.

export function $$component(cursor, factory, props, slots, events, changed, scope) {
  if (factory.$$clientOnly && cursor.hydrating) {
    // A client-only component (contract §9.2): the server rendered an empty
    // client range; the component mounts after the root commits (T-9.2b).
    const main = (inner) => {
      const block = $$component(inner, factory, props, slots, events, changed, scope);
      return { p: (dirty) => block.p(dirty) };
    };
    return $$client(cursor, main, null);
  }
  let anchor;
  let instance;
  // The child's script runs in its own context frame under the context of
  // this position (task 090); the props are computed before it opens.
  const ctx = cursor.ctx;
  if (cursor.hydrating) {
    // The child factory adopts the server DOM inside the component range.
    cursor.open();
    const initial = props();
    instance = withComponentCursor(cursor, () => createInstance(() => $$contextRun(ctx, () => factory(null, initial, slots || {}))));
    anchor = cursor.close();
  } else {
    anchor = cursor.comment();
    const initial = props();
    const create = () => createInstance(() => $$contextRun(ctx, () => factory(anchor, initial, slots || {})));
    // A block created while a root hydrates (a repaired range) creates its
    // children too.
    instance = $$session ? withComponentCursor(null, create) : create();
  }
  if (scope && instance.el) cursor.init(() => instance.el.setAttribute(scope, ''));
  if (events) {
    for (const name of Object.keys(events)) cursor.listen(instance.el, name, events[name]);
  }
  const block = {
    instance,
    p(dirty) {
      if (block.isDone()) return;
      // A child without settable state exposes no set().
      if ((!changed || changed(dirty)) && instance.set) instance.set(props());
    },
    move(before) {
      before.parentNode.insertBefore(instance.el, before);
      before.parentNode.insertBefore(anchor, before);
    },
  };
  // A release without DOM removal (abandon, B-3.4) keeps the child's DOM.
  return registerBlock(cursor, block, anchor, (removeDom) => {
    if (removeDom || !instance.abandon) instance.destroy();
    else instance.abandon();
  });
}

// ── $$dynamic ────────────────────────────────────────────────────────────
// <vela:component :this={…}>: select() returns the component factory to
// render, or null, undefined or false for nothing. The block owns a range
// like $$key; the current child is a $$component inside it. The same
// factory after an update keeps the child and calls set(); another factory
// destroys the child with its DOM and mounts the next one with a create
// cursor (B-3.6). Slot content belongs to the parent and moves to the next
// child (B-3.7).
//
// props() returns every prop the template passes; a child gets only the
// ones its factory declares ($$props, name → bindable). bindings lists the
// bind: props for the development warning about a child without that
// $bindable prop; the binding is inert for that child. where is the source
// position for errors. The range state is "" with a child and "x" without
// one; hydration compares the factory's $$id with the "d" payload entry the
// server wrote (S-6.12).

// dynamicValue checks the value of :this: a factory, a lazy value
// (lazy(), task 071), or null for nothing.
function dynamicValue(value, where) {
  if (value === null || value === undefined || value === false) return null;
  if (typeof value === 'function' || (typeof value === 'object' && value.$$lazy === true)) return value;
  throw new TypeError(`vela: <vela:component> at ${where}: :this is ${value === '' ? 'an empty string' : typeof value}, not a component`);
}

// factoryOf is the component of a selected value; null for a lazy value
// that is not loaded yet.
function factoryOf(value) {
  if (!value) return null;
  if (typeof value === 'function') return value;
  return value.loaded ? value.component : null;
}

function dynamicProps(factory, props) {
  const all = props();
  const declared = factory.$$props;
  if (!declared) return all;
  const out = {};
  for (const name of Object.keys(all)) {
    if (name.startsWith('$$onChange_')) {
      if (declared[name.slice(11)] === 1) out[name] = all[name];
    } else if (Object.prototype.hasOwnProperty.call(declared, name)) {
      out[name] = all[name];
    }
  }
  return out;
}

function warnBindings(factory, bindings, where) {
  const declared = factory.$$props;
  if (!bindings || !declared) return;
  for (const name of bindings) {
    if (declared[name] !== 1) {
      warn(`<vela:component> at ${where}: bind:${name} has no effect on ${factory.$$id || factory.name}, which does not declare export let ${name} = $bindable(…)`);
    }
  }
}

export function $$dynamic(cursor, select, props, slots, events, bindings, changed, scope, where) {
  let anchor;
  // selected is the value of :this, the identity compared after updates; a
  // lazy value keeps its identity while it loads.
  let selected = dynamicValue(select(), where);
  let current = null;
  const fragmentFor = (component) => {
    warnBindings(component, bindings, where);
    return (inner) => {
      const child = inner.block($$component, component, () => dynamicProps(component, props), slots, events, null, scope);
      return { p: (dirty) => child.p(dirty) };
    };
  };
  // show mounts the selected component, or for a lazy value that is not
  // loaded yet starts the load and mounts when it arrives, unless :this
  // changed or the block was destroyed meanwhile (B-3.5).
  const show = () => {
    const factory = factoryOf(selected);
    if (factory) {
      current = mountFragment(fragmentFor(factory), undefined, anchor, cursor.ctx);
      return;
    }
    if (!selected) return;
    const lazyValue = selected;
    // A load or mount failure goes to the enclosing {#boundary} (task 091).
    lazyValue.load().then(
      (component) => {
        if (block.isDone() || selected !== lazyValue || current) return;
        guarded(cursor.ctx, () => {
          current = mountFragment(fragmentFor(component), undefined, anchor, cursor.ctx);
        });
      },
      (error) => {
        if (block.isDone() || selected !== lazyValue) return;
        const boundary = $$boundaryOf(cursor.ctx);
        if (boundary) boundary.fail(error);
        else warn(`<vela:component> at ${where}: the lazy component ${lazyValue.id || '(unnamed)'} failed to load: ${error && error.message ? error.message : error}`);
      },
    );
  };
  const block = {
    p(dirty) {
      if (block.isDone()) return;
      if (changed && !changed(dirty)) return;
      const next = dynamicValue(select(), where);
      if (next !== selected) {
        unmount(current);
        current = null;
        selected = next;
        show();
        return;
      }
      updateMounted(current, dirty, false);
    },
    move(before) {
      if (current) moveRange(current.range, before);
      before.parentNode.insertBefore(anchor, before);
    },
  };
  if (cursor.hydrating) {
    const token = cursor.open();
    const factory = factoryOf(selected);
    if (selected && !factory) {
      // The server rendered the component; its module is not here yet.
      cursor.expect(false, `lazy-not-loaded: <vela:component> renders the lazy component ${selected.id || '(unnamed)'}, which is not loaded; await preloadHydration(container) before hydrate()`);
    }
    const id = factory ? factory.$$id || factory.name : null;
    cursor.expect(token === (factory ? '' : 'x'),
      factory ? `<vela:component> renders ${id}, the server rendered nothing` : `<vela:component> renders nothing, the server rendered a component`);
    if (factory) {
      const server = cursor.entry('d');
      cursor.expect(server === null || server === id, `<vela:component> renders ${id}, the server rendered ${server}`);
      current = cursor.mount(fragmentFor(factory));
    }
    anchor = cursor.close();
  } else {
    anchor = cursor.comment();
  }
  registerBlock(cursor, block, anchor, (removeDom) => {
    if (!current) return;
    if (removeDom) unmount(current);
    else current.owner.release();
  });
  if (!cursor.hydrating) show();
  return block;
}

// ── Slots ────────────────────────────────────────────────────────────────
// Slots use the component protocol: a slot is a function returning a
// DocumentFragment with the slot content. The parent
// owns the content: it is built on the first call, updated by the parent,
// and the same nodes are returned when the child opens the slot again.

// $$slotFactory builds slot content from a parent fragment. The content is
// owned by the parent's current owner and updated through `live`, a set the
// parent fragment walks on every update (B-3.7).
export function $$slotFactory(cursor, live, fragment) {
  let range = null;
  let nodes = null;
  // ctx is the context where the child opens the slot: slot content sees
  // the context of the component that renders it (task 090).
  const open = (ctx) => {
    const container = document.createDocumentFragment();
    if (range) {
      // Reopen: move the content back. If a child removed the nodes one by
      // one, the range chain is broken; fall back to the last snapshot.
      let current = rangeNodes(range);
      if (current[current.length - 1] !== range.end) current = nodes;
      for (const node of current) container.appendChild(node);
      nodes = current;
      return container;
    }
    const owner = $$owner(cursor.owner);
    const handle = fragment(createCursor(container, null, owner, ctx));
    if (handle && handle.p) {
      live.add(handle);
      owner.add(() => live.delete(handle));
    }
    const start = document.createComment('');
    const end = document.createComment('');
    container.insertBefore(start, container.firstChild);
    container.appendChild(end);
    range = { start, end };
    nodes = [...container.childNodes];
    return container;
  };
  // adopt hydrates the content where the server rendered it, inside the
  // child's slot range; reopening returns the adopted nodes.
  open.adopt = (target) => {
    const owner = $$owner(cursor.owner);
    const mounted = target.mount(fragment, undefined, owner);
    if (mounted.handle && mounted.handle.p) {
      live.add(mounted.handle);
      owner.add(() => live.delete(mounted.handle));
    }
    range = mounted.range || { start: null, end: null };
    nodes = rangeNodes(mounted.range);
    return mounted.range;
  };
  return open;
}

// $$slot opens slot content provided by the parent (from either engine) or
// mounts the child's own fallback. On release the parent's content is parked
// in a detached fragment rather than destroyed, so the parent can reopen it.
export function $$slot(cursor, factory, fallback) {
  let anchor;
  let first = null;
  let last = null;
  let current = null;
  if (cursor.hydrating) {
    cursor.open();
    if (factory) {
      cursor.expect(typeof factory.adopt === 'function', 'slot content without an adopt() method cannot be hydrated');
      const adopted = factory.adopt ? factory.adopt(cursor) : null;
      if (adopted) {
        first = adopted.start;
        last = adopted.end;
      }
    } else if (fallback) {
      current = cursor.mount(fallback);
    }
    anchor = cursor.close();
  } else {
    anchor = cursor.comment();
    const content = factory ? factory(cursor.ctx) : null;
    if (content && content.firstChild) {
      first = content.firstChild;
      last = content.lastChild;
      anchor.parentNode.insertBefore(content, anchor);
    } else if (fallback) {
      current = mountFragment(fallback, undefined, anchor, cursor.ctx);
    }
  }
  const park = () => {
    if (!first) return;
    const holder = document.createDocumentFragment();
    for (let node = first; node;) {
      const next = node.nextSibling;
      holder.appendChild(node);
      if (node === last) break;
      node = next;
    }
    first = last = null;
  };
  const block = {
    p(dirty) {
      // Parent content is updated by its parent; only the child's fallback
      // depends on the child's state.
      if (!block.isDone()) updateMounted(current, dirty, false);
    },
    move(before) {
      if (first) {
        for (let node = first; node;) {
          const next = node.nextSibling;
          before.parentNode.insertBefore(node, before);
          if (node === last) break;
          node = next;
        }
      }
      if (current) moveRange(current.range, before);
      before.parentNode.insertBefore(anchor, before);
    },
  };
  return registerBlock(cursor, block, anchor, (removeDom) => {
    park();
    if (!current) return;
    if (removeDom) unmount(current);
    else current.owner.release();
  });
}

// ── $$client ─────────────────────────────────────────────────────────────
// {#client} and client-only components (contract §9). A create cursor (CSR,
// or a block created after hydration) mounts the main branch directly and
// ignores the fallback (T-9.1f). Hydration adopts the server range, whose
// state token is "f" and whose content is the fallback, and after the root
// commits replaces the fallback with the main branch (T-9.1d). Destroying
// the owner, or rolling its hydration back, cancels a pending mount
// (T-9.1e).

export function $$client(cursor, main, fallback) {
  let anchor;
  let current = null;
  let mounted = false;
  const block = {
    p(dirty) {
      if (!block.isDone() && mounted) updateMounted(current, dirty, false);
    },
    move(before) {
      if (current) moveRange(current.range, before);
      before.parentNode.insertBefore(anchor, before);
    },
    state: () => (mounted ? 1 : 0),
  };
  if (cursor.hydrating) {
    const token = cursor.open();
    cursor.expect(token === "f", `#client range is ${token}, expected f`);
    if (fallback) current = cursor.mount(fallback);
    anchor = cursor.close();
    cursor.afterCommit(() => {
      if (block.isDone()) return;
      unmount(current);
      current = null;
      guarded(cursor.ctx, () => {
        current = mountFragment(main, undefined, anchor, cursor.ctx);
        mounted = true;
      });
    });
  } else {
    anchor = cursor.comment();
  }
  registerBlock(cursor, block, anchor, (removeDom) => {
    if (!current) return;
    if (removeDom) unmount(current);
    else current.owner.release();
  });
  if (!cursor.hydrating) {
    current = mountFragment(main, undefined, anchor, cursor.ctx);
    mounted = true;
  }
  return block;
}

// ── $$boundary ───────────────────────────────────────────────────────────
// {#boundary}…{:catch error, retry}…{/boundary} (task 091). The body mounts
// under a context frame that names this block, so errors that do not reach
// it as exceptions find it too: a component's own update ($$flush through
// rootView.fail), an {#await} branch mounted after its promise settled, a
// lazy() component that fails to load. A failure releases the body with its
// DOM, mounts the catch fragment with { error, retry } and dispatches a
// bubbling vela:error event ({ error, source }) from the block's parent
// element; retry() mounts the body again. Errors of the catch branch go to
// the enclosing boundary. Event handlers and other async code are not
// caught.
//
// Hydration: the state token is "" for an adopted body and "c" when the
// server rendered the catch branch, whose "b" entry holds the public
// message; the client adopts that branch without running the body. A body
// that fails while it hydrates is removed up to the range end and the catch
// branch is created in its place.

// $$boundaryOf returns the boundary that encloses a context, or null.
export function $$boundaryOf(ctx) {
  for (let frame = ctx; frame; frame = frame.parent) {
    if (frame.boundary) return frame.boundary;
  }
  return null;
}

// guarded runs fn, passing an error to the boundary of ctx; without one it
// rethrows.
function guarded(ctx, fn) {
  try {
    fn();
  } catch (error) {
    const boundary = $$boundaryOf(ctx);
    if (!boundary) throw error;
    boundary.fail(error);
  }
}

function reportError(anchor, error, where) {
  const dispatch = () => {
    const target = anchor.parentNode && anchor.isConnected ? anchor.parentNode : typeof document !== 'undefined' ? document : null;
    if (target) target.dispatchEvent(new CustomEvent('vela:error', { detail: { error, source: where || undefined }, bubbles: true }));
  };
  // A boundary that fails while its fragment is built is not in the
  // document yet.
  if (anchor.isConnected) dispatch();
  else Promise.resolve().then(dispatch);
}

export function $$boundary(cursor, body, catcher, where) {
  let anchor;
  let current = null;
  let failed = false;
  const ctx = { parent: cursor.ctx, map: null, open: false, boundary: null };
  const retry = () => {
    if (block.isDone() || !failed) return;
    unmount(current);
    current = null;
    failed = false;
    showBody();
  };
  const showCatch = (error) => {
    failed = true;
    reportError(anchor, error, where);
    current = mountFragment(catcher, { error, retry }, anchor, cursor.ctx);
  };
  const showBody = () => {
    try {
      current = mountGuarded(body, undefined, anchor, ctx);
    } catch (error) {
      current = null;
      showCatch(error);
    }
  };
  const fail = (error) => {
    if (block.isDone() || failed) return;
    const previous = current;
    current = null;
    failed = true;
    try {
      unmount(previous);
    } catch {
      // The failed body is gone either way.
      if (previous) removeRange(previous.range);
    }
    showCatch(error);
  };
  ctx.boundary = { fail };
  const block = {
    p(dirty) {
      if (block.isDone()) return;
      if (failed) {
        updateMounted(current, dirty, false);
        return;
      }
      try {
        updateMounted(current, dirty, false);
      } catch (error) {
        fail(error);
      }
    },
    move(before) {
      if (current) moveRange(current.range, before);
      before.parentNode.insertBefore(anchor, before);
    },
    state: () => (failed ? 'c' : ''),
  };
  if (cursor.hydrating) {
    const token = cursor.open();
    if (token === 'c') {
      // The server rendered the catch branch (its body failed there).
      const entry = cursor.entry('b') || {};
      const error = new Error(typeof entry.message === 'string' ? entry.message : 'Internal error');
      failed = true;
      current = cursor.mount(catcher, { error, retry });
      anchor = cursor.close();
    } else {
      cursor.expect(token === '', `#boundary range is ${token}, expected "" or c`);
      const restore = cursor.checkpoint();
      let failure = null;
      try {
        current = cursor.mount(body, undefined, null, ctx);
      } catch (error) {
        // A mismatch is repaired by the enclosing block as usual.
        if (error && error.code === 'VELA-HYDRATION-MISMATCH') throw error;
        restore();
        current = null;
        failure = error;
      }
      anchor = cursor.close();
      if (failure !== null) showCatch(failure);
    }
  } else {
    anchor = cursor.comment();
  }
  registerBlock(cursor, block, anchor, (removeDom) => {
    if (!current) return;
    if (removeDom) unmount(current);
    else current.owner.release();
  });
  if (!cursor.hydrating) showBody();
  return block;
}

// ── $$head ───────────────────────────────────────────────────────────────
// <vela:head> (task 091). Every tag is an entry of one registry of the
// document head. Entries with the same key ("title", "meta name=…", "meta
// property=…", "link canonical") replace each other: the one of the
// deepest component is in the document, at the same depth the later one;
// the others wait outside it and come back when it goes. Tags without a key
// are all in the document. The router registers the tags of the app
// (r.Head(), Config.Head) with $$appHead; at the same depth a component
// wins over them. Every tag carries data-vela-head: "<component ID>#<n>"
// for a component's, "app:<depth>" for the app's. Hydration adopts the
// server's tags by that attribute.

const headRegistry = { entries: new Set(), order: 0, scanned: false };

function headKeyOf(node) {
  const tag = node.localName;
  if (tag === 'title') return 'title';
  if (tag === 'meta') {
    const property = node.getAttribute('property');
    if (property) return `meta property=${property}`;
    const name = node.getAttribute('name');
    if (name) return `meta name=${name}`;
  }
  if (tag === 'link' && (node.getAttribute('rel') || '').trim().toLowerCase() === 'canonical') return 'link canonical';
  return null;
}

// scanHead registers the app's tags the server wrote, once.
function scanHead() {
  if (headRegistry.scanned || typeof document === 'undefined') return;
  headRegistry.scanned = true;
  for (const node of document.head.querySelectorAll('[data-vela-head^="app:"]')) {
    headRegistry.entries.add({ key: headKeyOf(node), depth: Number(node.getAttribute('data-vela-head').slice(4)) || 0, order: -1, node, on: true, app: true });
  }
}

// syncHead puts the winning entries into document.head and takes the
// others out. A keyed tag goes before a tag of the same key that the page
// has itself (a <title> of index.html), so that the browser uses it.
function syncHead() {
  const winners = new Map();
  for (const entry of headRegistry.entries) {
    if (!entry.key || !entry.on) continue;
    const best = winners.get(entry.key);
    if (!best || entry.depth > best.depth || (entry.depth === best.depth && entry.order > best.order)) winners.set(entry.key, entry);
  }
  for (const entry of headRegistry.entries) {
    const show = entry.on && (!entry.key || winners.get(entry.key) === entry);
    const node = entry.node;
    if (show && node.parentNode !== document.head) {
      document.head.insertBefore(node, entry.key ? ownHeadTag(entry.key) : null);
    } else if (!show && node.parentNode) {
      node.remove();
    }
  }
}

function ownHeadTag(key) {
  for (const node of document.head.children) {
    if (!node.hasAttribute('data-vela-head') && headKeyOf(node) === key) return node;
  }
  return null;
}

function writeHeadAttrs(node, list) {
  const seen = new Set(['data-vela-head']);
  for (let i = 0; i < list.length; i += 2) {
    const name = list[i];
    const value = list[i + 1];
    seen.add(name);
    if (value === null || value === undefined || value === false) {
      if (node.hasAttribute(name)) node.removeAttribute(name);
    } else {
      const text = value === true ? '' : String(value);
      if (node.getAttribute(name) !== text) node.setAttribute(name, text);
    }
  }
  for (const attr of [...node.attributes]) if (!seen.has(attr.name)) node.removeAttribute(attr.name);
}

export function $$head(cursor, specs, changed) {
  scanHead();
  const depth = componentDepth;
  const entries = specs.map(([tag, key, site, attrs, text, when]) => {
    let node = null;
    if (cursor.hydrating) {
      // The server's tag of this site, when it rendered one.
      for (const candidate of document.head.querySelectorAll(`[data-vela-head="${site}"]`)) {
        if (!headAdopted.has(candidate) && candidate.localName === tag) {
          node = candidate;
          break;
        }
      }
    }
    if (!node) {
      node = document.createElement(tag);
      node.setAttribute('data-vela-head', site);
    }
    headAdopted.add(node);
    return { key, depth, order: headRegistry.order++, node, on: false, attrs, text, when };
  });
  const render = () => {
    for (const entry of entries) {
      entry.on = !entry.when || entry.when();
      if (!entry.on) continue;
      writeHeadAttrs(entry.node, entry.attrs());
      if (entry.text) {
        const value = entry.text();
        if (entry.node.textContent !== value) entry.node.textContent = value;
      }
    }
    syncHead();
  };
  for (const entry of entries) headRegistry.entries.add(entry);
  render();
  const block = {
    p(dirty) {
      if (!block.isDone() && (!changed || changed(dirty))) render();
    },
    move() {},
  };
  // The block has no DOM in place; its tags leave the head with it.
  return registerBlock(cursor, block, { remove() {} }, () => {
    for (const entry of entries) {
      headRegistry.entries.delete(entry);
      headAdopted.delete(entry.node);
      entry.node.remove();
    }
    syncHead();
  });
}

const headAdopted = new WeakSet();

// $$appHead replaces the app's tags (the router, after a navigation):
// tags is a list of { key, depth, node }. Tags of components stay.
export function $$appHead(tags) {
  scanHead();
  for (const entry of [...headRegistry.entries]) {
    if (!entry.app) continue;
    headRegistry.entries.delete(entry);
    entry.node.remove();
  }
  for (const tag of tags) {
    tag.node.setAttribute('data-vela-head', `app:${tag.depth}`);
    headRegistry.entries.add({ key: tag.key === undefined ? headKeyOf(tag.node) : tag.key, depth: tag.depth, order: -1, node: tag.node, on: true, app: true });
  }
  syncHead();
}

// $$createCursor exposes the create cursor to the hydration runtime, which
// remounts a block whose server range does not match (X-7.3).
export function $$createCursor(parent, before, owner, ctx) {
  return createCursor(parent, before, owner, ctx);
}
