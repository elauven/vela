// ── Owners ───────────────────────────────────────────────────────────────
// An owner collects the resources created while a fragment mounts
// (listeners, child blocks, component instances, deferred work) and releases
// them in reverse registration order (B-3.2, B-3.3). Releasing never touches
// the DOM: the block that owns a range removes it as a whole.

export function $$owner(parent) {
  const owner = {
    done: false,
    cleanups: [],
    add(cleanup) {
      if (owner.done) {
        cleanup();
        return;
      }
      owner.cleanups.push(cleanup);
    },
    release() {
      if (owner.done) return;
      owner.done = true;
      const cleanups = owner.cleanups;
      owner.cleanups = [];
      for (let i = cleanups.length - 1; i >= 0; i--) cleanups[i]();
    },
  };
  if (parent) parent.add(() => owner.release());
  return owner;
}

// ── Ranges ───────────────────────────────────────────────────────────────
// A range is the DOM a fragment occupies. A single top-level element or text
// node is its own range; anything else is wrapped in an empty comment pair,
// so nodes added later by nested blocks stay inside it.

function rangeOf(fragment) {
  const nodes = fragment.childNodes;
  if (nodes.length === 1 && (nodes[0].nodeType === 1 || nodes[0].nodeType === 3)) {
    return { start: nodes[0], end: nodes[0] };
  }
  const start = document.createComment('');
  const end = document.createComment('');
  fragment.insertBefore(start, fragment.firstChild);
  fragment.appendChild(end);
  return { start, end };
}

function rangeNodes(range) {
  const nodes = [];
  for (let node = range.start; node; node = node.nextSibling) {
    nodes.push(node);
    if (node === range.end) break;
  }
  return nodes;
}

function removeRange(range) {
  for (const node of rangeNodes(range)) node.remove();
}

function moveRange(range, before) {
  const parent = before.parentNode;
  for (const node of rangeNodes(range)) parent.insertBefore(node, before);
}

function rangeContains(range, node) {
  for (const item of rangeNodes(range)) {
    if (item === node || item.contains(node)) return true;
  }
  return false;
}

// ── Create cursor ────────────────────────────────────────────────────────
// The create cursor builds new DOM (C-4.1). The hydrate cursor of task 041
// implements the same interface over existing server DOM.

export function $$template(html) {
  const template = document.createElement('template');
  template.innerHTML = html;
  return template;
}

function createCursor(parent, before, owner) {
  const stack = [];
  const cursor = {
    owner,
    hydrating: false,
    insert(node) {
      parent.insertBefore(node, before);
      return node;
    },
    // element creates an element with its static attributes, given as a flat
    // [name, value, ...] list (the scope attribute comes first).
    element(tag, attrs) {
      const element = document.createElement(tag);
      if (attrs) for (let i = 0; i < attrs.length; i += 2) element.setAttribute(attrs[i], attrs[i + 1]);
      return cursor.insert(element);
    },
    text(value) {
      return cursor.insert(document.createTextNode(value));
    },
    comment() {
      return cursor.insert(document.createComment(''));
    },
    static(template) {
      const content = template.content.cloneNode(true);
      const nodes = [...content.childNodes];
      cursor.insert(content);
      return nodes;
    },
    enter(element) {
      stack.push([parent, before]);
      parent = element;
      before = null;
    },
    exit() {
      [parent, before] = stack.pop();
    },
    // init runs an initial DOM write (attribute, property, class, style,
    // control value). The hydrate cursor adopts the server value instead
    // (F-2.2), so writes go through this hook rather than running inline.
    init(write) {
      write();
    },
    listen(target, event, handler, options) {
      target.addEventListener(event, handler, options);
      owner.add(() => target.removeEventListener(event, handler, options));
    },
    block(kind, ...args) {
      return kind(cursor, ...args);
    },
  };
  return cursor;
}

// mountFragment builds a fragment detached from the document, computes its
// range, then inserts it before `before`. The owning block releases the
// fragment, so its owner is not registered with a parent: a parent cleanup
// per mounted branch or row would accumulate across updates.
function mountFragment(fragmentFn, scope, before) {
  const owner = $$owner(null);
  const container = document.createDocumentFragment();
  const handle = fragmentFn(createCursor(container, null, owner), scope);
  const range = rangeOf(container);
  before.parentNode.insertBefore(container, before);
  return { owner, handle, range, scope };
}

function updateMounted(mounted, dirty, scopeChanged) {
  if (mounted && mounted.handle && mounted.handle.p) mounted.handle.p(dirty, scopeChanged);
}

function unmount(mounted) {
  if (!mounted) return;
  mounted.owner.release();
  removeRange(mounted.range);
}

// registerBlock ties a block to its owner and gives it the common
// destroy/abandon behaviour (B-3.3, B-3.4).
function registerBlock(cursor, block, anchor, release) {
  let done = false;
  const finish = (removeDom) => {
    if (done) return;
    done = true;
    release(removeDom);
    if (removeDom) anchor.remove();
  };
  block.destroy = () => finish(true);
  block.abandon = () => finish(false);
  block.isDone = () => done;
  cursor.owner.add(() => finish(false));
  return block;
}

// ── Root ─────────────────────────────────────────────────────────────────

// $$mountRoot mounts a component's root fragment into target (an element,
// or a comment anchor that the content is inserted before).
export function $$mountRoot(target, fragmentFn, scope) {
  const owner = $$owner(null);
  const before = target.nodeType === 8 ? target : null;
  const parent = before ? before.parentNode : target;
  const handle = fragmentFn(createCursor(parent, before, owner), scope);
  return {
    owner,
    p(dirty) {
      if (handle && handle.p) handle.p(dirty, false);
    },
    release() {
      owner.release();
    },
  };
}

// ── $$if ─────────────────────────────────────────────────────────────────
// select() returns the active branch index or -1.

export function $$if(cursor, select, branches, changed) {
  const anchor = cursor.comment();
  let index = -1;
  let current = null;
  const show = (next) => {
    index = next;
    current = next >= 0 ? mountFragment(branches[next], undefined, anchor) : null;
  };
  show(select());
  const block = {
    p(dirty) {
      if (block.isDone()) return;
      if (!changed || changed(dirty)) {
        const next = select();
        if (next !== index) {
          unmount(current);
          show(next);
          return;
        }
      }
      updateMounted(current, dirty, false);
    },
    move(before) {
      if (current) moveRange(current.range, before);
      before.parentNode.insertBefore(anchor, before);
    },
  };
  return registerBlock(cursor, block, anchor, (removeDom) => {
    if (!current) return;
    if (removeDom) unmount(current);
    else current.owner.release();
  });
}

// ── $$key ────────────────────────────────────────────────────────────────

export function $$key(cursor, value, body, changed) {
  const anchor = cursor.comment();
  let key = value();
  let current = mountFragment(body, undefined, anchor);
  const block = {
    p(dirty) {
      if (block.isDone()) return;
      if (!changed || changed(dirty)) {
        const next = value();
        if (next !== key) {
          key = next;
          unmount(current);
          current = mountFragment(body, undefined, anchor);
          return;
        }
      }
      updateMounted(current, dirty, false);
    },
    move(before) {
      moveRange(current.range, before);
      before.parentNode.insertBefore(anchor, before);
    },
  };
  return registerBlock(cursor, block, anchor, (removeDom) => {
    if (removeDom) unmount(current);
    else current.owner.release();
  });
}

// ── $$each ───────────────────────────────────────────────────────────────
// collection() returns the iterable; key(item, index) returns the row key or
// is null for an unkeyed list. A row fragment receives the scope
// { item, index } and is updated in place with scopeChanged = true.
// dirtyRows(), when given, returns the indexes of rows changed only by
// in-place mutation of a deep collection (or null): those rows update
// without a reconciliation, as long as the row count is unchanged.

export function $$each(cursor, collection, key, row, fallback, changed, dirtyRows) {
  const anchor = cursor.comment();
  let rows = [];
  let byKey = key ? new Map() : null;
  let empty = null;

  const mountRow = (item, index, before) => mountFragment(row, { item, index }, before);

  const reconcile = (dirty, initial) => {
    const items = Array.from(collection() || []);
    if (items.length === 0) {
      for (const mounted of rows) unmount(mounted);
      rows = [];
      if (byKey) byKey.clear();
      if (fallback && !empty) empty = mountFragment(fallback, undefined, anchor);
      else updateMounted(empty, dirty, false);
      return;
    }
    if (empty) {
      unmount(empty);
      empty = null;
    }
    if (!byKey) {
      // Unkeyed: rows are positional and update in place.
      for (let i = 0; i < items.length; i++) {
        if (i < rows.length) {
          rows[i].scope.item = items[i];
          rows[i].scope.index = i;
          updateMounted(rows[i], dirty, true);
        } else {
          rows.push(mountRow(items[i], i, anchor));
        }
      }
      for (const mounted of rows.splice(items.length)) unmount(mounted);
      return;
    }
    // Keyed: retain, move, create and remove rows by key; keep focus inside a
    // retained row that moves.
    const focused = initial ? null : document.activeElement;
    const restoreFocus = focused && focused !== document.body &&
      rows.some((mounted) => rangeContains(mounted.range, focused));
    const next = [];
    const nextKeys = new Map();
    for (let i = 0; i < items.length; i++) {
      const rowKey = key(items[i], i);
      nextKeys.set(rowKey, i);
      let mounted = byKey.get(rowKey);
      if (mounted) {
        mounted.scope.item = items[i];
        mounted.scope.index = i;
        updateMounted(mounted, dirty, true);
      } else {
        mounted = mountRow(items[i], i, anchor);
        byKey.set(rowKey, mounted);
      }
      mounted.key = rowKey;
      next.push(mounted);
    }
    for (const [rowKey, mounted] of byKey) {
      if (!nextKeys.has(rowKey)) {
        unmount(mounted);
        byKey.delete(rowKey);
      }
    }
    // Place rows in order, moving only those not already in position.
    let before = anchor;
    for (let i = next.length - 1; i >= 0; i--) {
      const mounted = next[i];
      if (mounted.range.end.nextSibling !== before) moveRange(mounted.range, before);
      before = mounted.range.start;
    }
    rows = next;
    if (restoreFocus && focused.isConnected && typeof focused.focus === 'function' &&
        document.activeElement !== focused) {
      focused.focus();
    }
  };

  reconcile(undefined, true);
  const block = {
    p(dirty) {
      if (block.isDone()) return;
      if (!changed || changed(dirty)) {
        const indexes = dirtyRows ? dirtyRows() : null;
        const items = indexes ? Array.from(collection() || []) : null;
        if (indexes && items.length === rows.length) {
          const updated = new Set(indexes);
          for (let i = 0; i < rows.length; i++) {
            if (updated.has(i)) {
              rows[i].scope.item = items[i];
              rows[i].scope.index = i;
              updateMounted(rows[i], dirty, true);
            } else {
              updateMounted(rows[i], dirty, false);
            }
          }
          return;
        }
        reconcile(dirty, false);
        return;
      }
      for (const mounted of rows) updateMounted(mounted, dirty, false);
      updateMounted(empty, dirty, false);
    },
    move(before) {
      for (const mounted of rows) moveRange(mounted.range, before);
      if (empty) moveRange(empty.range, before);
      before.parentNode.insertBefore(anchor, before);
    },
  };
  return registerBlock(cursor, block, anchor, (removeDom) => {
    for (const mounted of rows) {
      if (removeDom) unmount(mounted);
      else mounted.owner.release();
    }
    if (empty) {
      if (removeDom) unmount(empty);
      else empty.owner.release();
    }
  });
}

// ── $$await ──────────────────────────────────────────────────────────────
// Branch fragments receive { value } or { error }. A settlement of a promise
// that is no longer current is ignored.

export function $$await(cursor, operand, pending, then, catcher, changed) {
  const anchor = cursor.comment();
  let promise = null;
  let current = null;
  let state = -1;

  const show = (nextState, scope) => {
    unmount(current);
    current = null;
    state = nextState;
    const fragment = nextState === 0 ? pending : nextState === 1 ? then : catcher;
    if (fragment) current = mountFragment(fragment, scope, anchor);
  };

  const drive = () => {
    const next = Promise.resolve(operand());
    if (next === promise) return false;
    promise = next;
    show(0, undefined);
    next.then(
      (value) => {
        if (promise !== next || block.isDone()) return;
        show(1, { value });
      },
      (error) => {
        if (promise !== next || block.isDone()) return;
        show(2, { error });
      },
    );
    return true;
  };

  const block = {
    p(dirty) {
      if (block.isDone()) return;
      if ((!changed || changed(dirty)) && drive()) return;
      updateMounted(current, dirty, false);
    },
    move(before) {
      if (current) moveRange(current.range, before);
      before.parentNode.insertBefore(anchor, before);
    },
    state: () => state,
  };
  registerBlock(cursor, block, anchor, (removeDom) => {
    promise = null;
    if (!current) return;
    if (removeDom) unmount(current);
    else current.owner.release();
  });
  drive();
  return block;
}

// ── $$component ──────────────────────────────────────────────────────────
// Mounts a child through its public factory before an anchor. props()
// returns the current prop object; events maps component event names to
// handlers attached to the child's root element.

export function $$component(cursor, factory, props, slots, events, changed) {
  const anchor = cursor.comment();
  const instance = factory(anchor, props(), slots || {});
  if (events) {
    for (const name of Object.keys(events)) cursor.listen(instance.el, name, events[name]);
  }
  const block = {
    instance,
    p(dirty) {
      if (block.isDone()) return;
      if (!changed || changed(dirty)) instance.set(props());
    },
    move(before) {
      before.parentNode.insertBefore(instance.el, before);
      before.parentNode.insertBefore(anchor, before);
    },
  };
  return registerBlock(cursor, block, anchor, () => instance.destroy());
}

// ── Slots ────────────────────────────────────────────────────────────────
// The parent defines slot content; the child mounts it at its <slot>. The
// content belongs to the child's $$slot block, while its updates come from
// the parent through `live`, a set the parent's flush walks (B-3.7).

export function $$slotContent(live, fragment) {
  return (cursor) => {
    const handle = fragment(cursor);
    if (handle && handle.p) {
      live.add(handle);
      cursor.owner.add(() => live.delete(handle));
    }
    return undefined;
  };
}

export function $$slot(cursor, content, fallback) {
  const anchor = cursor.comment();
  const fragment = content || fallback;
  const isFallback = !content;
  const current = fragment ? mountFragment(fragment, undefined, anchor) : null;
  const block = {
    p(dirty) {
      // Parent content is updated by its own component; only the child's
      // fallback depends on the child's state.
      if (!block.isDone() && isFallback) updateMounted(current, dirty, false);
    },
    move(before) {
      if (current) moveRange(current.range, before);
      before.parentNode.insertBefore(anchor, before);
    },
  };
  return registerBlock(cursor, block, anchor, (removeDom) => {
    if (!current) return;
    if (removeDom) unmount(current);
    else current.owner.release();
  });
}

// ── $$client ─────────────────────────────────────────────────────────────
// CSR mounts the main branch directly (T-9.1f); hydration mounts it after
// the root commits (task 041).

export function $$client(cursor, main, fallback) {
  void fallback;
  const anchor = cursor.comment();
  const current = mountFragment(main, undefined, anchor);
  const block = {
    p(dirty) {
      if (!block.isDone()) updateMounted(current, dirty, false);
    },
    move(before) {
      moveRange(current.range, before);
      before.parentNode.insertBefore(anchor, before);
    },
  };
  return registerBlock(cursor, block, anchor, (removeDom) => {
    if (removeDom) unmount(current);
    else current.owner.release();
  });
}
