// withComponentCursor makes cursor the position the next component factory
// hydrates at.
function withComponentCursor(cursor, mount) {
  $$session.cursors.push(cursor);
  try {
    return mount();
  } finally {
    $$session.cursors.pop();
  }
}

// $$mountComponent mounts a component's root fragment. Created: into a new
// display:contents wrapper (when wrapperScope is not null; "" is a wrapper
// without a scope attribute, for a component without styles) or a detached
// fragment, then inserted at target. Hydrated: on the server DOM at the
// cursor of the enclosing block or root. setRoot receives the wrapper;
// getRoot returns the component element afterwards.
export function $$mountComponent(target, fragmentFn, wrapperScope, setRoot, getRoot) {
  // The script has run; the template gets the component's context.
  const ctx = $$contextClaim();
  const outer = $$session ? $$session.cursors[$$session.cursors.length - 1] || null : null;
  if (outer) {
    const owner = $$owner(null);
    const view = rootView(owner, null, ctx);
    if (wrapperScope != null) {
      const wrapper = outer.element('div', wrapperScope ? [wrapperScope, '', 'style', 'display: contents;'] : ['style', 'display: contents;']);
      setRoot(wrapper);
      outer.enter(wrapper);
      view.handle = fragmentFn(outer.sub(owner, ctx));
      outer.exit();
    } else {
      view.handle = fragmentFn(outer.sub(owner, ctx));
    }
    return view;
  }
  let view;
  if (wrapperScope != null) {
    const wrapper = document.createElement('div');
    if (wrapperScope) wrapper.setAttribute(wrapperScope, '');
    wrapper.style.display = 'contents';
    setRoot(wrapper);
    view = $$mountRoot(wrapper, fragmentFn, undefined, ctx);
  } else {
    view = $$mountRoot(document.createDocumentFragment(), fragmentFn, undefined, ctx);
  }
  const root = getRoot();
  if (target.nodeType === 8) target.parentNode.insertBefore(root, target);
  else target.appendChild(root);
  return view;
}

// rootView is the view of a component's template. fail(error) passes an
// error of the component's own update (its $$flush: template updates and
// effects) to the nearest enclosing {#boundary} and reports whether one
// took it; without one the component rethrows (task 091).
// viewSink collects the views created while a $$component factory runs;
// when the factory throws (a {#boundary} body), they are released.
let viewSink = null;

function rootView(owner, handle, ctx) {
  const view = {
    owner,
    handle,
    p(dirty) {
      if (view.handle && view.handle.p) view.handle.p(dirty, false);
    },
    release() {
      owner.release();
    },
    fail(error) {
      const boundary = $$boundaryOf(ctx);
      if (!boundary) return false;
      boundary.fail(error);
      return true;
    },
  };
  if (viewSink) viewSink.push(view);
  return view;
}

// createInstance calls a component factory; a factory that throws leaves
// no live view behind.
function createInstance(create) {
  const previous = viewSink;
  const sink = (viewSink = []);
  componentDepth++;
  try {
    return create();
  } catch (error) {
    for (const view of sink) view.release();
    throw error;
  } finally {
    componentDepth--;
    viewSink = previous;
  }
}

