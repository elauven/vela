package main

// unplugin_package.go — the @govela/unplugin npm package (task 063), the
// bundler plugin over the compiler service. Its manifest, README and the
// entry module of each bundler are generated with the compiler version; the
// plugin itself (index.js, index.d.ts) is written by hand.

import (
	"github.com/elauven/vela/runtime"

	"path"
)

// UnpluginPackageName is the npm package of the bundler plugin.
const UnpluginPackageName = "@govela/unplugin"

const unpluginPackageDir = "packages/unplugin"

// unpluginPackageSources are the hand-written files of packages/unplugin.
var unpluginPackageSources = []string{"index.js", "index.d.ts"}

// unpluginBundlers are the entry points: `@govela/unplugin/<bundler>`.
var unpluginBundlers = []string{"vite", "rollup", "rolldown", "esbuild", "webpack", "rspack"}

// unpluginVersion is the unplugin release the plugin is written against.
const unpluginVersion = "^3.4.0"

func unpluginPackageFiles() (map[string][]byte, error) {
	files := map[string][]byte{}
	exports := map[string]any{
		".":              conditionalExport{Types: "./index.d.ts", Default: "./index.js"},
		"./package.json": "./package.json",
	}
	published := append([]string{}, unpluginPackageSources...)
	for _, bundler := range unpluginBundlers {
		entry := "export { " + bundler + " as default } from './index.js';\n"
		files[path.Join(unpluginPackageDir, bundler+".js")] = []byte("// Generated by the compiler repository; do not edit.\n" + entry)
		files[path.Join(unpluginPackageDir, bundler+".d.ts")] = []byte(entry)
		exports["./"+bundler] = conditionalExport{Types: "./" + bundler + ".d.ts", Default: "./" + bundler + ".js"}
		published = append(published, bundler+".js", bundler+".d.ts")
	}
	manifest := struct {
		Name             string            `json:"name"`
		Version          string            `json:"version"`
		Description      string            `json:"description"`
		License          string            `json:"license"`
		Repository       packageRepository `json:"repository"`
		Type             string            `json:"type"`
		Exports          map[string]any    `json:"exports"`
		Types            string            `json:"types"`
		Files            []string          `json:"files"`
		Engines          map[string]string `json:"engines"`
		Dependencies     map[string]string `json:"dependencies"`
		PeerDependencies map[string]string `json:"peerDependencies"`
	}{
		Name:        UnpluginPackageName,
		Version:     runtime.Version,
		Description: "Vela components in Vite, Rollup, Rolldown, esbuild, webpack and Rspack. Manifest generated by the compiler repository; do not edit.",
		License:     "MIT",
		Repository:  repositoryOf(unpluginPackageDir),
		Type:        "module",
		Exports:     exports,
		Types:       "index.d.ts",
		Files:       append(published, "LICENSE"),
		// The engines of unplugin 3.
		Engines:          map[string]string{"node": "^20.19.0 || >=22.12.0"},
		Dependencies:     map[string]string{CompilerPackageName: runtime.Version, "unplugin": unpluginVersion},
		PeerDependencies: map[string]string{runtime.PackageName: runtime.Version},
	}
	encoded, err := encodePackageJSON(manifest)
	if err != nil {
		return nil, err
	}
	readme := "# " + UnpluginPackageName + "\n\n" +
		"Vela components in Vite, Rollup, Rolldown, esbuild, webpack and Rspack.\n" +
		"The bundler resolves, bundles and serves; the plugin compiles `.vela`\n" +
		"modules through the compiler service of `" + CompilerPackageName + "`.\n\n" +
		"```sh\n" +
		"npm i -D " + UnpluginPackageName + " && npm i " + runtime.PackageName + "\n" +
		"```\n\n" +
		"```js\n" +
		"// vite.config.js\n" +
		"import vela from '" + UnpluginPackageName + "/vite';\n\n" +
		"export default { plugins: [vela()] };\n" +
		"```\n\n" +
		"```js\n" +
		"// esbuild\n" +
		"import vela from '" + UnpluginPackageName + "/esbuild';\n\n" +
		"await esbuild.build({ entryPoints: ['src/main.js'], bundle: true, outdir: 'dist', plugins: [vela()] });\n" +
		"```\n\n" +
		"Options: `css` ('external', the default for Vite and esbuild: the CSS of\n" +
		"a component is the module `X.vela?vela&type=style&lang.css` for the\n" +
		"bundler's CSS pipeline; 'inject': the component adds it at runtime, the\n" +
		"default for the other bundlers), `cwd`, `config` (a vela.config.json),\n" +
		"`binary` and `compilerOptions` (file options such as `target`).\n" +
		"Diagnostics are bundler errors and warnings with their location.\n\n" +
		"Install `" + runtime.PackageName + "`, `" + CompilerPackageName + "` and this package with\n" +
		"the same version.\n\n" +
		"License: MIT.\n"
	files[path.Join(unpluginPackageDir, "package.json")] = encoded
	files[path.Join(unpluginPackageDir, "README.md")] = []byte(readme)
	files[path.Join(unpluginPackageDir, "LICENSE")] = licenseText
	return files, nil
}
