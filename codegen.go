package main

import (
	"fmt"
	"sort"
	"strings"
)

// ──────────────────────────────────────────────
//  CodeGen — walks the template AST and emits
//  a self-contained ES module component.
// ──────────────────────────────────────────────

type CodeGen struct {
	name     string
	scopeID  string
	analysis *Analysis
	sfc      *SFC
	counter  int

	// Accumulated code sections
	create  strings.Builder // DOM node creation
	wire    strings.Builder // appendChild / structural wiring
	events  strings.Builder // addEventListener calls
	init    strings.Builder // initial property assignments
	cleanup strings.Builder // removeEventListener / teardown

	// Map: reactive-var-name → list of JS update statements
	updates map[string][]string
}

func generateCode(
	name string,
	sfc *SFC,
	nodes []Node,
	analysis *Analysis,
	scopeID string,
) string {
	g := &CodeGen{
		name:     name,
		scopeID:  scopeID,
		analysis: analysis,
		sfc:      sfc,
		updates:  make(map[string][]string),
	}
	return g.emit(nodes)
}

func (g *CodeGen) id() string {
	id := g.counter
	g.counter++
	return fmt.Sprintf("$$n%d", id)
}

// ──────────────────────────────────────────────
//  Top-level emit
// ──────────────────────────────────────────────

func (g *CodeGen) emit(nodes []Node) string {
	var out strings.Builder

	// ── File header ─────────────────────────
	out.WriteString("// Generated by Vela Compiler — do not edit\n\n")

	// ── Re-exports / imports ─────────────────
	for _, imp := range g.analysis.Imports {
		src := imp.Source
		if src == "vela/store" || src == "vela" {
			src = "./runtime.js"
		} else {
			src = RewriteImportPath(src) // .vela → .js, extensionless → .js
		}
		if imp.Spec == "" {
			// Side-effect import:  import 'path'
			out.WriteString(fmt.Sprintf("import '%s';\n", src))
		} else {
			out.WriteString(fmt.Sprintf("import %s from '%s';\n", imp.Spec, src))
		}
	}
	if len(g.analysis.Imports) > 0 {
		out.WriteString("\n")
	}

	// ── Component factory function ───────────
	out.WriteString(fmt.Sprintf(
		"export function %s($$target, $$props, $$slots) {\n", g.name))
	out.WriteString("  $$props = Object.assign({}, $$props);\n")
	out.WriteString("  $$slots = $$slots || {};\n")
	// Suppress "declared but never read" warnings from strict linters /
	// TypeScript when a component happens not to receive children or
	// dispatch any events.  Both names are part of the runtime contract;
	// callers always pass them.
	out.WriteString("  void $$slots;\n\n")

	// ── $$dispatch — fire CustomEvents upward ─────────────────────────────
	out.WriteString("  function $$dispatch(name, detail) {\n")
	out.WriteString("    $$target.dispatchEvent(new CustomEvent(name, { detail, bubbles: true }));\n")
	out.WriteString("  }\n")
	out.WriteString("  void $$dispatch;\n\n")

	// ── $$insertHTML — append parsed HTML to a parent ─────────────────────
	// Element.insertAdjacentHTML works for elements but throws on
	// DocumentFragment, which is what slot factories return.  When the
	// target is a fragment (nodeType 11), parse via a <template>
	// element — its `.content` is itself a fragment whose children we
	// transfer.  For every other host we keep the original fast path.
	out.WriteString("  function $$insertHTML($$t, $$h) {\n")
	out.WriteString("    if ($$t.nodeType === 11) {\n")
	out.WriteString("      const $$tmp = document.createElement('template');\n")
	out.WriteString("      $$tmp.innerHTML = $$h;\n")
	out.WriteString("      $$t.appendChild($$tmp.content);\n")
	out.WriteString("    } else {\n")
	out.WriteString("      $$t.insertAdjacentHTML('beforeend', $$h);\n")
	out.WriteString("    }\n")
	out.WriteString("  }\n")
	out.WriteString("  void $$insertHTML;\n\n")

	// ── Props — populated from $$props, reactive via setters ─────────────
	if len(g.analysis.Props) > 0 {
		out.WriteString("  // props\n")
		for _, prop := range g.analysis.Props {
			if prop.Default != "" {
				out.WriteString(fmt.Sprintf(
					"  let %s = $$props.%s !== undefined ? $$props.%s : %s;\n",
					prop.Name, prop.Name, prop.Name, prop.Default))
			} else {
				out.WriteString(fmt.Sprintf("  let %s = $$props.%s;\n", prop.Name, prop.Name))
			}
		}
		out.WriteString("\n")
		// Bindable prop: a $$onChange_X callback lets parent observe changes
		for _, prop := range g.analysis.Props {
			if prop.Bindable {
				out.WriteString(fmt.Sprintf(
					"  const $$onChange_%s = $$props.$$onChange_%s || null;\n",
					prop.Name, prop.Name))
			}
		}
		if hasBind := func() bool {
			for _, p := range g.analysis.Props {
				if p.Bindable {
					return true
				}
			}
			return false
		}(); hasBind {
			out.WriteString("\n")
		}
	}

	// ── Scoped <style> injection ─────────────
	if g.sfc.Style != "" {
		css := ScopeCSS(g.sfc.Style, g.scopeID)
		out.WriteString("  // scoped styles\n")
		out.WriteString("  const $$style = document.createElement('style');\n")
		out.WriteString("  $$style.textContent = " + backtickString(css) + ";\n")
		out.WriteString("  document.head.appendChild($$style);\n\n")
	}

	// ── State variables ──────────────────────
	if len(g.analysis.StateVars) > 0 {
		// Are any deep-reactive?  If so emit the $$proxy helper once
		// at the top of the file.  Plain $state(...) variables stay
		// declared as before (no proxy overhead).
		anyDeep := false
		for _, sv := range g.analysis.StateVars {
			if sv.Deep {
				anyDeep = true
				break
			}
		}
		if anyDeep {
			out.WriteString("  // deep-reactive proxy helper\n")
			out.WriteString("  function $$proxy(val, notify) {\n")
			out.WriteString("    if (val === null || typeof val !== 'object') return val;\n")
			// Per-state-var cache: reading the same nested property
			// twice returns the same Proxy instance, so identity
			// comparisons (`obj.a === obj.a`) stay truthful.  Without
			// the cache, every property access would allocate a new
			// Proxy.
			out.WriteString("    const cache = new WeakMap();\n")
			out.WriteString("    const wrap = (v) => {\n")
			out.WriteString("      if (v === null || typeof v !== 'object') return v;\n")
			out.WriteString("      let p = cache.get(v);\n")
			out.WriteString("      if (p) return p;\n")
			out.WriteString("      p = new Proxy(v, {\n")
			out.WriteString("        get(t, k) { return wrap(t[k]); },\n")
			out.WriteString("        set(t, k, x) { t[k] = x; notify(); return true; },\n")
			out.WriteString("        deleteProperty(t, k) { delete t[k]; notify(); return true; },\n")
			out.WriteString("      });\n")
			out.WriteString("      cache.set(v, p);\n")
			out.WriteString("      return p;\n")
			out.WriteString("    };\n")
			out.WriteString("    return wrap(val);\n")
			out.WriteString("  }\n\n")
		}

		out.WriteString("  // state\n")
		for _, sv := range g.analysis.StateVars {
			if sv.Deep {
				// For deep state, the notify function fires the same
				// DOM updates that reassignment would.  We declare it
				// as a forward reference (`$$mut_X`) and define it
				// further down once the setter exists.  The initial
				// value is wrapped in a proxy at construction.
				out.WriteString(fmt.Sprintf(
					"  const $$mut_%s = () => $$set_%s_notify();\n", sv.Name, sv.Name))
				out.WriteString(fmt.Sprintf(
					"  let %s = $$proxy(%s, $$mut_%s);\n", sv.Name, sv.Initial, sv.Name))
			} else {
				out.WriteString(fmt.Sprintf("  let %s = %s;\n", sv.Name, sv.Initial))
			}
		}
		out.WriteString("\n")
	}

	// ── Derived variables + updaters ─────────
	if len(g.analysis.DerivedVars) > 0 {
		out.WriteString("  // derived\n")
		for _, dv := range g.analysis.DerivedVars {
			out.WriteString(fmt.Sprintf("  let %s;\n", dv.Name))
		}
		for _, dv := range g.analysis.DerivedVars {
			out.WriteString(fmt.Sprintf("  const $$upd_%s = () => { %s = %s; };\n",
				dv.Name, dv.Name, dv.Expr))
		}
		out.WriteString("\n")
	}

	// ── Effect wrapper functions ──────────────
	if len(g.analysis.Effects) > 0 {
		out.WriteString("  // effects\n")
		for i, eff := range g.analysis.Effects {
			// $$cleanupN stores the effect's return value (e.g. an unsubscribe
			// function). It is called before the effect re-runs so stale
			// subscriptions / listeners are torn down.
			out.WriteString(fmt.Sprintf("  let $$cleanup%d = null;\n", i))
			out.WriteString(fmt.Sprintf("  const $$effect%d = () => {\n", i))
			out.WriteString(fmt.Sprintf("    if ($$cleanup%d) { $$cleanup%d(); $$cleanup%d = null; }\n", i, i, i))
			out.WriteString(fmt.Sprintf("    $$cleanup%d = (function() {\n", i))
			for _, line := range strings.Split(eff.Body, "\n") {
				t := strings.TrimSpace(line)
				if t != "" {
					out.WriteString("      " + t + "\n")
				}
			}
			out.WriteString(fmt.Sprintf("    })();\n"))
			out.WriteString("  };\n")
		}
		out.WriteString("\n")
	}

	// ── Walk template → fill create/wire/events/init/cleanup ──
	//
	// $$root must always be declared because mount/destroy reference it.
	// When the template's first node IS an ElementNode, walkNodes assigns
	// varName="$$root" to it (zero extra wrapper).
	// When the first node is NOT an ElementNode (e.g. the template starts
	// with {#if ...} or {#each ...}), no element gets that name, causing
	// "$$root is not defined". Fix: always emit a transparent wrapper div
	// when the template root is non-element, and walk the nodes as its children.
	// A wrapper div is needed when the template has anything other than
	// exactly one root element.  Without this, multi-root templates
	// emitted each sibling as a child of the first element, which (1)
	// breaks the DOM tree (`<button><p>...</p></button>` etc.) and
	// (2) makes events on sibling elements bubble through the first
	// one — so clicking a "trigger" button could also fire the
	// "reload" button's handler attached to the visual root.
	//
	// display: contents on the wrapper means it has no box of its
	// own, so the visual layout is the same as if the wrapper weren't
	// there.
	needsWrapper := len(nodes) == 0
	if !needsWrapper {
		_, firstIsElem := nodes[0].(*ElementNode)
		needsWrapper = !firstIsElem
	}
	if !needsWrapper {
		// First child is an element — but check there's only one element
		// (or one element + non-element siblings that need to nest).
		// Multiple sibling elements still need a wrapper.
		elemCount := 0
		for _, n := range nodes {
			if _, ok := n.(*ElementNode); ok {
				elemCount++
			}
		}
		if elemCount > 1 {
			needsWrapper = true
		}
	}

	if needsWrapper {
		// Emit an invisible wrapper div as $$root; all template nodes become its children.
		g.create.WriteString("  const $$root = document.createElement('div');\n")
		g.create.WriteString(fmt.Sprintf("  $$root.setAttribute('%s', '');\n", g.scopeID))
		g.create.WriteString("  $$root.style.display = 'contents';\n")
		g.walkChildren(nodes, "$$root")
	} else {
		g.walkNodes(nodes, "$$root", true)
	}

	// ── Emit DOM creation ─────────────────────
	out.WriteString("  // DOM\n")
	out.WriteString(g.create.String())
	if g.wire.Len() > 0 {
		out.WriteString(g.wire.String())
	}
	out.WriteString("\n")

	// ── User script (component logic, functions, etc.) ─────────────────────────
	if g.analysis.CleanScript != "" {
		out.WriteString("  // component logic\n")
		for _, line := range strings.Split(g.analysis.CleanScript, "\n") {
			trimmed := strings.TrimSpace(line)
			if trimmed == "" {
				continue
			}
			// Skip import lines — emitted at the top of the file before export function.
			// They must NOT appear inside the function body (JS syntax error).
			if strings.HasPrefix(trimmed, "import ") || strings.HasPrefix(trimmed, "import{") {
				continue
			}
			out.WriteString("  " + line + "\n")
		}
		out.WriteString("\n")
	}

	// ── Reactive setters (state + props) ─────────────────────────────────────
	if len(g.analysis.StateVars) > 0 || len(g.analysis.Props) > 0 {
		out.WriteString("  // reactive setters\n")
		// $$defer is registered in runtime.js on globalThis[Symbol.for('vela.defer')].
		// Fallback to fn() keeps components functional even if runtime isn't loaded yet.
		out.WriteString("  const $$defer = globalThis[Symbol.for('vela.defer')] ?? (fn => fn());\n")
		for _, sv := range g.analysis.StateVars {
			out.WriteString(g.genSetter(sv.Name))
		}
		for _, prop := range g.analysis.Props {
			out.WriteString(g.genSetter(prop.Name))
		}
		out.WriteString("\n")
	}

	// ── Event listeners ──────────────────────
	if g.events.Len() > 0 {
		out.WriteString("  // events\n")
		out.WriteString(g.events.String())
		out.WriteString("\n")
	}

	// ── Initial derived computation ───────────
	if len(g.analysis.DerivedVars) > 0 {
		out.WriteString("  // initialise derived\n")
		for _, dv := range g.analysis.DerivedVars {
			out.WriteString(fmt.Sprintf("  $$upd_%s();\n", dv.Name))
		}
		out.WriteString("\n")
	}

	// ── Initial DOM hydration ─────────────────
	// Component constructors (Card, Modal, etc.) run here, which calls slot
	// functions and inserts anchor comments into the DOM. Effects MUST run
	// after this so that any immediately-firing subscribe callbacks can safely
	// call $$each / $$chain functions whose anchors already have a parentNode.
	if g.init.Len() > 0 {
		out.WriteString("  // initial render\n")
		out.WriteString(g.init.String())
		out.WriteString("\n")
	}

	// ── Run initial effects ─────────────────────────────────────────────────
	// Placed AFTER initial render so subscribe callbacks that fire immediately
	// (e.g. chartData.subscribe → $$set_chart → $$each_N) find their anchor
	// comments already parented inside the live DOM.
	for i := range g.analysis.Effects {
		out.WriteString(fmt.Sprintf("  $$effect%d();\n", i))
	}
	if len(g.analysis.Effects) > 0 {
		out.WriteString("\n")
	}

	// ── Mount ────────────────────────────────
	out.WriteString("  // mount\n")
	out.WriteString("  $$target.appendChild($$root);\n\n")

	// ── onMount callbacks (after DOM is inserted) ─────────────────────────
	// The onMount body is wrapped in an IIFE. Any `return fn` inside the
	// callback is the *cleanup return* (like an effect cleanup), NOT the
	// component's { destroy, set } return. Without the IIFE the `return`
	// exits the component factory function entirely, breaking e.g. Toast
	// auto-dismiss where onMount returns `() => clearTimeout(t)`.
	for i, lc := range g.analysis.Lifecycles {
		if lc.Kind == "onMount" {
			cleanupVar := fmt.Sprintf("$$mountCleanup%d", i)
			out.WriteString(fmt.Sprintf("  const %s = (function() {\n", cleanupVar))
			for _, line := range strings.Split(lc.Body, "\n") {
				if strings.TrimSpace(line) != "" {
					out.WriteString("    " + line + "\n")
				}
			}
			out.WriteString("  })();\n\n")
		}
	}

	// ── Return handle ─────────────────────────
	out.WriteString("  return {\n")
	out.WriteString("    destroy() {\n")
	// Run effect cleanups first (e.g. unsubscribe from stores)
	for i := range g.analysis.Effects {
		out.WriteString(fmt.Sprintf("      if ($$cleanup%d) { $$cleanup%d(); }\n", i, i))
	}
	// Run onMount cleanup functions (e.g. clearTimeout from Toast auto-dismiss)
	for i, lc := range g.analysis.Lifecycles {
		if lc.Kind == "onMount" {
			cleanupVar := fmt.Sprintf("$$mountCleanup%d", i)
			out.WriteString(fmt.Sprintf(
				"      if (typeof %s === 'function') { %s(); }\n", cleanupVar, cleanupVar))
		}
	}
	// onDestroy callbacks
	for _, lc := range g.analysis.Lifecycles {
		if lc.Kind == "onDestroy" {
			for _, line := range strings.Split(lc.Body, "\n") {
				if strings.TrimSpace(line) != "" {
					out.WriteString("      " + line + "\n")
				}
			}
		}
	}
	out.WriteString(g.cleanup.String())
	if g.sfc.Style != "" {
		out.WriteString("      $$style.remove();\n")
	}
	out.WriteString("      $$root.remove();\n")
	out.WriteString("    },\n")

	// set() accepts state vars AND props from parent
	hasSettable := len(g.analysis.StateVars) > 0 || len(g.analysis.Props) > 0
	if hasSettable {
		out.WriteString("    set(props) {\n")
		for _, sv := range g.analysis.StateVars {
			out.WriteString(fmt.Sprintf(
				"      if (props.%s !== undefined) $$set_%s(props.%s);\n",
				sv.Name, sv.Name, sv.Name))
		}
		for _, prop := range g.analysis.Props {
			out.WriteString(fmt.Sprintf(
				"      if (props.%s !== undefined) $$set_%s(props.%s);\n",
				prop.Name, prop.Name, prop.Name))
		}
		out.WriteString("    },\n")
	}

	out.WriteString("  };\n")
	out.WriteString("}\n")

	return out.String()
}

// ──────────────────────────────────────────────
//  Template walking
// ──────────────────────────────────────────────

func (g *CodeGen) walkNodes(nodes []Node, parentVar string, isRootList bool) {
	for i, node := range nodes {
		switch n := node.(type) {
		case *ElementNode:
			varName := g.id()
			if isRootList && i == 0 {
				varName = "$$root"
			}
			g.walkElement(n, varName, parentVar, isRootList && i == 0)
		case *IfChainNode:
			g.walkIfChain(n, parentVar)
		case *EachBlockNode:
			g.walkEachBlock(n, parentVar)
		case *AwaitBlockNode:
			g.walkAwaitBlock(n, parentVar)
		case *ComponentNode:
			// A ComponentNode with IfCond != "" never reaches this dispatch:
			// groupIfChains (parser.go) wraps every such component in an
			// IfChainNode before codegen runs, and walkIfChain handles those.
			if n.EachExpr != "" {
				g.walkComponentEach(n, parentVar)
			} else {
				g.walkComponent(n, parentVar)
			}
		case *SlotNode:
			g.walkSlot(n, parentVar)
		case *TextNode:
			g.walkText(n, parentVar)
		}
	}
}

func (g *CodeGen) walkElement(elem *ElementNode, varName, parentVar string, isRoot bool) {
	// #each takes precedence over #if
	if elem.EachExpr != "" {
		g.walkEach(elem, varName, parentVar)
		return
	}
	// Note: an ElementNode with IfCond != "" never reaches this dispatch —
	// groupIfChains (parser.go) wraps every such element in an IfChainNode
	// before codegen runs.  The former `if elem.IfCond != "" { walkIf(...) }`
	// arm and walkIf itself were deleted as unreachable code.

	// Create element
	g.create.WriteString(fmt.Sprintf("  const %s = document.createElement('%s');\n", varName, elem.Tag))
	g.create.WriteString(fmt.Sprintf("  %s.setAttribute('%s', '');\n", varName, g.scopeID))

	// Static attributes
	for _, attr := range elem.Attrs {
		switch {
		case attr.IsEvent:
			handler := g.rewriteHandlerAssignments(attr.Value)
			if isSimpleIdent(handler) {
				g.events.WriteString(fmt.Sprintf(
					"  %s.addEventListener('%s', %s);\n", varName, attr.Name, handler))
				g.cleanup.WriteString(fmt.Sprintf(
					"      %s.removeEventListener('%s', %s);\n", varName, attr.Name, handler))
			} else if isHandlerExpr(handler) {
				hv := varName + "_" + attr.Name + "_h"
				g.create.WriteString(fmt.Sprintf("  const %s = %s;\n", hv, handler))
				g.events.WriteString(fmt.Sprintf(
					"  %s.addEventListener('%s', %s);\n", varName, attr.Name, hv))
				g.cleanup.WriteString(fmt.Sprintf(
					"      %s.removeEventListener('%s', %s);\n", varName, attr.Name, hv))
			} else {
				hv := varName + "_" + attr.Name + "_h"
				g.create.WriteString(fmt.Sprintf(
					"  const %s = ($event) => { %s; };\n", hv, handler))
				g.events.WriteString(fmt.Sprintf(
					"  %s.addEventListener('%s', %s);\n", varName, attr.Name, hv))
				g.cleanup.WriteString(fmt.Sprintf(
					"      %s.removeEventListener('%s', %s);\n", varName, attr.Name, hv))
			}

		case attr.IsBindThis:
			// bind:this={ref} — write the live element into the user's
			// variable once it exists.  Cleared to null on destroy so
			// component teardown doesn't leak DOM references.
			g.emitBindThis(varName, attr.Value, &g.init, &g.cleanup, "  ", "      ")

		case attr.IsClassDir:
			// class:foo={cond}  →  toggle .foo on the element based on cond.
			// findDeps gets the converted JS form so it can see
			// dependencies inside string-interpolated values too.
			deps := findDeps(attrExprToJS(attr.Value), g.analysis.reactiveNames())
			stmt := classDirStmt(varName, attr.Name, attr.Value, "  ")
			g.init.WriteString(stmt + "\n")
			for _, dep := range deps {
				g.addUpdate(dep, stmt)
			}

		case attr.IsStyleDir:
			// style:foo={expr}  →  elem.style.setProperty('foo', String(expr)).
			deps := findDeps(attrExprToJS(attr.Value), g.analysis.reactiveNames())
			stmt := styleDirStmt(varName, attr.Name, attr.Value, "  ")
			g.init.WriteString(stmt + "\n")
			for _, dep := range deps {
				g.addUpdate(dep, stmt)
			}

		case attr.IsBind:
			deps := findDeps(attr.Value, g.analysis.reactiveNames())
			upd := bindAttrStmt(varName, attr.Name, attr.Value, "  ")
			// For two-way binds, write to the DOM PROPERTY rather than the
			// attribute.  setAttribute('value', x) sets the `defaultValue`,
			// which only affects the displayed value before the user has
			// interacted with the input.  Writing to `elem.value` updates
			// the live control so programmatic state changes (e.g. $$set_x)
			// actually appear on screen.  `bind:checked` is already handled
			// by isBoolAttr in bindAttrStmt (elem.checked = !!(expr)).
			if attr.IsTwoWay && attr.Name == "value" {
				upd = fmt.Sprintf("  %s.value = (%s);", varName, unwrapBraces(attr.Value))
			}
			g.init.WriteString(upd + "\n")
			for _, dep := range deps {
				g.addUpdate(dep, upd)
			}
			if attr.IsTwoWay {
				g.emitTwoWayListener(varName, elem.Tag, attr,
					&g.create, &g.events, &g.cleanup,
					"  ", "  ", "      ")
			}

		default:
			// Static attribute
			g.create.WriteString(fmt.Sprintf(
				"  %s.setAttribute('%s', '%s');\n", varName, attr.Name, escapeAttr(attr.Value)))
		}
	}

	// Emission-strategy decision tree:
	//   1. All children fully static → innerHTML (Step 1)
	//   2. All children hole-compatible with ≥1 dynamic leaf → template+holes (Step 3)
	//   3. Otherwise → recurse (walkChildren applies Step 2 run-batching)
	switch {
	case strings.ToLower(elem.Tag) != "template" &&
		len(elem.Children) > 0 &&
		hasElement(elem.Children) &&
		allStatic(elem.Children):
		// Step 1: whole subtree is static.
		html := emitStaticHTML(elem.Children, g.scopeID)
		g.create.WriteString(fmt.Sprintf("  %s.innerHTML = '%s';\n",
			varName, escapeJSString(html)))

	case strings.ToLower(elem.Tag) != "template" &&
		len(elem.Children) > 0 &&
		allHoleCompatible(elem.Children) &&
		hasDynamicLeaf(elem.Children):
		// Step 3: static frame with dynamic leaves — innerHTML + TreeWalker
		// capture + per-hole binding.  Captures the extremely common pattern
		// of a structural shell (<form>, <header>, <.card>) whose only
		// dynamic bits are a handful of <input>s, bindings, and {expr}s.
		//
		// Note: I tried adding an isWorthHoleCompression heuristic to skip
		// "small" subtrees where the TreeWalker overhead seemed to dominate.
		// Empirically that REGRESSED OrdersPage from 19 → 71 mount ops.  The
		// reason: Step 3 has multiplicative effects through nested emission
		// paths (slot lambdas, branch bodies) that don't show up in a local
		// op-count analysis of one subtree.  Firing aggressively wins.
		g.emitTemplateWithHoles(varName, elem.Children)

	default:
		// Step 2: recurse — walkChildren batches contiguous static runs
		// into insertAdjacentHTML calls between dynamic children.
		g.walkChildren(elem.Children, varName)
	}

	// Append to parent (unless this IS the root placeholder)
	if !isRoot {
		g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, varName))
	}
}

// emitBindThis wires `bind:this={ref}` for an element.  Writes the
// live DOM element into `ref` once after creation (init buffer), and
// clears the slot to null on destroy (cleanup buffer).
//
// Two cases for `ref`:
//   • a bare $state variable — emit `$$set_<name>(elem)` so reactive
//     dependents (e.g. `{ref?.tagName}` in the template) re-render.
//   • anything else — emit a plain assignment.  Useful for binding
//     into a local non-reactive variable or a member expression like
//     `refs.input`.
//
// Cleanup is symmetric: setter call with null for $state, plain
// assignment to null otherwise.
//
// `varName` is the JS local holding the freshly-created element.
// `targetExpr` is the user's variable / expression as written in the
// template (may carry surrounding braces from readAttrValue).
func (g *CodeGen) emitBindThis(
	varName, targetExpr string,
	initBuf, cleanupBuf *strings.Builder,
	initIndent, cleanupIndent string,
) {
	target := strings.TrimSpace(unwrapBraces(targetExpr))
	if target == "" {
		return
	}
	if g.analysis.isStateName(target) {
		initBuf.WriteString(fmt.Sprintf(
			"%s$$set_%s(%s);\n", initIndent, target, varName))
		if cleanupBuf != nil {
			cleanupBuf.WriteString(fmt.Sprintf(
				"%s$$set_%s(null);\n", cleanupIndent, target))
		}
		return
	}
	// Plain assignment — works for `let myRef` locals as well as
	// member expressions like `refs.input` (no setter rewriting).
	initBuf.WriteString(fmt.Sprintf(
		"%s%s = %s;\n", initIndent, target, varName))
	if cleanupBuf != nil {
		cleanupBuf.WriteString(fmt.Sprintf(
			"%s%s = null;\n", cleanupIndent, target))
	}
}

// emitTwoWayListener wires the JS event listener that powers the "write back
// to state" half of a bind: attribute.  Called from every site that generates
// DOM for an <input>/<textarea>/<select> (top-level walkElement, {#each} row
// builder, {#if} branch builder).
//
// Emits into three separate buffers so each caller can slot the listener into
// its own code section at its own indentation:
//
//   createBuf  — the `const <varName>_<event>_h = ($e) => $$set_X($e.target.Y);`
//                handler declaration.  Needs to live next to the element
//                creation so it's in-scope for the addEventListener call.
//   eventsBuf  — the `elem.addEventListener(event, handler)` line.
//   cleanupBuf — the matching removeEventListener, usually inside destroy().
//
// The three indent arguments let callers align output with their surrounding
// code style.  Unknown (tag, attr) combinations are ignored; the caller's
// one-way write still runs.  Non-state expressions (e.g. bind:value="obj.x")
// are also skipped — setter rewriting for member expressions is not yet
// implemented; users must bind to a bare $state variable.
//
// Writing an explicit @input / @change on the same element does NOT suppress
// this listener (matches Svelte semantics — both run).
func (g *CodeGen) emitTwoWayListener(
	varName, tag string,
	attr *Attr,
	createBuf, eventsBuf, cleanupBuf *strings.Builder,
	createIndent, eventsIndent, cleanupIndent string,
) {
	spec, ok := twoWayBindSpec(tag, attr.Name)
	if !ok {
		return
	}
	// Strip the surrounding `{…}` wrapper that readAttrValue preserves
	// from the template source.  bind:value={x} arrives here with
	// attr.Value == "{x}", which would never match a state-var name
	// and the listener would be silently skipped — the symptom users
	// see is "input field doesn't update my state."
	sv := strings.TrimSpace(unwrapBraces(attr.Value))
	if !g.analysis.isStateName(sv) {
		return
	}
	hv := varName + "_bind_" + spec.event + "_h"
	createBuf.WriteString(fmt.Sprintf(
		"%sconst %s = ($e) => $$set_%s($e.target.%s);\n",
		createIndent, hv, sv, spec.readProp))
	eventsBuf.WriteString(fmt.Sprintf(
		"%s%s.addEventListener('%s', %s);\n",
		eventsIndent, varName, spec.event, hv))
	// cleanupBuf may be nil when the element is inside a branch or each-row
	// whose destroy() calls .remove() on the parent — the listener goes away
	// along with the element, so explicit removeEventListener is unnecessary.
	if cleanupBuf != nil {
		cleanupBuf.WriteString(fmt.Sprintf(
			"%s%s.removeEventListener('%s', %s);\n",
			cleanupIndent, varName, spec.event, hv))
	}
}

// walkChildren emits DOM-construction code for a list of child nodes.
//
// Contiguous runs of fully-static children (text nodes with no interpolation,
// element subtrees with no events/bindings/directives/components) are emitted
// as ONE `insertAdjacentHTML('beforeend', '<html>')` call per run.  The browser's
// native HTML parser then builds the subtree in one pass.  Compared to
// individual createElement / setAttribute / appendChild calls per element, this
// is a large reduction in JS↔native crossings — typically 10× fewer ops for
// common shells (headers, cards, form scaffolds).
//
// Dynamic children (components, #if/#each blocks, interpolated text, elements
// with events or bindings) still route through per-child walkers, so document
// order is preserved: runs slot in exactly where they appeared in the template.
func (g *CodeGen) walkChildren(children []Node, parentVar string) {
	// Collect contiguous static runs.  i scans forward; staticStart is the
	// index of the current run's first child (or -1 if not in a run).
	staticStart := -1
	flushStatic := func(endExclusive int) {
		if staticStart < 0 || endExclusive <= staticStart {
			return
		}
		run := children[staticStart:endExclusive]
		// A run of pure text-only children is usually not worth the HTML-
		// parser overhead; the existing walkText path creates one text node
		// per piece, which is already cheap.  Require at least one element
		// in the run before compressing.
		if !hasElement(run) {
			// Fall back to per-child emission for the run.
			for _, c := range run {
				g.walkChildSingle(c, parentVar)
			}
			staticStart = -1
			return
		}
		html := emitStaticHTML(run, g.scopeID)
		g.create.WriteString(fmt.Sprintf(
			"  $$insertHTML(%s, '%s');\n",
			parentVar, escapeJSString(html)))
		staticStart = -1
	}

	for i, child := range children {
		if isFullyStatic(child) {
			if staticStart < 0 {
				staticStart = i
			}
			continue
		}
		// Dynamic child: flush any pending static run first, then emit.
		flushStatic(i)
		g.walkChildSingle(child, parentVar)
	}
	flushStatic(len(children))
}

// walkChildSingle is the per-node dispatch that walkChildren used to inline.
// Extracted so the static-run batching logic above can call it for the
// non-batched (dynamic) case.
func (g *CodeGen) walkChildSingle(child Node, parentVar string) {
	switch c := child.(type) {
	case *ElementNode:
		cv := g.id()
		g.walkElement(c, cv, parentVar, false)
	case *IfChainNode:
		g.walkIfChain(c, parentVar)
	case *EachBlockNode:
		g.walkEachBlock(c, parentVar)
	case *AwaitBlockNode:
		g.walkAwaitBlock(c, parentVar)
	case *ComponentNode:
		// IfCond path consumed by groupIfChains before codegen — see
		// walkNodes for the full rationale.
		if c.EachExpr != "" {
			g.walkComponentEach(c, parentVar)
		} else {
			g.walkComponent(c, parentVar)
		}
	case *SlotNode:
		g.walkSlot(c, parentVar)
	case *TextNode:
		g.walkText(c, parentVar)
	}
}

func (g *CodeGen) walkText(node *TextNode, parentVar string) {
	allStatic := true
	for _, p := range node.Parts {
		if !p.Static {
			allStatic = false
			break
		}
	}

	if allStatic {
		text := ""
		for _, p := range node.Parts {
			text += p.Value
		}
		if strings.TrimSpace(text) == "" {
			return
		}
		g.wire.WriteString(fmt.Sprintf(
			"  %s.appendChild(document.createTextNode(%s));\n",
			parentVar, backtickString(text)))
		return
	}

	tv := g.id()
	expr := buildExpr(node.Parts)
	deps := findDeps(expr, g.analysis.reactiveNames())

	g.create.WriteString(fmt.Sprintf("  const %s = document.createTextNode('');\n", tv))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, tv))
	g.init.WriteString(fmt.Sprintf("  %s.data = %s;\n", tv, expr))
	for _, dep := range deps {
		g.addUpdate(dep, fmt.Sprintf("  %s.data = %s;", tv, expr))
	}
}

// ──────────────────────────────────────────────
//  #if / #elseif / #else chains
// ──────────────────────────────────────────────

// walkIfChain generates a single update function that evaluates each branch
// condition in order and mounts/unmounts the correct DOM fragment.
//
//	$$ifchain_N($$branch) where $$branch is the index of the active branch,
//	or -1 for "none" (all conditions false and no #else).
//
// Each branch's element is cached in a dedicated variable so it is created
// at most once and re-used on subsequent re-evaluations.
func (g *CodeGen) walkIfChain(chain *IfChainNode, parentVar string) {
	// If every branch has a Comp (ComponentNode), use walkComponentIfChain
	allComp := true
	for _, b := range chain.Branches {
		if b.Comp == nil {
			allComp = false
			break
		}
	}
	if allComp {
		g.walkComponentIfChain(chain, parentVar)
		return
	}

	anchor := g.id() + "_a"
	fn := "$$chain_" + g.id()

	// One cached element variable per branch
	elVars := make([]string, len(chain.Branches))
	for i := range chain.Branches {
		elVars[i] = fmt.Sprintf("%s_b%d", fn, i)
	}

	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('if-chain');\n", anchor))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))
	for _, ev := range elVars {
		g.create.WriteString(fmt.Sprintf("  let %s = null;\n", ev))
	}

	// Build the chain update function with a re-entrancy guard.
	// Child components mounted inside a branch can synchronously trigger store
	// subscriptions that re-invoke this same chain function before the current
	// invocation has finished building its branch element. Without the guard,
	// the second call would null out the branch variable that the first call is
	// still working on, causing "$$chain_…_bN is null" TypeErrors.
	// The guard records a pending re-run and defers it to after the first call
	// completes so each invocation sees a fully-built DOM.
	runningFlag := fn + "_running"
	pendingFlag := fn + "_pending"
	g.create.WriteString(fmt.Sprintf("  let %s = false, %s = false;\n", runningFlag, pendingFlag))

	var fnBuf strings.Builder
	fnBuf.WriteString(fmt.Sprintf("  function %s() {\n", fn))
	fnBuf.WriteString(fmt.Sprintf("    if (%s) { %s = true; return; }\n", runningFlag, pendingFlag))
	fnBuf.WriteString(fmt.Sprintf("    %s = true;\n", runningFlag))
	fnBuf.WriteString(fmt.Sprintf("    try {\n"))

	// {#key expr} support: when the key expression's value changes
	// identity, force-destroy the cached subtree before the active-
	// branch re-check runs.  The branch's `if (!ev)` guard will then
	// trigger a fresh build.  Without this, the cached DOM would
	// stay mounted across key changes — defeating the whole point of
	// {#key}.
	//
	// A WeakRef-like sentinel ($$nokey) marks "uninitialized" so the
	// first call after mount doesn't see a falsy prev and trigger a
	// spurious destroy.
	if chain.KeyExpr != "" {
		keyPrev := fn + "_keyprev"
		// Sentinel: a unique object that can't match any user value.
		g.create.WriteString(fmt.Sprintf("  let %s = {};\n", keyPrev))
		fnBuf.WriteString(fmt.Sprintf("      const $$keynew = (%s);\n", chain.KeyExpr))
		fnBuf.WriteString(fmt.Sprintf("      if (%s !== $$keynew) {\n", keyPrev))
		for _, ev := range elVars {
			fnBuf.WriteString(fmt.Sprintf(
				"        if (%s) { %s.remove(); %s = null; }\n", ev, ev, ev))
		}
		fnBuf.WriteString(fmt.Sprintf("        %s = $$keynew;\n", keyPrev))
		fnBuf.WriteString("      }\n")
	}

	// Evaluate which branch is active
	fnBuf.WriteString("      let $$active = -1;\n")
	for i, branch := range chain.Branches {
		if branch.Cond == "" {
			fnBuf.WriteString(fmt.Sprintf("      if ($$active < 0) $$active = %d;\n", i))
		} else {
			fnBuf.WriteString(fmt.Sprintf("      if ($$active < 0 && (%s)) $$active = %d;\n",
				branch.Cond, i))
		}
	}

	// Remove any currently mounted branch that's no longer active.
	// Also null out all component-scope vars declared for each branch's children
	// so reactive updates guarded by `if (ev)` correctly skip inactive branches.
	// branchDeclared[i] is populated by emitBranchChildren below.
	branchDeclared := make([][]string, len(chain.Branches))
	for i, ev := range elVars {
		fnBuf.WriteString(fmt.Sprintf("      if ($$active !== %d && %s) { %s.remove(); %s = null;",
			i, ev, ev, ev))
		// Null-outs appended after emitBranchChildren fills branchDeclared[i]
		// — we'll fill in a placeholder and replace it once we know the vars.
		fnBuf.WriteString(fmt.Sprintf(" /* __null_%d__ */ }\n", i))
	}

	// Mount the active branch.
	// Each branch is created once and cached.  When a cached branch's anchor
	// regains a parentNode (e.g. Modal slot content re-entering the DOM), we
	// re-insert it so the content appears.
	for i, branch := range chain.Branches {
		ev := elVars[i]
		fnBuf.WriteString(fmt.Sprintf("      if ($$active === %d) {\n", i))
		fnBuf.WriteString(fmt.Sprintf("        if (!%s) {\n", ev))

		// Svelte-style {#if} blocks have no wrapper element (Elem == nil).
		// Use a plain <div> as a transparent container.
		tag := "div"
		var elemAttrs []*Attr
		if branch.Elem != nil {
			tag = branch.Elem.Tag
			elemAttrs = branch.Elem.Attrs
		}

		fnBuf.WriteString(fmt.Sprintf("          %s = document.createElement('%s');\n", ev, tag))
		fnBuf.WriteString(fmt.Sprintf("          %s.setAttribute('%s', '');\n", ev, g.scopeID))

		// Attrs on the branch container element (attribute-syntax branches).
		for _, attr := range elemAttrs {
			if attr.IsEvent {
				handler := g.rewriteHandlerAssignments(attr.Value)
				fnBuf.WriteString(fmt.Sprintf("          %s.addEventListener('%s', %s);\n",
					ev, attr.Name, handler))
			} else if attr.IsBind {
				fnBuf.WriteString(bindAttrStmt(ev, attr.Name, attr.Value, "          ") + "\n")
				// Register reactive update for container bound attrs — guarded by ev (branch active)
				updateStmt := fmt.Sprintf("  if (%s) %s", ev,
					strings.TrimSpace(bindAttrStmt(ev, attr.Name, attr.Value, "")))
				for _, dep := range findDeps(attr.Value, g.analysis.reactiveNames()) {
					g.addUpdate(dep, updateStmt)
				}
			} else {
				fnBuf.WriteString(fmt.Sprintf("          %s.setAttribute('%s', '%s');\n",
					ev, attr.Name, escapeAttr(attr.Value)))
			}
		}

		// Emit children — lifted vars land in g.create, attr/text updates in g.addUpdate.
		// branchVar = ev so updates are guarded by the branch container being active.
		branchDeclared[i] = g.emitBranchChildren(&fnBuf, ev, branch.Children, ev, "          ")

		fnBuf.WriteString(fmt.Sprintf("          %[1]s.before(%[2]s);\n", anchor, ev))
		fnBuf.WriteString("        }\n")
		// Re-insert if anchor has a live parent but the branch is in a different parent.
		fnBuf.WriteString(fmt.Sprintf(
			"        if (%[1]s.parentNode && %[2]s.parentNode !== %[1]s.parentNode) { %[1]s.before(%[2]s); }\n",
			anchor, ev))
		fnBuf.WriteString("      }\n")
	}
	fnBuf.WriteString(fmt.Sprintf("    } finally {\n"))
	fnBuf.WriteString(fmt.Sprintf("      %s = false;\n", runningFlag))
	fnBuf.WriteString(fmt.Sprintf("      if (%s) { %s = false; %s(); }\n", pendingFlag, pendingFlag, fn))
	fnBuf.WriteString("    }\n")
	fnBuf.WriteString("  }\n")

	// Back-fill the null-out statements for each branch's declared vars.
	// Component instance vars (suffix _comp) get .destroy() called before
	// being nulled so their event listeners and styles are cleaned up.
	fnStr := fnBuf.String()
	for i, vars := range branchDeclared {
		nullStmts := ""
		for _, v := range vars {
			if strings.HasSuffix(v, "_comp") {
				nullStmts += fmt.Sprintf(" if (%s) { %s.destroy(); %s = null; }", v, v, v)
			} else {
				nullStmts += fmt.Sprintf(" %s = null;", v)
			}
		}
		fnStr = strings.Replace(fnStr, fmt.Sprintf(" /* __null_%d__ */", i), nullStmts, 1)
	}
	g.create.WriteString(fnStr)

	// Chain function only re-runs when the CONDITION changes — not when inner
	// content (attrs, text) changes. Content changes go directly to g.addUpdate
	// via emitBranchChildren, so they update the DOM without re-running the chain.
	allDeps := map[string]bool{}
	for _, branch := range chain.Branches {
		for _, d := range findDeps(branch.Cond, g.analysis.reactiveNames()) {
			allDeps[d] = true
		}
		// Container element bound attrs also control visibility logic
		if branch.Elem != nil {
			for _, attr := range branch.Elem.Attrs {
				if attr.IsBind {
					for _, d := range findDeps(attr.Value, g.analysis.reactiveNames()) {
						allDeps[d] = true
					}
				}
			}
		}
	}
	// {#key} blocks: the chain needs to re-run when the key
	// expression changes, even though its truthy/falsy hasn't.  The
	// keychange check at the top of the chain function handles the
	// destroy; we just need to make sure it actually fires.
	if chain.KeyExpr != "" {
		for _, d := range findDeps(chain.KeyExpr, g.analysis.reactiveNames()) {
			allDeps[d] = true
		}
	}

	call := fmt.Sprintf("  %s();", fn)
	g.init.WriteString(call + "\n")
	for dep := range allDeps {
		g.addUpdate(dep, call)
	}
}

// ──────────────────────────────────────────────
//  Child component composition
// ──────────────────────────────────────────────

// componentPropsEntries builds the props-object entries for a child
// component invocation, including the `$$onChange_<name>` callback
// entries that wire two-way `bind:<name>={x}` shorthand back to the
// parent's state.
//
// Without this helper the parent emits only the one-way push — child
// would receive new values when the parent's state changed, but the
// child's own `$bindable(...)` writes would have nowhere to flow back
// to.  Symptom: `<Counter bind:count={appCount} />` propagates parent
// → child fine, but `count++` inside Counter never updates appCount.
//
// The callback shape mirrors what the child runtime expects (see the
// `const $$onChange_X = $$props.$$onChange_X || null` line in any
// component that uses $bindable on a prop X — codegen.go ~line 280):
//
//   $$onChange_count: ($$v) => $$set_appCount($$v)
//
// Skipped when the bind target isn't a $state variable (we don't
// generate setters for non-state locals, so there's no `$$set_` fn
// to call).  The one-way push entry is still emitted for those.
func (g *CodeGen) componentPropsEntries(attrs []*Attr) []string {
	var entries []string
	for _, attr := range attrs {
		if attr.IsEvent {
			continue
		}
		if attr.IsBind {
			entries = append(entries, fmt.Sprintf("%s: %s", attr.Name, unwrapBraces(attr.Value)))
			if attr.IsTwoWay {
				target := strings.TrimSpace(unwrapBraces(attr.Value))
				if g.analysis.isStateName(target) {
					entries = append(entries, fmt.Sprintf(
						"$$onChange_%s: ($$v) => $$set_%s($$v)",
						attr.Name, target))
				}
			}
			continue
		}
		entries = append(entries, fmt.Sprintf("%s: '%s'", attr.Name, escapeAttr(attr.Value)))
	}
	return entries
}

// walkComponent emits code to mount a child component.
func (g *CodeGen) walkComponent(comp *ComponentNode, parentVar string) {
	instanceVar := g.id() + "_comp"

	propsEntries := g.componentPropsEntries(comp.Attrs)
	propsObj := "{}"
	if len(propsEntries) > 0 {
		propsObj = "{ " + strings.Join(propsEntries, ", ") + " }"
	}

	// Build $$slots object.
	//
	// Each slot function returns a DocumentFragment of already-constructed DOM nodes.
	// The nodes are declared in g.create (component scope) and wired into g.updates
	// so reactive state changes update them live.
	//
	// ORDERING CRITICAL: slot content walk emits g.init entries (e.g. the initial
	// $$each_N(arr) call). These MUST run after the component constructor has been
	// called, because the constructor calls the slot function which inserts the
	// anchor comments into the DOM. If the each loop runs before the anchor has a
	// parentNode, insertBefore crashes with "parentNode is null".
	//
	// Solution: redirect g.init to a temporary buffer during the slot content walk.
	// Emit the component constructor to real g.init first, then append the deferred
	// slot init calls after it.
	slotsEntries := []string{}
	type slotInitEntry struct{ buf strings.Builder }
	slotInits := []slotInitEntry{}

	for slotName, slotNodes := range comp.Slots {
		fragVar := fmt.Sprintf("$$sf_%s_%s", slotName, g.id())
		cacheVar := fmt.Sprintf("$$sc_%s_%s", slotName, g.id())

		// Cache is an ARRAY of the slot's top-level child nodes, not a
		// DocumentFragment.  A DocumentFragment is emptied the moment it's
		// passed to appendChild() — the spec moves its children into the new
		// parent and leaves the fragment vacant.  Caching the fragment itself
		// means the second open of a Modal hands back an empty fragment and
		// the modal body appears blank.
		//
		// Caching the child nodes works because Node.appendChild reparents a
		// node, detaching it from any old parent first.  So on reopen we
		// build a fresh fragment, move the cached children into it, and hand
		// that fragment to the caller.  The fragment transfers them into the
		// caller's DOM location, preserving any child-component instances
		// (and their local state: focus, scroll, form values).
		g.create.WriteString(fmt.Sprintf("  let %s = null;\n", cacheVar))

		// Redirect wire to capture only this slot's appendChild calls.
		savedWireStr := g.wire.String()
		g.wire.Reset()

		// Redirect init so initial each/chain calls are deferred past the ctor.
		savedInitStr := g.init.String()
		g.init.Reset()

		// Redirect create so we can partition emissions: writes that
		// target `fragVar` belong inside the slot factory closure
		// (because fragVar is a local of that closure), while every
		// other create-write — element declarations, instance hoists,
		// scope-attribute setters — must remain at outer scope so
		// destroy() and other component-level code can see them.
		//
		// Without this partition, walkChildren's `fragVar.insertAdjacentHTML(...)`
		// landed at outer scope and referenced a name that doesn't exist
		// there ("Could not find name '$$sf_error_$$nN'").
		//
		// We capture via .String()+Reset() rather than copying the
		// Builder struct because Go forbids copying a non-zero
		// strings.Builder (the no-copy invariant is enforced at
		// runtime via copyCheck()).
		savedCreateStr := g.create.String()
		g.create.Reset()

		g.walkChildren(slotNodes, fragVar)

		// Partition the captured create-writes.
		capturedCreate := g.create.String()
		var slotCreate strings.Builder
		g.create.Reset()
		g.create.WriteString(savedCreateStr)
		for _, line := range strings.Split(capturedCreate, "\n") {
			if line == "" {
				continue
			}
			if strings.Contains(line, fragVar) {
				slotCreate.WriteString(line + "\n")
			} else {
				g.create.WriteString(line + "\n")
			}
		}

		slotWire := g.wire.String()
		g.wire.Reset()
		g.wire.WriteString(savedWireStr)

		var slotInitBuf strings.Builder
		slotInitBuf.WriteString(g.init.String())
		g.init.Reset()
		g.init.WriteString(savedInitStr)

		slotInits = append(slotInits, slotInitEntry{slotInitBuf})

		// Build the slot function.
		//
		//   First call  — create a fragment, populate it via slotWire, run
		//                 inits (they set up chains/eaches whose anchors are
		//                 now inside the fragment), cache the fragment's
		//                 children into `$$sc_<name>`, return the fragment.
		//   Reopen call — create a NEW fragment, re-append each cached child
		//                 to it, re-run inits (so chain/each reconcilers
		//                 re-insert dynamic content, now that the anchor's
		//                 parent chain leads back to the new fragment and
		//                 hence the caller's live DOM), return the fragment.
		var fragFn strings.Builder
		initiCalls := ""
		for _, line := range strings.Split(slotInitBuf.String(), "\n") {
			if trimmed := strings.TrimSpace(line); trimmed != "" {
				initiCalls += trimmed + " "
			}
		}

		// Reopen path: move still-attached cached children into a fresh
		// fragment, run inits, return.
		//
		// We skip any cached node whose `parentNode` is null.  Such nodes were
		// detached via `.remove()` by a chain-function teardown while the
		// slot's host was closed — e.g. an {#if cond} branch where `cond` went
		// falsy between close and reopen.  Re-adopting those would cause
		// stale branch content to appear alongside the freshly-rebuilt one
		// after the next chain run, producing duplicated DOM.  The chain
		// function will rebuild the branch as part of `initiCalls` below.
		fragFn.WriteString(fmt.Sprintf(
			"() => { if (%s) { const %s = document.createDocumentFragment(); for (const $$c of %s) { if ($$c.parentNode !== null) %s.appendChild($$c); } %sreturn %s; } ",
			cacheVar, fragVar, cacheVar, fragVar, initiCalls, fragVar))

		// First-open path: build the fragment and its contents, run inits,
		// then snapshot the fragment's children into the cache.
		fragFn.WriteString(fmt.Sprintf("const %s = document.createDocumentFragment(); ", fragVar))
		// Fragment-targeting create-writes captured above — these
		// include calls like `fragVar.insertAdjacentHTML('beforeend',
		// '<span>…</span>')` that populate the fragment with static
		// HTML.  Emit them before the appendChild calls in slotWire.
		for _, line := range strings.Split(slotCreate.String(), "\n") {
			if trimmed := strings.TrimSpace(line); trimmed != "" {
				fragFn.WriteString(trimmed + " ")
			}
		}
		for _, line := range strings.Split(slotWire, "\n") {
			if trimmed := strings.TrimSpace(line); trimmed != "" {
				fragFn.WriteString(trimmed + " ")
			}
		}
		fragFn.WriteString(initiCalls)
		// Snapshot children into the cache.  `childNodes` is a live NodeList
		// which would be emptied as soon as the fragment is appended, so we
		// copy into a plain array first.
		fragFn.WriteString(fmt.Sprintf("%s = Array.from(%s.childNodes); return %s; }",
			cacheVar, fragVar, fragVar))
		slotsEntries = append(slotsEntries, fmt.Sprintf("%q: %s", slotName, fragFn.String()))
	}
	slotsObj := "{}"
	if len(slotsEntries) > 0 {
		slotsObj = "{ " + strings.Join(slotsEntries, ", ") + " }"
	}

	wrapVar := instanceVar + "_wrap"
	g.create.WriteString(fmt.Sprintf("  const %s = document.createElement('div');\n", wrapVar))
	g.create.WriteString(fmt.Sprintf("  %s.setAttribute('%s', '');\n", wrapVar, g.scopeID))
	// Hoist the instance var to component (outer) scope.  When this component
	// is emitted inside a slot, g.init is redirected into the slot closure —
	// if we declared `const $$nX_comp = …` there, the destroy() block at outer
	// scope would reference a name that's only visible inside the closure,
	// throwing "ReferenceError: $$nX_comp is not defined" on destroy.  A
	// hoisted `let … = null` keeps the name visible everywhere and safe when
	// the slot never opens.
	g.create.WriteString(fmt.Sprintf("  let %s = null;\n", instanceVar))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, wrapVar))

	// Emit component constructor FIRST so the slot function is called inside it,
	// inserting anchor comments into the DOM before any slot init calls.
	// The slot function body already contains the init calls ($$chain_X(), $$each_N()),
	// so we do NOT emit them again here. Emitting them twice caused double-execution:
	//   • For always-visible slots: slot fn is called during constructor, inits run once ✓
	//   • For conditional slots (Modal starts closed): slot fn never called during constructor,
	//     but the deferred init calls were no-ops anyway. Init calls run when slot fn is
	//     first called (on modal open). ✓
	// Removing the deferred duplicates eliminates spurious double-renders (e.g. duplicate
	// filter buttons from $$each_$$n18 running twice).
	//
	// Guard against re-instantiation: when this component lives inside a
	// conditional slot (e.g. <Modal>…<Button/>…</Modal>), the slot
	// factory is called on every reopen.  Without the guard, each
	// reopen calls `Comp(wrap, props, slots)` again, and `Comp` ends
	// with `$$target.appendChild($$root)` — so the wrapper accumulates
	// another `<button>` (or whatever) every time.  The cached subtree
	// already contains the previously-built DOM; we only need to
	// construct the instance once.  Reactive prop changes still flow
	// in via the existing instance's `.set()` (handled below).
	g.init.WriteString(fmt.Sprintf(
		"  if (!%s) %s = %s(%s, %s, %s);\n",
		instanceVar, instanceVar, comp.Name, wrapVar, propsObj, slotsObj))

	// Reactive prop updates
	for _, attr := range comp.Attrs {
		if !attr.IsBind {
			continue
		}
		deps := findDeps(attr.Value, g.analysis.reactiveNames())
		update := fmt.Sprintf("  if (%s) %s.set({ %s: %s });",
			instanceVar, instanceVar, attr.Name, unwrapBraces(attr.Value))
		for _, dep := range deps {
			g.addUpdate(dep, update)
		}
	}
	// Event forwarding — guard with instanceof CustomEvent to prevent native
	// DOM events (e.g. the built-in 'select' event on inputs) from being
	// mishandled as component events when they share the same name.
	for _, attr := range comp.Attrs {
		if !attr.IsEvent {
			continue
		}
		hv := wrapVar + "_" + sanitizeIdent(attr.Name) + "_ch"
		g.events.WriteString(fmt.Sprintf(
			"  const %s = ($e) => { if ($e instanceof CustomEvent) { (%s)($e); } };\n",
			hv, g.rewriteHandlerAssignments(attr.Value)))
		g.events.WriteString(fmt.Sprintf(
			"  %s.addEventListener('%s', %s);\n", wrapVar, attr.Name, hv))
		g.cleanup.WriteString(fmt.Sprintf(
			"      %s.removeEventListener('%s', %s);\n", wrapVar, attr.Name, hv))
	}

	g.cleanup.WriteString(fmt.Sprintf("      if (%s) %s.destroy();\n", instanceVar, instanceVar))
}

// walkComponentEach handles <MyComp #each="arr as item" #key="item.id" :prop="item.x" />
func (g *CodeGen) walkComponentEach(comp *ComponentNode, parentVar string) {
	array, itemVar, indexVar := parseEachExpr(comp.EachExpr)
	if indexVar == "" {
		indexVar = "$$i"
	}
	keyExpr := comp.EachKey
	varName := g.id()
	anchor := varName + "_a"
	keyMap := varName + "_km"
	blocks := varName + "_bs"
	fn := "$$ceach_" + varName

	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('#each-comp');\n", anchor))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))

	// Build initial props object expression using the loop variables.
	propsEntries := g.componentPropsEntries(comp.Attrs)
	propsExpr := "{}"
	if len(propsEntries) > 0 {
		propsExpr = "{ " + strings.Join(propsEntries, ", ") + " }"
	}

	// Event listeners wired to the wrapper element.
	// Guard every handler with `instanceof CustomEvent` so native DOM events
	// (e.g. the built-in 'select' event on <input> / <textarea>) that happen to
	// share the same event name don't trigger the handler with detail=null.
	var evLines []string
	for _, attr := range comp.Attrs {
		if attr.IsEvent {
			evLines = append(evLines, fmt.Sprintf(
				"      $$wrap.addEventListener('%s', ($e) => { if ($e instanceof CustomEvent) { (%s)($e); } });",
				attr.Name, g.rewriteHandlerAssignments(attr.Value)))
		}
	}

	if keyExpr != "" {
		// Keyed: Map<key, {wrap, comp}> — update existing instances in place.
		g.create.WriteString(fmt.Sprintf("  const %s = new Map();\n", keyMap))
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", blocks))

		var fnBuf strings.Builder
		fnBuf.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fn))
		// Guard: no-op when anchor is detached (branch unmounted mid-update)
		fnBuf.WriteString(fmt.Sprintf("    if (!%s.parentNode) return;\n", anchor))
		fnBuf.WriteString("    const $$newKeys = new Set();\n")
		fnBuf.WriteString("    const $$newBlks = [];\n")
		fnBuf.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fnBuf.WriteString(fmt.Sprintf("      const $$key = String(%s);\n", keyExpr))
		fnBuf.WriteString("      $$newKeys.add($$key);\n")
		fnBuf.WriteString(fmt.Sprintf("      let $$blk = %s.get($$key);\n", keyMap))
		fnBuf.WriteString("      if ($$blk) {\n")
		fnBuf.WriteString(fmt.Sprintf("        $$blk.comp.set(%s);\n", propsExpr))
		fnBuf.WriteString("      } else {\n")
		fnBuf.WriteString("        const $$wrap = document.createElement('div');\n")
		fnBuf.WriteString(fmt.Sprintf("        $$wrap.setAttribute('%s','');\n", g.scopeID))
		for _, ev := range evLines {
			fnBuf.WriteString("  " + ev + "\n")
		}
		fnBuf.WriteString(fmt.Sprintf("        const $$c = %s($$wrap, %s, {});\n", comp.Name, propsExpr))
		fnBuf.WriteString("        $$blk = { wrap: $$wrap, comp: $$c };\n")
		fnBuf.WriteString(fmt.Sprintf("        %s.set($$key, $$blk);\n", keyMap))
		fnBuf.WriteString("      }\n")
		// Only move the element if it is not already in the correct position
		// (i.e. immediately before the anchor). Moving DOM elements fires blur
		// on any focused input inside them, breaking in-place editing.
		fnBuf.WriteString(fmt.Sprintf(
			"      if ($$blk.wrap.nextSibling !== %[1]s) { %[1]s.before($$blk.wrap); }\n",
			anchor))
		fnBuf.WriteString("      $$newBlks.push($$blk);\n")
		fnBuf.WriteString("    });\n")
		fnBuf.WriteString(fmt.Sprintf("    %s.forEach(($$blk, $$key) => {\n", keyMap))
		fnBuf.WriteString(fmt.Sprintf(
			"      if (!$$newKeys.has($$key)) { $$blk.comp.destroy(); %s.delete($$key); }\n", keyMap))
		fnBuf.WriteString("    });\n")
		fnBuf.WriteString(fmt.Sprintf("    %s = $$newBlks;\n", blocks))
		fnBuf.WriteString("  }\n")
		g.create.WriteString(fnBuf.String())
	} else {
		// Unkeyed: destroy all + rebuild.
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", blocks))

		var fnBuf strings.Builder
		fnBuf.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fn))
		// Guard: no-op when anchor is detached (branch unmounted mid-update)
		fnBuf.WriteString(fmt.Sprintf("    if (!%s.parentNode) return;\n", anchor))
		fnBuf.WriteString(fmt.Sprintf("    %s.forEach(b => b.comp.destroy()); %s = [];\n", blocks, blocks))
		fnBuf.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fnBuf.WriteString("      const $$wrap = document.createElement('div');\n")
		fnBuf.WriteString(fmt.Sprintf("      $$wrap.setAttribute('%s','');\n", g.scopeID))
		for _, ev := range evLines {
			fnBuf.WriteString("  " + ev + "\n")
		}
		fnBuf.WriteString(fmt.Sprintf("      const $$c = %s($$wrap, %s, {});\n", comp.Name, propsExpr))
		fnBuf.WriteString(fmt.Sprintf("      %[1]s.before($$wrap);\n", anchor))
		fnBuf.WriteString(fmt.Sprintf("      %s.push({ wrap: $$wrap, comp: $$c });\n", blocks))
		fnBuf.WriteString("    });\n  }\n")
		g.create.WriteString(fnBuf.String())
	}

	call := fmt.Sprintf("  %s(%s);", fn, array)
	g.init.WriteString(call + "\n")
	for _, dep := range findDeps(array, g.analysis.reactiveNames()) {
		g.addUpdate(dep, call)
	}
	for _, attr := range comp.Attrs {
		if attr.IsBind {
			for _, dep := range findDeps(attr.Value, g.analysis.reactiveNames()) {
				g.addUpdate(dep, call)
			}
		}
	}
	g.cleanup.WriteString(fmt.Sprintf("      %s.forEach(b => b.comp.destroy());\n", blocks))
}

// walkSlot emits code that renders $$slots["name"](parent) if the slot is
// filled by the parent, or falls back to the declared fallback children.
func (g *CodeGen) walkSlot(slot *SlotNode, parentVar string) {
	slotVar := g.id() + "_slot"
	anchor := slotVar + "_a"

	// Create the anchor comment and wire it into the DOM tree.
	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('slot:%s');\n", anchor, slot.Name))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))

	// The insertion of slot content MUST happen after wiring (anchor needs a parentNode),
	// so we emit into g.init rather than g.create.
	var fnBuf strings.Builder
	fnBuf.WriteString(fmt.Sprintf("  {\n"))
	fnBuf.WriteString(fmt.Sprintf("    const $$sf = $$slots[%q];\n", slot.Name))
	fnBuf.WriteString(fmt.Sprintf("    if ($$sf) {\n"))
	fnBuf.WriteString(fmt.Sprintf(
		"      { const $$sn = $$sf(); if ($$sn) %[1]s.before($$sn); }\n",
		anchor))
	fnBuf.WriteString(fmt.Sprintf("    }"))

	if len(slot.Fallback) > 0 {
		fnBuf.WriteString(fmt.Sprintf(" else {\n"))
		for _, child := range slot.Fallback {
			switch c := child.(type) {
			case *TextNode:
				expr := buildExpr(c.Parts)
				fnBuf.WriteString(fmt.Sprintf(
					"      %[1]s.before(document.createTextNode(%[2]s));\n",
					anchor, expr))
			case *ElementNode:
				fnBuf.WriteString(fmt.Sprintf(
					"      { const $$fb = document.createElement('%s');\n", c.Tag))
				fnBuf.WriteString(fmt.Sprintf(
					"        $$fb.setAttribute('%s','');\n", g.scopeID))
				// Static attributes only — bound attrs/events inside fallback
				// would need full codegen context; keep fallback simple.
				for _, attr := range c.Attrs {
					if !attr.IsEvent && !attr.IsBind {
						fnBuf.WriteString(fmt.Sprintf(
							"        $$fb.setAttribute('%s','%s');\n",
							attr.Name, escapeAttr(attr.Value)))
					}
				}
				// Inline static text children
				for _, cc := range c.Children {
					if t, ok := cc.(*TextNode); ok {
						fnBuf.WriteString(fmt.Sprintf(
							"        $$fb.appendChild(document.createTextNode(%s));\n",
							buildExpr(t.Parts)))
					}
				}
				fnBuf.WriteString(fmt.Sprintf(
					"        %[1]s.before($$fb); }\n", anchor))
			}
		}
		fnBuf.WriteString("    }\n")
	} else {
		fnBuf.WriteString("\n")
	}
	fnBuf.WriteString("  }\n")
	g.init.WriteString(fnBuf.String()) // ← init, not create
}

// walkComponentIfChain handles an IfChainNode where every branch holds a
// ComponentNode (#if / #elseif / #else on component tags).
// It emits a single $$chain_N() function with one cached instance per branch.
func (g *CodeGen) walkComponentIfChain(chain *IfChainNode, parentVar string) {
	anchor := g.id() + "_a"
	fn := "$$chain_" + g.id()

	// One {inst, wrap} pair per branch
	instVars := make([]string, len(chain.Branches))
	wrapVars := make([]string, len(chain.Branches))
	for i := range chain.Branches {
		instVars[i] = fmt.Sprintf("%s_i%d", fn, i)
		wrapVars[i] = fmt.Sprintf("%s_w%d", fn, i)
	}

	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('if-comp-chain');\n", anchor))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))
	for i := range chain.Branches {
		g.create.WriteString(fmt.Sprintf(
			"  let %s = null, %s = null;\n", instVars[i], wrapVars[i]))
	}

	runningFlagC := fn + "_running"
	pendingFlagC := fn + "_pending"
	g.create.WriteString(fmt.Sprintf("  let %s = false, %s = false;\n", runningFlagC, pendingFlagC))

	var fnBuf strings.Builder
	fnBuf.WriteString(fmt.Sprintf("  function %s() {\n", fn))
	fnBuf.WriteString(fmt.Sprintf("    if (%s) { %s = true; return; }\n", runningFlagC, pendingFlagC))
	fnBuf.WriteString(fmt.Sprintf("    %s = true;\n", runningFlagC))
	fnBuf.WriteString(fmt.Sprintf("    try {\n"))
	fnBuf.WriteString("      let $$active = -1;\n")
	for i, branch := range chain.Branches {
		if branch.Cond == "" {
			fnBuf.WriteString(fmt.Sprintf("      if ($$active < 0) $$active = %d;\n", i))
		} else {
			fnBuf.WriteString(fmt.Sprintf("      if ($$active < 0 && (%s)) $$active = %d;\n", branch.Cond, i))
		}
	}

	// Destroy any branch that is no longer active
	for i := range chain.Branches {
		fnBuf.WriteString(fmt.Sprintf(
			"      if ($$active !== %d && %s) { %s.destroy(); %s = null; %s.remove(); %s = null; }\n",
			i, instVars[i], instVars[i], instVars[i], wrapVars[i], wrapVars[i]))
	}

	// Mount the active branch (first time) or update (subsequent times)
	for i, branch := range chain.Branches {
		comp := branch.Comp
		propsEntries := g.componentPropsEntries(comp.Attrs)
		propsExpr := "{}"
		if len(propsEntries) > 0 {
			propsExpr = "{ " + strings.Join(propsEntries, ", ") + " }"
		}

		fnBuf.WriteString(fmt.Sprintf("      if ($$active === %d) {\n", i))
		fnBuf.WriteString(fmt.Sprintf("        if (!%s) {\n", instVars[i]))
		fnBuf.WriteString(fmt.Sprintf("          %s = document.createElement('div');\n", wrapVars[i]))
		fnBuf.WriteString(fmt.Sprintf("          %s.setAttribute('%s','');\n", wrapVars[i], g.scopeID))
		for _, attr := range comp.Attrs {
			if attr.IsEvent {
				fnBuf.WriteString(fmt.Sprintf(
					"          %s.addEventListener('%s', ($e) => { if ($e instanceof CustomEvent) { (%s)($e); } });\n",
					wrapVars[i], attr.Name, g.rewriteHandlerAssignments(attr.Value)))
			}
		}
		fnBuf.WriteString(fmt.Sprintf("          %s = %s(%s, %s, {});\n",
			instVars[i], comp.Name, wrapVars[i], propsExpr))
		fnBuf.WriteString(fmt.Sprintf("          if (%[1]s.parentNode) %[1]s.before(%[2]s);\n",
			anchor, wrapVars[i]))
		fnBuf.WriteString(fmt.Sprintf("        } else { %s.set(%s); }\n", instVars[i], propsExpr))
		fnBuf.WriteString("      }\n")
	}
	fnBuf.WriteString(fmt.Sprintf("    } finally {\n"))
	fnBuf.WriteString(fmt.Sprintf("      %s = false;\n", runningFlagC))
	fnBuf.WriteString(fmt.Sprintf("      if (%s) { %s = false; %s(); }\n", pendingFlagC, pendingFlagC, fn))
	fnBuf.WriteString("    }\n")
	fnBuf.WriteString("  }\n")
	g.create.WriteString(fnBuf.String())

	// Collect all deps from conditions and bound props
	allDeps := map[string]bool{}
	for _, branch := range chain.Branches {
		for _, d := range findDeps(branch.Cond, g.analysis.reactiveNames()) {
			allDeps[d] = true
		}
		for _, attr := range branch.Comp.Attrs {
			if attr.IsBind {
				for _, d := range findDeps(attr.Value, g.analysis.reactiveNames()) {
					allDeps[d] = true
				}
			}
		}
	}

	call := fmt.Sprintf("  %s();", fn)
	g.init.WriteString(call + "\n")
	for dep := range allDeps {
		g.addUpdate(dep, call)
	}

	// Cleanup
	for i := range chain.Branches {
		g.cleanup.WriteString(fmt.Sprintf("      if (%s) %s.destroy();\n", instVars[i], instVars[i]))
	}
}

// walkEachBlock handles Svelte-style {#each items as item (key)}...{/each}.
// The block children become the row content. If there's a single ElementNode
// child we use it as the row element directly (zero extra wrapper). Otherwise
// we wrap all children in a synthetic <div>.
func (g *CodeGen) walkEachBlock(block *EachBlockNode, parentVar string) {
	// Determine the row element: use single-child element directly, else wrap.
	var rowElem *ElementNode
	if len(block.Children) == 1 {
		if el, ok := block.Children[0].(*ElementNode); ok {
			rowElem = el
		}
	}

	if rowElem == nil {
		// Multiple children or non-element: synthesize a wrapper div
		rowElem = &ElementNode{
			Tag:      "div",
			Children: block.Children,
		}
	}

	// Copy the each/key onto a fresh element and delegate to the existing walkEach
	wrapper := &ElementNode{
		Tag:      rowElem.Tag,
		Attrs:    rowElem.Attrs,
		Children: rowElem.Children,
		EachExpr: block.EachExpr,
		EachKey:  block.EachKey,
	}
	varName := g.id()
	g.walkEach(wrapper, varName, parentVar)
}

// walkAwaitBlock emits code for {#await promise}...{:then v}...{:catch e}...{/await}.
//
// Strategy: lower to a 3-branch IfChainNode whose branches are
// gated by an internal state variable `$$promState_X` (0=pending,
// 1=resolved, 2=rejected).  The chain itself takes care of mount/
// unmount.  A separate "driver" attaches `.then`/`.catch` to the
// promise expression, flips the state, and triggers the chain.
//
// The promise expression's deps are tracked: if the user reassigns
// `let promise = $state(...)`, the driver re-runs against the new
// promise so the await block reflects the latest value.  Without
// that, only the initial promise would ever be observed.
//
// {:then VALUE} and {:catch ERR} bind VALUE/ERR as a let local
// inside the corresponding branch body so the children can reference
// them naturally.  We accomplish this by wrapping the branch body in
// a synthetic <div> with a leading `<script>let VALUE = $$value;</script>`
// — actually no, we emit the let directly into the branch via a
// pre-children injection.  Implementation: prepend a fake TextNode
// containing the let statement.  Easier: store the binding name in
// a dedicated branch field and have the chain codegen emit the let
// inside the `if ($$active === N) { if (!ev) {` block.  But that's
// intrusive.  Pragmatic alternative: rewrite the children to refer
// to a module-scope variable that the driver writes.
//
// I went with the module-scope approach: a per-await `$$awaitVal_X`
// and `$$awaitErr_X` are declared at component scope.  The {:then v}
// children get their `v` references rewritten to `$$awaitVal_X`
// before codegen sees them.  Same for catch.  This keeps the chain
// codegen unchanged.
func (g *CodeGen) walkAwaitBlock(block *AwaitBlockNode, parentVar string) {
	id := g.id()
	stateVar := "$$promState_" + id
	valVar := "$$awaitVal_" + id
	errVar := "$$awaitErr_" + id
	promCellVar := "$$promCell_" + id // the *current* promise; used for staleness checks

	// Declare component-scope storage for the resolved value, error,
	// and current state.  State starts at 0 (pending).
	g.create.WriteString(fmt.Sprintf("  let %s = 0;\n", stateVar))
	g.create.WriteString(fmt.Sprintf("  let %s = undefined;\n", valVar))
	g.create.WriteString(fmt.Sprintf("  let %s = undefined;\n", errVar))
	g.create.WriteString(fmt.Sprintf("  let %s = null;\n", promCellVar))

	// Build the synthetic chain.
	branches := []*IfBranch{}
	// Branch 0: pending — always exists (may be empty content).
	branches = append(branches, &IfBranch{
		Cond:     fmt.Sprintf("%s === 0", stateVar),
		Children: block.PendingChildren,
	})
	// Branch 1: resolved.  Rewrite ValueName references in children to valVar.
	if block.ThenChildren != nil {
		thenKids := rewriteIdentInNodes(block.ThenChildren, block.ValueName, valVar)
		branches = append(branches, &IfBranch{
			Cond:     fmt.Sprintf("%s === 1", stateVar),
			Children: thenKids,
		})
	}
	// Branch 2: rejected.  Rewrite ErrorName references to errVar.
	if block.CatchChildren != nil {
		catchKids := rewriteIdentInNodes(block.CatchChildren, block.ErrorName, errVar)
		branches = append(branches, &IfBranch{
			Cond:     fmt.Sprintf("%s === 2", stateVar),
			Children: catchKids,
		})
	}

	chain := &IfChainNode{Branches: branches}

	// The chain will register its function in g.create; we don't
	// have the name in hand, so we put a placeholder marker that we
	// fix up after the fact.  Simpler: pre-compute the chain function
	// name the same way walkIfChain does.  But that depends on g.id()
	// being called inside walkIfChain — which it is, immediately after
	// generating `anchor`.  That makes the chain fn name a function of
	// state we can't peek.
	//
	// Instead: after walking the chain, the most recent $$chain_*
	// function is ours.  We capture it via a closure that watches
	// g.events / g.init growth.  Actually the simplest path is to
	// pre-extract the chain ID: call g.id() once here for the chain,
	// inject it via a small accessor.  But walkIfChain already calls
	// g.id() internally for `anchor` AND for fn.  Plumbing a custom ID
	// is invasive.
	//
	// What I'll do: after walking the chain, scan g.init's tail line
	// to find the chain's call site (it always emits "  $$chain_NN();").
	// That's brittle but isolated and easy to test.
	initBefore := g.init.Len()
	g.walkIfChain(chain, parentVar)
	chainCall := strings.TrimSpace(g.init.String()[initBefore:])
	chainCall = strings.TrimSuffix(chainCall, "\n")

	// Promise driver: attach .then/.catch to the promise expression.
	// If the same promise resolves twice (someone awaits and the value
	// is overwritten), the staleness guard prevents the older settle
	// from clobbering a fresher one.
	//
	// The driver runs once at init AND every time deps of the promise
	// expression change — same registration as the chain function.
	driverName := "$$awaitDrive_" + id
	var drv strings.Builder
	drv.WriteString(fmt.Sprintf("  function %s() {\n", driverName))
	drv.WriteString(fmt.Sprintf("    const $$p = Promise.resolve(%s);\n", block.PromiseExpr))
	drv.WriteString(fmt.Sprintf("    if (%s === $$p) return;\n", promCellVar))
	drv.WriteString(fmt.Sprintf("    %s = $$p;\n", promCellVar))
	drv.WriteString(fmt.Sprintf("    %s = 0;\n", stateVar))
	drv.WriteString(fmt.Sprintf("    %s = undefined; %s = undefined;\n", valVar, errVar))
	drv.WriteString(fmt.Sprintf("    %s\n", chainCall))
	drv.WriteString("    $$p.then(\n")
	// Resolved.
	drv.WriteString(fmt.Sprintf("      v => { if (%s !== $$p) return; %s = v; %s = 1; %s },\n",
		promCellVar, valVar, stateVar, chainCall))
	// Rejected.
	drv.WriteString(fmt.Sprintf("      e => { if (%s !== $$p) return; %s = e; %s = 2; %s }\n",
		promCellVar, errVar, stateVar, chainCall))
	drv.WriteString("    );\n")
	drv.WriteString("  }\n")
	g.create.WriteString(drv.String())

	// Call driver initially.
	g.init.WriteString(fmt.Sprintf("  %s();\n", driverName))

	// Re-run driver when the promise expression's deps change.
	for _, dep := range findDeps(block.PromiseExpr, g.analysis.reactiveNames()) {
		g.addUpdate(dep, fmt.Sprintf("  %s();", driverName))
	}
}

// rewriteIdentInNodes returns a deep copy of nodes with every reference
// to `from` replaced by `to` inside any interpolated text and any
// attribute value or expression that the codegen will treat as JS.
//
// Used by walkAwaitBlock to redirect references to a {:then VALUE}
// binding from the user-visible name (`value`) into the compiler's
// module-scope storage variable (`$$awaitVal_NN`).
//
// If from is empty, the function is a no-op — `{:then}` with no
// binding name has nothing to rewrite.
func rewriteIdentInNodes(nodes []Node, from, to string) []Node {
	if from == "" || from == to {
		return nodes
	}
	out := make([]Node, len(nodes))
	for i, n := range nodes {
		out[i] = rewriteIdentInNode(n, from, to)
	}
	return out
}

func rewriteIdentInNode(n Node, from, to string) Node {
	switch v := n.(type) {
	case *TextNode:
		newParts := make([]*Part, len(v.Parts))
		for i, p := range v.Parts {
			np := *p
			if !p.Static {
				np.Value = rewriteIdentInExpr(p.Value, from, to)
			}
			newParts[i] = &np
		}
		return &TextNode{Parts: newParts}

	case *ElementNode:
		ne := *v
		ne.Attrs = make([]*Attr, len(v.Attrs))
		for i, a := range v.Attrs {
			na := *a
			// Rewrite anywhere the value will be interpreted as JS —
			// bindings, events, directives, braced-attr expressions.
			if a.IsBind || a.IsTwoWay || a.IsEvent ||
				a.IsClassDir || a.IsStyleDir || a.IsBindThis ||
				(strings.HasPrefix(a.Value, "{") && strings.HasSuffix(a.Value, "}")) {
				na.Value = rewriteIdentInExpr(a.Value, from, to)
			}
			ne.Attrs[i] = &na
		}
		if v.IfCond != "" {
			ne.IfCond = rewriteIdentInExpr(v.IfCond, from, to)
		}
		if v.EachExpr != "" {
			ne.EachExpr = rewriteIdentInExpr(v.EachExpr, from, to)
		}
		if v.EachKey != "" {
			ne.EachKey = rewriteIdentInExpr(v.EachKey, from, to)
		}
		ne.Children = rewriteIdentInNodes(v.Children, from, to)
		return &ne

	case *IfChainNode:
		nc := &IfChainNode{KeyExpr: v.KeyExpr}
		if v.KeyExpr != "" {
			nc.KeyExpr = rewriteIdentInExpr(v.KeyExpr, from, to)
		}
		nc.Branches = make([]*IfBranch, len(v.Branches))
		for i, b := range v.Branches {
			nb := &IfBranch{
				Cond:     rewriteIdentInExpr(b.Cond, from, to),
				Children: rewriteIdentInNodes(b.Children, from, to),
				Elem:     b.Elem,
				Comp:     b.Comp,
			}
			nc.Branches[i] = nb
		}
		return nc

	case *EachBlockNode:
		return &EachBlockNode{
			EachExpr: rewriteIdentInExpr(v.EachExpr, from, to),
			EachKey:  rewriteIdentInExpr(v.EachKey, from, to),
			Children: rewriteIdentInNodes(v.Children, from, to),
		}

	case *ComponentNode:
		nc := *v
		nc.Attrs = make([]*Attr, len(v.Attrs))
		for i, a := range v.Attrs {
			na := *a
			if a.IsBind || a.IsTwoWay || a.IsEvent ||
				(strings.HasPrefix(a.Value, "{") && strings.HasSuffix(a.Value, "}")) {
				na.Value = rewriteIdentInExpr(a.Value, from, to)
			}
			nc.Attrs[i] = &na
		}
		// Slots map is left untouched — we don't recurse into nested
		// component slot content because await bindings don't typically
		// leak across component boundaries.  (If users need that, they
		// can pass the value as a prop.)
		return &nc

	case *AwaitBlockNode:
		// Don't recurse into a nested {#await} — that block has its own
		// scope for any then/catch binding it declares.
		return v
	}
	return n
}

// rewriteIdentInExpr replaces identifier occurrences of `from` with
// `to` in a JS expression string, respecting property accesses
// (`obj.from` is not rewritten) and string/template literals.
//
// This is a small-scope rewriter — it doesn't try to be a full
// scope-aware substitution.  It's intended for the {:then value}
// binding case, where the binding name is a fresh identifier
// introduced by the await block, so simple lexical replacement is
// safe enough in practice.
func rewriteIdentInExpr(src, from, to string) string {
	if from == "" || !strings.Contains(src, from) {
		return src
	}
	var b strings.Builder
	i := 0
	for i < len(src) {
		c := src[i]
		// Skip string and template literals as opaque content.
		if c == '"' || c == '\'' || c == '`' {
			q := c
			b.WriteByte(c)
			i++
			for i < len(src) && src[i] != q {
				if src[i] == '\\' && i+1 < len(src) {
					b.WriteByte(src[i])
					b.WriteByte(src[i+1])
					i += 2
					continue
				}
				b.WriteByte(src[i])
				i++
			}
			if i < len(src) {
				b.WriteByte(src[i])
				i++
			}
			continue
		}
		// Try to match an identifier starting at i.
		if isIdentStart(c) {
			j := i + 1
			for j < len(src) && isIdentCont(src[j]) {
				j++
			}
			word := src[i:j]
			// Property access: a `.` immediately before the start
			// means we're in `obj.X` and X is a property, not an
			// identifier reference.  Don't rewrite.
			isProperty := i > 0 && src[i-1] == '.'
			if word == from && !isProperty {
				b.WriteString(to)
			} else {
				b.WriteString(word)
			}
			i = j
			continue
		}
		b.WriteByte(c)
		i++
	}
	return b.String()
}

// ──────────────────────────────────────────────
//  #each blocks  (keyed + recursive via FragGen)
// ──────────────────────────────────────────────

func (g *CodeGen) walkEach(elem *ElementNode, varName, parentVar string) {
	array, itemVar, indexVar := parseEachExpr(elem.EachExpr)
	if indexVar == "" {
		indexVar = "$$i"
	}
	keyExpr := elem.EachKey // "" means unkeyed

	anchor := varName + "_a"
	blocks := varName + "_bs"
	fn := "$$each_" + varName

	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('#each');\n", anchor))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))

	// Generate a fragment builder function for one row.
	// Use frag.id() for the root element so the counter is already at 1
	// when WalkNodes processes children — preventing variable name collisions.
	fragName := "$$frag_" + varName
	fragParams := []string{itemVar, indexVar}
	frag := newFragGen(fragName, fragParams, g.scopeID, g.analysis)
	// Row-scoped "current item" box — see FragGen struct comment.  Using
	// varName ($$nN) keeps the name unique across multiple {#each} blocks
	// in the same component.
	frag.itemVar = itemVar
	frag.boxVar = "$$item_" + varName

	rowVar := frag.id() // always "$$f0"; children will be $$f1, $$f2, …
	frag.create.WriteString(fmt.Sprintf("    const %s = document.createElement('%s');\n", rowVar, elem.Tag))
	frag.create.WriteString(fmt.Sprintf("    %s.setAttribute('%s', '');\n", rowVar, g.scopeID))

	for _, attr := range elem.Attrs {
		switch {
		case attr.IsEvent:
			handler := attr.Value
			// Rewrite bare row-item references so the handler closes over
			// the row's mutable box instead of the stale forEach parameter.
			handler = rewriteItemRef(handler, frag.itemVar, frag.boxVar)
			if isSimpleIdent(handler) {
				frag.events.WriteString(fmt.Sprintf(
					"    %s.addEventListener('%s', %s);\n", rowVar, attr.Name, handler))
				frag.cleanup.WriteString(fmt.Sprintf(
					"        %s.removeEventListener('%s', %s);\n", rowVar, attr.Name, handler))
			} else if isHandlerExpr(handler) {
				hv := rowVar + "_" + attr.Name + "_h"
				frag.create.WriteString(fmt.Sprintf("    const %s = %s;\n", hv, handler))
				frag.events.WriteString(fmt.Sprintf(
					"    %s.addEventListener('%s', %s);\n", rowVar, attr.Name, hv))
				frag.cleanup.WriteString(fmt.Sprintf(
					"        %s.removeEventListener('%s', %s);\n", rowVar, attr.Name, hv))
			} else {
				hv := rowVar + "_" + attr.Name + "_h"
				frag.create.WriteString(fmt.Sprintf(
					"    const %s = ($event) => { %s; };\n", hv, handler))
				frag.events.WriteString(fmt.Sprintf(
					"    %s.addEventListener('%s', %s);\n", rowVar, attr.Name, hv))
				frag.cleanup.WriteString(fmt.Sprintf(
					"        %s.removeEventListener('%s', %s);\n", rowVar, attr.Name, hv))
			}
		case attr.IsBindThis:
			// bind:this on an each-row would overwrite the same ref
			// on every iteration, leaving only the last row's element
			// accessible.  That's rarely what users want, so we skip
			// rather than emit something subtly broken.  Users who
			// need per-row element references can use a state array
			// indexed by the row's $$i.
			_ = attr
		case attr.IsClassDir:
			stmt := classDirStmt(rowVar, attr.Name, attr.Value, "    ")
			frag.init.WriteString(stmt + "\n")
			frag.update.WriteString("  " + stmt + "\n")
		case attr.IsStyleDir:
			stmt := styleDirStmt(rowVar, attr.Name, attr.Value, "    ")
			frag.init.WriteString(stmt + "\n")
			frag.update.WriteString("  " + stmt + "\n")
		case attr.IsBind:
			stmt := bindAttrStmt(rowVar, attr.Name, attr.Value, "    ")
			if attr.IsTwoWay && attr.Name == "value" {
				stmt = fmt.Sprintf("    %s.value = (%s);", rowVar, unwrapBraces(attr.Value))
			}
			frag.init.WriteString(stmt + "\n")
			frag.update.WriteString("  " + stmt + "\n")
			if attr.IsTwoWay {
				frag.emitTwoWayListener(rowVar, elem.Tag, attr)
			}
		default:
			frag.create.WriteString(fmt.Sprintf(
				"    %s.setAttribute('%s', '%s');\n", rowVar, attr.Name, escapeAttr(attr.Value)))
		}
	}

	// Recursively walk children into the fragment
	frag.WalkNodes(elem.Children, rowVar)

	// Emit the fragment function
	g.create.WriteString(frag.Emit())

	if keyExpr != "" {
		// ── Keyed reconciliation ─────────────────────────────────────────
		keyMap := varName + "_km"
		g.create.WriteString(fmt.Sprintf("  const %s = new Map();\n", keyMap))
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", blocks))

		var fnBuf strings.Builder
		fnBuf.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fn))
		// Guard: no-op when anchor is detached (branch unmounted mid-update)
		fnBuf.WriteString(fmt.Sprintf("    if (!%s.parentNode) return;\n", anchor))
		fnBuf.WriteString(fmt.Sprintf("    const $$newKeys = new Set();\n"))
		fnBuf.WriteString(fmt.Sprintf("    const $$newBlocks = [];\n"))
		fnBuf.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fnBuf.WriteString(fmt.Sprintf("      const $$key = String(%s);\n", keyExpr))
		fnBuf.WriteString(fmt.Sprintf("      $$newKeys.add($$key);\n"))
		fnBuf.WriteString(fmt.Sprintf("      let $$blk = %s.get($$key);\n", keyMap))
		fnBuf.WriteString(fmt.Sprintf("      if ($$blk) {\n"))
		// Update existing block with new item/index values
		fnBuf.WriteString(fmt.Sprintf("        if ($$blk.update) $$blk.update(%s, %s);\n", itemVar, indexVar))
		fnBuf.WriteString(fmt.Sprintf("      } else {\n"))
		// Create new block
		fnBuf.WriteString(fmt.Sprintf("        $$blk = %s(%s, %s);\n", fragName, itemVar, indexVar))
		fnBuf.WriteString(fmt.Sprintf("        %s.set($$key, $$blk);\n", keyMap))
		fnBuf.WriteString(fmt.Sprintf("      }\n"))
		// Move/insert into correct position before anchor
		fnBuf.WriteString(fmt.Sprintf("      %[1]s.before($$blk.el);\n", anchor))
		fnBuf.WriteString(fmt.Sprintf("      $$newBlocks.push($$blk);\n"))
		fnBuf.WriteString(fmt.Sprintf("    });\n"))
		// Remove stale blocks
		fnBuf.WriteString(fmt.Sprintf("    %s.forEach(($$blk, $$key) => {\n", keyMap))
		fnBuf.WriteString(fmt.Sprintf("      if (!$$newKeys.has($$key)) { $$blk.destroy(); %s.delete($$key); }\n", keyMap))
		fnBuf.WriteString(fmt.Sprintf("    });\n"))
		fnBuf.WriteString(fmt.Sprintf("    %s = $$newBlocks;\n", blocks))
		fnBuf.WriteString(fmt.Sprintf("  }\n"))
		g.create.WriteString(fnBuf.String())
	} else {
		// ── Unkeyed: full teardown + rebuild ─────────────────────────────
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", blocks))

		var fnBuf strings.Builder
		fnBuf.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fn))
		// Guard: no-op when anchor is detached (branch unmounted mid-update)
		fnBuf.WriteString(fmt.Sprintf("    if (!%s.parentNode) return;\n", anchor))
		fnBuf.WriteString(fmt.Sprintf("    %s.forEach(b => b.destroy());\n", blocks))
		fnBuf.WriteString(fmt.Sprintf("    %s = [];\n", blocks))
		fnBuf.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fnBuf.WriteString(fmt.Sprintf("      const $$blk = %s(%s, %s);\n", fragName, itemVar, indexVar))
		fnBuf.WriteString(fmt.Sprintf("      %[1]s.before($$blk.el);\n", anchor))
		fnBuf.WriteString(fmt.Sprintf("      %s.push($$blk);\n", blocks))
		fnBuf.WriteString(fmt.Sprintf("    });\n  }\n"))
		g.create.WriteString(fnBuf.String())
	}

	call := fmt.Sprintf("  %s(%s);", fn, array)
	g.init.WriteString(call + "\n")
	for _, dep := range findDeps(array, g.analysis.reactiveNames()) {
		g.addUpdate(dep, call)
	}

	// Re-run on changes to any variable referenced inside the row:
	// — bind attrs on the root element itself (e.g. :class="activePage === p.id")
	// — any expression in the row's children
	innerDeps := map[string]bool{}
	for _, attr := range elem.Attrs {
		if attr.IsBind {
			for _, d := range findDeps(attr.Value, g.analysis.reactiveNames()) {
				innerDeps[d] = true
			}
		}
	}
	for dep := range g.collectFragDeps(elem.Children) {
		innerDeps[dep] = true
	}
	for dep := range innerDeps {
		g.addUpdate(dep, call)
	}

	// Wire cleanup
	g.cleanup.WriteString(fmt.Sprintf("      %s.forEach(b => b.destroy());\n", blocks))
}

// collectFragDeps walks a node subtree and returns all reactive variable names
// that appear in expressions (text interpolations, bind attrs, if conditions).
func (g *CodeGen) collectFragDeps(nodes []Node) map[string]bool {
	deps := map[string]bool{}
	allNames := g.analysis.reactiveNames()

	var walk func([]Node)
	walk = func(ns []Node) {
		for _, node := range ns {
			switch n := node.(type) {
			case *TextNode:
				expr := buildExpr(n.Parts)
				for _, d := range findDeps(expr, allNames) {
					deps[d] = true
				}
			case *ElementNode:
				for _, attr := range n.Attrs {
					if attr.IsBind {
						for _, d := range findDeps(attr.Value, allNames) {
							deps[d] = true
						}
					}
				}
				if n.IfCond != "" {
					for _, d := range findDeps(n.IfCond, allNames) {
						deps[d] = true
					}
				}
				walk(n.Children)
			case *IfChainNode:
				for _, branch := range n.Branches {
					for _, d := range findDeps(branch.Cond, allNames) {
						deps[d] = true
					}
					walk(branch.Children)
				}
			case *EachBlockNode:
				for _, d := range findDeps(parseEachExprArray(n.EachExpr), allNames) {
					deps[d] = true
				}
				walk(n.Children)
			}
		}
	}
	walk(nodes)
	return deps
}

// emitBranchChildren recursively emits DOM creation code for a node list
// directly into a strings.Builder (used inside #if chain functions and similar
// closures where we can't use the normal g.create/g.wire buffers).
// parentVar is the JS variable that children should be appended to.
// indent is the leading whitespace for each emitted line.
func (g *CodeGen) emitBranchChildren(b *strings.Builder, branchVar string, nodes []Node, parentVar, indent string) []string {
	var declared []string
	// Contiguous static runs inside a branch compress to a single
	// insertAdjacentHTML call, same strategy as walkChildren.  This is a
	// large DOM-ops reduction when branches contain mostly decorative
	// static markup (icons, headers, separators) surrounding a small
	// number of dynamic siblings.
	i := 0
	for i < len(nodes) {
		// Look ahead for a run of static nodes containing at least one
		// ElementNode.  Pure-text runs aren't compressed — walkText's
		// direct createTextNode is already a single op.
		if isFullyStatic(nodes[i]) {
			j := i + 1
			for j < len(nodes) && isFullyStatic(nodes[j]) {
				j++
			}
			run := nodes[i:j]
			if hasElement(run) {
				html := emitStaticHTML(run, g.scopeID)
				b.WriteString(fmt.Sprintf(
					"%s$$insertHTML(%s, '%s');\n",
					indent, parentVar, escapeJSString(html)))
				i = j
				continue
			}
			// Fall through to per-node emission below for pure-text runs.
		}
		node := nodes[i]
		i++
		switch n := node.(type) {
		case *TextNode:
			expr := buildExpr(n.Parts)
			hasExpr := false
			for _, p := range n.Parts {
				if !p.Static {
					hasExpr = true
					break
				}
			}
			if hasExpr && branchVar != "" {
				tv := g.id()
				g.create.WriteString(fmt.Sprintf("  let %s = null;\n", tv))
				b.WriteString(fmt.Sprintf("%s%s = document.createTextNode(%s);\n", indent, tv, expr))
				b.WriteString(fmt.Sprintf("%s%s.appendChild(%s);\n", indent, parentVar, tv))
				for _, dep := range findDeps(expr, g.analysis.reactiveNames()) {
					g.addUpdate(dep, fmt.Sprintf("  if (%s) %s.data = %s;", branchVar, tv, expr))
				}
				declared = append(declared, tv)
			} else {
				b.WriteString(fmt.Sprintf("%s%s.appendChild(document.createTextNode(%s));\n",
					indent, parentVar, expr))
			}

		case *ElementNode:
			if n.EachExpr != "" || n.IfCond != "" {
				b.WriteString(fmt.Sprintf("%s// (nested directive on <%s> — skipped in branch)\n", indent, n.Tag))
				continue
			}
			subVar := g.id()
			if branchVar != "" {
				g.create.WriteString(fmt.Sprintf("  let %s = null;\n", subVar))
				b.WriteString(fmt.Sprintf("%s%s = document.createElement('%s');\n", indent, subVar, n.Tag))
			} else {
				b.WriteString(fmt.Sprintf("%sconst %s = document.createElement('%s');\n", indent, subVar, n.Tag))
			}
			b.WriteString(fmt.Sprintf("%s%s.setAttribute('%s', '');\n", indent, subVar, g.scopeID))
			for _, attr := range n.Attrs {
				if attr.IsEvent {
					handler := g.rewriteHandlerAssignments(attr.Value)
					b.WriteString(fmt.Sprintf("%s%s.addEventListener('%s', %s);\n",
						indent, subVar, attr.Name, handler))
				} else if attr.IsBindThis {
					// bind:this inside a branch.  Write into the user's
					// ref when the branch builds; we don't bother
					// clearing on branch teardown because the next
					// build (or another bind:this) will overwrite, and
					// holding a stale ref between toggles matches
					// Svelte's semantics (the variable still points to
					// the detached element until reassigned).
					g.emitBindThis(subVar, attr.Value, b, nil, indent, "")
				} else if attr.IsClassDir {
					stmt := classDirStmt(subVar, attr.Name, attr.Value, indent)
					b.WriteString(stmt + "\n")
					if branchVar != "" {
						upd := fmt.Sprintf("  if (%s) %s", branchVar,
							strings.TrimSpace(classDirStmt(subVar, attr.Name, attr.Value, "")))
						for _, dep := range findDeps(attrExprToJS(attr.Value), g.analysis.reactiveNames()) {
							g.addUpdate(dep, upd)
						}
					}
				} else if attr.IsStyleDir {
					stmt := styleDirStmt(subVar, attr.Name, attr.Value, indent)
					b.WriteString(stmt + "\n")
					if branchVar != "" {
						upd := fmt.Sprintf("  if (%s) %s", branchVar,
							strings.TrimSpace(styleDirStmt(subVar, attr.Name, attr.Value, "")))
						for _, dep := range findDeps(attrExprToJS(attr.Value), g.analysis.reactiveNames()) {
							g.addUpdate(dep, upd)
						}
					}
				} else if attr.IsBind {
					stmt := bindAttrStmt(subVar, attr.Name, attr.Value, indent)
					if attr.IsTwoWay && attr.Name == "value" {
						stmt = fmt.Sprintf("%s%s.value = (%s);", indent, subVar, unwrapBraces(attr.Value))
					}
					b.WriteString(stmt + "\n")
					if branchVar != "" {
						updStmt := bindAttrStmt(subVar, attr.Name, attr.Value, "")
						if attr.IsTwoWay && attr.Name == "value" {
							updStmt = fmt.Sprintf("%s.value = (%s);", subVar, unwrapBraces(attr.Value))
						}
						upd := fmt.Sprintf("  if (%s) %s", branchVar, strings.TrimSpace(updStmt))
						for _, dep := range findDeps(attr.Value, g.analysis.reactiveNames()) {
							g.addUpdate(dep, upd)
						}
					}
					if attr.IsTwoWay {
						// Listener lives in the branch body (b).  No cleanup
						// needed — the branch element's .remove() in the
						// chain-teardown path takes the listener with it.
						g.emitTwoWayListener(subVar, n.Tag, attr,
							b, b, nil, indent, indent, "")
					}
				} else {
					b.WriteString(fmt.Sprintf("%s%s.setAttribute('%s', '%s');\n",
						indent, subVar, attr.Name, escapeAttr(attr.Value)))
				}
			}
			// Static-subtree compression inside a branch — mirrors walkElement's
			// fast path.  Saves (element-count × 2-3) DOM ops at mount time
			// when the branch is taken.
			if strings.ToLower(n.Tag) != "template" &&
				len(n.Children) > 0 &&
				hasElement(n.Children) &&
				allStatic(n.Children) {
				html := emitStaticHTML(n.Children, g.scopeID)
				b.WriteString(fmt.Sprintf("%s%s.innerHTML = '%s';\n",
					indent, subVar, escapeJSString(html)))
			} else if strings.ToLower(n.Tag) != "template" &&
				len(n.Children) > 0 &&
				allHoleCompatible(n.Children) &&
				hasDynamicLeaf(n.Children) {
				// Step 3 inside a branch: template-with-holes.  No threshold —
				// see walkElement comment for why aggressive firing wins.
				branchDecl := g.emitTemplateWithHolesInto(b, subVar, n.Children, branchVar, indent)
				declared = append(declared, branchDecl...)
			} else {
				childDeclared := g.emitBranchChildren(b, branchVar, n.Children, subVar, indent)
				declared = append(declared, childDeclared...)
			}
			b.WriteString(fmt.Sprintf("%s%s.appendChild(%s);\n", indent, parentVar, subVar))
			if branchVar != "" {
				declared = append(declared, subVar)
			}

		case *IfChainNode:
			for i, branch := range n.Branches {
				if i == 0 {
					b.WriteString(fmt.Sprintf("%sif (%s) {\n", indent, branch.Cond))
				} else if branch.Cond == "" {
					b.WriteString(fmt.Sprintf("%s} else {\n", indent))
				} else {
					b.WriteString(fmt.Sprintf("%s} else if (%s) {\n", indent, branch.Cond))
				}
				g.emitBranchChildren(b, "", branch.Children, parentVar, indent+"  ")
			}
			if len(n.Branches) > 0 {
				b.WriteString(fmt.Sprintf("%s}\n", indent))
			}

		case *EachBlockNode:
			if eachChildrenNeedCodegen(n.Children) {
				// Children contain ComponentNode / IfChainNode — FragGen can't handle
				// these, so we generate a keyed live reconciler here in codegen.
				// This replaces the old static forEach (which never updated on re-render).
				g.emitEachWithComponents(b, n, parentVar, branchVar, indent)
				break
			}
			savedWire := g.wire
			savedInit := g.init
			g.wire = strings.Builder{}
			g.init = strings.Builder{}
			g.walkEachBlock(n, parentVar)
			eachWire := g.wire.String()
			eachInit := g.init.String()
			g.wire = savedWire
			g.init = savedInit
			for _, line := range strings.Split(eachWire, "\n") {
				if t := strings.TrimSpace(line); t != "" {
					b.WriteString(indent + t + "\n")
				}
			}
			for _, line := range strings.Split(eachInit, "\n") {
				if t := strings.TrimSpace(line); t != "" {
					b.WriteString(indent + t + "\n")
				}
			}

		case *ComponentNode:
			compDeclared := g.emitBranchComponent(b, n, parentVar, indent)
			declared = append(declared, compDeclared...)

		case *SlotNode:
			sv := fmt.Sprintf("$$sf_%s", g.id())
			b.WriteString(fmt.Sprintf("%sconst %s = $$slots[%q];\n", indent, sv, n.Name))
			b.WriteString(fmt.Sprintf("%sif (%s) { %s.appendChild(%s()); }\n", indent, sv, parentVar, sv))
			if len(n.Fallback) > 0 {
				b.WriteString(fmt.Sprintf("%selse {\n", indent))
				g.emitBranchChildren(b, "", n.Fallback, parentVar, indent+"  ")
				b.WriteString(fmt.Sprintf("%s}\n", indent))
			}
		}
	}
	return declared
}


// ─────────────────────────────────────────────────────────────────────────
//  Live {#each} reconciler for complex children (components, {#if}, etc.)
// ─────────────────────────────────────────────────────────────────────────

// emitEachWithComponents generates a keyed live reconciler for an {#each}
// block whose children contain ComponentNode, IfChainNode, or nested each
// — node types that FragGen cannot handle.
//
// Unlike the old static forEach, this generates an $$each_N(arr) function
// at component scope.  The function is:
//   • Called immediately from the branch body to render on first mount.
//   • Registered in g.addUpdate so it re-runs whenever the array changes.
//   • Guarded by `if (!anchor.parentNode) return` so it no-ops when the
//     enclosing {#if} branch is not currently mounted.
//
// Each row is represented as a { root, update(item), destroy() } block
// stored in a Map<key, block>.  Existing rows call update(); new rows are
// created; missing rows are destroyed.  This preserves component instance
// state (focus, scroll, form values) across array mutations.
func (g *CodeGen) emitEachWithComponents(
	b *strings.Builder,
	n *EachBlockNode,
	parentVar, branchVar, indent string,
) {
	array, itemVar, indexVar := parseEachExpr(n.EachExpr)
	if indexVar == "" {
		indexVar = "$$i"
	}
	keyExpr := n.EachKey // may be "" for unkeyed

	// All variables live at component scope so the update function
	// can reference them even when called from a setter (outside the branch).
	anchorVar := g.id() + "_a"
	kmVar     := g.id() + "_km"
	fnVar     := "$$each_" + g.id()

	g.create.WriteString(fmt.Sprintf("  const %s = document.createComment('#each');\n", anchorVar))
	if keyExpr != "" {
		g.create.WriteString(fmt.Sprintf("  const %s = new Map();\n", kmVar))
	} else {
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", kmVar)) // array of blocks
	}

	// Build the reconciler function body
	var fn strings.Builder

	fn.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fnVar))
	// Guard: no-op when anchor is not in the DOM (branch not mounted yet)
	fn.WriteString(fmt.Sprintf("    if (!%s.parentNode) return;\n", anchorVar))

	if keyExpr != "" {
		fn.WriteString("    const $$newKeys = new Set();\n")
		fn.WriteString("    const $$newBlks = [];\n")
		fn.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fn.WriteString(fmt.Sprintf("      const $$key = String(%s);\n", keyExpr))
		fn.WriteString("      $$newKeys.add($$key);\n")
		fn.WriteString(fmt.Sprintf("      let $$blk = %s.get($$key);\n", kmVar))
		fn.WriteString("      if ($$blk) {\n")
		fn.WriteString("        $$blk.update(" + itemVar + ");\n")
		fn.WriteString("      } else {\n")
		// Create row
		fn.WriteString("        $$blk = (() => {\n")
		fn.WriteString("          const $$row = document.createElement('div');\n")
		fn.WriteString(fmt.Sprintf("          $$row.setAttribute('%s','');\n", g.scopeID))
		var createBuf, updateBuf, destroyBuf strings.Builder
		g.emitEachRowBody(&createBuf, &updateBuf, &destroyBuf, n.Children, "$$row", itemVar, "          ")
		fn.WriteString(createBuf.String())
		fn.WriteString("          return {\n")
		fn.WriteString("            root: $$row,\n")
		fn.WriteString("            update(" + itemVar + ") {\n")
		fn.WriteString(updateBuf.String())
		fn.WriteString("            },\n")
		fn.WriteString("            destroy() {\n")
		fn.WriteString(destroyBuf.String())
		fn.WriteString("              $$row.remove();\n")
		fn.WriteString("            }\n")
		fn.WriteString("          };\n")
		fn.WriteString("        })();\n")
		fn.WriteString(fmt.Sprintf("        %s.set($$key, $$blk);\n", kmVar))
		fn.WriteString("      }\n")
		// Position: insert before anchor if not already there
		fn.WriteString(fmt.Sprintf(
			"      if ($$blk.root.nextSibling !== %s) { %s.before($$blk.root); }\n",
			anchorVar, anchorVar))
		fn.WriteString("      $$newBlks.push($$blk);\n")
		fn.WriteString("    });\n")
		// Destroy removed rows
		fn.WriteString(fmt.Sprintf(
			"    %s.forEach(($$blk, $$k) => { if (!$$newKeys.has($$k)) { $$blk.destroy(); %s.delete($$k); } });\n",
			kmVar, kmVar))
	} else {
		// Unkeyed: destroy all, then rebuild
		fn.WriteString(fmt.Sprintf("    %s.forEach($$blk => $$blk.destroy());\n", kmVar))
		fn.WriteString(fmt.Sprintf("    %s = [];\n", kmVar))
		fn.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fn.WriteString("      const $$row = document.createElement('div');\n")
		fn.WriteString(fmt.Sprintf("      $$row.setAttribute('%s','');\n", g.scopeID))
		var createBuf, updateBuf, destroyBuf strings.Builder
		g.emitEachRowBody(&createBuf, &updateBuf, &destroyBuf, n.Children, "$$row", itemVar, "      ")
		fn.WriteString(createBuf.String())
		fn.WriteString(fmt.Sprintf("      %s.before($$row);\n", anchorVar))
		fn.WriteString(fmt.Sprintf("      %s.push({ root: $$row, destroy() {\n", kmVar))
		fn.WriteString(destroyBuf.String())
		fn.WriteString("        $$row.remove();\n")
		fn.WriteString("      }});\n")
		fn.WriteString("    });\n")
	}
	fn.WriteString("  }\n")

	g.create.WriteString(fn.String())

	// Branch body: append anchor, call the reconciler once for initial render
	b.WriteString(fmt.Sprintf("%s%s.appendChild(%s);\n", indent, parentVar, anchorVar))
	b.WriteString(fmt.Sprintf("%s%s(%s);\n", indent, fnVar, array))

	// Register reactive update: fires whenever the array variable changes,
	// even when the branch condition itself hasn't changed.
	for _, dep := range findDeps(array, g.analysis.reactiveNames()) {
		guard := ""
		if branchVar != "" {
			guard = fmt.Sprintf("  if (%s) ", branchVar)
		}
		g.addUpdate(dep, guard+fmt.Sprintf("%s(%s);", fnVar, array))
	}
}

// emitEachRowBody generates the create / update / destroy snippets for one
// row of an {#each} block.  It recursively handles elements, text, and
// components.
//
//   createBuf  — statements that build DOM (run once per row creation)
//   updateBuf  — statements that refresh bound values (run on each array update)
//   destroyBuf — statements that clean up (run when row is removed)
//   nodes      — the children of the {#each} block
//   parentVar  — JS variable the row nodes are appended to ("$$row")
//   itemVar    — the loop variable name (e.g. "order")
//   indent     — leading whitespace
func (g *CodeGen) emitEachRowBody(
	createBuf, updateBuf, destroyBuf *strings.Builder,
	nodes []Node,
	parentVar, itemVar, indent string,
) {
	// Row-scoped "current item" box.  Event handlers captured at row creation
	// close over this name instead of the outer `itemVar`; update(u) writes
	// the fresh item into it at the top, so subsequent clicks see up-to-date
	// data.  Without this, clicking Edit on a row whose fields changed via
	// another flow (e.g. save) passes the stale row item to the handler.
	boxVar := "$$item_" + g.id()

	// Hoisted declarations (`let $$nX = null;`, `let $$b_... = false;`) from
	// nested if-branches must live in ROW scope, not inside the if block
	// where createBuf's cursor happens to be.  Using a separate buffer that
	// we prepend to createBuf guarantees that — previously we passed
	// createBuf as its own hoistBuf, so hoists landed inside whatever block
	// the cursor had entered, producing ReferenceError in update() when the
	// if-branch hadn't been taken (or had been torn down and rebuilt).
	var hoistBuf strings.Builder

	// Box declaration and refresh go in hoistBuf too so they stay at row
	// scope regardless of nested structure.
	hoistBuf.WriteString(fmt.Sprintf("%slet %s = %s;\n", indent, boxVar, itemVar))
	updateBuf.WriteString(fmt.Sprintf("              %s = %s;\n", boxVar, itemVar))

	// Walk into a temp createBuf so we can prepend hoistBuf cleanly.
	var bodyBuf strings.Builder
	g.emitEachRowBodyGuarded(&hoistBuf, &bodyBuf, updateBuf, destroyBuf,
		nodes, parentVar, itemVar, boxVar, indent, "")

	// Assemble: hoists first, then the create-body (which may reference
	// hoisted variables from inside nested if blocks).
	createBuf.WriteString(hoistBuf.String())
	createBuf.WriteString(bodyBuf.String())
}

// emitEachRowBodyGuarded is the recursive implementation.
//
//   hoistBuf   — where `let $$nX = null;` lines go (always at row scope, outside
//                any if-block), so bindings remain visible to update()/destroy().
//   createBuf  — where the code that assigns/builds DOM goes (may be nested
//                inside if-blocks).
//   itemVar    — the template loop variable name (e.g. "u").
//   boxVar     — row-scoped identifier to substitute for itemVar inside
//                event handler closures.  Empty string means "don't rewrite"
//                (used by internal calls that don't participate in the box
//                mechanism — currently none, but keeps the API symmetric).
//   branchVar  — when non-empty, every update / destroy statement emitted for
//                nodes inside this call is guarded with `if (branchVar)` so a
//                false conditional doesn't try to touch null bindings.  Inside
//                a branch, DOM declarations are emitted as assignments to the
//                already-hoisted bindings rather than fresh `const`s.
func (g *CodeGen) emitEachRowBodyGuarded(
	hoistBuf, createBuf, updateBuf, destroyBuf *strings.Builder,
	nodes []Node,
	parentVar, itemVar, boxVar, indent, branchVar string,
) {
	// decl emits a declaration appropriate for the current scope:
	//   at top level:    const $$nX = <init>;   (in createBuf)
	//   inside a branch: let $$nX = null;       (in hoistBuf — visible to update)
	//                    $$nX = <init>;         (in createBuf — runs when branch is active)
	decl := func(name, init string) {
		if branchVar == "" {
			createBuf.WriteString(fmt.Sprintf("%sconst %s = %s;\n", indent, name, init))
		} else {
			hoistBuf.WriteString(fmt.Sprintf("          let %s = null;\n", name))
			createBuf.WriteString(fmt.Sprintf("%s%s = %s;\n", indent, name, init))
		}
	}
	// writeUpdate wraps an update statement in `if (branchVar)` when inside a
	// branch, so the update is a no-op when the branch isn't active.
	writeUpdate := func(stmt string) {
		if branchVar == "" {
			updateBuf.WriteString(fmt.Sprintf("              %s\n", stmt))
		} else {
			updateBuf.WriteString(fmt.Sprintf("              if (%s) { %s }\n", branchVar, stmt))
		}
	}
	// writeDestroy wraps destroy in the same guard.
	writeDestroy := func(stmt string) {
		if branchVar == "" {
			destroyBuf.WriteString(fmt.Sprintf("              %s\n", stmt))
		} else {
			destroyBuf.WriteString(fmt.Sprintf("              if (%s) { %s }\n", branchVar, stmt))
		}
	}

	// Contiguous static-run batching — same strategy as walkChildren and
	// emitBranchChildren.  Each row is instantiated once per item; compressing
	// its static skeleton to insertAdjacentHTML pays off multiplicatively as
	// the array grows.
	i := 0
	for i < len(nodes) {
		if isFullyStatic(nodes[i]) {
			j := i + 1
			for j < len(nodes) && isFullyStatic(nodes[j]) {
				j++
			}
			run := nodes[i:j]
			if hasElement(run) {
				html := emitStaticHTML(run, g.scopeID)
				createBuf.WriteString(fmt.Sprintf(
					"%s$$insertHTML(%s, '%s');\n",
					indent, parentVar, escapeJSString(html)))
				i = j
				continue
			}
		}
		node := nodes[i]
		i++
		switch n := node.(type) {

		case *TextNode:
			expr := buildExpr(n.Parts)
			hasExpr := false
			for _, p := range n.Parts {
				if !p.Static {
					hasExpr = true
					break
				}
			}
			if hasExpr {
				tv := g.id()
				decl(tv, fmt.Sprintf("document.createTextNode(%s)", expr))
				createBuf.WriteString(fmt.Sprintf("%s%s.appendChild(%s);\n", indent, parentVar, tv))
				// Only add to update if the expression references the item variable
				if strings.Contains(expr, itemVar) {
					writeUpdate(fmt.Sprintf("%s.data = %s;", tv, expr))
				}
			} else {
				createBuf.WriteString(fmt.Sprintf("%s%s.appendChild(document.createTextNode(%s));\n", indent, parentVar, expr))
			}

		case *ElementNode:
			if n.EachExpr != "" || n.IfCond != "" {
				// Nested directive — recurse children directly into same parent
				g.emitEachRowBodyGuarded(hoistBuf, createBuf, updateBuf, destroyBuf,
					n.Children, parentVar, itemVar, boxVar, indent, branchVar)
				continue
			}
			sv := g.id()
			decl(sv, fmt.Sprintf("document.createElement('%s')", n.Tag))
			createBuf.WriteString(fmt.Sprintf("%s%s.setAttribute('%s','');\n", indent, sv, g.scopeID))
			for _, attr := range n.Attrs {
				if attr.IsEvent {
					handler := g.rewriteHandlerAssignments(attr.Value)
					// Rewrite bare row-item references so the handler closes
					// over the row's mutable box instead of the stale forEach
					// parameter.  See rewriteItemRef for details.
					handler = rewriteItemRef(handler, itemVar, boxVar)
					createBuf.WriteString(fmt.Sprintf("%s%s.addEventListener('%s', %s);\n",
						indent, sv, attr.Name, handler))
				} else if attr.IsBind {
					stmt := bindAttrStmt(sv, attr.Name, attr.Value, indent)
					if attr.IsTwoWay && attr.Name == "value" {
						stmt = fmt.Sprintf("%s%s.value = (%s);", indent, sv, unwrapBraces(attr.Value))
					}
					createBuf.WriteString(stmt + "\n")
					if strings.Contains(attr.Value, itemVar) {
						updStmt := bindAttrStmt(sv, attr.Name, attr.Value, "")
						if attr.IsTwoWay && attr.Name == "value" {
							updStmt = fmt.Sprintf("%s.value = (%s);", sv, unwrapBraces(attr.Value))
						}
						writeUpdate(strings.TrimSpace(updStmt))
					}
					if attr.IsTwoWay {
						// Listener lives in the row's IIFE (createBuf).  No
						// cleanup needed — destroy() calls $$row.remove() and
						// the listener goes with the element.
						g.emitTwoWayListener(sv, n.Tag, attr,
							createBuf, createBuf, nil, indent, indent, "")
					}
				} else {
					createBuf.WriteString(fmt.Sprintf("%s%s.setAttribute('%s','%s');\n",
						indent, sv, attr.Name, escapeAttr(attr.Value)))
				}
			}
			// Static-subtree compression — element-level in an each-row.
			// Fully-static children become one innerHTML assignment.
			if strings.ToLower(n.Tag) != "template" &&
				len(n.Children) > 0 &&
				hasElement(n.Children) &&
				allStatic(n.Children) {
				html := emitStaticHTML(n.Children, g.scopeID)
				createBuf.WriteString(fmt.Sprintf("%s%s.innerHTML = '%s';\n",
					indent, sv, escapeJSString(html)))
			} else {
				g.emitEachRowBodyGuarded(hoistBuf, createBuf, updateBuf, destroyBuf,
					n.Children, sv, itemVar, boxVar, indent, branchVar)
			}
			createBuf.WriteString(fmt.Sprintf("%s%s.appendChild(%s);\n", indent, parentVar, sv))

		case *ComponentNode:
			wv := g.id()
			cv := g.id() + "_comp"
			// Build props expression from bound attrs
			propsEntries := g.componentPropsEntries(n.Attrs)
			propsExpr := "{}"
			if len(propsEntries) > 0 {
				propsExpr = "{ " + strings.Join(propsEntries, ", ") + " }"
			}
			decl(wv, "document.createElement('div')")
			createBuf.WriteString(fmt.Sprintf("%s%s.setAttribute('%s','');\n", indent, wv, g.scopeID))
			// Wire event listeners — rewrite bare item refs to the row box so
			// the captured handler stays current on array updates.
			for _, attr := range n.Attrs {
				if attr.IsEvent {
					boxedHandler := rewriteItemRef(g.rewriteHandlerAssignments(attr.Value), itemVar, boxVar)
					createBuf.WriteString(fmt.Sprintf(
						"%s%s.addEventListener('%s', ($e) => { if ($e instanceof CustomEvent) { (%s)($e); } });\n",
						indent, wv, attr.Name, boxedHandler))
				}
			}
			decl(cv, fmt.Sprintf("%s(%s, %s, {})", n.Name, wv, propsExpr))
			createBuf.WriteString(fmt.Sprintf("%s%s.appendChild(%s);\n", indent, parentVar, wv))
			// Update: call .set() with fresh props if any reference itemVar
			if strings.Contains(propsExpr, itemVar) {
				writeUpdate(fmt.Sprintf("%s.set(%s);", cv, propsExpr))
			}
			// Destroy: call .destroy()
			writeDestroy(fmt.Sprintf("%s.destroy();", cv))

		case *IfChainNode:
			// Inline if/else inside a row.
			//
			// Child declarations (element / text-node / component consts) must
			// be HOISTED to row scope so they remain visible to update() and
			// destroy() callbacks.  Inside the `if` block we only assign.
			// Each branch gets a unique flag variable so update / destroy
			// statements can skip the branch when it's inactive.
			for i, branch := range n.Branches {
				branchFlag := fmt.Sprintf("$$b_%s_%d", g.id(), i)
				hoistBuf.WriteString(fmt.Sprintf("          let %s = false;\n", branchFlag))
				if i == 0 {
					createBuf.WriteString(fmt.Sprintf("%sif (%s) {\n", indent, branch.Cond))
				} else if branch.Cond == "" {
					createBuf.WriteString(fmt.Sprintf("%s} else {\n", indent))
				} else {
					createBuf.WriteString(fmt.Sprintf("%s} else if (%s) {\n", indent, branch.Cond))
				}
				createBuf.WriteString(fmt.Sprintf("%s  %s = true;\n", indent, branchFlag))
				g.emitEachRowBodyGuarded(hoistBuf, createBuf, updateBuf, destroyBuf,
					branch.Children, parentVar, itemVar, boxVar, indent+"  ", branchFlag)
			}
			if len(n.Branches) > 0 {
				createBuf.WriteString(fmt.Sprintf("%s}\n", indent))
			}
		}
	}
}

// eachChildrenNeedCodegen returns true when an {#each} block's children contain
// node types that require the full codegen pipeline (IfChainNode, ComponentNode)
// and therefore cannot safely be processed by FragGen inside walkEachBlock.
// When true, emitBranchChildren falls back to an inline forEach instead.
func eachChildrenNeedCodegen(nodes []Node) bool {
	for _, n := range nodes {
		switch c := n.(type) {
		case *IfChainNode:
			return true
		case *ComponentNode:
			return true
		case *EachBlockNode:
			return true
		case *ElementNode:
			if eachChildrenNeedCodegen(c.Children) {
				return true
			}
		}
	}
	return false
}

// rewriteItemRef parses src, walks the AST with scope tracking, and replaces
// every bare reference to itemVar with boxVar.  Property-access positions
// (`obj.itemVar`, `{itemVar: …}` as a key) and shadowed references (inside
// a function whose parameter list or a nested `let/const/var` re-declares
// itemVar) are correctly left untouched.
//
// Used by emitEachRowBody to rewrite event-handler source text so row-scoped
// handlers read the always-fresh "current item" box rather than closing
// over the forEach callback's `itemVar` parameter (which never updates).
//
// Behaviour matrix:
//   () => openEdit(u)             →  () => openEdit($$item_N)
//   () => toggleStatus(u.id)      →  () => toggleStatus($$item_N.id)
//   () => obj.u                   →  unchanged (property access)
//   () => ({u: x})                →  unchanged (object key)
//   () => ({[u]: x})              →  ({[$$item_N]: x})  (computed key)
//   (u) => u + 1                  →  unchanged (shadowed)
//   () => { const u = 1; return u; } →  unchanged (block-scoped shadow)
//   `${u}`                        →  `${$$item_N}` (template hole — now
//                                    handled correctly; the old token-based
//                                    rewriter couldn't descend into these)
//
// If src fails to parse, the original source is returned unchanged rather
// than producing malformed JS — callers fall back to the stale-closure
// behaviour, which is the same pre-fix behaviour.
func rewriteItemRef(src, itemVar, boxVar string) string {
	if itemVar == "" || boxVar == "" || itemVar == boxVar {
		return src
	}
	if !strings.Contains(src, itemVar) {
		return src
	}

	prog := ParseJS(src)
	if prog == nil {
		return src
	}

	// Collect (pos, end) spans of every JsIdent that should be rewritten.
	// We then splice all of them at once in source order.
	var hits []struct{ pos, end int }

	// Scope stack: each entry is true iff itemVar is shadowed at that level.
	// The outermost scope starts unshadowed.
	shadow := []bool{false}
	isShadowed := func() bool {
		for i := len(shadow) - 1; i >= 0; i-- {
			if shadow[i] {
				return true
			}
		}
		return false
	}

	// patternBindsItem reports whether a binding pattern (JsIdent, or
	// JsObject/JsArrayExpr used as a pattern) introduces a new binding named
	// itemVar.  Called on function parameters and var-decl LHS.
	var patternBindsItem func(JsNode) bool
	patternBindsItem = func(n JsNode) bool {
		switch p := n.(type) {
		case *JsIdent:
			return p.Name == itemVar
		case *JsObjectExpr:
			for _, prop := range p.Props {
				if prop.Spread {
					if patternBindsItem(prop.Value) {
						return true
					}
					continue
				}
				if patternBindsItem(prop.Value) {
					return true
				}
			}
		case *JsArrayExpr:
			for _, el := range p.Elems {
				if el == nil {
					continue
				}
				if sp, ok := el.(*JsSpreadExpr); ok {
					if patternBindsItem(sp.X) {
						return true
					}
					continue
				}
				if patternBindsItem(el) {
					return true
				}
			}
		case *JsAssignExpr:
			// Default value in a pattern:  { x = 5 }  or  (x = 5) => ...
			if p.Op == "=" {
				return patternBindsItem(p.L)
			}
		}
		return false
	}

	// blockShadowsItem scans direct children of a block for `let/const/var
	// itemVar` declarations.  var-scoping up-leaks through blocks in real
	// JS but in the handler bodies we see (short, arrow-flavoured code),
	// treating a block-level var as block-scoped is safe: we only rewrite
	// BARE references, and if something is declared by any name in an
	// enclosing scope, rewriting the name would be wrong anyway.
	blockShadowsItem := func(body []JsStmt) bool {
		for _, s := range body {
			vd, ok := s.(*JsVarDecl)
			if !ok {
				continue
			}
			for _, d := range vd.Decls {
				if patternBindsItem(d.Id) {
					return true
				}
			}
		}
		return false
	}

	// visit is the recursive walker.  Mirrors WalkNode's shape but handles
	// scope push/pop and filters property-access positions explicitly.
	var visit func(JsNode)
	visit = func(n JsNode) {
		if n == nil {
			return
		}
		switch node := n.(type) {

		case *JsIdent:
			if node.Name == itemVar && !isShadowed() {
				hits = append(hits, struct{ pos, end int }{node.Pos, node.End})
			}

		// ── Scope-introducing nodes ──────────────────────────────────────
		case *JsArrowFunc:
			shadowed := false
			for _, p := range node.Params {
				if patternBindsItem(p) {
					shadowed = true
					break
				}
			}
			shadow = append(shadow, shadowed)
			// Visit param defaults (RHS of `= default`), but their LHS
			// bindings should not trigger rewrites — patternBindsItem
			// already told us if the bound name matches.  For pattern
			// analysis we conservatively skip visiting params entirely,
			// since template handlers don't typically put state-refs in
			// default expressions.
			visit(node.Body)
			shadow = shadow[:len(shadow)-1]
		case *JsFuncExpr:
			shadowed := false
			for _, p := range node.Params {
				if patternBindsItem(p) {
					shadowed = true
					break
				}
			}
			shadow = append(shadow, shadowed)
			visit(node.Body)
			shadow = shadow[:len(shadow)-1]
		case *JsFuncDecl:
			shadowed := false
			for _, p := range node.Params {
				if patternBindsItem(p) {
					shadowed = true
					break
				}
			}
			shadow = append(shadow, shadowed)
			visit(node.Body)
			shadow = shadow[:len(shadow)-1]
		case *JsBlock:
			shadow = append(shadow, blockShadowsItem(node.Body))
			for _, s := range node.Body {
				visit(s)
			}
			shadow = shadow[:len(shadow)-1]

		// ── Property-access filtering ────────────────────────────────────
		case *JsMemberExpr:
			visit(node.Obj)
			// Skip node.Prop unless it's computed — `x[u]` should
			// rewrite the `u`, but `x.u` should leave it alone.
			if node.Computed {
				visit(node.Prop)
			}
		case *JsObjectExpr:
			for _, prop := range node.Props {
				// Computed keys `{[expr]: x}` ARE value-position expressions
				// and should be rewritten.  Literal keys `{u: x}` are not
				// references to the state var — skip.
				if prop.Computed {
					visit(prop.Key)
				}
				// Spread:  {...rest}  — Value is the expression being spread.
				if prop.Spread {
					visit(prop.Value)
					continue
				}
				// Regular property (`{u: x}` or shorthand `{u}`): Value is
				// the value-position expression.  For shorthand the parser
				// uses the same JsIdent for Key and Value, so visiting Value
				// correctly registers a hit.
				visit(prop.Value)
			}

		case *JsProgram:
			for _, s := range node.Body {
				visit(s)
			}
		case *JsExprStmt:
			visit(node.X)
		case *JsVarDecl:
			shadowHere := blockShadowsItem([]JsStmt{node})
			if shadowHere {
				// The declaration shadows — but its Init expressions are
				// evaluated BEFORE the binding is in scope (TDZ notwithstanding
				// for sequential decls).  For simplicity we treat the whole
				// statement as shadowed, which may miss a theoretical edge
				// case but is correct in every handler pattern we see.
				shadow = append(shadow, true)
				for _, d := range node.Decls {
					if d.Init != nil {
						visit(d.Init)
					}
				}
				shadow = shadow[:len(shadow)-1]
			} else {
				for _, d := range node.Decls {
					if d.Init != nil {
						visit(d.Init)
					}
				}
			}
		case *JsIfStmt:
			visit(node.Test)
			visit(node.Then)
			if node.Else != nil {
				visit(node.Else)
			}
		case *JsForStmt:
			if node.Init != nil {
				visit(node.Init)
			}
			if node.Test != nil {
				visit(node.Test)
			}
			if node.Update != nil {
				visit(node.Update)
			}
			visit(node.Body)
		case *JsForInStmt:
			visit(node.Left)
			visit(node.Right)
			visit(node.Body)
		case *JsWhileStmt:
			visit(node.Test)
			visit(node.Body)
		case *JsDoWhileStmt:
			visit(node.Body)
			visit(node.Test)
		case *JsReturnStmt:
			if node.Arg != nil {
				visit(node.Arg)
			}
		case *JsThrowStmt:
			visit(node.Arg)
		case *JsTryStmt:
			visit(node.Block)
			if node.CatchParam != nil {
				// catch(param) — treat the param as a new binding; if it
				// shadows itemVar, the handler body shouldn't rewrite.
				shadowed := patternBindsItem(node.CatchParam)
				shadow = append(shadow, shadowed)
				if node.Handler != nil {
					visit(node.Handler)
				}
				shadow = shadow[:len(shadow)-1]
			} else if node.Handler != nil {
				visit(node.Handler)
			}
			if node.Finalizer != nil {
				visit(node.Finalizer)
			}
		case *JsSwitchStmt:
			visit(node.Disc)
			for _, c := range node.Cases {
				if c.Test != nil {
					visit(c.Test)
				}
				for _, s := range c.Body {
					visit(s)
				}
			}
		case *JsUnaryExpr:
			visit(node.X)
		case *JsBinaryExpr:
			visit(node.L)
			visit(node.R)
		case *JsLogicalExpr:
			visit(node.L)
			visit(node.R)
		case *JsAssignExpr:
			visit(node.L)
			visit(node.R)
		case *JsCallExpr:
			visit(node.Callee)
			for _, a := range node.Args {
				visit(a)
			}
		case *JsNewExpr:
			visit(node.Callee)
			for _, a := range node.Args {
				visit(a)
			}
		case *JsConditionalExpr:
			visit(node.Test)
			visit(node.Then)
			visit(node.Else)
		case *JsSeqExpr:
			for _, e := range node.Exprs {
				visit(e)
			}
		case *JsSpreadExpr:
			visit(node.X)
		case *JsAwaitExpr:
			visit(node.X)
		case *JsYieldExpr:
			if node.X != nil {
				visit(node.X)
			}
		case *JsArrayExpr:
			for _, e := range node.Elems {
				if e != nil {
					visit(e)
				}
			}
		case *JsTemplateLit:
			// Template literals are structured: descend into each
			// ${…} interpolation expression so dependency collection
			// sees identifiers used inside string interpolation.
			for _, e := range node.Exprs {
				visit(e)
			}
		// Leaves / no-op nodes
		case *JsLiteral, *JsThisExpr, *JsSuperExpr,
			*JsBreakStmt, *JsContinueStmt,
			*JsEmptyStmt, *JsDebuggerStmt:
		default:
			// Fallback: fall back to generic WalkNode to at least visit
			// children.  This may double-visit if we later add a specific
			// case, but the hits list de-dupes via overlap-elimination
			// at splice time.
			WalkNode(node, func(c JsNode) bool {
				if c == node {
					return true // don't re-dispatch self
				}
				visit(c)
				return false // visit handled descent
			})
		}
	}

	visit(prog)

	if len(hits) == 0 {
		return src
	}

	// Sort hits by pos, then splice.
	sort.Slice(hits, func(i, j int) bool { return hits[i].pos < hits[j].pos })

	var out strings.Builder
	out.Grow(len(src) + 16)
	cursor := 0
	for _, h := range hits {
		if h.pos < cursor {
			// Shouldn't happen with well-formed AST; skip overlapping.
			continue
		}
		out.WriteString(src[cursor:h.pos])
		out.WriteString(boxVar)
		cursor = h.end
	}
	out.WriteString(src[cursor:])
	return out.String()
}

// emitBranchComponent emits inline component mounting code inside a branch
// and returns the names of component-scope variables it declared (instanceVar,
// wrapVar) so walkIfChain can null them out when the branch is removed.
func (g *CodeGen) emitBranchComponent(b *strings.Builder, comp *ComponentNode, parentVar, indent string) []string {
	var declared []string
	// Build props object expression
	propsEntries := g.componentPropsEntries(comp.Attrs)
	propsExpr := "{}"
	if len(propsEntries) > 0 {
		propsExpr = "{ " + strings.Join(propsEntries, ", ") + " }"
	}

	// Event listener snippets (CustomEvent-guarded)
	evWire := func(wrapVar string, indentLevel string) string {
		var s strings.Builder
		for _, attr := range comp.Attrs {
			if attr.IsEvent {
				s.WriteString(fmt.Sprintf(
					"%s%s.addEventListener('%s', ($e) => { if ($e instanceof CustomEvent) { (%s)($e); } });\n",
					indentLevel, wrapVar, attr.Name, g.rewriteHandlerAssignments(attr.Value)))
			}
		}
		return s.String()
	}

	if comp.IfCond != "" {
		// <Comp #if="cond" /> inside a branch — lift vars to component scope so
		// bound props can be updated reactively via g.addUpdate.
		wrapVar  := g.id()
		instVar  := g.id() + "_comp"
		g.create.WriteString(fmt.Sprintf("  let %s = null;\n", wrapVar))
		g.create.WriteString(fmt.Sprintf("  let %s = null;\n", instVar))
		b.WriteString(fmt.Sprintf("%sif (%s) {\n", indent, comp.IfCond))
		b.WriteString(fmt.Sprintf("%s  %s = document.createElement('div');\n", indent, wrapVar))
		b.WriteString(fmt.Sprintf("%s  %s.setAttribute('%s','');\n", indent, wrapVar, g.scopeID))
		b.WriteString(evWire(wrapVar, indent+"  "))
		b.WriteString(fmt.Sprintf("%s  %s = %s(%s, %s, {});\n", indent, instVar, comp.Name, wrapVar, propsExpr))
		b.WriteString(fmt.Sprintf("%s  %s.appendChild(%s);\n", indent, parentVar, wrapVar))
		b.WriteString(fmt.Sprintf("%s}\n", indent))
		// Register reactive prop updates — guarded by instVar so they no-op when condition is false
		for _, attr := range comp.Attrs {
			if !attr.IsBind {
				continue
			}
			update := fmt.Sprintf("  if (%s) %s.set({ %s: %s });", instVar, instVar, attr.Name, unwrapBraces(attr.Value))
			for _, dep := range findDeps(attr.Value, g.analysis.reactiveNames()) {
				g.addUpdate(dep, update)
			}
		}
		declared = append(declared, wrapVar, instVar)
		return declared
	}

	if comp.EachExpr == "" {
		// Plain single-mount component inside a branch.
		//
		// wrapVar and instVar are lifted to COMPONENT SCOPE (let ... = null in g.create)
		// so that:
		//   (a) Reactive setters can call instVar.set({prop: val}) via g.addUpdate
		//       registrations, updating the component when bound props change — even
		//       when the branch condition hasn't changed.
		//   (b) walkIfChain nulls them out (via branchDeclared) when the branch is
		//       removed, which triggers the guard `if (instVar)` in update statements.
		//   (c) The destroy() call fires on branch removal so the child component
		//       cleans up its own event listeners and styles.
		wrapVar := g.id()
		instVar := g.id() + "_comp"
		g.create.WriteString(fmt.Sprintf("  let %s = null;\n", wrapVar))
		g.create.WriteString(fmt.Sprintf("  let %s = null;\n", instVar))
		b.WriteString(fmt.Sprintf("%s%s = document.createElement('div');\n", indent, wrapVar))
		b.WriteString(fmt.Sprintf("%s%s.setAttribute('%s','');\n", indent, wrapVar, g.scopeID))
		b.WriteString(evWire(wrapVar, indent))
		b.WriteString(fmt.Sprintf("%s%s = %s(%s, %s, {});\n", indent, instVar, comp.Name, wrapVar, propsExpr))
		b.WriteString(fmt.Sprintf("%s%s.appendChild(%s);\n", indent, parentVar, wrapVar))
		// Register reactive prop updates — fire directly from setters, bypassing
		// the chain function so the component gets fresh props without DOM recreation.
		for _, attr := range comp.Attrs {
			if !attr.IsBind {
				continue
			}
			update := fmt.Sprintf("  if (%s) %s.set({ %s: %s });", instVar, instVar, attr.Name, unwrapBraces(attr.Value))
			for _, dep := range findDeps(attr.Value, g.analysis.reactiveNames()) {
				g.addUpdate(dep, update)
			}
		}
		declared = append(declared, wrapVar, instVar)
		return declared
	}

	// ── #each component inside a branch ──────────────────────────────────────
	// Both the anchor AND the update function must live at component scope so
	// that the hoisted $$bceach_ function can reference the anchor by name.
	// If the anchor were declared inside the branch body (b), it would be
	// undefined when $$bceach_ is called from dep-triggered updates.
	array, itemVar, indexVar := parseEachExpr(comp.EachExpr)
	if indexVar == "" {
		indexVar = "$$i"
	}

	anchorVar := g.id() + "_a"
	fnVar := "$$bceach_" + g.id()
	allNames := g.analysis.reactiveNames()

	// Anchor: declared and wired at component scope.
	// The branch body appends it to parentVar when the branch first mounts.
	g.create.WriteString(fmt.Sprintf("  const %s = document.createComment('#each-comp');\n", anchorVar))
	// Wire: appended to parentVar from the branch body (below) — not via g.wire
	// because parentVar is a branch-local variable, not a fixed component element.
	// Instead we write the appendChild into b (runs on first branch mount).
	b.WriteString(fmt.Sprintf("%s%s.appendChild(%s);\n", indent, parentVar, anchorVar))

	if comp.EachKey != "" {
		// Keyed — hoist Map and update fn to component scope
		kmVar := g.id() + "_km"
		bsVar := g.id() + "_bs"

		// Component-scope declarations
		g.create.WriteString(fmt.Sprintf("  const %s = new Map();\n", kmVar))
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", bsVar))

		// Component-scope update function — guarded so it's a no-op when the
		// branch hasn't mounted yet (anchor has no parentNode).
		var fn strings.Builder
		fn.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fnVar))
		fn.WriteString(fmt.Sprintf("    if (!%s.parentNode) return;\n", anchorVar))
		fn.WriteString("    const $$newKeys = new Set();\n")
		fn.WriteString("    const $$newBlks = [];\n")
		fn.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fn.WriteString(fmt.Sprintf("      const $$key = String(%s);\n", comp.EachKey))
		fn.WriteString("      $$newKeys.add($$key);\n")
		fn.WriteString(fmt.Sprintf("      let $$blk = %s.get($$key);\n", kmVar))
		fn.WriteString(fmt.Sprintf("      if ($$blk) { $$blk.comp.set(%s); } else {\n", propsExpr))
		wrapVar := g.id()
		fn.WriteString(fmt.Sprintf("        const %s = document.createElement('div');\n", wrapVar))
		fn.WriteString(fmt.Sprintf("        %s.setAttribute('%s','');\n", wrapVar, g.scopeID))
		fn.WriteString(evWire(wrapVar, "        "))
		fn.WriteString(fmt.Sprintf("        const $$c = %s(%s, %s, {});\n", comp.Name, wrapVar, propsExpr))
		fn.WriteString(fmt.Sprintf("        $$blk = { wrap: %s, comp: $$c };\n", wrapVar))
		fn.WriteString(fmt.Sprintf("        %s.set($$key, $$blk);\n", kmVar))
		fn.WriteString("      }\n")
		fn.WriteString(fmt.Sprintf("      if ($$blk.wrap.nextSibling !== %s) { %s.before($$blk.wrap); }\n",
			anchorVar, anchorVar))
		fn.WriteString("      $$newBlks.push($$blk);\n")
		fn.WriteString("    });\n")
		fn.WriteString(fmt.Sprintf("    %s.forEach(($$blk, $$k) => { if (!$$newKeys.has($$k)) { $$blk.comp.destroy(); %s.delete($$k); } });\n", kmVar, kmVar))
		fn.WriteString(fmt.Sprintf("    %s = $$newBlks;\n", bsVar))
		fn.WriteString("  }\n")
		g.create.WriteString(fn.String())

		// Cleanup: destroy all blocks
		g.cleanup.WriteString(fmt.Sprintf("      %s.forEach(b => b.comp.destroy());\n", bsVar))

		// Call from branch (first mount or re-evaluation)
		b.WriteString(fmt.Sprintf("%s%s(%s);\n", indent, fnVar, array))

		// Register as dep update for array and any bound prop expressions
		call := fmt.Sprintf("  %s(%s);", fnVar, array)
		for _, dep := range findDeps(array, allNames) {
			g.addUpdate(dep, call)
		}
		for _, attr := range comp.Attrs {
			if attr.IsBind {
				for _, dep := range findDeps(attr.Value, allNames) {
					g.addUpdate(dep, call)
				}
			}
		}
	} else {
		// Unkeyed — hoist blocks slice and update fn to component scope
		bsVar := g.id() + "_bs"
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", bsVar))

		var fn strings.Builder
		fn.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fnVar))
		fn.WriteString(fmt.Sprintf("    if (!%s.parentNode) return;\n", anchorVar))
		fn.WriteString(fmt.Sprintf("    %s.forEach(b => b.comp.destroy()); %s = [];\n", bsVar, bsVar))
		fn.WriteString(fmt.Sprintf("    ((%s)||[]).forEach(function(%s, %s) {\n", array, itemVar, indexVar))
		wrapVar := g.id()
		fn.WriteString(fmt.Sprintf("      const %s = document.createElement('div');\n", wrapVar))
		fn.WriteString(fmt.Sprintf("      %s.setAttribute('%s','');\n", wrapVar, g.scopeID))
		fn.WriteString(evWire(wrapVar, "      "))
		fn.WriteString(fmt.Sprintf("      const $$c = %s(%s, %s, {});\n", comp.Name, wrapVar, propsExpr))
		fn.WriteString(fmt.Sprintf("      %[1]s.before(%[2]s);\n", anchorVar, wrapVar))
		fn.WriteString(fmt.Sprintf("      %s.push({ wrap: %s, comp: $$c });\n", bsVar, wrapVar))
		fn.WriteString("    });\n  }\n")
		g.create.WriteString(fn.String())

		g.cleanup.WriteString(fmt.Sprintf("      %s.forEach(b => b.comp.destroy());\n", bsVar))

		b.WriteString(fmt.Sprintf("%s%s(%s);\n", indent, fnVar, array))

		call := fmt.Sprintf("  %s(%s);", fnVar, array)
		for _, dep := range findDeps(array, allNames) {
			g.addUpdate(dep, call)
		}
		for _, attr := range comp.Attrs {
			if attr.IsBind {
				for _, dep := range findDeps(attr.Value, allNames) {
					g.addUpdate(dep, call)
				}
			}
		}
	}
	return declared
}

// rewriteHandlerAssignments rewrites state-variable assignments inside an
// inline event handler expression, e.g.:
//
//	"($e) => visible = $e.target.checked"
//	→ "($e) => $$set_visible($e.target.checked)"
//
//	"($e) => { count = count + 1; step = 2; }"
//	→ "($e) => { $$set_count(count + 1); $$set_step(2); }"
//
// The component-level RewriteAssignments pass never sees template attribute
// strings, so this function handles them independently.
func (g *CodeGen) rewriteHandlerAssignments(handler string) string {
	// The template parser preserves the source `{…}` wrapper in
	// attribute values, so this function must strip it before doing
	// any string surgery — otherwise the outer braces get mistaken
	// for a block-statement body and the inner arrow ends up wrapped
	// in a useless `{ () => … }` block at the emission site.
	handler = unwrapBraces(handler)
	if len(g.analysis.StateVars) == 0 && len(g.analysis.Props) == 0 {
		return handler
	}
	ss := g.analysis.stateSet()

	// Find the arrow (=>) and extract the body portion.
	// This handles both concise bodies and block bodies.
	arrowIdx := strings.Index(handler, "=>")
	if arrowIdx < 0 {
		return handler // not an arrow — call RewriteAssignments on the whole thing
	}
	body := strings.TrimSpace(handler[arrowIdx+2:])
	params := handler[:arrowIdx+2] // everything up to and including =>

	// Block body: ($e) => { stmts }
	if strings.HasPrefix(body, "{") && strings.HasSuffix(strings.TrimSpace(body), "}") {
		// Strip outer braces, rewrite statements inside, restore braces
		inner := body[1 : len(body)-1]
		prog := ParseJS(inner)
		rewritten := RewriteAssignments(inner, prog, ss)
		return params + " { " + strings.TrimSpace(rewritten) + " }"
	}

	// Concise body: ($e) => expr
	// If it's a simple assignment `x = rhs`, rewrite it directly.
	// Parse as a statement by appending semicolon.
	bodyStmt := body + ";"
	prog := ParseJS(bodyStmt)
	rewritten := RewriteAssignments(bodyStmt, prog, ss)
	if rewritten != bodyStmt {
		// Strip trailing semicolon that RewriteAssignments or the original had
		rewritten = strings.TrimSpace(rewritten)
		rewritten = strings.TrimSuffix(rewritten, ";")
		return params + " " + strings.TrimSpace(rewritten)
	}

	return handler
}

func (g *CodeGen) emitEachChild(b *strings.Builder, node Node, parentVar string) {
	// Inline simple cases without full FragGen overhead (used in legacy paths)
	switch n := node.(type) {
	case *TextNode:
		expr := buildExpr(n.Parts)
		b.WriteString(fmt.Sprintf("      %s.appendChild(document.createTextNode(%s));\n",
			parentVar, expr))
	case *ElementNode:
		b.WriteString(fmt.Sprintf("      {\n"))
		b.WriteString(fmt.Sprintf("        const $$sub = document.createElement('%s');\n", n.Tag))
		b.WriteString(fmt.Sprintf("        $$sub.setAttribute('%s', '');\n", g.scopeID))
		for _, attr := range n.Attrs {
			if attr.IsBind {
				b.WriteString(bindAttrStmt("$$sub", attr.Name, attr.Value, "        ") + "\n")
			} else if !attr.IsEvent {
				b.WriteString(fmt.Sprintf("        $$sub.setAttribute('%s','%s');\n",
					attr.Name, escapeAttr(attr.Value)))
			}
		}
		for _, cc := range n.Children {
			g.emitEachChild(b, cc, "$$sub")
		}
		b.WriteString(fmt.Sprintf("        %s.appendChild($$sub);\n", parentVar))
		b.WriteString(fmt.Sprintf("      }\n"))
	}
}

// ──────────────────────────────────────────────
//  Reactive setters
// ──────────────────────────────────────────────

func (g *CodeGen) genSetter(name string) string {
	// Is this a deep-reactive state var?  Affects what we emit.
	deep := false
	for _, sv := range g.analysis.StateVars {
		if sv.Name == name {
			deep = sv.Deep
			break
		}
	}

	// Build the "notify" body — everything that runs after a value
	// change, regardless of whether the change came from a
	// reassignment ($$set_X) or from a deep-proxy mutation
	// ($$mut_X via $$proxy traps).  This used to be inlined inside
	// $$set_X; extracting it lets deep state run the same reactions
	// on in-place mutations like arr.push(x).
	var notify strings.Builder

	// Fire $$onChange for bindable props so parent can observe.
	// For mutation-based notifies the new value IS the same reference
	// (we mutated it), but the parent still wants to know — and the
	// no-op guard in their setter will short-circuit if appropriate.
	for _, prop := range g.analysis.Props {
		if prop.Name == name && prop.Bindable {
			notify.WriteString(fmt.Sprintf(
				"    if ($$onChange_%s) $$onChange_%s(%s);\n", name, name, name))
		}
	}

	// Recompute derived vars that (transitively) depend on this var
	for _, dv := range g.analysis.DerivedVars {
		if containsStr(dv.Deps, name) {
			notify.WriteString(fmt.Sprintf("    $$upd_%s();\n", dv.Name))
		}
	}

	// Collect DOM updates: direct + via derived.
	//
	// Ordering matters. A single setter can fire both:
	//   (a) STRUCTURAL updates — $$chain_N() / $$each_N(arr) / $$ceach_N(...) —
	//       which mount or unmount conditional DOM subtrees,
	//   (b) ATTRIBUTE updates — elem.setAttribute(..., String(x.y)) etc. —
	//       which read into that same DOM subtree.
	//
	// If (b) runs before (a), a transition from "object" → "null" (e.g.
	// `editTarget = null` after saving a modal form) crashes: the branch is
	// still mounted, its guard `if ($$chain_N_b0)` passes, so the attribute
	// update dereferences `null.someField`. Running (a) first unmounts the
	// branch, nulls the cached element var, and (b) cleanly no-ops.
	//
	// Going the other direction (null → object) the order is equally fine:
	// (a) mounts the branch first, (b) then populates its attributes.
	//
	// All DOM-touching calls are wrapped in $$defer so that when multiple
	// setters fire from the same store notification batch, DOM updates wait
	// until every state variable has been assigned its new value.
	seen := map[string]bool{}
	var structural, attr []string
	collect := func(u string) {
		if seen[u] {
			return
		}
		seen[u] = true
		if isStructuralUpdate(u) {
			structural = append(structural, u)
		} else {
			attr = append(attr, u)
		}
	}

	for _, u := range g.updates[name] {
		collect(u)
	}
	for _, dv := range g.analysis.DerivedVars {
		if containsStr(dv.Deps, name) {
			for _, u := range g.updates[dv.Name] {
				collect(u)
			}
		}
	}

	// Emit one bundled $$defer per setter, with all updates as statements
	// inside a single closure body.  Reduces per-setter-call cost from
	// N closure allocations + N queue pushes + N flush invocations to
	// 1 / 1 / 1 — significant savings for setters that touch many DOM
	// positions (e.g. App.$$set_user fires 3 updates, $$set_loading fires 2-4).
	//
	// Ordering preserved: structural updates emitted before attribute
	// updates inside the same closure, so structural changes (chain
	// re-render, each reconcile) still happen before attribute reads.
	//
	// Trade-off: if one statement throws, subsequent statements in the
	// same closure don't run.  Pre-consolidation, the queue continued with
	// the next $$defer's fn after an exception.  In practice this rarely
	// matters: the existing code guards each update with `if ($$chain_X_b0)`
	// when the ref might be null, so the "throw" case is already prevented.
	if len(structural) > 0 || len(attr) > 0 {
		notify.WriteString("    $$defer(() => {\n")
		for _, u := range structural {
			notify.WriteString(fmt.Sprintf("      %s\n", strings.TrimSpace(u)))
		}
		for _, u := range attr {
			notify.WriteString(fmt.Sprintf("      %s\n", strings.TrimSpace(u)))
		}
		notify.WriteString("    });\n")
	}

	// Trigger effects
	for i, eff := range g.analysis.Effects {
		if containsStr(eff.Deps, name) {
			notify.WriteString(fmt.Sprintf("    $$effect%d();\n", i))
		}
	}

	notifyBody := notify.String()

	// Build the final emission.
	var b strings.Builder

	// For deep state, expose the notify body under a stable name so
	// the $$mut_X arrow declared earlier (forward reference) can
	// reach it.  Plain setters need no separate notify function —
	// the body just lives inline.
	if deep {
		b.WriteString(fmt.Sprintf("  function $$set_%s_notify() {\n", name))
		b.WriteString(notifyBody)
		b.WriteString("  }\n")
	}

	b.WriteString(fmt.Sprintf("  function $$set_%s($$v) {\n", name))
	// Early-return on no-op writes.  Two reasons:
	//   1. Breaks the two-way binding cycle.  When `bind:x={y}` wires
	//      child→parent via $$onChange_x and parent→child via
	//      `instance.set({x: y})`, a single user write would otherwise
	//      bounce between $$set_y (parent) and $$set_x (child)
	//      indefinitely.  Detecting "value didn't change" stops the
	//      ping-pong on the second hop.
	//   2. Skips redundant DOM updates and downstream callbacks.
	// Identity comparison matches Svelte semantics — writing a fresh
	// object with the same contents is still considered a change.
	b.WriteString(fmt.Sprintf("    if (%s === $$v) return;\n", name))
	if deep {
		// Reassigning a deep-state variable wraps the incoming value
		// in a fresh proxy so subsequent mutations on the new value
		// also fire updates.  The old proxy is dropped along with its
		// WeakMap cache.
		b.WriteString(fmt.Sprintf("    %s = $$proxy($$v, $$mut_%s);\n", name, name))
		b.WriteString(fmt.Sprintf("    $$set_%s_notify();\n", name))
	} else {
		b.WriteString(fmt.Sprintf("    %s = $$v;\n", name))
		b.WriteString(notifyBody)
	}
	b.WriteString("  }\n")
	return b.String()
}

func (g *CodeGen) addUpdate(dep, code string) {
	g.addUpdateSeen(dep, code, map[string]bool{})
}

// addUpdateSeen is the recursive helper for addUpdate. If dep is a DerivedVar,
// it recursively registers the update for all of that derived var's own deps
// (which may themselves be derived), eventually reaching state vars and props.
// This ensures that e.g. {#each filtered as o} inside a Card slot correctly
// re-renders when allOrders changes — even though the each expression uses the
// derived name "filtered", not "allOrders" directly.
func (g *CodeGen) addUpdateSeen(dep, code string, seen map[string]bool) {
	if seen[dep] {
		return // guard against circular deps
	}
	seen[dep] = true
	for _, dv := range g.analysis.DerivedVars {
		if dv.Name == dep {
			// dep is a derived var — register for each of its source deps
			for _, srcDep := range findDeps(dv.Expr, g.analysis.reactiveNames()) {
				g.addUpdateSeen(srcDep, code, seen)
			}
			return
		}
	}
	// dep is a state var or prop — register directly
	g.updates[dep] = append(g.updates[dep], code)
}

