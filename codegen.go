package main

import (
	"fmt"
	"strings"
)

// ──────────────────────────────────────────────
//  CodeGen — walks the template AST and emits
//  a self-contained ES module component.
// ──────────────────────────────────────────────

type CodeGen struct {
	name     string
	scopeID  string
	analysis *Analysis
	sfc      *SFC
	counter  int

	// Accumulated code sections
	create  strings.Builder // DOM node creation
	wire    strings.Builder // appendChild / structural wiring
	events  strings.Builder // addEventListener calls
	init    strings.Builder // initial property assignments
	cleanup strings.Builder // removeEventListener / teardown

	// Map: reactive-var-name → list of JS update statements
	updates map[string][]string
}

func generateCode(
	name string,
	sfc *SFC,
	nodes []Node,
	analysis *Analysis,
	scopeID string,
) string {
	g := &CodeGen{
		name:     name,
		scopeID:  scopeID,
		analysis: analysis,
		sfc:      sfc,
		updates:  make(map[string][]string),
	}
	return g.emit(nodes)
}

func (g *CodeGen) id() string {
	id := g.counter
	g.counter++
	return fmt.Sprintf("$$n%d", id)
}

// ──────────────────────────────────────────────
//  Top-level emit
// ──────────────────────────────────────────────

func (g *CodeGen) emit(nodes []Node) string {
	var out strings.Builder

	// ── File header ─────────────────────────
	out.WriteString("// Generated by Vela Compiler — do not edit\n\n")

	// ── Re-exports / imports ─────────────────
	for _, imp := range g.analysis.Imports {
		src := imp.Source
		if src == "vela/store" || src == "vela" {
			src = "./runtime.js"
		} else {
			src = RewriteImportPath(src) // .vela → .js, extensionless → .js
		}
		out.WriteString(fmt.Sprintf("import %s from '%s';\n", imp.Spec, src))
	}
	if len(g.analysis.Imports) > 0 {
		out.WriteString("\n")
	}

	// ── Component factory function ───────────
	out.WriteString(fmt.Sprintf(
		"export function %s($$target, $$props, $$slots) {\n", g.name))
	out.WriteString("  $$props = Object.assign({}, $$props);\n")
	out.WriteString("  $$slots = $$slots || {};\n\n")

	// ── $$dispatch — fire CustomEvents upward ─────────────────────────────
	out.WriteString("  function $$dispatch(name, detail) {\n")
	out.WriteString("    $$target.dispatchEvent(new CustomEvent(name, { detail, bubbles: true }));\n")
	out.WriteString("  }\n\n")

	// ── Props — populated from $$props, reactive via setters ─────────────
	if len(g.analysis.Props) > 0 {
		out.WriteString("  // props\n")
		for _, prop := range g.analysis.Props {
			if prop.Default != "" {
				out.WriteString(fmt.Sprintf(
					"  let %s = $$props.%s !== undefined ? $$props.%s : %s;\n",
					prop.Name, prop.Name, prop.Name, prop.Default))
			} else {
				out.WriteString(fmt.Sprintf("  let %s = $$props.%s;\n", prop.Name, prop.Name))
			}
		}
		out.WriteString("\n")
		// Bindable prop: a $$onChange_X callback lets parent observe changes
		for _, prop := range g.analysis.Props {
			if prop.Bindable {
				out.WriteString(fmt.Sprintf(
					"  const $$onChange_%s = $$props.$$onChange_%s || null;\n",
					prop.Name, prop.Name))
			}
		}
		if hasBind := func() bool {
			for _, p := range g.analysis.Props {
				if p.Bindable {
					return true
				}
			}
			return false
		}(); hasBind {
			out.WriteString("\n")
		}
	}

	// ── Scoped <style> injection ─────────────
	if g.sfc.Style != "" {
		css := ScopeCSS(g.sfc.Style, g.scopeID)
		out.WriteString("  // scoped styles\n")
		out.WriteString("  const $$style = document.createElement('style');\n")
		out.WriteString("  $$style.textContent = " + backtickString(css) + ";\n")
		out.WriteString("  document.head.appendChild($$style);\n\n")
	}

	// ── State variables ──────────────────────
	if len(g.analysis.StateVars) > 0 {
		out.WriteString("  // state\n")
		for _, sv := range g.analysis.StateVars {
			out.WriteString(fmt.Sprintf("  let %s = %s;\n", sv.Name, sv.Initial))
		}
		out.WriteString("\n")
	}

	// ── Derived variables + updaters ─────────
	if len(g.analysis.DerivedVars) > 0 {
		out.WriteString("  // derived\n")
		for _, dv := range g.analysis.DerivedVars {
			out.WriteString(fmt.Sprintf("  let %s;\n", dv.Name))
		}
		for _, dv := range g.analysis.DerivedVars {
			out.WriteString(fmt.Sprintf("  const $$upd_%s = () => { %s = %s; };\n",
				dv.Name, dv.Name, dv.Expr))
		}
		out.WriteString("\n")
	}

	// ── Effect wrapper functions ──────────────
	if len(g.analysis.Effects) > 0 {
		out.WriteString("  // effects\n")
		for i, eff := range g.analysis.Effects {
			// $$cleanupN stores the effect's return value (e.g. an unsubscribe
			// function). It is called before the effect re-runs so stale
			// subscriptions / listeners are torn down.
			out.WriteString(fmt.Sprintf("  let $$cleanup%d = null;\n", i))
			out.WriteString(fmt.Sprintf("  const $$effect%d = () => {\n", i))
			out.WriteString(fmt.Sprintf("    if ($$cleanup%d) { $$cleanup%d(); $$cleanup%d = null; }\n", i, i, i))
			out.WriteString(fmt.Sprintf("    $$cleanup%d = (function() {\n", i))
			for _, line := range strings.Split(eff.Body, "\n") {
				t := strings.TrimSpace(line)
				if t != "" {
					out.WriteString("      " + t + "\n")
				}
			}
			out.WriteString(fmt.Sprintf("    })();\n"))
			out.WriteString("  };\n")
		}
		out.WriteString("\n")
	}

	// ── Walk template → fill create/wire/events/init/cleanup ──
	//
	// $$root must always be declared because mount/destroy reference it.
	// When the template's first node IS an ElementNode, walkNodes assigns
	// varName="$$root" to it (zero extra wrapper).
	// When the first node is NOT an ElementNode (e.g. the template starts
	// with {#if ...} or {#each ...}), no element gets that name, causing
	// "$$root is not defined". Fix: always emit a transparent wrapper div
	// when the template root is non-element, and walk the nodes as its children.
	needsWrapper := len(nodes) == 0
	if !needsWrapper {
		_, firstIsElem := nodes[0].(*ElementNode)
		needsWrapper = !firstIsElem
	}

	if needsWrapper {
		// Emit an invisible wrapper div as $$root; all template nodes become its children.
		g.create.WriteString("  const $$root = document.createElement('div');\n")
		g.create.WriteString(fmt.Sprintf("  $$root.setAttribute('%s', '');\n", g.scopeID))
		g.create.WriteString("  $$root.style.display = 'contents';\n")
		g.walkChildren(nodes, "$$root")
	} else {
		g.walkNodes(nodes, "$$root", true)
	}

	// ── Emit DOM creation ─────────────────────
	out.WriteString("  // DOM\n")
	out.WriteString(g.create.String())
	if g.wire.Len() > 0 {
		out.WriteString(g.wire.String())
	}
	out.WriteString("\n")

	// ── User script (component logic, functions, etc.) ─────────────────────────
	if g.analysis.CleanScript != "" {
		out.WriteString("  // component logic\n")
		for _, line := range strings.Split(g.analysis.CleanScript, "\n") {
			trimmed := strings.TrimSpace(line)
			if trimmed == "" {
				continue
			}
			// Skip import lines — emitted at the top of the file before export function.
			// They must NOT appear inside the function body (JS syntax error).
			if strings.HasPrefix(trimmed, "import ") || strings.HasPrefix(trimmed, "import{") {
				continue
			}
			out.WriteString("  " + line + "\n")
		}
		out.WriteString("\n")
	}

	// ── Reactive setters (state + props) ─────────────────────────────────────
	if len(g.analysis.StateVars) > 0 || len(g.analysis.Props) > 0 {
		out.WriteString("  // reactive setters\n")
		// $$defer is registered in runtime.js on globalThis[Symbol.for('vela.defer')].
		// Fallback to fn() keeps components functional even if runtime isn't loaded yet.
		out.WriteString("  const $$defer = globalThis[Symbol.for('vela.defer')] ?? (fn => fn());\n")
		for _, sv := range g.analysis.StateVars {
			out.WriteString(g.genSetter(sv.Name))
		}
		for _, prop := range g.analysis.Props {
			out.WriteString(g.genSetter(prop.Name))
		}
		out.WriteString("\n")
	}

	// ── Event listeners ──────────────────────
	if g.events.Len() > 0 {
		out.WriteString("  // events\n")
		out.WriteString(g.events.String())
		out.WriteString("\n")
	}

	// ── Initial derived computation ───────────
	if len(g.analysis.DerivedVars) > 0 {
		out.WriteString("  // initialise derived\n")
		for _, dv := range g.analysis.DerivedVars {
			out.WriteString(fmt.Sprintf("  $$upd_%s();\n", dv.Name))
		}
		out.WriteString("\n")
	}

	// ── Initial DOM hydration ─────────────────
	// Component constructors (Card, Modal, etc.) run here, which calls slot
	// functions and inserts anchor comments into the DOM. Effects MUST run
	// after this so that any immediately-firing subscribe callbacks can safely
	// call $$each / $$chain functions whose anchors already have a parentNode.
	if g.init.Len() > 0 {
		out.WriteString("  // initial render\n")
		out.WriteString(g.init.String())
		out.WriteString("\n")
	}

	// ── Run initial effects ─────────────────────────────────────────────────
	// Placed AFTER initial render so subscribe callbacks that fire immediately
	// (e.g. chartData.subscribe → $$set_chart → $$each_N) find their anchor
	// comments already parented inside the live DOM.
	for i := range g.analysis.Effects {
		out.WriteString(fmt.Sprintf("  $$effect%d();\n", i))
	}
	if len(g.analysis.Effects) > 0 {
		out.WriteString("\n")
	}

	// ── Mount ────────────────────────────────
	out.WriteString("  // mount\n")
	out.WriteString("  $$target.appendChild($$root);\n\n")

	// ── onMount callbacks (after DOM is inserted) ─────────────────────────
	// The onMount body is wrapped in an IIFE. Any `return fn` inside the
	// callback is the *cleanup return* (like an effect cleanup), NOT the
	// component's { destroy, set } return. Without the IIFE the `return`
	// exits the component factory function entirely, breaking e.g. Toast
	// auto-dismiss where onMount returns `() => clearTimeout(t)`.
	for i, lc := range g.analysis.Lifecycles {
		if lc.Kind == "onMount" {
			cleanupVar := fmt.Sprintf("$$mountCleanup%d", i)
			out.WriteString(fmt.Sprintf("  const %s = (function() {\n", cleanupVar))
			for _, line := range strings.Split(lc.Body, "\n") {
				if strings.TrimSpace(line) != "" {
					out.WriteString("    " + line + "\n")
				}
			}
			out.WriteString("  })();\n\n")
		}
	}

	// ── Return handle ─────────────────────────
	out.WriteString("  return {\n")
	out.WriteString("    destroy() {\n")
	// Run effect cleanups first (e.g. unsubscribe from stores)
	for i := range g.analysis.Effects {
		out.WriteString(fmt.Sprintf("      if ($$cleanup%d) { $$cleanup%d(); }\n", i, i))
	}
	// Run onMount cleanup functions (e.g. clearTimeout from Toast auto-dismiss)
	for i, lc := range g.analysis.Lifecycles {
		if lc.Kind == "onMount" {
			cleanupVar := fmt.Sprintf("$$mountCleanup%d", i)
			out.WriteString(fmt.Sprintf(
				"      if (typeof %s === 'function') { %s(); }\n", cleanupVar, cleanupVar))
		}
	}
	// onDestroy callbacks
	for _, lc := range g.analysis.Lifecycles {
		if lc.Kind == "onDestroy" {
			for _, line := range strings.Split(lc.Body, "\n") {
				if strings.TrimSpace(line) != "" {
					out.WriteString("      " + line + "\n")
				}
			}
		}
	}
	out.WriteString(g.cleanup.String())
	if g.sfc.Style != "" {
		out.WriteString("      $$style.remove();\n")
	}
	out.WriteString("      $$root.remove();\n")
	out.WriteString("    },\n")

	// set() accepts state vars AND props from parent
	hasSettable := len(g.analysis.StateVars) > 0 || len(g.analysis.Props) > 0
	if hasSettable {
		out.WriteString("    set(props) {\n")
		for _, sv := range g.analysis.StateVars {
			out.WriteString(fmt.Sprintf(
				"      if (props.%s !== undefined) $$set_%s(props.%s);\n",
				sv.Name, sv.Name, sv.Name))
		}
		for _, prop := range g.analysis.Props {
			out.WriteString(fmt.Sprintf(
				"      if (props.%s !== undefined) $$set_%s(props.%s);\n",
				prop.Name, prop.Name, prop.Name))
		}
		out.WriteString("    },\n")
	}

	out.WriteString("  };\n")
	out.WriteString("}\n")

	return out.String()
}

// ──────────────────────────────────────────────
//  Template walking
// ──────────────────────────────────────────────

func (g *CodeGen) walkNodes(nodes []Node, parentVar string, isRootList bool) {
	for i, node := range nodes {
		switch n := node.(type) {
		case *ElementNode:
			varName := g.id()
			if isRootList && i == 0 {
				varName = "$$root"
			}
			g.walkElement(n, varName, parentVar, isRootList && i == 0)
		case *IfChainNode:
			g.walkIfChain(n, parentVar)
		case *EachBlockNode:
			g.walkEachBlock(n, parentVar)
		case *ComponentNode:
			if n.EachExpr != "" {
				g.walkComponentEach(n, parentVar)
			} else if n.IfCond != "" {
				g.walkComponentIf(n, parentVar)
			} else {
				g.walkComponent(n, parentVar)
			}
		case *SlotNode:
			g.walkSlot(n, parentVar)
		case *TextNode:
			g.walkText(n, parentVar)
		}
	}
}

func (g *CodeGen) walkElement(elem *ElementNode, varName, parentVar string, isRoot bool) {
	// #each takes precedence over #if
	if elem.EachExpr != "" {
		g.walkEach(elem, varName, parentVar)
		return
	}
	if elem.IfCond != "" {
		g.walkIf(elem, varName, parentVar)
		return
	}

	// Create element
	g.create.WriteString(fmt.Sprintf("  const %s = document.createElement('%s');\n", varName, elem.Tag))
	g.create.WriteString(fmt.Sprintf("  %s.setAttribute('%s', '');\n", varName, g.scopeID))

	// Static attributes
	for _, attr := range elem.Attrs {
		switch {
		case attr.IsEvent:
			handler := g.rewriteHandlerAssignments(attr.Value)
			if isSimpleIdent(handler) {
				g.events.WriteString(fmt.Sprintf(
					"  %s.addEventListener('%s', %s);\n", varName, attr.Name, handler))
				g.cleanup.WriteString(fmt.Sprintf(
					"      %s.removeEventListener('%s', %s);\n", varName, attr.Name, handler))
			} else if isHandlerExpr(handler) {
				hv := varName + "_" + attr.Name + "_h"
				g.create.WriteString(fmt.Sprintf("  const %s = %s;\n", hv, handler))
				g.events.WriteString(fmt.Sprintf(
					"  %s.addEventListener('%s', %s);\n", varName, attr.Name, hv))
				g.cleanup.WriteString(fmt.Sprintf(
					"      %s.removeEventListener('%s', %s);\n", varName, attr.Name, hv))
			} else {
				hv := varName + "_" + attr.Name + "_h"
				g.create.WriteString(fmt.Sprintf(
					"  const %s = ($event) => { %s; };\n", hv, handler))
				g.events.WriteString(fmt.Sprintf(
					"  %s.addEventListener('%s', %s);\n", varName, attr.Name, hv))
				g.cleanup.WriteString(fmt.Sprintf(
					"      %s.removeEventListener('%s', %s);\n", varName, attr.Name, hv))
			}

		case attr.IsBind:
			deps := findDeps(attr.Value, g.analysis.reactiveNames())
			upd := bindAttrStmt(varName, attr.Name, attr.Value, "  ")
			g.init.WriteString(upd + "\n")
			for _, dep := range deps {
				g.addUpdate(dep, upd)
			}
			// Two-way binding: :value on input/textarea also wires an input listener
			if attr.Name == "value" && (elem.Tag == "input" || elem.Tag == "textarea") {
				if g.analysis.isStateName(attr.Value) {
					sv := attr.Value
					g.events.WriteString(fmt.Sprintf(
						"  %s.addEventListener('input', ($e) => $$set_%s($e.target.value));\n",
						varName, sv))
					g.cleanup.WriteString(fmt.Sprintf(
						"      %s.removeEventListener('input', ($e) => $$set_%s($e.target.value));\n",
						varName, sv))
				}
			}

		default:
			// Static attribute
			g.create.WriteString(fmt.Sprintf(
				"  %s.setAttribute('%s', '%s');\n", varName, attr.Name, escapeAttr(attr.Value)))
		}
	}

	// Recurse into children
	g.walkChildren(elem.Children, varName)

	// Append to parent (unless this IS the root placeholder)
	if !isRoot {
		g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, varName))
	}
}

func (g *CodeGen) walkChildren(children []Node, parentVar string) {
	for _, child := range children {
		switch c := child.(type) {
		case *ElementNode:
			cv := g.id()
			g.walkElement(c, cv, parentVar, false)
		case *IfChainNode:
			g.walkIfChain(c, parentVar)
		case *EachBlockNode:
			g.walkEachBlock(c, parentVar)
		case *ComponentNode:
			if c.EachExpr != "" {
				g.walkComponentEach(c, parentVar)
			} else if c.IfCond != "" {
				g.walkComponentIf(c, parentVar)
			} else {
				g.walkComponent(c, parentVar)
			}
		case *SlotNode:
			g.walkSlot(c, parentVar)
		case *TextNode:
			g.walkText(c, parentVar)
		}
	}
}

func (g *CodeGen) walkText(node *TextNode, parentVar string) {
	allStatic := true
	for _, p := range node.Parts {
		if !p.Static {
			allStatic = false
			break
		}
	}

	if allStatic {
		text := ""
		for _, p := range node.Parts {
			text += p.Value
		}
		if strings.TrimSpace(text) == "" {
			return
		}
		g.wire.WriteString(fmt.Sprintf(
			"  %s.appendChild(document.createTextNode(%s));\n",
			parentVar, backtickString(text)))
		return
	}

	tv := g.id()
	expr := buildExpr(node.Parts)
	deps := findDeps(expr, g.analysis.reactiveNames())

	g.create.WriteString(fmt.Sprintf("  const %s = document.createTextNode('');\n", tv))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, tv))
	g.init.WriteString(fmt.Sprintf("  %s.data = %s;\n", tv, expr))
	for _, dep := range deps {
		g.addUpdate(dep, fmt.Sprintf("  %s.data = %s;", tv, expr))
	}
}

// ──────────────────────────────────────────────
//  #if / #elseif / #else chains
// ──────────────────────────────────────────────

// walkIfChain generates a single update function that evaluates each branch
// condition in order and mounts/unmounts the correct DOM fragment.
//
//	$$ifchain_N($$branch) where $$branch is the index of the active branch,
//	or -1 for "none" (all conditions false and no #else).
//
// Each branch's element is cached in a dedicated variable so it is created
// at most once and re-used on subsequent re-evaluations.
func (g *CodeGen) walkIfChain(chain *IfChainNode, parentVar string) {
	// If every branch has a Comp (ComponentNode), use walkComponentIfChain
	allComp := true
	for _, b := range chain.Branches {
		if b.Comp == nil {
			allComp = false
			break
		}
	}
	if allComp {
		g.walkComponentIfChain(chain, parentVar)
		return
	}

	anchor := g.id() + "_a"
	fn := "$$chain_" + g.id()

	// One cached element variable per branch
	elVars := make([]string, len(chain.Branches))
	for i := range chain.Branches {
		elVars[i] = fmt.Sprintf("%s_b%d", fn, i)
	}

	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('if-chain');\n", anchor))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))
	for _, ev := range elVars {
		g.create.WriteString(fmt.Sprintf("  let %s = null;\n", ev))
	}

	// Build the chain update function with a re-entrancy guard.
	// Child components mounted inside a branch can synchronously trigger store
	// subscriptions that re-invoke this same chain function before the current
	// invocation has finished building its branch element. Without the guard,
	// the second call would null out the branch variable that the first call is
	// still working on, causing "$$chain_…_bN is null" TypeErrors.
	// The guard records a pending re-run and defers it to after the first call
	// completes so each invocation sees a fully-built DOM.
	runningFlag := fn + "_running"
	pendingFlag := fn + "_pending"
	g.create.WriteString(fmt.Sprintf("  let %s = false, %s = false;\n", runningFlag, pendingFlag))

	var fnBuf strings.Builder
	fnBuf.WriteString(fmt.Sprintf("  function %s() {\n", fn))
	fnBuf.WriteString(fmt.Sprintf("    if (%s) { %s = true; return; }\n", runningFlag, pendingFlag))
	fnBuf.WriteString(fmt.Sprintf("    %s = true;\n", runningFlag))
	fnBuf.WriteString(fmt.Sprintf("    try {\n"))

	// Evaluate which branch is active
	fnBuf.WriteString("      let $$active = -1;\n")
	for i, branch := range chain.Branches {
		if branch.Cond == "" {
			fnBuf.WriteString(fmt.Sprintf("      if ($$active < 0) $$active = %d;\n", i))
		} else {
			fnBuf.WriteString(fmt.Sprintf("      if ($$active < 0 && (%s)) $$active = %d;\n",
				branch.Cond, i))
		}
	}

	// Remove any currently mounted branch that's no longer active.
	// Also null out all component-scope vars declared for each branch's children
	// so reactive updates guarded by `if (ev)` correctly skip inactive branches.
	// branchDeclared[i] is populated by emitBranchChildren below.
	branchDeclared := make([][]string, len(chain.Branches))
	for i, ev := range elVars {
		fnBuf.WriteString(fmt.Sprintf("      if ($$active !== %d && %s) { %s.remove(); %s = null;",
			i, ev, ev, ev))
		// Null-outs appended after emitBranchChildren fills branchDeclared[i]
		// — we'll fill in a placeholder and replace it once we know the vars.
		fnBuf.WriteString(fmt.Sprintf(" /* __null_%d__ */ }\n", i))
	}

	// Mount the active branch.
	// Each branch is created once and cached.  When a cached branch's anchor
	// regains a parentNode (e.g. Modal slot content re-entering the DOM), we
	// re-insert it so the content appears.
	for i, branch := range chain.Branches {
		ev := elVars[i]
		fnBuf.WriteString(fmt.Sprintf("      if ($$active === %d) {\n", i))
		fnBuf.WriteString(fmt.Sprintf("        if (!%s) {\n", ev))

		// Svelte-style {#if} blocks have no wrapper element (Elem == nil).
		// Use a plain <div> as a transparent container.
		tag := "div"
		var elemAttrs []*Attr
		if branch.Elem != nil {
			tag = branch.Elem.Tag
			elemAttrs = branch.Elem.Attrs
		}

		fnBuf.WriteString(fmt.Sprintf("          %s = document.createElement('%s');\n", ev, tag))
		fnBuf.WriteString(fmt.Sprintf("          %s.setAttribute('%s', '');\n", ev, g.scopeID))

		// Attrs on the branch container element (attribute-syntax branches).
		for _, attr := range elemAttrs {
			if attr.IsEvent {
				handler := g.rewriteHandlerAssignments(attr.Value)
				fnBuf.WriteString(fmt.Sprintf("          %s.addEventListener('%s', %s);\n",
					ev, attr.Name, handler))
			} else if attr.IsBind {
				fnBuf.WriteString(bindAttrStmt(ev, attr.Name, attr.Value, "          ") + "\n")
				// Register reactive update for container bound attrs — guarded by ev (branch active)
				updateStmt := fmt.Sprintf("  if (%s) %s", ev,
					strings.TrimSpace(bindAttrStmt(ev, attr.Name, attr.Value, "")))
				for _, dep := range findDeps(attr.Value, g.analysis.reactiveNames()) {
					g.addUpdate(dep, updateStmt)
				}
			} else {
				fnBuf.WriteString(fmt.Sprintf("          %s.setAttribute('%s', '%s');\n",
					ev, attr.Name, escapeAttr(attr.Value)))
			}
		}

		// Emit children — lifted vars land in g.create, attr/text updates in g.addUpdate.
		// branchVar = ev so updates are guarded by the branch container being active.
		branchDeclared[i] = g.emitBranchChildren(&fnBuf, ev, branch.Children, ev, "          ")

		fnBuf.WriteString(fmt.Sprintf("          %[1]s.before(%[2]s);\n", anchor, ev))
		fnBuf.WriteString("        }\n")
		// Re-insert if anchor has a live parent but the branch is in a different parent.
		fnBuf.WriteString(fmt.Sprintf(
			"        if (%[1]s.parentNode && %[2]s.parentNode !== %[1]s.parentNode) { %[1]s.before(%[2]s); }\n",
			anchor, ev))
		fnBuf.WriteString("      }\n")
	}
	fnBuf.WriteString(fmt.Sprintf("    } finally {\n"))
	fnBuf.WriteString(fmt.Sprintf("      %s = false;\n", runningFlag))
	fnBuf.WriteString(fmt.Sprintf("      if (%s) { %s = false; %s(); }\n", pendingFlag, pendingFlag, fn))
	fnBuf.WriteString("    }\n")
	fnBuf.WriteString("  }\n")

	// Back-fill the null-out statements for each branch's declared vars.
	// Component instance vars (suffix _comp) get .destroy() called before
	// being nulled so their event listeners and styles are cleaned up.
	fnStr := fnBuf.String()
	for i, vars := range branchDeclared {
		nullStmts := ""
		for _, v := range vars {
			if strings.HasSuffix(v, "_comp") {
				nullStmts += fmt.Sprintf(" if (%s) { %s.destroy(); %s = null; }", v, v, v)
			} else {
				nullStmts += fmt.Sprintf(" %s = null;", v)
			}
		}
		fnStr = strings.Replace(fnStr, fmt.Sprintf(" /* __null_%d__ */", i), nullStmts, 1)
	}
	g.create.WriteString(fnStr)

	// Chain function only re-runs when the CONDITION changes — not when inner
	// content (attrs, text) changes. Content changes go directly to g.addUpdate
	// via emitBranchChildren, so they update the DOM without re-running the chain.
	allDeps := map[string]bool{}
	for _, branch := range chain.Branches {
		for _, d := range findDeps(branch.Cond, g.analysis.reactiveNames()) {
			allDeps[d] = true
		}
		// Container element bound attrs also control visibility logic
		if branch.Elem != nil {
			for _, attr := range branch.Elem.Attrs {
				if attr.IsBind {
					for _, d := range findDeps(attr.Value, g.analysis.reactiveNames()) {
						allDeps[d] = true
					}
				}
			}
		}
	}

	call := fmt.Sprintf("  %s();", fn)
	g.init.WriteString(call + "\n")
	for dep := range allDeps {
		g.addUpdate(dep, call)
	}
}

