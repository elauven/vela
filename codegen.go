package main

import (
	"fmt"
	"strings"
)

// ──────────────────────────────────────────────
//  CodeGen — walks the template AST and emits
//  a self-contained ES module component.
// ──────────────────────────────────────────────

type CodeGen struct {
	name     string
	scopeID  string
	analysis *Analysis
	sfc      *SFC
	counter  int

	// Accumulated code sections
	create  strings.Builder // DOM node creation
	wire    strings.Builder // appendChild / structural wiring
	events  strings.Builder // addEventListener calls
	init    strings.Builder // initial property assignments
	cleanup strings.Builder // removeEventListener / teardown

	// Map: reactive-var-name → list of JS update statements
	updates map[string][]string
}

func generateCode(
	name string,
	sfc *SFC,
	nodes []Node,
	analysis *Analysis,
	scopeID string,
) string {
	g := &CodeGen{
		name:     name,
		scopeID:  scopeID,
		analysis: analysis,
		sfc:      sfc,
		updates:  make(map[string][]string),
	}
	return g.emit(nodes)
}

func (g *CodeGen) id() string {
	id := g.counter
	g.counter++
	return fmt.Sprintf("$$n%d", id)
}

// ──────────────────────────────────────────────
//  Top-level emit
// ──────────────────────────────────────────────

func (g *CodeGen) emit(nodes []Node) string {
	var out strings.Builder

	// ── File header ─────────────────────────
	out.WriteString("// Generated by Vela Compiler — do not edit\n\n")

	// ── Re-exports / imports ─────────────────
	for _, imp := range g.analysis.Imports {
		src := imp.Source
		if src == "vela/store" || src == "vela" {
			src = "./runtime.js"
		}
		out.WriteString(fmt.Sprintf("import %s from '%s';\n", imp.Spec, src))
	}
	if len(g.analysis.Imports) > 0 {
		out.WriteString("\n")
	}

	// ── Component factory function ───────────
	out.WriteString(fmt.Sprintf(
		"export function %s($$target, $$props, $$slots) {\n", g.name))
	out.WriteString("  $$props = Object.assign({}, $$props);\n")
	out.WriteString("  $$slots = $$slots || {};\n\n")

	// ── $$dispatch — fire CustomEvents upward ─────────────────────────────
	out.WriteString("  function $$dispatch(name, detail) {\n")
	out.WriteString("    $$target.dispatchEvent(new CustomEvent(name, { detail, bubbles: true }));\n")
	out.WriteString("  }\n\n")

	// ── Props — populated from $$props, reactive via setters ─────────────
	if len(g.analysis.Props) > 0 {
		out.WriteString("  // props\n")
		for _, prop := range g.analysis.Props {
			if prop.Default != "" {
				out.WriteString(fmt.Sprintf(
					"  let %s = $$props.%s !== undefined ? $$props.%s : %s;\n",
					prop.Name, prop.Name, prop.Name, prop.Default))
			} else {
				out.WriteString(fmt.Sprintf("  let %s = $$props.%s;\n", prop.Name, prop.Name))
			}
		}
		out.WriteString("\n")
		// Bindable prop: a $$onChange_X callback lets parent observe changes
		for _, prop := range g.analysis.Props {
			if prop.Bindable {
				out.WriteString(fmt.Sprintf(
					"  const $$onChange_%s = $$props.$$onChange_%s || null;\n",
					prop.Name, prop.Name))
			}
		}
		if hasBind := func() bool {
			for _, p := range g.analysis.Props {
				if p.Bindable {
					return true
				}
			}
			return false
		}(); hasBind {
			out.WriteString("\n")
		}
	}

	// ── Scoped <style> injection ─────────────
	if g.sfc.Style != "" {
		css := ScopeCSS(g.sfc.Style, g.scopeID)
		out.WriteString("  // scoped styles\n")
		out.WriteString("  const $$style = document.createElement('style');\n")
		out.WriteString("  $$style.textContent = " + backtickString(css) + ";\n")
		out.WriteString("  document.head.appendChild($$style);\n\n")
	}

	// ── State variables ──────────────────────
	if len(g.analysis.StateVars) > 0 {
		out.WriteString("  // state\n")
		for _, sv := range g.analysis.StateVars {
			out.WriteString(fmt.Sprintf("  let %s = %s;\n", sv.Name, sv.Initial))
		}
		out.WriteString("\n")
	}

	// ── Derived variables + updaters ─────────
	if len(g.analysis.DerivedVars) > 0 {
		out.WriteString("  // derived\n")
		for _, dv := range g.analysis.DerivedVars {
			out.WriteString(fmt.Sprintf("  let %s;\n", dv.Name))
		}
		for _, dv := range g.analysis.DerivedVars {
			out.WriteString(fmt.Sprintf("  const $$upd_%s = () => { %s = %s; };\n",
				dv.Name, dv.Name, dv.Expr))
		}
		out.WriteString("\n")
	}

	// ── Effect wrapper functions ──────────────
	if len(g.analysis.Effects) > 0 {
		out.WriteString("  // effects\n")
		for i, eff := range g.analysis.Effects {
			out.WriteString(fmt.Sprintf("  const $$effect%d = () => {\n", i))
			for _, line := range strings.Split(eff.Body, "\n") {
				t := strings.TrimSpace(line)
				if t != "" {
					out.WriteString("    " + t + "\n")
				}
			}
			out.WriteString("  };\n")
		}
		out.WriteString("\n")
	}

	// ── Walk template → fill create/wire/events/init/cleanup ──
	g.walkNodes(nodes, "$$root", true)

	// ── Emit DOM creation ─────────────────────
	out.WriteString("  // DOM\n")
	out.WriteString(g.create.String())
	if g.wire.Len() > 0 {
		out.WriteString(g.wire.String())
	}
	out.WriteString("\n")

	// ── User script (reactive declarations stripped, assignments already rewritten) ──
	if g.analysis.CleanScript != "" {
		out.WriteString("  // component logic\n")
		for _, line := range strings.Split(g.analysis.CleanScript, "\n") {
			if strings.TrimSpace(line) == "" {
				continue
			}
			out.WriteString("  " + line + "\n")
		}
		out.WriteString("\n")
	}

	// ── Reactive setters (state + props) ─────────────────────────────────────
	if len(g.analysis.StateVars) > 0 || len(g.analysis.Props) > 0 {
		out.WriteString("  // reactive setters\n")
		for _, sv := range g.analysis.StateVars {
			out.WriteString(g.genSetter(sv.Name))
		}
		for _, prop := range g.analysis.Props {
			out.WriteString(g.genSetter(prop.Name))
		}
		out.WriteString("\n")
	}

	// ── Event listeners ──────────────────────
	if g.events.Len() > 0 {
		out.WriteString("  // events\n")
		out.WriteString(g.events.String())
		out.WriteString("\n")
	}

	// ── Initial derived computation ───────────
	if len(g.analysis.DerivedVars) > 0 {
		out.WriteString("  // initialise derived\n")
		for _, dv := range g.analysis.DerivedVars {
			out.WriteString(fmt.Sprintf("  $$upd_%s();\n", dv.Name))
		}
		out.WriteString("\n")
	}

	// ── Run initial effects ───────────────────
	for i := range g.analysis.Effects {
		out.WriteString(fmt.Sprintf("  $$effect%d();\n", i))
	}
	if len(g.analysis.Effects) > 0 {
		out.WriteString("\n")
	}

	// ── onMount callbacks ─────────────────────
	for _, lc := range g.analysis.Lifecycles {
		if lc.Kind == "onMount" {
			out.WriteString("  // onMount\n")
			for _, line := range strings.Split(lc.Body, "\n") {
				if strings.TrimSpace(line) != "" {
					out.WriteString("  " + line + "\n")
				}
			}
			out.WriteString("\n")
		}
	}

	// ── Initial DOM hydration ─────────────────
	if g.init.Len() > 0 {
		out.WriteString("  // initial render\n")
		out.WriteString(g.init.String())
		out.WriteString("\n")
	}

	// ── Mount ────────────────────────────────
	out.WriteString("  // mount\n")
	out.WriteString("  $$target.appendChild($$root);\n\n")

	// ── Return handle ─────────────────────────
	out.WriteString("  return {\n")
	out.WriteString("    destroy() {\n")
	// onDestroy callbacks first
	for _, lc := range g.analysis.Lifecycles {
		if lc.Kind == "onDestroy" {
			for _, line := range strings.Split(lc.Body, "\n") {
				if strings.TrimSpace(line) != "" {
					out.WriteString("      " + line + "\n")
				}
			}
		}
	}
	out.WriteString(g.cleanup.String())
	if g.sfc.Style != "" {
		out.WriteString("      $$style.remove();\n")
	}
	out.WriteString("      $$root.remove();\n")
	out.WriteString("    },\n")

	// set() accepts state vars AND props from parent
	hasSettable := len(g.analysis.StateVars) > 0 || len(g.analysis.Props) > 0
	if hasSettable {
		out.WriteString("    set(props) {\n")
		for _, sv := range g.analysis.StateVars {
			out.WriteString(fmt.Sprintf(
				"      if (props.%s !== undefined) $$set_%s(props.%s);\n",
				sv.Name, sv.Name, sv.Name))
		}
		for _, prop := range g.analysis.Props {
			out.WriteString(fmt.Sprintf(
				"      if (props.%s !== undefined) $$set_%s(props.%s);\n",
				prop.Name, prop.Name, prop.Name))
		}
		out.WriteString("    },\n")
	}

	out.WriteString("  };\n")
	out.WriteString("}\n")

	return out.String()
}

// ──────────────────────────────────────────────
//  Template walking
// ──────────────────────────────────────────────

func (g *CodeGen) walkNodes(nodes []Node, parentVar string, isRootList bool) {
	for i, node := range nodes {
		switch n := node.(type) {
		case *ElementNode:
			varName := g.id()
			if isRootList && i == 0 {
				varName = "$$root"
			}
			g.walkElement(n, varName, parentVar, isRootList && i == 0)
		case *IfChainNode:
			g.walkIfChain(n, parentVar)
		case *ComponentNode:
			if n.EachExpr != "" {
				g.walkComponentEach(n, parentVar)
			} else if n.IfCond != "" {
				g.walkComponentIf(n, parentVar)
			} else {
				g.walkComponent(n, parentVar)
			}
		case *SlotNode:
			g.walkSlot(n, parentVar)
		case *TextNode:
			g.walkText(n, parentVar)
		}
	}
}

func (g *CodeGen) walkElement(elem *ElementNode, varName, parentVar string, isRoot bool) {
	// #each takes precedence over #if
	if elem.EachExpr != "" {
		g.walkEach(elem, varName, parentVar)
		return
	}
	if elem.IfCond != "" {
		g.walkIf(elem, varName, parentVar)
		return
	}

	// Create element
	g.create.WriteString(fmt.Sprintf("  const %s = document.createElement('%s');\n", varName, elem.Tag))
	g.create.WriteString(fmt.Sprintf("  %s.setAttribute('%s', '');\n", varName, g.scopeID))

	// Static attributes
	for _, attr := range elem.Attrs {
		switch {
		case attr.IsEvent:
			handler := attr.Value
			if isSimpleIdent(handler) {
				// Plain identifier — use directly: addEventListener('click', myFunc)
				g.events.WriteString(fmt.Sprintf(
					"  %s.addEventListener('%s', %s);\n", varName, attr.Name, handler))
				g.cleanup.WriteString(fmt.Sprintf(
					"      %s.removeEventListener('%s', %s);\n", varName, attr.Name, handler))
			} else if isHandlerExpr(handler) {
				// Already a function/arrow expression — assign to a const and use it
				// so removeEventListener gets the same reference.
				hv := varName + "_" + attr.Name + "_h"
				g.create.WriteString(fmt.Sprintf("  const %s = %s;\n", hv, handler))
				g.events.WriteString(fmt.Sprintf(
					"  %s.addEventListener('%s', %s);\n", varName, attr.Name, hv))
				g.cleanup.WriteString(fmt.Sprintf(
					"      %s.removeEventListener('%s', %s);\n", varName, attr.Name, hv))
			} else {
				// Arbitrary expression (e.g. a method call) — wrap in an arrow
				hv := varName + "_" + attr.Name + "_h"
				g.create.WriteString(fmt.Sprintf(
					"  const %s = ($event) => { %s; };\n", hv, handler))
				g.events.WriteString(fmt.Sprintf(
					"  %s.addEventListener('%s', %s);\n", varName, attr.Name, hv))
				g.cleanup.WriteString(fmt.Sprintf(
					"      %s.removeEventListener('%s', %s);\n", varName, attr.Name, hv))
			}

		case attr.IsBind:
			deps := findDeps(attr.Value, g.analysis.reactiveNames())
			upd := bindAttrStmt(varName, attr.Name, attr.Value, "  ")
			g.init.WriteString(upd + "\n")
			for _, dep := range deps {
				g.addUpdate(dep, upd)
			}
			// Two-way binding: :value on input/textarea also wires an input listener
			if attr.Name == "value" && (elem.Tag == "input" || elem.Tag == "textarea") {
				if g.analysis.isStateName(attr.Value) {
					sv := attr.Value
					g.events.WriteString(fmt.Sprintf(
						"  %s.addEventListener('input', ($e) => $$set_%s($e.target.value));\n",
						varName, sv))
					g.cleanup.WriteString(fmt.Sprintf(
						"      %s.removeEventListener('input', ($e) => $$set_%s($e.target.value));\n",
						varName, sv))
				}
			}

		default:
			// Static attribute
			g.create.WriteString(fmt.Sprintf(
				"  %s.setAttribute('%s', '%s');\n", varName, attr.Name, escapeAttr(attr.Value)))
		}
	}

	// Recurse into children
	g.walkChildren(elem.Children, varName)

	// Append to parent (unless this IS the root placeholder)
	if !isRoot {
		g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, varName))
	}
}

func (g *CodeGen) walkChildren(children []Node, parentVar string) {
	for _, child := range children {
		switch c := child.(type) {
		case *ElementNode:
			cv := g.id()
			g.walkElement(c, cv, parentVar, false)
		case *IfChainNode:
			g.walkIfChain(c, parentVar)
		case *ComponentNode:
			if c.EachExpr != "" {
				g.walkComponentEach(c, parentVar)
			} else if c.IfCond != "" {
				g.walkComponentIf(c, parentVar)
			} else {
				g.walkComponent(c, parentVar)
			}
		case *SlotNode:
			g.walkSlot(c, parentVar)
		case *TextNode:
			g.walkText(c, parentVar)
		}
	}
}

func (g *CodeGen) walkText(node *TextNode, parentVar string) {
	allStatic := true
	for _, p := range node.Parts {
		if !p.Static {
			allStatic = false
			break
		}
	}

	if allStatic {
		text := ""
		for _, p := range node.Parts {
			text += p.Value
		}
		if strings.TrimSpace(text) == "" {
			return
		}
		g.wire.WriteString(fmt.Sprintf(
			"  %s.appendChild(document.createTextNode(%s));\n",
			parentVar, backtickString(text)))
		return
	}

	tv := g.id()
	expr := buildExpr(node.Parts)
	deps := findDeps(expr, g.analysis.reactiveNames())

	g.create.WriteString(fmt.Sprintf("  const %s = document.createTextNode('');\n", tv))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, tv))
	g.init.WriteString(fmt.Sprintf("  %s.data = %s;\n", tv, expr))
	for _, dep := range deps {
		g.addUpdate(dep, fmt.Sprintf("  %s.data = %s;", tv, expr))
	}
}

// ──────────────────────────────────────────────
//  #if / #elseif / #else chains
// ──────────────────────────────────────────────

// walkIfChain generates a single update function that evaluates each branch
// condition in order and mounts/unmounts the correct DOM fragment.
//
//	$$ifchain_N($$branch) where $$branch is the index of the active branch,
//	or -1 for "none" (all conditions false and no #else).
//
// Each branch's element is cached in a dedicated variable so it is created
// at most once and re-used on subsequent re-evaluations.
func (g *CodeGen) walkIfChain(chain *IfChainNode, parentVar string) {
	anchor := g.id() + "_a"
	fn := "$$chain_" + g.id()

	// One cached element variable per branch
	elVars := make([]string, len(chain.Branches))
	for i := range chain.Branches {
		elVars[i] = fmt.Sprintf("%s_b%d", fn, i)
	}

	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('if-chain');\n", anchor))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))
	for _, ev := range elVars {
		g.create.WriteString(fmt.Sprintf("  let %s = null;\n", ev))
	}

	// Build the chain update function
	var fnBuf strings.Builder
	fnBuf.WriteString(fmt.Sprintf("  function %s() {\n", fn))

	// Evaluate which branch is active
	fnBuf.WriteString("    let $$active = -1;\n")
	for i, branch := range chain.Branches {
		if branch.Cond == "" {
			// #else — always matches if we get here
			fnBuf.WriteString(fmt.Sprintf("    if ($$active < 0) $$active = %d;\n", i))
		} else {
			fnBuf.WriteString(fmt.Sprintf("    if ($$active < 0 && (%s)) $$active = %d;\n",
				branch.Cond, i))
		}
	}

	// Remove any currently mounted branch that's no longer active
	for i, ev := range elVars {
		fnBuf.WriteString(fmt.Sprintf("    if ($$active !== %d && %s) { %s.remove(); %s = null; }\n",
			i, ev, ev, ev))
	}

	// Mount the active branch (create element on first mount)
	for i, branch := range chain.Branches {
		ev := elVars[i]
		fnBuf.WriteString(fmt.Sprintf("    if ($$active === %d) {\n", i))
		fnBuf.WriteString(fmt.Sprintf("      if (!%s) {\n", ev))
		fnBuf.WriteString(fmt.Sprintf("        %s = document.createElement('%s');\n",
			ev, branch.Elem.Tag))
		fnBuf.WriteString(fmt.Sprintf("        %s.setAttribute('%s', '');\n", ev, g.scopeID))

		// Attrs
		for _, attr := range branch.Elem.Attrs {
			if attr.IsEvent {
				fnBuf.WriteString(fmt.Sprintf("        %s.addEventListener('%s', %s);\n",
					ev, attr.Name, attr.Value))
			} else if attr.IsBind {
				fnBuf.WriteString(bindAttrStmt(ev, attr.Name, attr.Value, "        ") + "\n")
			} else {
				fnBuf.WriteString(fmt.Sprintf("        %s.setAttribute('%s', '%s');\n",
					ev, attr.Name, escapeAttr(attr.Value)))
			}
		}

		// Children (text content for now; full nested codegen via emitBranchChildren)
		innerExpr := g.buildChildrenExpr(branch.Children)
		if innerExpr != "" {
			fnBuf.WriteString(fmt.Sprintf("        %s.textContent = %s;\n", ev, innerExpr))
		}
		fnBuf.WriteString(fmt.Sprintf("        %s.parentNode.insertBefore(%s, %s);\n",
			anchor, ev, anchor))
		fnBuf.WriteString(fmt.Sprintf("      }"))

		// Dynamic inner content update on re-evaluation
		if innerExpr != "" {
			fnBuf.WriteString(fmt.Sprintf(" else { %s.textContent = %s; }", ev, innerExpr))
		}
		fnBuf.WriteString("\n")
		fnBuf.WriteString("    }\n")
	}
	fnBuf.WriteString("  }\n")
	g.create.WriteString(fnBuf.String())

	// Collect all deps: branch conditions + inner content
	allDeps := map[string]bool{}
	for _, branch := range chain.Branches {
		for _, d := range findDeps(branch.Cond, g.analysis.reactiveNames()) {
			allDeps[d] = true
		}
		innerExpr := g.buildChildrenExpr(branch.Children)
		for _, d := range findDeps(innerExpr, g.analysis.reactiveNames()) {
			allDeps[d] = true
		}
	}

	call := fmt.Sprintf("  %s();", fn)
	g.init.WriteString(call + "\n")
	for dep := range allDeps {
		g.addUpdate(dep, call)
	}
}

// ──────────────────────────────────────────────
//  Child component composition
// ──────────────────────────────────────────────

// walkComponent emits code to mount a child component.
func (g *CodeGen) walkComponent(comp *ComponentNode, parentVar string) {
	instanceVar := g.id() + "_comp"

	var propsEntries []string
	for _, attr := range comp.Attrs {
		if attr.IsBind {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: %s", attr.Name, attr.Value))
		} else if !attr.IsEvent {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: '%s'", attr.Name, escapeAttr(attr.Value)))
		}
	}
	propsObj := "{}"
	if len(propsEntries) > 0 {
		propsObj = "{ " + strings.Join(propsEntries, ", ") + " }"
	}

	// Build $$slots object: each slot is a function returning a DocumentFragment.
	slotsEntries := []string{}
	for slotName, slotNodes := range comp.Slots {
		var fragBuf strings.Builder
		fragBuf.WriteString("() => { const $$f = document.createDocumentFragment(); ")
		for _, child := range slotNodes {
			switch c := child.(type) {
			case *TextNode:
				expr := buildExpr(c.Parts)
				fragBuf.WriteString(fmt.Sprintf("$$f.appendChild(document.createTextNode(%s)); ", expr))
			case *ElementNode:
				fragBuf.WriteString(fmt.Sprintf(
					"const $$se = document.createElement('%s'); $$se.setAttribute('%s',''); $$f.appendChild($$se); ",
					c.Tag, g.scopeID))
			}
		}
		fragBuf.WriteString("return $$f; }")
		slotsEntries = append(slotsEntries, fmt.Sprintf("%q: %s", slotName, fragBuf.String()))
	}
	slotsObj := "{}"
	if len(slotsEntries) > 0 {
		slotsObj = "{ " + strings.Join(slotsEntries, ", ") + " }"
	}

	wrapVar := instanceVar + "_wrap"
	g.create.WriteString(fmt.Sprintf("  const %s = document.createElement('div');\n", wrapVar))
	g.create.WriteString(fmt.Sprintf("  %s.setAttribute('%s', '');\n", wrapVar, g.scopeID))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, wrapVar))

	g.init.WriteString(fmt.Sprintf(
		"  const %s = %s(%s, %s, %s);\n",
		instanceVar, comp.Name, wrapVar, propsObj, slotsObj))

	// Reactive prop updates
	for _, attr := range comp.Attrs {
		if !attr.IsBind {
			continue
		}
		deps := findDeps(attr.Value, g.analysis.reactiveNames())
		update := fmt.Sprintf("  if (%s) %s.set({ %s: %s });",
			instanceVar, instanceVar, attr.Name, attr.Value)
		for _, dep := range deps {
			g.addUpdate(dep, update)
		}
	}
	// Event forwarding — guard with instanceof CustomEvent to prevent native
	// DOM events (e.g. the built-in 'select' event on inputs) from being
	// mishandled as component events when they share the same name.
	for _, attr := range comp.Attrs {
		if !attr.IsEvent {
			continue
		}
		hv := wrapVar + "_" + attr.Name + "_ch"
		g.events.WriteString(fmt.Sprintf(
			"  const %s = ($e) => { if ($e instanceof CustomEvent) { (%s)($e); } };\n",
			hv, attr.Value))
		g.events.WriteString(fmt.Sprintf(
			"  %s.addEventListener('%s', %s);\n", wrapVar, attr.Name, hv))
		g.cleanup.WriteString(fmt.Sprintf(
			"      %s.removeEventListener('%s', %s);\n", wrapVar, attr.Name, hv))
	}

	g.cleanup.WriteString(fmt.Sprintf("      if (%s) %s.destroy();\n", instanceVar, instanceVar))
}

// walkComponentEach handles <MyComp #each="arr as item" #key="item.id" :prop="item.x" />
func (g *CodeGen) walkComponentEach(comp *ComponentNode, parentVar string) {
	array, itemVar, indexVar := parseEachExpr(comp.EachExpr)
	if indexVar == "" {
		indexVar = "$$i"
	}
	keyExpr := comp.EachKey
	varName := g.id()
	anchor := varName + "_a"
	keyMap := varName + "_km"
	blocks := varName + "_bs"
	fn := "$$ceach_" + varName

	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('#each-comp');\n", anchor))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))

	// Build initial props object expression using the loop variables.
	var propsEntries []string
	for _, attr := range comp.Attrs {
		if attr.IsBind {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: %s", attr.Name, attr.Value))
		} else if !attr.IsEvent {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: '%s'", attr.Name, escapeAttr(attr.Value)))
		}
	}
	propsExpr := "{}"
	if len(propsEntries) > 0 {
		propsExpr = "{ " + strings.Join(propsEntries, ", ") + " }"
	}

	// Event listeners wired to the wrapper element.
	// Guard every handler with `instanceof CustomEvent` so native DOM events
	// (e.g. the built-in 'select' event on <input> / <textarea>) that happen to
	// share the same event name don't trigger the handler with detail=null.
	var evLines []string
	for _, attr := range comp.Attrs {
		if attr.IsEvent {
			evLines = append(evLines, fmt.Sprintf(
				"      $$wrap.addEventListener('%s', ($e) => { if ($e instanceof CustomEvent) { (%s)($e); } });",
				attr.Name, attr.Value))
		}
	}

	if keyExpr != "" {
		// Keyed: Map<key, {wrap, comp}> — update existing instances in place.
		g.create.WriteString(fmt.Sprintf("  const %s = new Map();\n", keyMap))
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", blocks))

		var fnBuf strings.Builder
		fnBuf.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fn))
		fnBuf.WriteString("    const $$newKeys = new Set();\n")
		fnBuf.WriteString("    const $$newBlks = [];\n")
		fnBuf.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fnBuf.WriteString(fmt.Sprintf("      const $$key = String(%s);\n", keyExpr))
		fnBuf.WriteString("      $$newKeys.add($$key);\n")
		fnBuf.WriteString(fmt.Sprintf("      let $$blk = %s.get($$key);\n", keyMap))
		fnBuf.WriteString("      if ($$blk) {\n")
		fnBuf.WriteString(fmt.Sprintf("        $$blk.comp.set(%s);\n", propsExpr))
		fnBuf.WriteString("      } else {\n")
		fnBuf.WriteString("        const $$wrap = document.createElement('div');\n")
		fnBuf.WriteString(fmt.Sprintf("        $$wrap.setAttribute('%s','');\n", g.scopeID))
		for _, ev := range evLines {
			fnBuf.WriteString("  " + ev + "\n")
		}
		fnBuf.WriteString(fmt.Sprintf("        const $$c = %s($$wrap, %s, {});\n", comp.Name, propsExpr))
		fnBuf.WriteString("        $$blk = { wrap: $$wrap, comp: $$c };\n")
		fnBuf.WriteString(fmt.Sprintf("        %s.set($$key, $$blk);\n", keyMap))
		fnBuf.WriteString("      }\n")
		// Only move the element if it is not already in the correct position
		// (i.e. immediately before the anchor). Moving DOM elements fires blur
		// on any focused input inside them, breaking in-place editing.
		fnBuf.WriteString(fmt.Sprintf(
			"      if ($$blk.wrap.nextSibling !== %s) { %s.parentNode.insertBefore($$blk.wrap, %s); }\n",
			anchor, anchor, anchor))
		fnBuf.WriteString("      $$newBlks.push($$blk);\n")
		fnBuf.WriteString("    });\n")
		fnBuf.WriteString(fmt.Sprintf("    %s.forEach(($$blk, $$key) => {\n", keyMap))
		fnBuf.WriteString(fmt.Sprintf(
			"      if (!$$newKeys.has($$key)) { $$blk.comp.destroy(); %s.delete($$key); }\n", keyMap))
		fnBuf.WriteString("    });\n")
		fnBuf.WriteString(fmt.Sprintf("    %s = $$newBlks;\n", blocks))
		fnBuf.WriteString("  }\n")
		g.create.WriteString(fnBuf.String())
	} else {
		// Unkeyed: destroy all + rebuild.
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", blocks))

		var fnBuf strings.Builder
		fnBuf.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fn))
		fnBuf.WriteString(fmt.Sprintf("    %s.forEach(b => b.comp.destroy()); %s = [];\n", blocks, blocks))
		fnBuf.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fnBuf.WriteString("      const $$wrap = document.createElement('div');\n")
		fnBuf.WriteString(fmt.Sprintf("      $$wrap.setAttribute('%s','');\n", g.scopeID))
		for _, ev := range evLines {
			fnBuf.WriteString("  " + ev + "\n")
		}
		fnBuf.WriteString(fmt.Sprintf("      const $$c = %s($$wrap, %s, {});\n", comp.Name, propsExpr))
		fnBuf.WriteString(fmt.Sprintf("      %s.parentNode.insertBefore($$wrap, %s);\n", anchor, anchor))
		fnBuf.WriteString(fmt.Sprintf("      %s.push({ wrap: $$wrap, comp: $$c });\n", blocks))
		fnBuf.WriteString("    });\n  }\n")
		g.create.WriteString(fnBuf.String())
	}

	call := fmt.Sprintf("  %s(%s);", fn, array)
	g.init.WriteString(call + "\n")
	for _, dep := range findDeps(array, g.analysis.reactiveNames()) {
		g.addUpdate(dep, call)
	}
	for _, attr := range comp.Attrs {
		if attr.IsBind {
			for _, dep := range findDeps(attr.Value, g.analysis.reactiveNames()) {
				g.addUpdate(dep, call)
			}
		}
	}
	g.cleanup.WriteString(fmt.Sprintf("      %s.forEach(b => b.comp.destroy());\n", blocks))
}

// walkComponentIf handles <MyComp #if="cond" :prop="val" />
func (g *CodeGen) walkComponentIf(comp *ComponentNode, parentVar string) {
	varName := g.id()
	anchor := varName + "_a"
	instVar := varName + "_inst"
	wrapVar := varName + "_wrap"
	fn := "$$cif_" + varName

	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('if-comp');\n", anchor))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))
	g.create.WriteString(fmt.Sprintf("  let %s = null, %s = null;\n", instVar, wrapVar))

	var propsEntries []string
	for _, attr := range comp.Attrs {
		if attr.IsBind {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: %s", attr.Name, attr.Value))
		} else if !attr.IsEvent {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: '%s'", attr.Name, escapeAttr(attr.Value)))
		}
	}
	propsExpr := "{}"
	if len(propsEntries) > 0 {
		propsExpr = "{ " + strings.Join(propsEntries, ", ") + " }"
	}

	var fnBuf strings.Builder
	fnBuf.WriteString(fmt.Sprintf("  function %s($$cond) {\n", fn))
	fnBuf.WriteString("    if ($$cond) {\n")
	fnBuf.WriteString(fmt.Sprintf("      if (!%s) {\n", instVar))
	fnBuf.WriteString(fmt.Sprintf("        %s = document.createElement('div');\n", wrapVar))
	fnBuf.WriteString(fmt.Sprintf("        %s.setAttribute('%s','');\n", wrapVar, g.scopeID))
	for _, attr := range comp.Attrs {
		if attr.IsEvent {
			fnBuf.WriteString(fmt.Sprintf(
				"        %s.addEventListener('%s', ($e) => { if ($e instanceof CustomEvent) { (%s)($e); } });\n",
				wrapVar, attr.Name, attr.Value))
		}
	}
	fnBuf.WriteString(fmt.Sprintf("        %s = %s(%s, %s, {});\n", instVar, comp.Name, wrapVar, propsExpr))
	fnBuf.WriteString(fmt.Sprintf("        %s.parentNode.insertBefore(%s, %s);\n", anchor, wrapVar, anchor))
	fnBuf.WriteString("      } else {\n")
	fnBuf.WriteString(fmt.Sprintf("        %s.set(%s);\n", instVar, propsExpr))
	fnBuf.WriteString("      }\n")
	fnBuf.WriteString(fmt.Sprintf("    } else if (%s) {\n", instVar))
	fnBuf.WriteString(fmt.Sprintf("      %s.destroy(); %s = null; %s = null;\n", instVar, instVar, wrapVar))
	fnBuf.WriteString("    }\n  }\n")
	g.create.WriteString(fnBuf.String())

	call := fmt.Sprintf("  %s(%s);", fn, comp.IfCond)
	g.init.WriteString(call + "\n")
	allDeps := findDeps(comp.IfCond, g.analysis.reactiveNames())
	for _, attr := range comp.Attrs {
		if attr.IsBind {
			allDeps = append(allDeps, findDeps(attr.Value, g.analysis.reactiveNames())...)
		}
	}
	for _, dep := range allDeps {
		g.addUpdate(dep, call)
	}
	g.cleanup.WriteString(fmt.Sprintf("      if (%s) %s.destroy();\n", instVar, instVar))
}

// walkSlot emits code that renders $$slots["name"](parent) if the slot is
// filled by the parent, or falls back to the declared fallback children.
func (g *CodeGen) walkSlot(slot *SlotNode, parentVar string) {
	slotVar := g.id() + "_slot"
	anchor := slotVar + "_a"

	// Create the anchor comment and wire it into the DOM tree.
	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('slot:%s');\n", anchor, slot.Name))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))

	// The insertion of slot content MUST happen after wiring (anchor needs a parentNode),
	// so we emit into g.init rather than g.create.
	var fnBuf strings.Builder
	fnBuf.WriteString(fmt.Sprintf("  {\n"))
	fnBuf.WriteString(fmt.Sprintf("    const $$sf = $$slots[%q];\n", slot.Name))
	fnBuf.WriteString(fmt.Sprintf("    if ($$sf) {\n"))
	fnBuf.WriteString(fmt.Sprintf(
		"      const $$sn = $$sf(); %s.parentNode.insertBefore($$sn, %s);\n",
		anchor, anchor))
	fnBuf.WriteString(fmt.Sprintf("    }"))

	if len(slot.Fallback) > 0 {
		fnBuf.WriteString(fmt.Sprintf(" else {\n"))
		for _, child := range slot.Fallback {
			switch c := child.(type) {
			case *TextNode:
				expr := buildExpr(c.Parts)
				fnBuf.WriteString(fmt.Sprintf(
					"      %s.parentNode.insertBefore(document.createTextNode(%s), %s);\n",
					anchor, expr, anchor))
			case *ElementNode:
				fnBuf.WriteString(fmt.Sprintf(
					"      const $$fb = document.createElement('%s');\n", c.Tag))
				fnBuf.WriteString(fmt.Sprintf(
					"      $$fb.setAttribute('%s','');\n", g.scopeID))
				fnBuf.WriteString(fmt.Sprintf(
					"      %s.parentNode.insertBefore($$fb, %s);\n", anchor, anchor))
			}
		}
		fnBuf.WriteString("    }\n")
	} else {
		fnBuf.WriteString("\n")
	}
	fnBuf.WriteString("  }\n")
	g.init.WriteString(fnBuf.String()) // ← init, not create
}

// ──────────────────────────────────────────────
//  Legacy single #if
// ──────────────────────────────────────────────

func (g *CodeGen) walkIf(elem *ElementNode, varName, parentVar string) {
	// Wrap in a single-branch IfChainNode and delegate.
	chain := &IfChainNode{
		Branches: []*IfBranch{{
			Cond:     elem.IfCond,
			Children: elem.Children,
			Elem:     elem,
		}},
	}
	g.walkIfChain(chain, parentVar)
}

// ──────────────────────────────────────────────
//  #each blocks  (keyed + recursive via FragGen)
// ──────────────────────────────────────────────

func (g *CodeGen) walkEach(elem *ElementNode, varName, parentVar string) {
	array, itemVar, indexVar := parseEachExpr(elem.EachExpr)
	if indexVar == "" {
		indexVar = "$$i"
	}
	keyExpr := elem.EachKey // "" means unkeyed

	anchor := varName + "_a"
	blocks := varName + "_bs"
	fn := "$$each_" + varName

	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('#each');\n", anchor))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))

	// Generate a fragment builder function for one row.
	// Use frag.id() for the root element so the counter is already at 1
	// when WalkNodes processes children — preventing variable name collisions.
	fragName := "$$frag_" + varName
	fragParams := []string{itemVar, indexVar}
	frag := newFragGen(fragName, fragParams, g.scopeID, g.analysis)

	rowVar := frag.id() // always "$$f0"; children will be $$f1, $$f2, …
	frag.create.WriteString(fmt.Sprintf("    const %s = document.createElement('%s');\n", rowVar, elem.Tag))
	frag.create.WriteString(fmt.Sprintf("    %s.setAttribute('%s', '');\n", rowVar, g.scopeID))

	for _, attr := range elem.Attrs {
		switch {
		case attr.IsEvent:
			handler := attr.Value
			if isSimpleIdent(handler) {
				frag.events.WriteString(fmt.Sprintf(
					"    %s.addEventListener('%s', %s);\n", rowVar, attr.Name, handler))
				frag.cleanup.WriteString(fmt.Sprintf(
					"        %s.removeEventListener('%s', %s);\n", rowVar, attr.Name, handler))
			} else if isHandlerExpr(handler) {
				hv := rowVar + "_" + attr.Name + "_h"
				frag.create.WriteString(fmt.Sprintf("    const %s = %s;\n", hv, handler))
				frag.events.WriteString(fmt.Sprintf(
					"    %s.addEventListener('%s', %s);\n", rowVar, attr.Name, hv))
				frag.cleanup.WriteString(fmt.Sprintf(
					"        %s.removeEventListener('%s', %s);\n", rowVar, attr.Name, hv))
			} else {
				hv := rowVar + "_" + attr.Name + "_h"
				frag.create.WriteString(fmt.Sprintf(
					"    const %s = ($event) => { %s; };\n", hv, handler))
				frag.events.WriteString(fmt.Sprintf(
					"    %s.addEventListener('%s', %s);\n", rowVar, attr.Name, hv))
				frag.cleanup.WriteString(fmt.Sprintf(
					"        %s.removeEventListener('%s', %s);\n", rowVar, attr.Name, hv))
			}
		case attr.IsBind:
			stmt := bindAttrStmt(rowVar, attr.Name, attr.Value, "    ")
			frag.init.WriteString(stmt + "\n")
			frag.update.WriteString("  " + stmt + "\n")
		default:
			frag.create.WriteString(fmt.Sprintf(
				"    %s.setAttribute('%s', '%s');\n", rowVar, attr.Name, escapeAttr(attr.Value)))
		}
	}

	// Recursively walk children into the fragment
	frag.WalkNodes(elem.Children, rowVar)

	// Emit the fragment function
	g.create.WriteString(frag.Emit())

	if keyExpr != "" {
		// ── Keyed reconciliation ─────────────────────────────────────────
		keyMap := varName + "_km"
		g.create.WriteString(fmt.Sprintf("  const %s = new Map();\n", keyMap))
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", blocks))

		var fnBuf strings.Builder
		fnBuf.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fn))
		fnBuf.WriteString(fmt.Sprintf("    const $$newKeys = new Set();\n"))
		fnBuf.WriteString(fmt.Sprintf("    const $$newBlocks = [];\n"))
		fnBuf.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fnBuf.WriteString(fmt.Sprintf("      const $$key = String(%s);\n", keyExpr))
		fnBuf.WriteString(fmt.Sprintf("      $$newKeys.add($$key);\n"))
		fnBuf.WriteString(fmt.Sprintf("      let $$blk = %s.get($$key);\n", keyMap))
		fnBuf.WriteString(fmt.Sprintf("      if ($$blk) {\n"))
		// Update existing block with new item/index values
		fnBuf.WriteString(fmt.Sprintf("        if ($$blk.update) $$blk.update(%s, %s);\n", itemVar, indexVar))
		fnBuf.WriteString(fmt.Sprintf("      } else {\n"))
		// Create new block
		fnBuf.WriteString(fmt.Sprintf("        $$blk = %s(%s, %s);\n", fragName, itemVar, indexVar))
		fnBuf.WriteString(fmt.Sprintf("        %s.set($$key, $$blk);\n", keyMap))
		fnBuf.WriteString(fmt.Sprintf("      }\n"))
		// Move/insert into correct position before anchor
		fnBuf.WriteString(fmt.Sprintf("      %s.parentNode.insertBefore($$blk.el, %s);\n", anchor, anchor))
		fnBuf.WriteString(fmt.Sprintf("      $$newBlocks.push($$blk);\n"))
		fnBuf.WriteString(fmt.Sprintf("    });\n"))
		// Remove stale blocks
		fnBuf.WriteString(fmt.Sprintf("    %s.forEach(($$blk, $$key) => {\n", keyMap))
		fnBuf.WriteString(fmt.Sprintf("      if (!$$newKeys.has($$key)) { $$blk.destroy(); %s.delete($$key); }\n", keyMap))
		fnBuf.WriteString(fmt.Sprintf("    });\n"))
		fnBuf.WriteString(fmt.Sprintf("    %s = $$newBlocks;\n", blocks))
		fnBuf.WriteString(fmt.Sprintf("  }\n"))
		g.create.WriteString(fnBuf.String())
	} else {
		// ── Unkeyed: full teardown + rebuild ─────────────────────────────
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", blocks))

		var fnBuf strings.Builder
		fnBuf.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fn))
		fnBuf.WriteString(fmt.Sprintf("    %s.forEach(b => b.destroy());\n", blocks))
		fnBuf.WriteString(fmt.Sprintf("    %s = [];\n", blocks))
		fnBuf.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fnBuf.WriteString(fmt.Sprintf("      const $$blk = %s(%s, %s);\n", fragName, itemVar, indexVar))
		fnBuf.WriteString(fmt.Sprintf("      %s.parentNode.insertBefore($$blk.el, %s);\n", anchor, anchor))
		fnBuf.WriteString(fmt.Sprintf("      %s.push($$blk);\n", blocks))
		fnBuf.WriteString(fmt.Sprintf("    });\n  }\n"))
		g.create.WriteString(fnBuf.String())
	}

	call := fmt.Sprintf("  %s(%s);", fn, array)
	g.init.WriteString(call + "\n")
	for _, dep := range findDeps(array, g.analysis.reactiveNames()) {
		g.addUpdate(dep, call)
	}

	// Also re-run on changes to any variable referenced inside the row
	// (item expressions reference outer state like `active`, `selectedId`, etc.)
	// We do this by scanning the children for reactive deps.
	innerDeps := g.collectFragDeps(elem.Children)
	for dep := range innerDeps {
		g.addUpdate(dep, call)
	}

	// Wire cleanup
	g.cleanup.WriteString(fmt.Sprintf("      %s.forEach(b => b.destroy());\n", blocks))
}

// collectFragDeps walks a node subtree and returns all reactive variable names
// that appear in expressions (text interpolations, bind attrs, if conditions).
func (g *CodeGen) collectFragDeps(nodes []Node) map[string]bool {
	deps := map[string]bool{}
	allNames := g.analysis.reactiveNames()

	var walk func([]Node)
	walk = func(ns []Node) {
		for _, node := range ns {
			switch n := node.(type) {
			case *TextNode:
				expr := buildExpr(n.Parts)
				for _, d := range findDeps(expr, allNames) {
					deps[d] = true
				}
			case *ElementNode:
				for _, attr := range n.Attrs {
					if attr.IsBind {
						for _, d := range findDeps(attr.Value, allNames) {
							deps[d] = true
						}
					}
				}
				if n.IfCond != "" {
					for _, d := range findDeps(n.IfCond, allNames) {
						deps[d] = true
					}
				}
				walk(n.Children)
			case *IfChainNode:
				for _, branch := range n.Branches {
					for _, d := range findDeps(branch.Cond, allNames) {
						deps[d] = true
					}
					walk(branch.Children)
				}
			}
		}
	}
	walk(nodes)
	return deps
}

// emitEachChild is retained for backward-compat but now delegates to WalkNodes.
func (g *CodeGen) emitEachChild(b *strings.Builder, node Node, parentVar string) {
	// Inline simple cases without full FragGen overhead (used in legacy paths)
	switch n := node.(type) {
	case *TextNode:
		expr := buildExpr(n.Parts)
		b.WriteString(fmt.Sprintf("      %s.appendChild(document.createTextNode(%s));\n",
			parentVar, expr))
	case *ElementNode:
		b.WriteString(fmt.Sprintf("      {\n"))
		b.WriteString(fmt.Sprintf("        const $$sub = document.createElement('%s');\n", n.Tag))
		b.WriteString(fmt.Sprintf("        $$sub.setAttribute('%s', '');\n", g.scopeID))
		for _, attr := range n.Attrs {
			if attr.IsBind {
				b.WriteString(bindAttrStmt("$$sub", attr.Name, attr.Value, "        ") + "\n")
			} else if !attr.IsEvent {
				b.WriteString(fmt.Sprintf("        $$sub.setAttribute('%s','%s');\n",
					attr.Name, escapeAttr(attr.Value)))
			}
		}
		for _, cc := range n.Children {
			g.emitEachChild(b, cc, "$$sub")
		}
		b.WriteString(fmt.Sprintf("        %s.appendChild($$sub);\n", parentVar))
		b.WriteString(fmt.Sprintf("      }\n"))
	}
}

// ──────────────────────────────────────────────
//  Reactive setters
// ──────────────────────────────────────────────

func (g *CodeGen) genSetter(name string) string {
	var b strings.Builder
	b.WriteString(fmt.Sprintf("  function $$set_%s($$v) {\n", name))
	b.WriteString(fmt.Sprintf("    %s = $$v;\n", name))

	// Fire $$onChange for bindable props so parent can observe
	for _, prop := range g.analysis.Props {
		if prop.Name == name && prop.Bindable {
			b.WriteString(fmt.Sprintf(
				"    if ($$onChange_%s) $$onChange_%s($$v);\n", name, name))
		}
	}

	// Recompute derived vars that (transitively) depend on this var
	for _, dv := range g.analysis.DerivedVars {
		if containsStr(dv.Deps, name) {
			b.WriteString(fmt.Sprintf("    $$upd_%s();\n", dv.Name))
		}
	}

	// Collect DOM updates: direct + via derived
	seen := map[string]bool{}
	writeUpdate := func(u string) {
		if !seen[u] {
			seen[u] = true
			b.WriteString(u + "\n")
		}
	}

	for _, u := range g.updates[name] {
		writeUpdate(u)
	}
	for _, dv := range g.analysis.DerivedVars {
		if containsStr(dv.Deps, name) {
			for _, u := range g.updates[dv.Name] {
				writeUpdate(u)
			}
		}
	}

	// Trigger effects
	for i, eff := range g.analysis.Effects {
		if containsStr(eff.Deps, name) {
			b.WriteString(fmt.Sprintf("    $$effect%d();\n", i))
		}
	}

	b.WriteString("  }\n")
	return b.String()
}

func (g *CodeGen) addUpdate(dep, code string) {
	g.updates[dep] = append(g.updates[dep], code)
}

// ──────────────────────────────────────────────
//  Expression builders
// ──────────────────────────────────────────────

// buildExpr produces a JS expression that evaluates to the text content
// of a mixed static/dynamic TextNode.
func buildExpr(parts []*Part) string {
	if len(parts) == 1 {
		if parts[0].Static {
			return backtickString(parts[0].Value)
		}
		return "String(" + parts[0].Value + ")"
	}
	var b strings.Builder
	b.WriteByte('`')
	for _, p := range parts {
		if p.Static {
			b.WriteString(escapeTL(p.Value))
		} else {
			b.WriteString("${")
			b.WriteString(p.Value)
			b.WriteByte('}')
		}
	}
	b.WriteByte('`')
	return b.String()
}

// buildChildrenExpr produces a single JS expression that represents all text
// content of a node's children (for simple #if blocks).
func (g *CodeGen) buildChildrenExpr(children []Node) string {
	var parts []*Part
	for _, child := range children {
		if t, ok := child.(*TextNode); ok {
			parts = append(parts, t.Parts...)
		}
	}
	if len(parts) == 0 {
		return ""
	}
	return buildExpr(parts)
}

