// walkComponent emits code to mount a child component.
func (g *CodeGen) walkComponent(comp *ComponentNode, parentVar string) {
	instanceVar := g.id() + "_comp"

	var propsEntries []string
	for _, attr := range comp.Attrs {
		if attr.IsBind {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: %s", attr.Name, attr.Value))
		} else if !attr.IsEvent {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: '%s'", attr.Name, escapeAttr(attr.Value)))
		}
	}
	propsObj := "{}"
	if len(propsEntries) > 0 {
		propsObj = "{ " + strings.Join(propsEntries, ", ") + " }"
	}

	// Build $$slots object: each slot is a function returning a DocumentFragment.
	// Uses emitBranchChildren to recursively build the full DOM tree for every
	// slot — previously only top-level elements were created, leaving their
	// children (toolbars, tables, inputs, etc.) completely empty.
	slotsEntries := []string{}
	for slotName, slotNodes := range comp.Slots {
		var fragBuf strings.Builder
		fragBuf.WriteString("() => { const $$f = document.createDocumentFragment(); ")
		g.emitBranchChildren(&fragBuf, slotNodes, "$$f", "")
		fragBuf.WriteString("return $$f; }")
		slotsEntries = append(slotsEntries, fmt.Sprintf("%q: %s", slotName, fragBuf.String()))
	}
	slotsObj := "{}"
	if len(slotsEntries) > 0 {
		slotsObj = "{ " + strings.Join(slotsEntries, ", ") + " }"
	}

	wrapVar := instanceVar + "_wrap"
	g.create.WriteString(fmt.Sprintf("  const %s = document.createElement('div');\n", wrapVar))
	g.create.WriteString(fmt.Sprintf("  %s.setAttribute('%s', '');\n", wrapVar, g.scopeID))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, wrapVar))

	g.init.WriteString(fmt.Sprintf(
		"  const %s = %s(%s, %s, %s);\n",
		instanceVar, comp.Name, wrapVar, propsObj, slotsObj))

	// Reactive prop updates
	for _, attr := range comp.Attrs {
		if !attr.IsBind {
			continue
		}
		deps := findDeps(attr.Value, g.analysis.reactiveNames())
		update := fmt.Sprintf("  if (%s) %s.set({ %s: %s });",
			instanceVar, instanceVar, attr.Name, attr.Value)
		for _, dep := range deps {
			g.addUpdate(dep, update)
		}
	}
	// Event forwarding — guard with instanceof CustomEvent to prevent native
	// DOM events (e.g. the built-in 'select' event on inputs) from being
	// mishandled as component events when they share the same name.
	for _, attr := range comp.Attrs {
		if !attr.IsEvent {
			continue
		}
		hv := wrapVar + "_" + attr.Name + "_ch"
		g.events.WriteString(fmt.Sprintf(
			"  const %s = ($e) => { if ($e instanceof CustomEvent) { (%s)($e); } };\n",
			hv, attr.Value))
		g.events.WriteString(fmt.Sprintf(
			"  %s.addEventListener('%s', %s);\n", wrapVar, attr.Name, hv))
		g.cleanup.WriteString(fmt.Sprintf(
			"      %s.removeEventListener('%s', %s);\n", wrapVar, attr.Name, hv))
	}

	g.cleanup.WriteString(fmt.Sprintf("      if (%s) %s.destroy();\n", instanceVar, instanceVar))
}

// walkComponentEach handles <MyComp #each="arr as item" #key="item.id" :prop="item.x" />
func (g *CodeGen) walkComponentEach(comp *ComponentNode, parentVar string) {
	array, itemVar, indexVar := parseEachExpr(comp.EachExpr)
	if indexVar == "" {
		indexVar = "$$i"
	}
	keyExpr := comp.EachKey
	varName  := g.id()
	anchor   := varName + "_a"
	keyMap   := varName + "_km"
	blocks   := varName + "_bs"
	fn       := "$$ceach_" + varName

	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('#each-comp');\n", anchor))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))

	// Build initial props object expression using the loop variables.
	var propsEntries []string
	for _, attr := range comp.Attrs {
		if attr.IsBind {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: %s", attr.Name, attr.Value))
		} else if !attr.IsEvent {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: '%s'", attr.Name, escapeAttr(attr.Value)))
		}
	}
	propsExpr := "{}"
	if len(propsEntries) > 0 {
		propsExpr = "{ " + strings.Join(propsEntries, ", ") + " }"
	}

	// Event listeners wired to the wrapper element.
	// Guard every handler with `instanceof CustomEvent` so native DOM events
	// (e.g. the built-in 'select' event on <input> / <textarea>) that happen to
	// share the same event name don't trigger the handler with detail=null.
	var evLines []string
	for _, attr := range comp.Attrs {
		if attr.IsEvent {
			evLines = append(evLines, fmt.Sprintf(
				"      $$wrap.addEventListener('%s', ($e) => { if ($e instanceof CustomEvent) { (%s)($e); } });",
				attr.Name, attr.Value))
		}
	}

	if keyExpr != "" {
		// Keyed: Map<key, {wrap, comp}> — update existing instances in place.
		g.create.WriteString(fmt.Sprintf("  const %s = new Map();\n", keyMap))
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", blocks))

		var fnBuf strings.Builder
		fnBuf.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fn))
		fnBuf.WriteString("    const $$newKeys = new Set();\n")
		fnBuf.WriteString("    const $$newBlks = [];\n")
		fnBuf.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fnBuf.WriteString(fmt.Sprintf("      const $$key = String(%s);\n", keyExpr))
		fnBuf.WriteString("      $$newKeys.add($$key);\n")
		fnBuf.WriteString(fmt.Sprintf("      let $$blk = %s.get($$key);\n", keyMap))
		fnBuf.WriteString("      if ($$blk) {\n")
		fnBuf.WriteString(fmt.Sprintf("        $$blk.comp.set(%s);\n", propsExpr))
		fnBuf.WriteString("      } else {\n")
		fnBuf.WriteString("        const $$wrap = document.createElement('div');\n")
		fnBuf.WriteString(fmt.Sprintf("        $$wrap.setAttribute('%s','');\n", g.scopeID))
		for _, ev := range evLines {
			fnBuf.WriteString("  " + ev + "\n")
		}
		fnBuf.WriteString(fmt.Sprintf("        const $$c = %s($$wrap, %s, {});\n", comp.Name, propsExpr))
		fnBuf.WriteString("        $$blk = { wrap: $$wrap, comp: $$c };\n")
		fnBuf.WriteString(fmt.Sprintf("        %s.set($$key, $$blk);\n", keyMap))
		fnBuf.WriteString("      }\n")
		// Only move the element if it is not already in the correct position
		// (i.e. immediately before the anchor). Moving DOM elements fires blur
		// on any focused input inside them, breaking in-place editing.
		fnBuf.WriteString(fmt.Sprintf(
			"      if ($$blk.wrap.nextSibling !== %s) { %s.parentNode.insertBefore($$blk.wrap, %s); }\n",
			anchor, anchor, anchor))
		fnBuf.WriteString("      $$newBlks.push($$blk);\n")
		fnBuf.WriteString("    });\n")
		fnBuf.WriteString(fmt.Sprintf("    %s.forEach(($$blk, $$key) => {\n", keyMap))
		fnBuf.WriteString(fmt.Sprintf(
			"      if (!$$newKeys.has($$key)) { $$blk.comp.destroy(); %s.delete($$key); }\n", keyMap))
		fnBuf.WriteString("    });\n")
		fnBuf.WriteString(fmt.Sprintf("    %s = $$newBlks;\n", blocks))
		fnBuf.WriteString("  }\n")
		g.create.WriteString(fnBuf.String())
	} else {
		// Unkeyed: destroy all + rebuild.
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", blocks))

		var fnBuf strings.Builder
		fnBuf.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fn))
		fnBuf.WriteString(fmt.Sprintf("    %s.forEach(b => b.comp.destroy()); %s = [];\n", blocks, blocks))
		fnBuf.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fnBuf.WriteString("      const $$wrap = document.createElement('div');\n")
		fnBuf.WriteString(fmt.Sprintf("      $$wrap.setAttribute('%s','');\n", g.scopeID))
		for _, ev := range evLines {
			fnBuf.WriteString("  " + ev + "\n")
		}
		fnBuf.WriteString(fmt.Sprintf("      const $$c = %s($$wrap, %s, {});\n", comp.Name, propsExpr))
		fnBuf.WriteString(fmt.Sprintf("      %s.parentNode.insertBefore($$wrap, %s);\n", anchor, anchor))
		fnBuf.WriteString(fmt.Sprintf("      %s.push({ wrap: $$wrap, comp: $$c });\n", blocks))
		fnBuf.WriteString("    });\n  }\n")
		g.create.WriteString(fnBuf.String())
	}

	call := fmt.Sprintf("  %s(%s);", fn, array)
	g.init.WriteString(call + "\n")
	for _, dep := range findDeps(array, g.analysis.reactiveNames()) {
		g.addUpdate(dep, call)
	}
	for _, attr := range comp.Attrs {
		if attr.IsBind {
			for _, dep := range findDeps(attr.Value, g.analysis.reactiveNames()) {
				g.addUpdate(dep, call)
			}
		}
	}
	g.cleanup.WriteString(fmt.Sprintf("      %s.forEach(b => b.comp.destroy());\n", blocks))
}

// walkComponentIf handles <MyComp #if="cond" :prop="val" />
func (g *CodeGen) walkComponentIf(comp *ComponentNode, parentVar string) {
	varName  := g.id()
	anchor   := varName + "_a"
	instVar  := varName + "_inst"
	wrapVar  := varName + "_wrap"
	fn       := "$$cif_" + varName

	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('if-comp');\n", anchor))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))
	g.create.WriteString(fmt.Sprintf("  let %s = null, %s = null;\n", instVar, wrapVar))

	var propsEntries []string
	for _, attr := range comp.Attrs {
		if attr.IsBind {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: %s", attr.Name, attr.Value))
		} else if !attr.IsEvent {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: '%s'", attr.Name, escapeAttr(attr.Value)))
		}
	}
	propsExpr := "{}"
	if len(propsEntries) > 0 {
		propsExpr = "{ " + strings.Join(propsEntries, ", ") + " }"
	}

	var fnBuf strings.Builder
	fnBuf.WriteString(fmt.Sprintf("  function %s($$cond) {\n", fn))
	fnBuf.WriteString("    if ($$cond) {\n")
	fnBuf.WriteString(fmt.Sprintf("      if (!%s) {\n", instVar))
	fnBuf.WriteString(fmt.Sprintf("        %s = document.createElement('div');\n", wrapVar))
	fnBuf.WriteString(fmt.Sprintf("        %s.setAttribute('%s','');\n", wrapVar, g.scopeID))
	for _, attr := range comp.Attrs {
		if attr.IsEvent {
			fnBuf.WriteString(fmt.Sprintf(
				"        %s.addEventListener('%s', ($e) => { if ($e instanceof CustomEvent) { (%s)($e); } });\n",
				wrapVar, attr.Name, attr.Value))
		}
	}
	fnBuf.WriteString(fmt.Sprintf("        %s = %s(%s, %s, {});\n", instVar, comp.Name, wrapVar, propsExpr))
	fnBuf.WriteString(fmt.Sprintf("        %s.parentNode.insertBefore(%s, %s);\n", anchor, wrapVar, anchor))
	fnBuf.WriteString("      } else {\n")
	fnBuf.WriteString(fmt.Sprintf("        %s.set(%s);\n", instVar, propsExpr))
	fnBuf.WriteString("      }\n")
	fnBuf.WriteString(fmt.Sprintf("    } else if (%s) {\n", instVar))
	fnBuf.WriteString(fmt.Sprintf("      %s.destroy(); %s = null; %s = null;\n", instVar, instVar, wrapVar))
	fnBuf.WriteString("    }\n  }\n")
	g.create.WriteString(fnBuf.String())

	call := fmt.Sprintf("  %s(%s);", fn, comp.IfCond)
	g.init.WriteString(call + "\n")
	allDeps := findDeps(comp.IfCond, g.analysis.reactiveNames())
	for _, attr := range comp.Attrs {
		if attr.IsBind {
			allDeps = append(allDeps, findDeps(attr.Value, g.analysis.reactiveNames())...)
		}
	}
	for _, dep := range allDeps {
		g.addUpdate(dep, call)
	}
	g.cleanup.WriteString(fmt.Sprintf("      if (%s) %s.destroy();\n", instVar, instVar))
}

// walkSlot emits code that renders $$slots["name"](parent) if the slot is
// filled by the parent, or falls back to the declared fallback children.
func (g *CodeGen) walkSlot(slot *SlotNode, parentVar string) {
	slotVar := g.id() + "_slot"
	anchor := slotVar + "_a"

	// Create the anchor comment and wire it into the DOM tree.
	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('slot:%s');\n", anchor, slot.Name))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))

	// The insertion of slot content MUST happen after wiring (anchor needs a parentNode),
	// so we emit into g.init rather than g.create.
	var fnBuf strings.Builder
	fnBuf.WriteString(fmt.Sprintf("  {\n"))
	fnBuf.WriteString(fmt.Sprintf("    const $$sf = $$slots[%q];\n", slot.Name))
	fnBuf.WriteString(fmt.Sprintf("    if ($$sf) {\n"))
	fnBuf.WriteString(fmt.Sprintf(
		"      const $$sn = $$sf(); %s.parentNode.insertBefore($$sn, %s);\n",
		anchor, anchor))
	fnBuf.WriteString(fmt.Sprintf("    }"))

	if len(slot.Fallback) > 0 {
		fnBuf.WriteString(fmt.Sprintf(" else {\n"))
		for _, child := range slot.Fallback {
			switch c := child.(type) {
			case *TextNode:
				expr := buildExpr(c.Parts)
				fnBuf.WriteString(fmt.Sprintf(
					"      %s.parentNode.insertBefore(document.createTextNode(%s), %s);\n",
					anchor, expr, anchor))
			case *ElementNode:
				fnBuf.WriteString(fmt.Sprintf(
					"      const $$fb = document.createElement('%s');\n", c.Tag))
				fnBuf.WriteString(fmt.Sprintf(
					"      $$fb.setAttribute('%s','');\n", g.scopeID))
				fnBuf.WriteString(fmt.Sprintf(
					"      %s.parentNode.insertBefore($$fb, %s);\n", anchor, anchor))
			}
		}
		fnBuf.WriteString("    }\n")
	} else {
		fnBuf.WriteString("\n")
	}
	fnBuf.WriteString("  }\n")
	g.init.WriteString(fnBuf.String()) // ← init, not create
}

// walkComponentIfChain handles an IfChainNode where every branch holds a
// ComponentNode (#if / #elseif / #else on component tags).
// It emits a single $$chain_N() function with one cached instance per branch.
func (g *CodeGen) walkComponentIfChain(chain *IfChainNode, parentVar string) {
	anchor := g.id() + "_a"
	fn := "$$chain_" + g.id()

	// One {inst, wrap} pair per branch
	instVars := make([]string, len(chain.Branches))
	wrapVars := make([]string, len(chain.Branches))
	for i := range chain.Branches {
		instVars[i] = fmt.Sprintf("%s_i%d", fn, i)
		wrapVars[i] = fmt.Sprintf("%s_w%d", fn, i)
	}

	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('if-comp-chain');\n", anchor))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))
	for i := range chain.Branches {
		g.create.WriteString(fmt.Sprintf(
			"  let %s = null, %s = null;\n", instVars[i], wrapVars[i]))
	}

	runningFlagC := fn + "_running"
	pendingFlagC := fn + "_pending"
	g.create.WriteString(fmt.Sprintf("  let %s = false, %s = false;\n", runningFlagC, pendingFlagC))

	var fnBuf strings.Builder
	fnBuf.WriteString(fmt.Sprintf("  function %s() {\n", fn))
	fnBuf.WriteString(fmt.Sprintf("    if (%s) { %s = true; return; }\n", runningFlagC, pendingFlagC))
	fnBuf.WriteString(fmt.Sprintf("    %s = true;\n", runningFlagC))
	fnBuf.WriteString(fmt.Sprintf("    try {\n"))
	fnBuf.WriteString("      let $$active = -1;\n")
	for i, branch := range chain.Branches {
		if branch.Cond == "" {
			fnBuf.WriteString(fmt.Sprintf("      if ($$active < 0) $$active = %d;\n", i))
		} else {
			fnBuf.WriteString(fmt.Sprintf("      if ($$active < 0 && (%s)) $$active = %d;\n", branch.Cond, i))
		}
	}

	// Destroy any branch that is no longer active
	for i := range chain.Branches {
		fnBuf.WriteString(fmt.Sprintf(
			"      if ($$active !== %d && %s) { %s.destroy(); %s = null; %s.remove(); %s = null; }\n",
			i, instVars[i], instVars[i], instVars[i], wrapVars[i], wrapVars[i]))
	}

	// Mount the active branch (first time) or update (subsequent times)
	for i, branch := range chain.Branches {
		comp := branch.Comp
		var propsEntries []string
		for _, attr := range comp.Attrs {
			if attr.IsBind {
				propsEntries = append(propsEntries, fmt.Sprintf("%s: %s", attr.Name, attr.Value))
			} else if !attr.IsEvent {
				propsEntries = append(propsEntries, fmt.Sprintf("%s: '%s'", attr.Name, escapeAttr(attr.Value)))
			}
		}
		propsExpr := "{}"
		if len(propsEntries) > 0 {
			propsExpr = "{ " + strings.Join(propsEntries, ", ") + " }"
		}

		fnBuf.WriteString(fmt.Sprintf("      if ($$active === %d) {\n", i))
		fnBuf.WriteString(fmt.Sprintf("        if (!%s) {\n", instVars[i]))
		fnBuf.WriteString(fmt.Sprintf("          %s = document.createElement('div');\n", wrapVars[i]))
		fnBuf.WriteString(fmt.Sprintf("          %s.setAttribute('%s','');\n", wrapVars[i], g.scopeID))
		for _, attr := range comp.Attrs {
			if attr.IsEvent {
				fnBuf.WriteString(fmt.Sprintf(
					"          %s.addEventListener('%s', ($e) => { if ($e instanceof CustomEvent) { (%s)($e); } });\n",
					wrapVars[i], attr.Name, attr.Value))
			}
		}
		fnBuf.WriteString(fmt.Sprintf("          %s = %s(%s, %s, {});\n",
			instVars[i], comp.Name, wrapVars[i], propsExpr))
		fnBuf.WriteString(fmt.Sprintf("          %s.parentNode.insertBefore(%s, %s);\n",
			anchor, wrapVars[i], anchor))
		fnBuf.WriteString(fmt.Sprintf("        } else { %s.set(%s); }\n", instVars[i], propsExpr))
		fnBuf.WriteString("      }\n")
	}
	fnBuf.WriteString(fmt.Sprintf("    } finally {\n"))
	fnBuf.WriteString(fmt.Sprintf("      %s = false;\n", runningFlagC))
	fnBuf.WriteString(fmt.Sprintf("      if (%s) { %s = false; %s(); }\n", pendingFlagC, pendingFlagC, fn))
	fnBuf.WriteString("    }\n")
	fnBuf.WriteString("  }\n")
	g.create.WriteString(fnBuf.String())

	// Collect all deps from conditions and bound props
	allDeps := map[string]bool{}
	for _, branch := range chain.Branches {
		for _, d := range findDeps(branch.Cond, g.analysis.reactiveNames()) {
			allDeps[d] = true
		}
		for _, attr := range branch.Comp.Attrs {
			if attr.IsBind {
				for _, d := range findDeps(attr.Value, g.analysis.reactiveNames()) {
					allDeps[d] = true
				}
			}
		}
	}

	call := fmt.Sprintf("  %s();", fn)
	g.init.WriteString(call + "\n")
	for dep := range allDeps {
		g.addUpdate(dep, call)
	}

	// Cleanup
	for i := range chain.Branches {
		g.cleanup.WriteString(fmt.Sprintf("      if (%s) %s.destroy();\n", instVars[i], instVars[i]))
	}
}

