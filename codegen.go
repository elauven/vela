// walkComponent emits code to mount a child component.
func (g *CodeGen) walkComponent(comp *ComponentNode, parentVar string) {
	instanceVar := g.id() + "_comp"

	var propsEntries []string
	for _, attr := range comp.Attrs {
		if attr.IsBind {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: %s", attr.Name, attr.Value))
		} else if !attr.IsEvent {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: '%s'", attr.Name, escapeAttr(attr.Value)))
		}
	}
	propsObj := "{}"
	if len(propsEntries) > 0 {
		propsObj = "{ " + strings.Join(propsEntries, ", ") + " }"
	}

	// Build $$slots object.
	//
	// Each slot function returns a DocumentFragment of already-constructed DOM nodes.
	// The nodes are declared in g.create (component scope) and wired into g.updates
	// so reactive state changes update them live.
	//
	// ORDERING CRITICAL: slot content walk emits g.init entries (e.g. the initial
	// $$each_N(arr) call). These MUST run after the component constructor has been
	// called, because the constructor calls the slot function which inserts the
	// anchor comments into the DOM. If the each loop runs before the anchor has a
	// parentNode, insertBefore crashes with "parentNode is null".
	//
	// Solution: redirect g.init to a temporary buffer during the slot content walk.
	// Emit the component constructor to real g.init first, then append the deferred
	// slot init calls after it.
	slotsEntries := []string{}
	type slotInitEntry struct{ buf strings.Builder }
	slotInits := []slotInitEntry{}

	for slotName, slotNodes := range comp.Slots {
		fragVar  := fmt.Sprintf("$$sf_%s_%s", slotName, g.id())
		cacheVar := fmt.Sprintf("$$sc_%s_%s", slotName, g.id())

		// Declare the cache variable at component scope (null = not yet built).
		// Slot function builds the DocumentFragment ONCE and caches it so that
		// child component state (scroll, form values, focus) is preserved across
		// re-opens (e.g. Modal close → reopen).
		g.create.WriteString(fmt.Sprintf("  let %s = null;\n", cacheVar))

		// Redirect wire to capture only this slot's appendChild calls.
		savedWire := g.wire
		g.wire = strings.Builder{}

		// Redirect init so initial each/chain calls are deferred past the ctor.
		savedInit := g.init
		g.init = strings.Builder{}

		g.walkChildren(slotNodes, fragVar)

		slotWire := g.wire.String()
		g.wire = savedWire

		var slotInitBuf strings.Builder
		slotInitBuf.WriteString(g.init.String())
		g.init = savedInit

		slotInits = append(slotInits, slotInitEntry{slotInitBuf})

		// Build the slot function with caching:
		//
		//   First call  → build DocumentFragment, cache it, return it.
		//   Reopen call → re-run chain/each inits (so detached branches
		//                 re-insert into the now-live DOM), return cache.
		//
		// The re-insert logic in $$chain_N() moves existing DOM nodes from the
		// old detached parent into the new fragment/live parent, so child component
		// instances (and their local state) are reused rather than recreated.
		var fragFn strings.Builder
		initiCalls := ""
		for _, line := range strings.Split(slotInitBuf.String(), "\n") {
			if trimmed := strings.TrimSpace(line); trimmed != "" {
				initiCalls += trimmed + " "
			}
		}
		// Reopen path: cache already populated, just re-run inits and return
		fragFn.WriteString(fmt.Sprintf("() => { if (%s) { %sreturn %s; } ", cacheVar, initiCalls, cacheVar))
		// First-open path: build fragment, populate, cache, return
		fragFn.WriteString(fmt.Sprintf("const %s = document.createDocumentFragment(); ", fragVar))
		for _, line := range strings.Split(slotWire, "\n") {
			if trimmed := strings.TrimSpace(line); trimmed != "" {
				fragFn.WriteString(trimmed + " ")
			}
		}
		fragFn.WriteString(initiCalls)
		fragFn.WriteString(fmt.Sprintf("%s = %s; return %s; }", cacheVar, fragVar, cacheVar))
		slotsEntries = append(slotsEntries, fmt.Sprintf("%q: %s", slotName, fragFn.String()))
	}
	slotsObj := "{}"
	if len(slotsEntries) > 0 {
		slotsObj = "{ " + strings.Join(slotsEntries, ", ") + " }"
	}

	wrapVar := instanceVar + "_wrap"
	g.create.WriteString(fmt.Sprintf("  const %s = document.createElement('div');\n", wrapVar))
	g.create.WriteString(fmt.Sprintf("  %s.setAttribute('%s', '');\n", wrapVar, g.scopeID))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, wrapVar))

	// Emit component constructor FIRST so the slot function is called inside it,
	// inserting anchor comments into the DOM before any slot init calls.
	// The slot function body already contains the init calls ($$chain_X(), $$each_N()),
	// so we do NOT emit them again here. Emitting them twice caused double-execution:
	//   • For always-visible slots: slot fn is called during constructor, inits run once ✓
	//   • For conditional slots (Modal starts closed): slot fn never called during constructor,
	//     but the deferred init calls were no-ops anyway. Init calls run when slot fn is
	//     first called (on modal open). ✓
	// Removing the deferred duplicates eliminates spurious double-renders (e.g. duplicate
	// filter buttons from $$each_$$n18 running twice).
	g.init.WriteString(fmt.Sprintf(
		"  const %s = %s(%s, %s, %s);\n",
		instanceVar, comp.Name, wrapVar, propsObj, slotsObj))

	// Reactive prop updates
	for _, attr := range comp.Attrs {
		if !attr.IsBind {
			continue
		}
		deps := findDeps(attr.Value, g.analysis.reactiveNames())
		update := fmt.Sprintf("  if (%s) %s.set({ %s: %s });",
			instanceVar, instanceVar, attr.Name, attr.Value)
		for _, dep := range deps {
			g.addUpdate(dep, update)
		}
	}
	// Event forwarding — guard with instanceof CustomEvent to prevent native
	// DOM events (e.g. the built-in 'select' event on inputs) from being
	// mishandled as component events when they share the same name.
	for _, attr := range comp.Attrs {
		if !attr.IsEvent {
			continue
		}
		hv := wrapVar + "_" + attr.Name + "_ch"
		g.events.WriteString(fmt.Sprintf(
			"  const %s = ($e) => { if ($e instanceof CustomEvent) { (%s)($e); } };\n",
			hv, attr.Value))
		g.events.WriteString(fmt.Sprintf(
			"  %s.addEventListener('%s', %s);\n", wrapVar, attr.Name, hv))
		g.cleanup.WriteString(fmt.Sprintf(
			"      %s.removeEventListener('%s', %s);\n", wrapVar, attr.Name, hv))
	}

	g.cleanup.WriteString(fmt.Sprintf("      if (%s) %s.destroy();\n", instanceVar, instanceVar))
}

// walkComponentEach handles <MyComp #each="arr as item" #key="item.id" :prop="item.x" />
func (g *CodeGen) walkComponentEach(comp *ComponentNode, parentVar string) {
	array, itemVar, indexVar := parseEachExpr(comp.EachExpr)
	if indexVar == "" {
		indexVar = "$$i"
	}
	keyExpr := comp.EachKey
	varName := g.id()
	anchor := varName + "_a"
	keyMap := varName + "_km"
	blocks := varName + "_bs"
	fn := "$$ceach_" + varName

	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('#each-comp');\n", anchor))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))

	// Build initial props object expression using the loop variables.
	var propsEntries []string
	for _, attr := range comp.Attrs {
		if attr.IsBind {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: %s", attr.Name, attr.Value))
		} else if !attr.IsEvent {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: '%s'", attr.Name, escapeAttr(attr.Value)))
		}
	}
	propsExpr := "{}"
	if len(propsEntries) > 0 {
		propsExpr = "{ " + strings.Join(propsEntries, ", ") + " }"
	}

	// Event listeners wired to the wrapper element.
	// Guard every handler with `instanceof CustomEvent` so native DOM events
	// (e.g. the built-in 'select' event on <input> / <textarea>) that happen to
	// share the same event name don't trigger the handler with detail=null.
	var evLines []string
	for _, attr := range comp.Attrs {
		if attr.IsEvent {
			evLines = append(evLines, fmt.Sprintf(
				"      $$wrap.addEventListener('%s', ($e) => { if ($e instanceof CustomEvent) { (%s)($e); } });",
				attr.Name, attr.Value))
		}
	}

	if keyExpr != "" {
		// Keyed: Map<key, {wrap, comp}> — update existing instances in place.
		g.create.WriteString(fmt.Sprintf("  const %s = new Map();\n", keyMap))
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", blocks))

		var fnBuf strings.Builder
		fnBuf.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fn))
		fnBuf.WriteString("    const $$newKeys = new Set();\n")
		fnBuf.WriteString("    const $$newBlks = [];\n")
		fnBuf.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fnBuf.WriteString(fmt.Sprintf("      const $$key = String(%s);\n", keyExpr))
		fnBuf.WriteString("      $$newKeys.add($$key);\n")
		fnBuf.WriteString(fmt.Sprintf("      let $$blk = %s.get($$key);\n", keyMap))
		fnBuf.WriteString("      if ($$blk) {\n")
		fnBuf.WriteString(fmt.Sprintf("        $$blk.comp.set(%s);\n", propsExpr))
		fnBuf.WriteString("      } else {\n")
		fnBuf.WriteString("        const $$wrap = document.createElement('div');\n")
		fnBuf.WriteString(fmt.Sprintf("        $$wrap.setAttribute('%s','');\n", g.scopeID))
		for _, ev := range evLines {
			fnBuf.WriteString("  " + ev + "\n")
		}
		fnBuf.WriteString(fmt.Sprintf("        const $$c = %s($$wrap, %s, {});\n", comp.Name, propsExpr))
		fnBuf.WriteString("        $$blk = { wrap: $$wrap, comp: $$c };\n")
		fnBuf.WriteString(fmt.Sprintf("        %s.set($$key, $$blk);\n", keyMap))
		fnBuf.WriteString("      }\n")
		// Only move the element if it is not already in the correct position
		// (i.e. immediately before the anchor). Moving DOM elements fires blur
		// on any focused input inside them, breaking in-place editing.
		fnBuf.WriteString(fmt.Sprintf(
			"      if (%[2]s.parentNode && $$blk.wrap.nextSibling !== %[1]s) { %[2]s.before($$blk.wrap); }\n",
			anchor, anchor, anchor))
		fnBuf.WriteString("      $$newBlks.push($$blk);\n")
		fnBuf.WriteString("    });\n")
		fnBuf.WriteString(fmt.Sprintf("    %s.forEach(($$blk, $$key) => {\n", keyMap))
		fnBuf.WriteString(fmt.Sprintf(
			"      if (!$$newKeys.has($$key)) { $$blk.comp.destroy(); %s.delete($$key); }\n", keyMap))
		fnBuf.WriteString("    });\n")
		fnBuf.WriteString(fmt.Sprintf("    %s = $$newBlks;\n", blocks))
		fnBuf.WriteString("  }\n")
		g.create.WriteString(fnBuf.String())
	} else {
		// Unkeyed: destroy all + rebuild.
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", blocks))

		var fnBuf strings.Builder
		fnBuf.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fn))
		fnBuf.WriteString(fmt.Sprintf("    %s.forEach(b => b.comp.destroy()); %s = [];\n", blocks, blocks))
		fnBuf.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fnBuf.WriteString("      const $$wrap = document.createElement('div');\n")
		fnBuf.WriteString(fmt.Sprintf("      $$wrap.setAttribute('%s','');\n", g.scopeID))
		for _, ev := range evLines {
			fnBuf.WriteString("  " + ev + "\n")
		}
		fnBuf.WriteString(fmt.Sprintf("      const $$c = %s($$wrap, %s, {});\n", comp.Name, propsExpr))
		fnBuf.WriteString(fmt.Sprintf("      %[1]s.before($$wrap);\n", anchor, anchor))
		fnBuf.WriteString(fmt.Sprintf("      %s.push({ wrap: $$wrap, comp: $$c });\n", blocks))
		fnBuf.WriteString("    });\n  }\n")
		g.create.WriteString(fnBuf.String())
	}

	call := fmt.Sprintf("  %s(%s);", fn, array)
	g.init.WriteString(call + "\n")
	for _, dep := range findDeps(array, g.analysis.reactiveNames()) {
		g.addUpdate(dep, call)
	}
	for _, attr := range comp.Attrs {
		if attr.IsBind {
			for _, dep := range findDeps(attr.Value, g.analysis.reactiveNames()) {
				g.addUpdate(dep, call)
			}
		}
	}
	g.cleanup.WriteString(fmt.Sprintf("      %s.forEach(b => b.comp.destroy());\n", blocks))
}

// walkComponentIf handles <MyComp #if="cond" :prop="val" />
func (g *CodeGen) walkComponentIf(comp *ComponentNode, parentVar string) {
	varName := g.id()
	anchor := varName + "_a"
	instVar := varName + "_inst"
	wrapVar := varName + "_wrap"
	fn := "$$cif_" + varName

	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('if-comp');\n", anchor))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))
	g.create.WriteString(fmt.Sprintf("  let %s = null, %s = null;\n", instVar, wrapVar))

	var propsEntries []string
	for _, attr := range comp.Attrs {
		if attr.IsBind {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: %s", attr.Name, attr.Value))
		} else if !attr.IsEvent {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: '%s'", attr.Name, escapeAttr(attr.Value)))
		}
	}
	propsExpr := "{}"
	if len(propsEntries) > 0 {
		propsExpr = "{ " + strings.Join(propsEntries, ", ") + " }"
	}

	var fnBuf strings.Builder
	fnBuf.WriteString(fmt.Sprintf("  function %s($$cond) {\n", fn))
	fnBuf.WriteString("    if ($$cond) {\n")
	fnBuf.WriteString(fmt.Sprintf("      if (!%s) {\n", instVar))
	fnBuf.WriteString(fmt.Sprintf("        %s = document.createElement('div');\n", wrapVar))
	fnBuf.WriteString(fmt.Sprintf("        %s.setAttribute('%s','');\n", wrapVar, g.scopeID))
	for _, attr := range comp.Attrs {
		if attr.IsEvent {
			fnBuf.WriteString(fmt.Sprintf(
				"        %s.addEventListener('%s', ($e) => { if ($e instanceof CustomEvent) { (%s)($e); } });\n",
				wrapVar, attr.Name, attr.Value))
		}
	}
	fnBuf.WriteString(fmt.Sprintf("        %s = %s(%s, %s, {});\n", instVar, comp.Name, wrapVar, propsExpr))
	fnBuf.WriteString(fmt.Sprintf("        %[1]s.before(%[2]s);\n", anchor, wrapVar, anchor))
	fnBuf.WriteString("      } else {\n")
	fnBuf.WriteString(fmt.Sprintf("        %s.set(%s);\n", instVar, propsExpr))
	fnBuf.WriteString("      }\n")
	fnBuf.WriteString(fmt.Sprintf("    } else if (%s) {\n", instVar))
	fnBuf.WriteString(fmt.Sprintf("      %s.destroy(); %s = null; %s = null;\n", instVar, instVar, wrapVar))
	fnBuf.WriteString("    }\n  }\n")
	g.create.WriteString(fnBuf.String())

	call := fmt.Sprintf("  %s(%s);", fn, comp.IfCond)
	g.init.WriteString(call + "\n")
	allDeps := findDeps(comp.IfCond, g.analysis.reactiveNames())
	for _, attr := range comp.Attrs {
		if attr.IsBind {
			allDeps = append(allDeps, findDeps(attr.Value, g.analysis.reactiveNames())...)
		}
	}
	for _, dep := range allDeps {
		g.addUpdate(dep, call)
	}
	g.cleanup.WriteString(fmt.Sprintf("      if (%s) %s.destroy();\n", instVar, instVar))
}

// walkSlot emits code that renders $$slots["name"](parent) if the slot is
// filled by the parent, or falls back to the declared fallback children.
func (g *CodeGen) walkSlot(slot *SlotNode, parentVar string) {
	slotVar := g.id() + "_slot"
	anchor := slotVar + "_a"

	// Create the anchor comment and wire it into the DOM tree.
	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('slot:%s');\n", anchor, slot.Name))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))

	// The insertion of slot content MUST happen after wiring (anchor needs a parentNode),
	// so we emit into g.init rather than g.create.
	var fnBuf strings.Builder
	fnBuf.WriteString(fmt.Sprintf("  {\n"))
	fnBuf.WriteString(fmt.Sprintf("    const $$sf = $$slots[%q];\n", slot.Name))
	fnBuf.WriteString(fmt.Sprintf("    if ($$sf) {\n"))
	fnBuf.WriteString(fmt.Sprintf(
		"      { const $$sn = $$sf(); %[1]s.before($$sn); }\n",
		anchor, anchor))
	fnBuf.WriteString(fmt.Sprintf("    }"))

	if len(slot.Fallback) > 0 {
		fnBuf.WriteString(fmt.Sprintf(" else {\n"))
		for _, child := range slot.Fallback {
			switch c := child.(type) {
			case *TextNode:
				expr := buildExpr(c.Parts)
				fnBuf.WriteString(fmt.Sprintf(
					"      %[1]s.before(document.createTextNode(%[2]s));\n",
					anchor, expr, anchor))
			case *ElementNode:
				fnBuf.WriteString(fmt.Sprintf(
					"      const $$fb = document.createElement('%s');\n", c.Tag))
				fnBuf.WriteString(fmt.Sprintf(
					"      $$fb.setAttribute('%s','');\n", g.scopeID))
				fnBuf.WriteString(fmt.Sprintf(
					"      %[1]s.before($$fb);\n", anchor, anchor))
			}
		}
		fnBuf.WriteString("    }\n")
	} else {
		fnBuf.WriteString("\n")
	}
	fnBuf.WriteString("  }\n")
	g.init.WriteString(fnBuf.String()) // ← init, not create
}

// walkComponentIfChain handles an IfChainNode where every branch holds a
// ComponentNode (#if / #elseif / #else on component tags).
// It emits a single $$chain_N() function with one cached instance per branch.
func (g *CodeGen) walkComponentIfChain(chain *IfChainNode, parentVar string) {
	anchor := g.id() + "_a"
	fn := "$$chain_" + g.id()

	// One {inst, wrap} pair per branch
	instVars := make([]string, len(chain.Branches))
	wrapVars := make([]string, len(chain.Branches))
	for i := range chain.Branches {
		instVars[i] = fmt.Sprintf("%s_i%d", fn, i)
		wrapVars[i] = fmt.Sprintf("%s_w%d", fn, i)
	}

	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('if-comp-chain');\n", anchor))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))
	for i := range chain.Branches {
		g.create.WriteString(fmt.Sprintf(
			"  let %s = null, %s = null;\n", instVars[i], wrapVars[i]))
	}

	runningFlagC := fn + "_running"
	pendingFlagC := fn + "_pending"
	g.create.WriteString(fmt.Sprintf("  let %s = false, %s = false;\n", runningFlagC, pendingFlagC))

	var fnBuf strings.Builder
	fnBuf.WriteString(fmt.Sprintf("  function %s() {\n", fn))
	fnBuf.WriteString(fmt.Sprintf("    if (%s) { %s = true; return; }\n", runningFlagC, pendingFlagC))
	fnBuf.WriteString(fmt.Sprintf("    %s = true;\n", runningFlagC))
	fnBuf.WriteString(fmt.Sprintf("    try {\n"))
	fnBuf.WriteString("      let $$active = -1;\n")
	for i, branch := range chain.Branches {
		if branch.Cond == "" {
			fnBuf.WriteString(fmt.Sprintf("      if ($$active < 0) $$active = %d;\n", i))
		} else {
			fnBuf.WriteString(fmt.Sprintf("      if ($$active < 0 && (%s)) $$active = %d;\n", branch.Cond, i))
		}
	}

	// Destroy any branch that is no longer active
	for i := range chain.Branches {
		fnBuf.WriteString(fmt.Sprintf(
			"      if ($$active !== %d && %s) { %s.destroy(); %s = null; %s.remove(); %s = null; }\n",
			i, instVars[i], instVars[i], instVars[i], wrapVars[i], wrapVars[i]))
	}

	// Mount the active branch (first time) or update (subsequent times)
	for i, branch := range chain.Branches {
		comp := branch.Comp
		var propsEntries []string
		for _, attr := range comp.Attrs {
			if attr.IsBind {
				propsEntries = append(propsEntries, fmt.Sprintf("%s: %s", attr.Name, attr.Value))
			} else if !attr.IsEvent {
				propsEntries = append(propsEntries, fmt.Sprintf("%s: '%s'", attr.Name, escapeAttr(attr.Value)))
			}
		}
		propsExpr := "{}"
		if len(propsEntries) > 0 {
			propsExpr = "{ " + strings.Join(propsEntries, ", ") + " }"
		}

		fnBuf.WriteString(fmt.Sprintf("      if ($$active === %d) {\n", i))
		fnBuf.WriteString(fmt.Sprintf("        if (!%s) {\n", instVars[i]))
		fnBuf.WriteString(fmt.Sprintf("          %s = document.createElement('div');\n", wrapVars[i]))
		fnBuf.WriteString(fmt.Sprintf("          %s.setAttribute('%s','');\n", wrapVars[i], g.scopeID))
		for _, attr := range comp.Attrs {
			if attr.IsEvent {
				fnBuf.WriteString(fmt.Sprintf(
					"          %s.addEventListener('%s', ($e) => { if ($e instanceof CustomEvent) { (%s)($e); } });\n",
					wrapVars[i], attr.Name, attr.Value))
			}
		}
		fnBuf.WriteString(fmt.Sprintf("          %s = %s(%s, %s, {});\n",
			instVars[i], comp.Name, wrapVars[i], propsExpr))
		fnBuf.WriteString(fmt.Sprintf("          if (%[1]s.parentNode) %[1]s.before(%[2]s);\n",
			anchor, wrapVars[i]))
		fnBuf.WriteString(fmt.Sprintf("        } else { %s.set(%s); }\n", instVars[i], propsExpr))
		fnBuf.WriteString("      }\n")
	}
	fnBuf.WriteString(fmt.Sprintf("    } finally {\n"))
	fnBuf.WriteString(fmt.Sprintf("      %s = false;\n", runningFlagC))
	fnBuf.WriteString(fmt.Sprintf("      if (%s) { %s = false; %s(); }\n", pendingFlagC, pendingFlagC, fn))
	fnBuf.WriteString("    }\n")
	fnBuf.WriteString("  }\n")
	g.create.WriteString(fnBuf.String())

	// Collect all deps from conditions and bound props
	allDeps := map[string]bool{}
	for _, branch := range chain.Branches {
		for _, d := range findDeps(branch.Cond, g.analysis.reactiveNames()) {
			allDeps[d] = true
		}
		for _, attr := range branch.Comp.Attrs {
			if attr.IsBind {
				for _, d := range findDeps(attr.Value, g.analysis.reactiveNames()) {
					allDeps[d] = true
				}
			}
		}
	}

	call := fmt.Sprintf("  %s();", fn)
	g.init.WriteString(call + "\n")
	for dep := range allDeps {
		g.addUpdate(dep, call)
	}

	// Cleanup
	for i := range chain.Branches {
		g.cleanup.WriteString(fmt.Sprintf("      if (%s) %s.destroy();\n", instVars[i], instVars[i]))
	}
}

// ──────────────────────────────────────────────
//  Legacy single #if
// ──────────────────────────────────────────────

func (g *CodeGen) walkIf(elem *ElementNode, varName, parentVar string) {
	// Wrap in a single-branch IfChainNode and delegate.
	chain := &IfChainNode{
		Branches: []*IfBranch{{
			Cond:     elem.IfCond,
			Children: elem.Children,
			Elem:     elem,
		}},
	}
	g.walkIfChain(chain, parentVar)
}

// walkEachBlock handles Svelte-style {#each items as item (key)}...{/each}.
// The block children become the row content. If there's a single ElementNode
// child we use it as the row element directly (zero extra wrapper). Otherwise
// we wrap all children in a synthetic <div>.
func (g *CodeGen) walkEachBlock(block *EachBlockNode, parentVar string) {
	// Determine the row element: use single-child element directly, else wrap.
	var rowElem *ElementNode
	if len(block.Children) == 1 {
		if el, ok := block.Children[0].(*ElementNode); ok {
			rowElem = el
		}
	}

	if rowElem == nil {
		// Multiple children or non-element: synthesize a wrapper div
		rowElem = &ElementNode{
			Tag:      "div",
			Children: block.Children,
		}
	}

	// Copy the each/key onto a fresh element and delegate to the existing walkEach
	wrapper := &ElementNode{
		Tag:      rowElem.Tag,
		Attrs:    rowElem.Attrs,
		Children: rowElem.Children,
		EachExpr: block.EachExpr,
		EachKey:  block.EachKey,
	}
	varName := g.id()
	g.walkEach(wrapper, varName, parentVar)
}

// ──────────────────────────────────────────────
//  #each blocks  (keyed + recursive via FragGen)
// ──────────────────────────────────────────────

func (g *CodeGen) walkEach(elem *ElementNode, varName, parentVar string) {
	array, itemVar, indexVar := parseEachExpr(elem.EachExpr)
	if indexVar == "" {
		indexVar = "$$i"
	}
	keyExpr := elem.EachKey // "" means unkeyed

	anchor := varName + "_a"
	blocks := varName + "_bs"
	fn := "$$each_" + varName

	g.create.WriteString(fmt.Sprintf(
		"  const %s = document.createComment('#each');\n", anchor))
	g.wire.WriteString(fmt.Sprintf("  %s.appendChild(%s);\n", parentVar, anchor))

	// Generate a fragment builder function for one row.
	// Use frag.id() for the root element so the counter is already at 1
	// when WalkNodes processes children — preventing variable name collisions.
	fragName := "$$frag_" + varName
	fragParams := []string{itemVar, indexVar}
	frag := newFragGen(fragName, fragParams, g.scopeID, g.analysis)

	rowVar := frag.id() // always "$$f0"; children will be $$f1, $$f2, …
	frag.create.WriteString(fmt.Sprintf("    const %s = document.createElement('%s');\n", rowVar, elem.Tag))
	frag.create.WriteString(fmt.Sprintf("    %s.setAttribute('%s', '');\n", rowVar, g.scopeID))

	for _, attr := range elem.Attrs {
		switch {
		case attr.IsEvent:
			handler := attr.Value
			if isSimpleIdent(handler) {
				frag.events.WriteString(fmt.Sprintf(
					"    %s.addEventListener('%s', %s);\n", rowVar, attr.Name, handler))
				frag.cleanup.WriteString(fmt.Sprintf(
					"        %s.removeEventListener('%s', %s);\n", rowVar, attr.Name, handler))
			} else if isHandlerExpr(handler) {
				hv := rowVar + "_" + attr.Name + "_h"
				frag.create.WriteString(fmt.Sprintf("    const %s = %s;\n", hv, handler))
				frag.events.WriteString(fmt.Sprintf(
					"    %s.addEventListener('%s', %s);\n", rowVar, attr.Name, hv))
				frag.cleanup.WriteString(fmt.Sprintf(
					"        %s.removeEventListener('%s', %s);\n", rowVar, attr.Name, hv))
			} else {
				hv := rowVar + "_" + attr.Name + "_h"
				frag.create.WriteString(fmt.Sprintf(
					"    const %s = ($event) => { %s; };\n", hv, handler))
				frag.events.WriteString(fmt.Sprintf(
					"    %s.addEventListener('%s', %s);\n", rowVar, attr.Name, hv))
				frag.cleanup.WriteString(fmt.Sprintf(
					"        %s.removeEventListener('%s', %s);\n", rowVar, attr.Name, hv))
			}
		case attr.IsBind:
			stmt := bindAttrStmt(rowVar, attr.Name, attr.Value, "    ")
			frag.init.WriteString(stmt + "\n")
			frag.update.WriteString("  " + stmt + "\n")
		default:
			frag.create.WriteString(fmt.Sprintf(
				"    %s.setAttribute('%s', '%s');\n", rowVar, attr.Name, escapeAttr(attr.Value)))
		}
	}

	// Recursively walk children into the fragment
	frag.WalkNodes(elem.Children, rowVar)

	// Emit the fragment function
	g.create.WriteString(frag.Emit())

	if keyExpr != "" {
		// ── Keyed reconciliation ─────────────────────────────────────────
		keyMap := varName + "_km"
		g.create.WriteString(fmt.Sprintf("  const %s = new Map();\n", keyMap))
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", blocks))

		var fnBuf strings.Builder
		fnBuf.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fn))
		fnBuf.WriteString(fmt.Sprintf("    const $$newKeys = new Set();\n"))
		fnBuf.WriteString(fmt.Sprintf("    const $$newBlocks = [];\n"))
		fnBuf.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fnBuf.WriteString(fmt.Sprintf("      const $$key = String(%s);\n", keyExpr))
		fnBuf.WriteString(fmt.Sprintf("      $$newKeys.add($$key);\n"))
		fnBuf.WriteString(fmt.Sprintf("      let $$blk = %s.get($$key);\n", keyMap))
		fnBuf.WriteString(fmt.Sprintf("      if ($$blk) {\n"))
		// Update existing block with new item/index values
		fnBuf.WriteString(fmt.Sprintf("        if ($$blk.update) $$blk.update(%s, %s);\n", itemVar, indexVar))
		fnBuf.WriteString(fmt.Sprintf("      } else {\n"))
		// Create new block
		fnBuf.WriteString(fmt.Sprintf("        $$blk = %s(%s, %s);\n", fragName, itemVar, indexVar))
		fnBuf.WriteString(fmt.Sprintf("        %s.set($$key, $$blk);\n", keyMap))
		fnBuf.WriteString(fmt.Sprintf("      }\n"))
		// Move/insert into correct position before anchor
		fnBuf.WriteString(fmt.Sprintf("      %[1]s.before($$blk.el);\n", anchor))
		fnBuf.WriteString(fmt.Sprintf("      $$newBlocks.push($$blk);\n"))
		fnBuf.WriteString(fmt.Sprintf("    });\n"))
		// Remove stale blocks
		fnBuf.WriteString(fmt.Sprintf("    %s.forEach(($$blk, $$key) => {\n", keyMap))
		fnBuf.WriteString(fmt.Sprintf("      if (!$$newKeys.has($$key)) { $$blk.destroy(); %s.delete($$key); }\n", keyMap))
		fnBuf.WriteString(fmt.Sprintf("    });\n"))
		fnBuf.WriteString(fmt.Sprintf("    %s = $$newBlocks;\n", blocks))
		fnBuf.WriteString(fmt.Sprintf("  }\n"))
		g.create.WriteString(fnBuf.String())
	} else {
		// ── Unkeyed: full teardown + rebuild ─────────────────────────────
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", blocks))

		var fnBuf strings.Builder
		fnBuf.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fn))
		fnBuf.WriteString(fmt.Sprintf("    %s.forEach(b => b.destroy());\n", blocks))
		fnBuf.WriteString(fmt.Sprintf("    %s = [];\n", blocks))
		fnBuf.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fnBuf.WriteString(fmt.Sprintf("      const $$blk = %s(%s, %s);\n", fragName, itemVar, indexVar))
		fnBuf.WriteString(fmt.Sprintf("      %[1]s.before($$blk.el);\n", anchor))
		fnBuf.WriteString(fmt.Sprintf("      %s.push($$blk);\n", blocks))
		fnBuf.WriteString(fmt.Sprintf("    });\n  }\n"))
		g.create.WriteString(fnBuf.String())
	}

	call := fmt.Sprintf("  %s(%s);", fn, array)
	g.init.WriteString(call + "\n")
	for _, dep := range findDeps(array, g.analysis.reactiveNames()) {
		g.addUpdate(dep, call)
	}

	// Re-run on changes to any variable referenced inside the row:
	// — bind attrs on the root element itself (e.g. :class="activePage === p.id")
	// — any expression in the row's children
	innerDeps := map[string]bool{}
	for _, attr := range elem.Attrs {
		if attr.IsBind {
			for _, d := range findDeps(attr.Value, g.analysis.reactiveNames()) {
				innerDeps[d] = true
			}
		}
	}
	for dep := range g.collectFragDeps(elem.Children) {
		innerDeps[dep] = true
	}
	for dep := range innerDeps {
		g.addUpdate(dep, call)
	}

	// Wire cleanup
	g.cleanup.WriteString(fmt.Sprintf("      %s.forEach(b => b.destroy());\n", blocks))
}

// collectFragDeps walks a node subtree and returns all reactive variable names
// that appear in expressions (text interpolations, bind attrs, if conditions).
func (g *CodeGen) collectFragDeps(nodes []Node) map[string]bool {
	deps := map[string]bool{}
	allNames := g.analysis.reactiveNames()

	var walk func([]Node)
	walk = func(ns []Node) {
		for _, node := range ns {
			switch n := node.(type) {
			case *TextNode:
				expr := buildExpr(n.Parts)
				for _, d := range findDeps(expr, allNames) {
					deps[d] = true
				}
			case *ElementNode:
				for _, attr := range n.Attrs {
					if attr.IsBind {
						for _, d := range findDeps(attr.Value, allNames) {
							deps[d] = true
						}
					}
				}
				if n.IfCond != "" {
					for _, d := range findDeps(n.IfCond, allNames) {
						deps[d] = true
					}
				}
				walk(n.Children)
			case *IfChainNode:
				for _, branch := range n.Branches {
					for _, d := range findDeps(branch.Cond, allNames) {
						deps[d] = true
					}
					walk(branch.Children)
				}
			case *EachBlockNode:
				for _, d := range findDeps(parseEachExprArray(n.EachExpr), allNames) {
					deps[d] = true
				}
				walk(n.Children)
			}
		}
	}
	walk(nodes)
	return deps
}

// emitBranchChildren recursively emits DOM creation code for a node list
// directly into a strings.Builder (used inside #if chain functions and similar
// closures where we can't use the normal g.create/g.wire buffers).
// parentVar is the JS variable that children should be appended to.
// indent is the leading whitespace for each emitted line.
func (g *CodeGen) emitBranchChildren(b *strings.Builder, branchVar string, nodes []Node, parentVar, indent string) []string {
	var declared []string
	for _, node := range nodes {
		switch n := node.(type) {
		case *TextNode:
			expr := buildExpr(n.Parts)
			hasExpr := false
			for _, p := range n.Parts {
				if !p.Static {
					hasExpr = true
					break
				}
			}
			if hasExpr && branchVar != "" {
				tv := g.id()
				g.create.WriteString(fmt.Sprintf("  let %s = null;\n", tv))
				b.WriteString(fmt.Sprintf("%s%s = document.createTextNode(%s);\n", indent, tv, expr))
				b.WriteString(fmt.Sprintf("%s%s.appendChild(%s);\n", indent, parentVar, tv))
				for _, dep := range findDeps(expr, g.analysis.reactiveNames()) {
					g.addUpdate(dep, fmt.Sprintf("  if (%s) %s.data = %s;", branchVar, tv, expr))
				}
				declared = append(declared, tv)
			} else {
				b.WriteString(fmt.Sprintf("%s%s.appendChild(document.createTextNode(%s));\n",
					indent, parentVar, expr))
			}

		case *ElementNode:
			if n.EachExpr != "" || n.IfCond != "" {
				b.WriteString(fmt.Sprintf("%s// (nested directive on <%s> — skipped in branch)\n", indent, n.Tag))
				continue
			}
			subVar := g.id()
			if branchVar != "" {
				g.create.WriteString(fmt.Sprintf("  let %s = null;\n", subVar))
				b.WriteString(fmt.Sprintf("%s%s = document.createElement('%s');\n", indent, subVar, n.Tag))
			} else {
				b.WriteString(fmt.Sprintf("%sconst %s = document.createElement('%s');\n", indent, subVar, n.Tag))
			}
			b.WriteString(fmt.Sprintf("%s%s.setAttribute('%s', '');\n", indent, subVar, g.scopeID))
			for _, attr := range n.Attrs {
				if attr.IsEvent {
					handler := g.rewriteHandlerAssignments(attr.Value)
					b.WriteString(fmt.Sprintf("%s%s.addEventListener('%s', %s);\n",
						indent, subVar, attr.Name, handler))
				} else if attr.IsBind {
					b.WriteString(bindAttrStmt(subVar, attr.Name, attr.Value, indent) + "\n")
					if branchVar != "" {
						upd := fmt.Sprintf("  if (%s) %s", branchVar,
							strings.TrimSpace(bindAttrStmt(subVar, attr.Name, attr.Value, "")))
						for _, dep := range findDeps(attr.Value, g.analysis.reactiveNames()) {
							g.addUpdate(dep, upd)
						}
					}
				} else {
					b.WriteString(fmt.Sprintf("%s%s.setAttribute('%s', '%s');\n",
						indent, subVar, attr.Name, escapeAttr(attr.Value)))
				}
			}
			childDeclared := g.emitBranchChildren(b, branchVar, n.Children, subVar, indent)
			b.WriteString(fmt.Sprintf("%s%s.appendChild(%s);\n", indent, parentVar, subVar))
			if branchVar != "" {
				declared = append(declared, subVar)
			}
			declared = append(declared, childDeclared...)

		case *IfChainNode:
			for i, branch := range n.Branches {
				if i == 0 {
					b.WriteString(fmt.Sprintf("%sif (%s) {\n", indent, branch.Cond))
				} else if branch.Cond == "" {
					b.WriteString(fmt.Sprintf("%s} else {\n", indent))
				} else {
					b.WriteString(fmt.Sprintf("%s} else if (%s) {\n", indent, branch.Cond))
				}
				g.emitBranchChildren(b, "", branch.Children, parentVar, indent+"  ")
			}
			if len(n.Branches) > 0 {
				b.WriteString(fmt.Sprintf("%s}\n", indent))
			}

		case *EachBlockNode:
			if eachChildrenNeedCodegen(n.Children) {
				// Children contain ComponentNode / IfChainNode — FragGen can't handle
				// these, so we generate a keyed live reconciler here in codegen.
				// This replaces the old static forEach (which never updated on re-render).
				g.emitEachWithComponents(b, n, parentVar, branchVar, indent)
				break
			}
			savedWire := g.wire
			savedInit := g.init
			g.wire = strings.Builder{}
			g.init = strings.Builder{}
			g.walkEachBlock(n, parentVar)
			eachWire := g.wire.String()
			eachInit := g.init.String()
			g.wire = savedWire
			g.init = savedInit
			for _, line := range strings.Split(eachWire, "\n") {
				if t := strings.TrimSpace(line); t != "" {
					b.WriteString(indent + t + "\n")
				}
			}
			for _, line := range strings.Split(eachInit, "\n") {
				if t := strings.TrimSpace(line); t != "" {
					b.WriteString(indent + t + "\n")
				}
			}

		case *ComponentNode:
			compDeclared := g.emitBranchComponent(b, n, parentVar, indent)
			declared = append(declared, compDeclared...)

		case *SlotNode:
			sv := fmt.Sprintf("$$sf_%s", g.id())
			b.WriteString(fmt.Sprintf("%sconst %s = $$slots[%q];\n", indent, sv, n.Name))
			b.WriteString(fmt.Sprintf("%sif (%s) { %s.appendChild(%s()); }\n", indent, sv, parentVar, sv))
			if len(n.Fallback) > 0 {
				b.WriteString(fmt.Sprintf("%selse {\n", indent))
				g.emitBranchChildren(b, "", n.Fallback, parentVar, indent+"  ")
				b.WriteString(fmt.Sprintf("%s}\n", indent))
			}
		}
	}
	return declared
}


// ─────────────────────────────────────────────────────────────────────────
//  Live {#each} reconciler for complex children (components, {#if}, etc.)
// ─────────────────────────────────────────────────────────────────────────

// emitEachWithComponents generates a keyed live reconciler for an {#each}
// block whose children contain ComponentNode, IfChainNode, or nested each
// — node types that FragGen cannot handle.
//
// Unlike the old static forEach, this generates an $$each_N(arr) function
// at component scope.  The function is:
//   • Called immediately from the branch body to render on first mount.
//   • Registered in g.addUpdate so it re-runs whenever the array changes.
//   • Guarded by `if (!anchor.parentNode) return` so it no-ops when the
//     enclosing {#if} branch is not currently mounted.
//
// Each row is represented as a { root, update(item), destroy() } block
// stored in a Map<key, block>.  Existing rows call update(); new rows are
// created; missing rows are destroyed.  This preserves component instance
// state (focus, scroll, form values) across array mutations.
func (g *CodeGen) emitEachWithComponents(
	b *strings.Builder,
	n *EachBlockNode,
	parentVar, branchVar, indent string,
) {
	array, itemVar, indexVar := parseEachExpr(n.EachExpr)
	if indexVar == "" {
		indexVar = "$$i"
	}
	keyExpr := n.EachKey // may be "" for unkeyed

	// All variables live at component scope so the update function
	// can reference them even when called from a setter (outside the branch).
	anchorVar := g.id() + "_a"
	kmVar     := g.id() + "_km"
	fnVar     := "$$each_" + g.id()

	g.create.WriteString(fmt.Sprintf("  const %s = document.createComment('#each');\n", anchorVar))
	if keyExpr != "" {
		g.create.WriteString(fmt.Sprintf("  const %s = new Map();\n", kmVar))
	} else {
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", kmVar)) // array of blocks
	}

	// Build the reconciler function body
	var fn strings.Builder

	fn.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fnVar))
	// Guard: no-op when anchor is not in the DOM (branch not mounted yet)
	fn.WriteString(fmt.Sprintf("    if (!%s.parentNode) return;\n", anchorVar))

	if keyExpr != "" {
		fn.WriteString("    const $$newKeys = new Set();\n")
		fn.WriteString("    const $$newBlks = [];\n")
		fn.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fn.WriteString(fmt.Sprintf("      const $$key = String(%s);\n", keyExpr))
		fn.WriteString("      $$newKeys.add($$key);\n")
		fn.WriteString(fmt.Sprintf("      let $$blk = %s.get($$key);\n", kmVar))
		fn.WriteString("      if ($$blk) {\n")
		fn.WriteString("        $$blk.update(" + itemVar + ");\n")
		fn.WriteString("      } else {\n")
		// Create row
		fn.WriteString("        $$blk = (() => {\n")
		fn.WriteString("          const $$row = document.createElement('div');\n")
		fn.WriteString(fmt.Sprintf("          $$row.setAttribute('%s','');\n", g.scopeID))
		var createBuf, updateBuf, destroyBuf strings.Builder
		g.emitEachRowBody(&createBuf, &updateBuf, &destroyBuf, n.Children, "$$row", itemVar, "          ")
		fn.WriteString(createBuf.String())
		fn.WriteString("          return {\n")
		fn.WriteString("            root: $$row,\n")
		fn.WriteString("            update(" + itemVar + ") {\n")
		fn.WriteString(updateBuf.String())
		fn.WriteString("            },\n")
		fn.WriteString("            destroy() {\n")
		fn.WriteString(destroyBuf.String())
		fn.WriteString("              $$row.remove();\n")
		fn.WriteString("            }\n")
		fn.WriteString("          };\n")
		fn.WriteString("        })();\n")
		fn.WriteString(fmt.Sprintf("        %s.set($$key, $$blk);\n", kmVar))
		fn.WriteString("      }\n")
		// Position: insert before anchor if not already there
		fn.WriteString(fmt.Sprintf(
			"      if ($$blk.root.nextSibling !== %s) { %s.before($$blk.root); }\n",
			anchorVar, anchorVar))
		fn.WriteString("      $$newBlks.push($$blk);\n")
		fn.WriteString("    });\n")
		// Destroy removed rows
		fn.WriteString(fmt.Sprintf(
			"    %s.forEach(($$blk, $$k) => { if (!$$newKeys.has($$k)) { $$blk.destroy(); %s.delete($$k); } });\n",
			kmVar, kmVar))
	} else {
		// Unkeyed: destroy all, then rebuild
		fn.WriteString(fmt.Sprintf("    %s.forEach($$blk => $$blk.destroy());\n", kmVar))
		fn.WriteString(fmt.Sprintf("    %s = [];\n", kmVar))
		fn.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fn.WriteString("      const $$row = document.createElement('div');\n")
		fn.WriteString(fmt.Sprintf("      $$row.setAttribute('%s','');\n", g.scopeID))
		var createBuf, updateBuf, destroyBuf strings.Builder
		g.emitEachRowBody(&createBuf, &updateBuf, &destroyBuf, n.Children, "$$row", itemVar, "      ")
		fn.WriteString(createBuf.String())
		fn.WriteString(fmt.Sprintf("      %s.before($$row);\n", anchorVar))
		fn.WriteString(fmt.Sprintf("      %s.push({ root: $$row, destroy() {\n", kmVar))
		fn.WriteString(destroyBuf.String())
		fn.WriteString("        $$row.remove();\n")
		fn.WriteString("      }});\n")
		fn.WriteString("    });\n")
	}
	fn.WriteString("  }\n")

	g.create.WriteString(fn.String())

	// Branch body: append anchor, call the reconciler once for initial render
	b.WriteString(fmt.Sprintf("%s%s.appendChild(%s);\n", indent, parentVar, anchorVar))
	b.WriteString(fmt.Sprintf("%s%s(%s);\n", indent, fnVar, array))

	// Register reactive update: fires whenever the array variable changes,
	// even when the branch condition itself hasn't changed.
	for _, dep := range findDeps(array, g.analysis.reactiveNames()) {
		guard := ""
		if branchVar != "" {
			guard = fmt.Sprintf("  if (%s) ", branchVar)
		}
		g.addUpdate(dep, guard+fmt.Sprintf("%s(%s);", fnVar, array))
	}
}

// emitEachRowBody generates the create / update / destroy snippets for one
// row of an {#each} block.  It recursively handles elements, text, and
// components.
//
//   createBuf  — statements that build DOM (run once per row creation)
//   updateBuf  — statements that refresh bound values (run on each array update)
//   destroyBuf — statements that clean up (run when row is removed)
//   nodes      — the children of the {#each} block
//   parentVar  — JS variable the row nodes are appended to ("$$row")
//   itemVar    — the loop variable name (e.g. "order")
//   indent     — leading whitespace
func (g *CodeGen) emitEachRowBody(
	createBuf, updateBuf, destroyBuf *strings.Builder,
	nodes []Node,
	parentVar, itemVar, indent string,
) {
	for _, node := range nodes {
		switch n := node.(type) {

		case *TextNode:
			expr := buildExpr(n.Parts)
			hasExpr := false
			for _, p := range n.Parts {
				if !p.Static { hasExpr = true; break }
			}
			if hasExpr {
				tv := g.id()
				createBuf.WriteString(fmt.Sprintf("%sconst %s = document.createTextNode(%s);\n", indent, tv, expr))
				createBuf.WriteString(fmt.Sprintf("%s%s.appendChild(%s);\n", indent, parentVar, tv))
				// Only add to update if the expression references the item variable
				if strings.Contains(expr, itemVar) {
					updateBuf.WriteString(fmt.Sprintf("              %s.data = %s;\n", tv, expr))
				}
			} else {
				createBuf.WriteString(fmt.Sprintf("%s%s.appendChild(document.createTextNode(%s));\n", indent, parentVar, expr))
			}

		case *ElementNode:
			if n.EachExpr != "" || n.IfCond != "" {
				// Nested directive — recurse children directly into same parent
				g.emitEachRowBody(createBuf, updateBuf, destroyBuf, n.Children, parentVar, itemVar, indent)
				continue
			}
			sv := g.id()
			createBuf.WriteString(fmt.Sprintf("%sconst %s = document.createElement('%s');\n", indent, sv, n.Tag))
			createBuf.WriteString(fmt.Sprintf("%s%s.setAttribute('%s','');\n", indent, sv, g.scopeID))
			for _, attr := range n.Attrs {
				if attr.IsEvent {
					handler := g.rewriteHandlerAssignments(attr.Value)
					createBuf.WriteString(fmt.Sprintf("%s%s.addEventListener('%s', %s);\n",
						indent, sv, attr.Name, handler))
				} else if attr.IsBind {
					createBuf.WriteString(bindAttrStmt(sv, attr.Name, attr.Value, indent) + "\n")
					if strings.Contains(attr.Value, itemVar) {
						updateBuf.WriteString(fmt.Sprintf("              %s\n",
							strings.TrimSpace(bindAttrStmt(sv, attr.Name, attr.Value, ""))))
					}
				} else {
					createBuf.WriteString(fmt.Sprintf("%s%s.setAttribute('%s','%s');\n",
						indent, sv, attr.Name, escapeAttr(attr.Value)))
				}
			}
			g.emitEachRowBody(createBuf, updateBuf, destroyBuf, n.Children, sv, itemVar, indent)
			createBuf.WriteString(fmt.Sprintf("%s%s.appendChild(%s);\n", indent, parentVar, sv))

		case *ComponentNode:
			wv := g.id()
			cv := g.id() + "_comp"
			// Build props expression from bound attrs
			var propsEntries []string
			for _, attr := range n.Attrs {
				if attr.IsBind {
					propsEntries = append(propsEntries, fmt.Sprintf("%s: %s", attr.Name, attr.Value))
				} else if !attr.IsEvent {
					propsEntries = append(propsEntries, fmt.Sprintf("%s: '%s'", attr.Name, escapeAttr(attr.Value)))
				}
			}
			propsExpr := "{}"
			if len(propsEntries) > 0 {
				propsExpr = "{ " + strings.Join(propsEntries, ", ") + " }"
			}
			createBuf.WriteString(fmt.Sprintf("%sconst %s = document.createElement('div');\n", indent, wv))
			createBuf.WriteString(fmt.Sprintf("%s%s.setAttribute('%s','');\n", indent, wv, g.scopeID))
			// Wire event listeners
			for _, attr := range n.Attrs {
				if attr.IsEvent {
					createBuf.WriteString(fmt.Sprintf(
						"%s%s.addEventListener('%s', ($e) => { if ($e instanceof CustomEvent) { (%s)($e); } });\n",
						indent, wv, attr.Name, attr.Value))
				}
			}
			createBuf.WriteString(fmt.Sprintf("%sconst %s = %s(%s, %s, {});\n",
				indent, cv, n.Name, wv, propsExpr))
			createBuf.WriteString(fmt.Sprintf("%s%s.appendChild(%s);\n", indent, parentVar, wv))
			// Update: call .set() with fresh props if any reference itemVar
			if strings.Contains(propsExpr, itemVar) {
				updateBuf.WriteString(fmt.Sprintf("              %s.set(%s);\n", cv, propsExpr))
			}
			// Destroy: call .destroy()
			destroyBuf.WriteString(fmt.Sprintf("              %s.destroy();\n", cv))

		case *IfChainNode:
			// Inline if/else inside a row — static for now (condition evaluated at create time)
			// TODO: make reactive by generating a per-row chain function
			for i, branch := range n.Branches {
				if i == 0 {
					createBuf.WriteString(fmt.Sprintf("%sif (%s) {\n", indent, branch.Cond))
				} else if branch.Cond == "" {
					createBuf.WriteString(fmt.Sprintf("%s} else {\n", indent))
				} else {
					createBuf.WriteString(fmt.Sprintf("%s} else if (%s) {\n", indent, branch.Cond))
				}
				g.emitEachRowBody(createBuf, updateBuf, destroyBuf, branch.Children, parentVar, itemVar, indent+"  ")
			}
			if len(n.Branches) > 0 {
				createBuf.WriteString(fmt.Sprintf("%s}\n", indent))
			}
		}
	}
}

// eachChildrenNeedCodegen returns true when an {#each} block's children contain
// node types that require the full codegen pipeline (IfChainNode, ComponentNode)
// and therefore cannot safely be processed by FragGen inside walkEachBlock.
// When true, emitBranchChildren falls back to an inline forEach instead.
func eachChildrenNeedCodegen(nodes []Node) bool {
	for _, n := range nodes {
		switch c := n.(type) {
		case *IfChainNode:
			return true
		case *ComponentNode:
			return true
		case *EachBlockNode:
			return true
		case *ElementNode:
			if eachChildrenNeedCodegen(c.Children) {
				return true
			}
		}
	}
	return false
}

// emitBranchComponent emits inline component mounting code inside a branch
// and returns the names of component-scope variables it declared (instanceVar,
// wrapVar) so walkIfChain can null them out when the branch is removed.
func (g *CodeGen) emitBranchComponent(b *strings.Builder, comp *ComponentNode, parentVar, indent string) []string {
	var declared []string
	// Build props object expression
	var propsEntries []string
	for _, attr := range comp.Attrs {
		if attr.IsBind {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: %s", attr.Name, attr.Value))
		} else if !attr.IsEvent {
			propsEntries = append(propsEntries, fmt.Sprintf("%s: '%s'", attr.Name, escapeAttr(attr.Value)))
		}
	}
	propsExpr := "{}"
	if len(propsEntries) > 0 {
		propsExpr = "{ " + strings.Join(propsEntries, ", ") + " }"
	}

	// Event listener snippets (CustomEvent-guarded)
	evWire := func(wrapVar string, indentLevel string) string {
		var s strings.Builder
		for _, attr := range comp.Attrs {
			if attr.IsEvent {
				s.WriteString(fmt.Sprintf(
					"%s%s.addEventListener('%s', ($e) => { if ($e instanceof CustomEvent) { (%s)($e); } });\n",
					indentLevel, wrapVar, attr.Name, attr.Value))
			}
		}
		return s.String()
	}

	if comp.IfCond != "" {
		// <Comp #if="cond" /> inside a branch — lift vars to component scope so
		// bound props can be updated reactively via g.addUpdate.
		wrapVar  := g.id()
		instVar  := g.id() + "_comp"
		g.create.WriteString(fmt.Sprintf("  let %s = null;\n", wrapVar))
		g.create.WriteString(fmt.Sprintf("  let %s = null;\n", instVar))
		b.WriteString(fmt.Sprintf("%sif (%s) {\n", indent, comp.IfCond))
		b.WriteString(fmt.Sprintf("%s  %s = document.createElement('div');\n", indent, wrapVar))
		b.WriteString(fmt.Sprintf("%s  %s.setAttribute('%s','');\n", indent, wrapVar, g.scopeID))
		b.WriteString(evWire(wrapVar, indent+"  "))
		b.WriteString(fmt.Sprintf("%s  %s = %s(%s, %s, {});\n", indent, instVar, comp.Name, wrapVar, propsExpr))
		b.WriteString(fmt.Sprintf("%s  %s.appendChild(%s);\n", indent, parentVar, wrapVar))
		b.WriteString(fmt.Sprintf("%s}\n", indent))
		// Register reactive prop updates — guarded by instVar so they no-op when condition is false
		for _, attr := range comp.Attrs {
			if !attr.IsBind {
				continue
			}
			update := fmt.Sprintf("  if (%s) %s.set({ %s: %s });", instVar, instVar, attr.Name, attr.Value)
			for _, dep := range findDeps(attr.Value, g.analysis.reactiveNames()) {
				g.addUpdate(dep, update)
			}
		}
		declared = append(declared, wrapVar, instVar)
		return declared
	}

	if comp.EachExpr == "" {
		// Plain single-mount component inside a branch.
		//
		// wrapVar and instVar are lifted to COMPONENT SCOPE (let ... = null in g.create)
		// so that:
		//   (a) Reactive setters can call instVar.set({prop: val}) via g.addUpdate
		//       registrations, updating the component when bound props change — even
		//       when the branch condition hasn't changed.
		//   (b) walkIfChain nulls them out (via branchDeclared) when the branch is
		//       removed, which triggers the guard `if (instVar)` in update statements.
		//   (c) The destroy() call fires on branch removal so the child component
		//       cleans up its own event listeners and styles.
		wrapVar := g.id()
		instVar := g.id() + "_comp"
		g.create.WriteString(fmt.Sprintf("  let %s = null;\n", wrapVar))
		g.create.WriteString(fmt.Sprintf("  let %s = null;\n", instVar))
		b.WriteString(fmt.Sprintf("%s%s = document.createElement('div');\n", indent, wrapVar))
		b.WriteString(fmt.Sprintf("%s%s.setAttribute('%s','');\n", indent, wrapVar, g.scopeID))
		b.WriteString(evWire(wrapVar, indent))
		b.WriteString(fmt.Sprintf("%s%s = %s(%s, %s, {});\n", indent, instVar, comp.Name, wrapVar, propsExpr))
		b.WriteString(fmt.Sprintf("%s%s.appendChild(%s);\n", indent, parentVar, wrapVar))
		// Register reactive prop updates — fire directly from setters, bypassing
		// the chain function so the component gets fresh props without DOM recreation.
		for _, attr := range comp.Attrs {
			if !attr.IsBind {
				continue
			}
			update := fmt.Sprintf("  if (%s) %s.set({ %s: %s });", instVar, instVar, attr.Name, attr.Value)
			for _, dep := range findDeps(attr.Value, g.analysis.reactiveNames()) {
				g.addUpdate(dep, update)
			}
		}
		declared = append(declared, wrapVar, instVar)
		return declared
	}

	// ── #each component inside a branch ──────────────────────────────────────
	// Both the anchor AND the update function must live at component scope so
	// that the hoisted $$bceach_ function can reference the anchor by name.
	// If the anchor were declared inside the branch body (b), it would be
	// undefined when $$bceach_ is called from dep-triggered updates.
	array, itemVar, indexVar := parseEachExpr(comp.EachExpr)
	if indexVar == "" {
		indexVar = "$$i"
	}

	anchorVar := g.id() + "_a"
	fnVar := "$$bceach_" + g.id()
	allNames := g.analysis.reactiveNames()

	// Anchor: declared and wired at component scope.
	// The branch body appends it to parentVar when the branch first mounts.
	g.create.WriteString(fmt.Sprintf("  const %s = document.createComment('#each-comp');\n", anchorVar))
	// Wire: appended to parentVar from the branch body (below) — not via g.wire
	// because parentVar is a branch-local variable, not a fixed component element.
	// Instead we write the appendChild into b (runs on first branch mount).
	b.WriteString(fmt.Sprintf("%s%s.appendChild(%s);\n", indent, parentVar, anchorVar))

	if comp.EachKey != "" {
		// Keyed — hoist Map and update fn to component scope
		kmVar := g.id() + "_km"
		bsVar := g.id() + "_bs"

		// Component-scope declarations
		g.create.WriteString(fmt.Sprintf("  const %s = new Map();\n", kmVar))
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", bsVar))

		// Component-scope update function — guarded so it's a no-op when the
		// branch hasn't mounted yet (anchor has no parentNode).
		var fn strings.Builder
		fn.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fnVar))
		fn.WriteString(fmt.Sprintf("    if (!%s.parentNode) return;\n", anchorVar))
		fn.WriteString("    const $$newKeys = new Set();\n")
		fn.WriteString("    const $$newBlks = [];\n")
		fn.WriteString(fmt.Sprintf("    ($$arr||[]).forEach(function(%s, %s) {\n", itemVar, indexVar))
		fn.WriteString(fmt.Sprintf("      const $$key = String(%s);\n", comp.EachKey))
		fn.WriteString("      $$newKeys.add($$key);\n")
		fn.WriteString(fmt.Sprintf("      let $$blk = %s.get($$key);\n", kmVar))
		fn.WriteString(fmt.Sprintf("      if ($$blk) { $$blk.comp.set(%s); } else {\n", propsExpr))
		wrapVar := g.id()
		fn.WriteString(fmt.Sprintf("        const %s = document.createElement('div');\n", wrapVar))
		fn.WriteString(fmt.Sprintf("        %s.setAttribute('%s','');\n", wrapVar, g.scopeID))
		fn.WriteString(evWire(wrapVar, "        "))
		fn.WriteString(fmt.Sprintf("        const $$c = %s(%s, %s, {});\n", comp.Name, wrapVar, propsExpr))
		fn.WriteString(fmt.Sprintf("        $$blk = { wrap: %s, comp: $$c };\n", wrapVar))
		fn.WriteString(fmt.Sprintf("        %s.set($$key, $$blk);\n", kmVar))
		fn.WriteString("      }\n")
		fn.WriteString(fmt.Sprintf("      if ($$blk.wrap.nextSibling !== %s) { %s.before($$blk.wrap); }\n",
			anchorVar, anchorVar, anchorVar))
		fn.WriteString("      $$newBlks.push($$blk);\n")
		fn.WriteString("    });\n")
		fn.WriteString(fmt.Sprintf("    %s.forEach(($$blk, $$k) => { if (!$$newKeys.has($$k)) { $$blk.comp.destroy(); %s.delete($$k); } });\n", kmVar, kmVar))
		fn.WriteString(fmt.Sprintf("    %s = $$newBlks;\n", bsVar))
		fn.WriteString("  }\n")
		g.create.WriteString(fn.String())

		// Cleanup: destroy all blocks
		g.cleanup.WriteString(fmt.Sprintf("      %s.forEach(b => b.comp.destroy());\n", bsVar))

		// Call from branch (first mount or re-evaluation)
		b.WriteString(fmt.Sprintf("%s%s(%s);\n", indent, fnVar, array))

		// Register as dep update for array and any bound prop expressions
		call := fmt.Sprintf("  %s(%s);", fnVar, array)
		for _, dep := range findDeps(array, allNames) {
			g.addUpdate(dep, call)
		}
		for _, attr := range comp.Attrs {
			if attr.IsBind {
				for _, dep := range findDeps(attr.Value, allNames) {
					g.addUpdate(dep, call)
				}
			}
		}
	} else {
		// Unkeyed — hoist blocks slice and update fn to component scope
		bsVar := g.id() + "_bs"
		g.create.WriteString(fmt.Sprintf("  let %s = [];\n", bsVar))

		var fn strings.Builder
		fn.WriteString(fmt.Sprintf("  function %s($$arr) {\n", fnVar))
		fn.WriteString(fmt.Sprintf("    if (!%s.parentNode) return;\n", anchorVar))
		fn.WriteString(fmt.Sprintf("    %s.forEach(b => b.comp.destroy()); %s = [];\n", bsVar, bsVar))
		fn.WriteString(fmt.Sprintf("    ((%s)||[]).forEach(function(%s, %s) {\n", array, itemVar, indexVar))
		wrapVar := g.id()
		fn.WriteString(fmt.Sprintf("      const %s = document.createElement('div');\n", wrapVar))
		fn.WriteString(fmt.Sprintf("      %s.setAttribute('%s','');\n", wrapVar, g.scopeID))
		fn.WriteString(evWire(wrapVar, "      "))
		fn.WriteString(fmt.Sprintf("      const $$c = %s(%s, %s, {});\n", comp.Name, wrapVar, propsExpr))
		fn.WriteString(fmt.Sprintf("      %[1]s.before(%[2]s);\n", anchorVar, wrapVar, anchorVar))
		fn.WriteString(fmt.Sprintf("      %s.push({ wrap: %s, comp: $$c });\n", bsVar, wrapVar))
		fn.WriteString("    });\n  }\n")
		g.create.WriteString(fn.String())

		g.cleanup.WriteString(fmt.Sprintf("      %s.forEach(b => b.comp.destroy());\n", bsVar))

		b.WriteString(fmt.Sprintf("%s%s(%s);\n", indent, fnVar, array))

		call := fmt.Sprintf("  %s(%s);", fnVar, array)
		for _, dep := range findDeps(array, allNames) {
			g.addUpdate(dep, call)
		}
		for _, attr := range comp.Attrs {
			if attr.IsBind {
				for _, dep := range findDeps(attr.Value, allNames) {
					g.addUpdate(dep, call)
				}
			}
		}
	}
	return declared
}

// rewriteHandlerAssignments rewrites state-variable assignments inside an
// inline event handler expression, e.g.:
//
//	"($e) => visible = $e.target.checked"
//	→ "($e) => $$set_visible($e.target.checked)"
//
//	"($e) => { count = count + 1; step = 2; }"
//	→ "($e) => { $$set_count(count + 1); $$set_step(2); }"
//
// The component-level RewriteAssignments pass never sees template attribute
// strings, so this function handles them independently.
func (g *CodeGen) rewriteHandlerAssignments(handler string) string {
	if len(g.analysis.StateVars) == 0 && len(g.analysis.Props) == 0 {
		return handler
	}
	ss := g.analysis.stateSet()

	// Find the arrow (=>) and extract the body portion.
	// This handles both concise bodies and block bodies.
	arrowIdx := strings.Index(handler, "=>")
	if arrowIdx < 0 {
		return handler // not an arrow — call RewriteAssignments on the whole thing
	}
	body := strings.TrimSpace(handler[arrowIdx+2:])
	params := handler[:arrowIdx+2] // everything up to and including =>

	// Block body: ($e) => { stmts }
	if strings.HasPrefix(body, "{") && strings.HasSuffix(strings.TrimSpace(body), "}") {
		// Strip outer braces, rewrite statements inside, restore braces
		inner := body[1 : len(body)-1]
		prog := ParseJS(inner)
		rewritten := RewriteAssignments(inner, prog, ss)
		return params + " { " + strings.TrimSpace(rewritten) + " }"
	}

	// Concise body: ($e) => expr
	// If it's a simple assignment `x = rhs`, rewrite it directly.
	// Parse as a statement by appending semicolon.
	bodyStmt := body + ";"
	prog := ParseJS(bodyStmt)
	rewritten := RewriteAssignments(bodyStmt, prog, ss)
	if rewritten != bodyStmt {
		// Strip trailing semicolon that RewriteAssignments or the original had
		rewritten = strings.TrimSpace(rewritten)
		rewritten = strings.TrimSuffix(rewritten, ";")
		return params + " " + strings.TrimSpace(rewritten)
	}

	return handler
}

func (g *CodeGen) emitEachChild(b *strings.Builder, node Node, parentVar string) {
	// Inline simple cases without full FragGen overhead (used in legacy paths)
	switch n := node.(type) {
	case *TextNode:
		expr := buildExpr(n.Parts)
		b.WriteString(fmt.Sprintf("      %s.appendChild(document.createTextNode(%s));\n",
			parentVar, expr))
	case *ElementNode:
		b.WriteString(fmt.Sprintf("      {\n"))
		b.WriteString(fmt.Sprintf("        const $$sub = document.createElement('%s');\n", n.Tag))
		b.WriteString(fmt.Sprintf("        $$sub.setAttribute('%s', '');\n", g.scopeID))
		for _, attr := range n.Attrs {
			if attr.IsBind {
				b.WriteString(bindAttrStmt("$$sub", attr.Name, attr.Value, "        ") + "\n")
			} else if !attr.IsEvent {
				b.WriteString(fmt.Sprintf("        $$sub.setAttribute('%s','%s');\n",
					attr.Name, escapeAttr(attr.Value)))
			}
		}
		for _, cc := range n.Children {
			g.emitEachChild(b, cc, "$$sub")
		}
		b.WriteString(fmt.Sprintf("        %s.appendChild($$sub);\n", parentVar))
		b.WriteString(fmt.Sprintf("      }\n"))
	}
}

// ──────────────────────────────────────────────
//  Reactive setters
// ──────────────────────────────────────────────

func (g *CodeGen) genSetter(name string) string {
	var b strings.Builder
	b.WriteString(fmt.Sprintf("  function $$set_%s($$v) {\n", name))
	b.WriteString(fmt.Sprintf("    %s = $$v;\n", name))

	// Fire $$onChange for bindable props so parent can observe
	for _, prop := range g.analysis.Props {
		if prop.Name == name && prop.Bindable {
			b.WriteString(fmt.Sprintf(
				"    if ($$onChange_%s) $$onChange_%s($$v);\n", name, name))
		}
	}

	// Recompute derived vars that (transitively) depend on this var
	for _, dv := range g.analysis.DerivedVars {
		if containsStr(dv.Deps, name) {
			b.WriteString(fmt.Sprintf("    $$upd_%s();\n", dv.Name))
		}
	}

	// Collect DOM updates: direct + via derived
	// All DOM-touching calls are wrapped in $$defer so that when multiple
	// setters fire from the same store notification batch, DOM updates wait
	// until every state variable has been assigned its new value.
	seen := map[string]bool{}
	writeUpdate := func(u string) {
		if !seen[u] {
			seen[u] = true
			trimmed := strings.TrimSpace(u)
			b.WriteString(fmt.Sprintf("    $$defer(() => { %s });\n", trimmed))
		}
	}

	for _, u := range g.updates[name] {
		writeUpdate(u)
	}
	for _, dv := range g.analysis.DerivedVars {
		if containsStr(dv.Deps, name) {
			for _, u := range g.updates[dv.Name] {
				writeUpdate(u)
			}
		}
	}

	// Trigger effects
	for i, eff := range g.analysis.Effects {
		if containsStr(eff.Deps, name) {
			b.WriteString(fmt.Sprintf("    $$effect%d();\n", i))
		}
	}

	b.WriteString("  }\n")
	return b.String()
}

func (g *CodeGen) addUpdate(dep, code string) {
	g.addUpdateSeen(dep, code, map[string]bool{})
}

// addUpdateSeen is the recursive helper for addUpdate. If dep is a DerivedVar,
// it recursively registers the update for all of that derived var's own deps
// (which may themselves be derived), eventually reaching state vars and props.
// This ensures that e.g. {#each filtered as o} inside a Card slot correctly
// re-renders when allOrders changes — even though the each expression uses the
// derived name "filtered", not "allOrders" directly.
func (g *CodeGen) addUpdateSeen(dep, code string, seen map[string]bool) {
	if seen[dep] {
		return // guard against circular deps
	}
	seen[dep] = true
	for _, dv := range g.analysis.DerivedVars {
		if dv.Name == dep {
			// dep is a derived var — register for each of its source deps
			for _, srcDep := range findDeps(dv.Expr, g.analysis.reactiveNames()) {
				g.addUpdateSeen(srcDep, code, seen)
			}
			return
		}
	}
	// dep is a state var or prop — register directly
	g.updates[dep] = append(g.updates[dep], code)
}

// ──────────────────────────────────────────────
//  Expression builders
// ──────────────────────────────────────────────

// buildExpr produces a JS expression that evaluates to the text content
// of a mixed static/dynamic TextNode.
func buildExpr(parts []*Part) string {
	if len(parts) == 1 {
		if parts[0].Static {
			return backtickString(parts[0].Value)
		}
		return "String(" + parts[0].Value + ")"
	}
	var b strings.Builder
	b.WriteByte('`')
	for _, p := range parts {
		if p.Static {
			b.WriteString(escapeTL(p.Value))
		} else {
			b.WriteString("${")
			b.WriteString(p.Value)
			b.WriteByte('}')
		}
	}
	b.WriteByte('`')
	return b.String()
}

// buildChildrenExpr produces a single JS expression that represents all text
// content of a node's children (for simple #if blocks).
func (g *CodeGen) buildChildrenExpr(children []Node) string {
	var parts []*Part
	for _, child := range children {
		if t, ok := child.(*TextNode); ok {
			parts = append(parts, t.Parts...)
		}
	}
	if len(parts) == 0 {
		return ""
	}
	return buildExpr(parts)
}

