// TestingPackageName is the npm package of the test helpers.
const TestingPackageName = "@govela/testing"

// CreatePackageName is the npm package of the starter. `create-vela` is
// another project's name on npm; `npm create @govela` runs this one.
const CreatePackageName = "@govela/create"

const (
	testingPackageDir = "packages/testing"
	createPackageDir  = "packages/create"
	appManifestPath   = "packages/app/package.json"
)

// testingPackageSources are the hand-written files of packages/testing.
var testingPackageSources = []string{"index.js", "index.d.ts"}

// createPackageSources are the hand-written files of packages/create: the
// command and every file of the templates.
func createPackageSources() ([]string, error) {
	sources := []string{"bin/create.js"}
	root := filepath.FromSlash(createPackageDir)
	err := filepath.WalkDir(filepath.Join(root, "templates"), func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, err := filepath.Rel(root, p)
		if err != nil {
			return err
		}
		sources = append(sources, filepath.ToSlash(rel))
		return nil
	})
	sort.Strings(sources[1:])
	return sources, err
}

// appVersion is the version of @govela/app the templates install. The app
// layer is a module of its own, released apart from the compiler.
func appVersion() (string, error) {
	data, err := os.ReadFile(filepath.FromSlash(appManifestPath))
	if err != nil {
		return "", err
	}
	var manifest struct{ Version string }
	if err := json.Unmarshal(data, &manifest); err != nil || manifest.Version == "" {
		return "", fmt.Errorf("%s: no version", appManifestPath)
	}
	return manifest.Version, nil
}

func starterPackageFiles() (map[string][]byte, error) {
	files := map[string][]byte{}

	testing := struct {
		Name             string            `json:"name"`
		Version          string            `json:"version"`
		Description      string            `json:"description"`
		License          string            `json:"license"`
		Repository       packageRepository `json:"repository"`
		Type             string            `json:"type"`
		Exports          map[string]any    `json:"exports"`
		Types            string            `json:"types"`
		Files            []string          `json:"files"`
		PeerDependencies map[string]string `json:"peerDependencies"`
	}{
		Name:        TestingPackageName,
		Version:     runtime.Version,
		Description: "Test helpers for Vela components: render, fireEvent, cleanup, tick. Manifest generated by the compiler repository; do not edit.",
		License:     "MIT",
		Repository:  repositoryOf(testingPackageDir),
		Type:        "module",
		Exports: map[string]any{
			".":              conditionalExport{Types: "./index.d.ts", Default: "./index.js"},
			"./package.json": "./package.json",
		},
		Types:            "index.d.ts",
		Files:            append(append([]string{}, testingPackageSources...), "LICENSE"),
		PeerDependencies: map[string]string{runtime.PackageName: runtime.Version},
	}
	encoded, err := encodePackageJSON(testing)
	if err != nil {
		return nil, err
	}
	files[path.Join(testingPackageDir, "package.json")] = encoded
	files[path.Join(testingPackageDir, "LICENSE")] = licenseText
	files[path.Join(testingPackageDir, "README.md")] = []byte("# " + TestingPackageName + "\n\n" +
		"Test helpers for Vela components, for Vitest with happy-dom or jsdom.\n" +
		"The components are compiled by `" + UnpluginPackageName + "`, as in the\n" +
		"application.\n\n" +
		"```sh\n" +
		"npm i -D " + TestingPackageName + " " + UnpluginPackageName + " vitest happy-dom\n" +
		"```\n\n" +
		"```js\n" +
		"// vite.config.js\n" +
		"import vela from '" + UnpluginPackageName + "/vite';\n\n" +
		"export default { plugins: [vela()], test: { environment: 'happy-dom' } };\n" +
		"```\n\n" +
		"```js\n" +
		"import { afterEach, expect, test } from 'vitest';\n" +
		"import { cleanup, fireEvent, render } from '" + TestingPackageName + "';\n" +
		"import Counter from './Counter.vela';\n\n" +
		"afterEach(cleanup);\n\n" +
		"test('counts', async () => {\n" +
		"  const { container } = render(Counter, { props: { step: 2 } });\n" +
		"  await fireEvent.click(container.querySelector('button'));\n" +
		"  expect(container.textContent).toContain('2');\n" +
		"});\n" +
		"```\n\n" +
		"- `render(Component, { props, slots, events, target })` mounts the\n" +
		"  component into a new `<div>` of `document.body` and returns\n" +
		"  `{ container, component, rerender(props), unmount() }`. A slot is an\n" +
		"  HTML string, a node or a function returning one; `events` listens to\n" +
		"  the component's `$$dispatch` events.\n" +
		"- `fireEvent(element, event)`, `fireEvent.click(element)`,\n" +
		"  `fireEvent.input(element, value)` and the others dispatch the event\n" +
		"  and wait until the component has updated.\n" +
		"- `cleanup()` unmounts every rendered component; `tick()` waits for\n" +
		"  pending updates.\n\n" +
		"License: MIT.\n")

	app, err := appVersion()
	if err != nil {
		return nil, err
	}
	create := struct {
		Name        string            `json:"name"`
		Version     string            `json:"version"`
		Description string            `json:"description"`
		License     string            `json:"license"`
		Repository  packageRepository `json:"repository"`
		Type        string            `json:"type"`
		Bin         map[string]string `json:"bin"`
		Files       []string          `json:"files"`
		Engines     map[string]string `json:"engines"`
		Govela      map[string]string `json:"govela"`
	}{
		Name:        CreatePackageName,
		Version:     runtime.Version,
		Description: "Creates a Vela application: npm create @govela. Manifest generated by the compiler repository; do not edit.",
		License:     "MIT",
		Repository:  repositoryOf(createPackageDir),
		Type:        "module",
		Bin:         map[string]string{"create-govela": "bin/create.js"},
		Files:       []string{"bin", "templates", "LICENSE"},
		// The engines of the templates' Vite and Vitest.
		Engines: map[string]string{"node": "^20.19.0 || >=22.12.0"},
		// The version of @govela/app and github.com/elauven/vela/app the app
		// template installs.
		Govela: map[string]string{"app": app},
	}
	if encoded, err = encodePackageJSON(create); err != nil {
		return nil, err
	}
	eslint, err := eslintPluginPackageFiles()
	if err != nil {
		return nil, err
	}
	for name, data := range eslint {
		files[name] = data
	}
	files[path.Join(createPackageDir, "package.json")] = encoded
	files[path.Join(createPackageDir, "LICENSE")] = licenseText
	files[path.Join(createPackageDir, "README.md")] = []byte("# " + CreatePackageName + "\n\n" +
		"Creates a Vela application.\n\n" +
		"```sh\n" +
		"npm create @govela my-app             # Vite, Vitest with " + TestingPackageName + "\n" +
		"npm create @govela my-app -- --ssr    # a Go server renders, Vite builds the client\n" +
		"npm create @govela my-app -- --app    # a Vela App: routes with Go loaders\n" +
		"```\n\n" +
		"`--module example.com/my-app` sets the Go module path of `--ssr` and\n" +
		"`--app`. Every project has a component test, `npm run check`\n" +
		"(`vela check`), a GitHub Actions workflow running the check, the tests\n" +
		"and the build, and an `AGENTS.md` pointing to the Vela authoring guide.\n\n" +
		"License: MIT.\n")
	return files, nil
}

// ESLintPluginPackageName is the npm package of the ESLint processor
// (task 067).
const ESLintPluginPackageName = "@govela/eslint-plugin"

const eslintPluginPackageDir = "packages/eslint-plugin"

// eslintPluginPackageSources are the hand-written files of
// packages/eslint-plugin.
var eslintPluginPackageSources = []string{"index.js", "index.d.ts"}

func eslintPluginPackageFiles() (map[string][]byte, error) {
	manifest := struct {
		Name             string            `json:"name"`
		Version          string            `json:"version"`
		Description      string            `json:"description"`
		License          string            `json:"license"`
		Repository       packageRepository `json:"repository"`
		Type             string            `json:"type"`
		Exports          map[string]any    `json:"exports"`
		Types            string            `json:"types"`
		Files            []string          `json:"files"`
		Dependencies     map[string]string `json:"dependencies"`
		PeerDependencies map[string]string `json:"peerDependencies"`
	}{
		Name:        ESLintPluginPackageName,
		Version:     runtime.Version,
		Description: "ESLint for Vela components: a processor for the script and the template expressions of .vela files. Manifest generated by the compiler repository; do not edit.",
		License:     "MIT",
		Repository:  repositoryOf(eslintPluginPackageDir),
		Type:        "module",
		Exports: map[string]any{
			".":              conditionalExport{Types: "./index.d.ts", Default: "./index.js"},
			"./package.json": "./package.json",
		},
		Types:            "index.d.ts",
		Files:            append(append([]string{}, eslintPluginPackageSources...), "LICENSE"),
		Dependencies:     map[string]string{CompilerPackageName: runtime.Version},
		PeerDependencies: map[string]string{"eslint": ">=9"},
	}
	encoded, err := encodePackageJSON(manifest)
	if err != nil {
		return nil, err
	}
	readme := "# " + ESLintPluginPackageName + "\n\n" +
		"ESLint for Vela components. The processor lints the `<script>` and the\n" +
		"template expressions of a `.vela` file as one program, the virtual\n" +
		"document of `vela document`: a variable used only in the template is\n" +
		"used, an undefined name in `{expression}` is reported at its place, and\n" +
		"the names of `{#each}` and `{#await}` are declared. Messages about\n" +
		"generated text are dropped; fixes inside the component's own text apply.\n\n" +
		"```sh\n" +
		"npm i -D " + ESLintPluginPackageName + " eslint @eslint/js globals\n" +
		"```\n\n" +
		"```js\n" +
		"// eslint.config.js\n" +
		"import js from '@eslint/js';\n" +
		"import globals from 'globals';\n" +
		"import vela from '" + ESLintPluginPackageName + "';\n\n" +
		"export default [\n" +
		"  js.configs.recommended,\n" +
		"  ...vela.configs.recommended,\n" +
		"  // The code of the components: the virtual files App.vela/0_App.vela.js.\n" +
		"  { files: ['**/*.vela/*.js'], languageOptions: { globals: globals.browser } },\n" +
		"];\n" +
		"```\n\n" +
		"`configs.recommended` sets the processor for `**/*.vela` and declares\n" +
		"`$state`, `$derived`, `$effect`, `$bindable` and `$$dispatch`. The\n" +
		"template markup is not linted. The compiler binary is the one of\n" +
		"`" + CompilerPackageName + "` (or `VELA_BINARY`).\n\n" +
		"License: MIT.\n"
	return map[string][]byte{
		path.Join(eslintPluginPackageDir, "package.json"): encoded,
		path.Join(eslintPluginPackageDir, "README.md"):    []byte(readme),
		path.Join(eslintPluginPackageDir, "LICENSE"):      licenseText,
	}, nil
}
