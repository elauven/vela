package main

// typescript_plugin_package.go — the @govela/typescript-plugin npm package
// (task 085): `.vela` components in TypeScript's language server. Its
// manifest and README are generated with the compiler version; the plugin
// (index.js) is written by hand.

import (
	"github.com/elauven/vela/runtime"

	"path"
)

// TypeScriptPluginPackageName is the npm package of the TypeScript server
// plugin.
const TypeScriptPluginPackageName = "@govela/typescript-plugin"

const typescriptPluginPackageDir = "packages/typescript-plugin"

// typescriptPluginPackageSources are the hand-written files of the package.
var typescriptPluginPackageSources = []string{"index.js"}

func typescriptPluginPackageFiles() (map[string][]byte, error) {
	manifest := struct {
		Name                 string            `json:"name"`
		Version              string            `json:"version"`
		Description          string            `json:"description"`
		License              string            `json:"license"`
		Repository           packageRepository `json:"repository"`
		Main                 string            `json:"main"`
		Files                []string          `json:"files"`
		PeerDependencies     map[string]string `json:"peerDependencies"`
		PeerDependenciesMeta map[string]any    `json:"peerDependenciesMeta"`
	}{
		Name:        TypeScriptPluginPackageName,
		Version:     runtime.Version,
		Description: "Vela components in TypeScript's language server: .ts modules see the types of the .vela files they import. Manifest generated by the compiler repository; do not edit.",
		License:     "MIT",
		Repository:  repositoryOf(typescriptPluginPackageDir),
		Main:        "index.js",
		Files:       append(append([]string{}, typescriptPluginPackageSources...), "LICENSE"),
		// The binary is the compiler's of the project, and the declarations
		// import the runtime's types; the VS Code extension bundles the
		// plugin without them.
		PeerDependencies: map[string]string{"typescript": ">=5.8", CompilerPackageName: runtime.Version, runtime.PackageName: runtime.Version},
		PeerDependenciesMeta: map[string]any{
			"typescript":        map[string]bool{"optional": true},
			CompilerPackageName: map[string]bool{"optional": true},
			runtime.PackageName: map[string]bool{"optional": true},
		},
	}
	encoded, err := encodePackageJSON(manifest)
	if err != nil {
		return nil, err
	}
	readme := "# " + TypeScriptPluginPackageName + "\n\n" +
		"`.vela` components in TypeScript's language server: a `.ts` module that\n" +
		"imports `./Card.vela` sees the component's props, events, slots and\n" +
		"bindable props, in any editor that runs `tsserver`.\n\n" +
		"```sh\n" +
		"npm i -D " + TypeScriptPluginPackageName + " " + CompilerPackageName + "\n" +
		"```\n\n" +
		"```json\n" +
		"{ \"compilerOptions\": { \"plugins\": [{ \"name\": \"" + TypeScriptPluginPackageName + "\" }] } }\n" +
		"```\n\n" +
		"VS Code loads it with the Vela extension. The types are the declarations\n" +
		"of `vela --dts`, read through `vela compile --dts` of `" + CompilerPackageName + "`\n" +
		"(option `binary` or `VELA_BINARY` for another build). `tsc` does not run\n" +
		"plugins; `vela check --types` checks a project from the command line.\n\n" +
		"License: MIT.\n"
	return map[string][]byte{
		path.Join(typescriptPluginPackageDir, "package.json"): encoded,
		path.Join(typescriptPluginPackageDir, "README.md"):    []byte(readme),
		path.Join(typescriptPluginPackageDir, "LICENSE"):      licenseText,
	}, nil
}
