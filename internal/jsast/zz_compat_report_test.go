package jsast

// Collects the outcome of every matrix row and prints / writes a report.
//
//	go test -run TestCompat -v                     # summary at the end of the output
//	AST_COMPAT_MD=COMPAT.md go test -run TestCompat   # also write a markdown table
//	AST_COMPAT_JSON=out.json go test -run TestCompat  # machine-readable results
//	AST_COMPAT_STRICT=1 go test -run TestCompat       # ignore Gap markers: show every failure
//
// This file's name sorts last so the report test runs after all the others.

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"
	"sync"
	"testing"
)

type ctResult struct {
	ID    string `json:"id"`
	Group string `json:"group"`
	Name  string `json:"name"`
	Pass  bool   `json:"pass"`
	Gap   string `json:"gap,omitempty"`
	Err   string `json:"error,omitempty"`
	Src   string `json:"src,omitempty"`
}

var (
	ctMu      sync.Mutex
	ctResults []ctResult
)

func ctRecord(r ctResult) {
	ctMu.Lock()
	defer ctMu.Unlock()
	ctResults = append(ctResults, r)
}

func ctStrict() bool { return os.Getenv("AST_COMPAT_STRICT") != "" }

func ctGroupOrder(results []ctResult) []string {
	var order []string
	seen := map[string]bool{}
	for _, r := range results {
		if !seen[r.Group] {
			seen[r.Group] = true
			order = append(order, r.Group)
		}
	}
	return order
}

func TestCompatZReport(t *testing.T) {
	ctMu.Lock()
	results := append([]ctResult(nil), ctResults...)
	ctMu.Unlock()
	if len(results) == 0 {
		t.Skip("no matrix results recorded (run together with the other TestCompat* tests)")
	}

	if p := os.Getenv("AST_COMPAT_JSON"); p != "" {
		b, _ := json.MarshalIndent(results, "", "  ")
		if err := os.WriteFile(p, b, 0o644); err != nil {
			t.Errorf("write %s: %v", p, err)
		}
	}

	order := ctGroupOrder(results)
	byGroup := map[string][]ctResult{}
	for _, r := range results {
		byGroup[r.Group] = append(byGroup[r.Group], r)
	}

	var sb strings.Builder
	total, passed := 0, 0
	fmt.Fprintf(&sb, "\nJS parser compatibility summary\n")
	fmt.Fprintf(&sb, "%-12s %6s %6s %6s\n", "group", "pass", "fail", "total")
	for _, g := range order {
		p := 0
		for _, r := range byGroup[g] {
			if r.Pass {
				p++
			}
		}
		fmt.Fprintf(&sb, "%-12s %6d %6d %6d\n", g, p, len(byGroup[g])-p, len(byGroup[g]))
		total += len(byGroup[g])
		passed += p
	}
	fmt.Fprintf(&sb, "%-12s %6d %6d %6d\n", "TOTAL", passed, total-passed, total)

	var gaps []ctResult
	for _, r := range results {
		if !r.Pass {
			gaps = append(gaps, r)
		}
	}
	if len(gaps) > 0 {
		fmt.Fprintf(&sb, "\nOpen gaps (%d):\n", len(gaps))
		for _, r := range gaps {
			why := r.Gap
			if why == "" {
				why = "(unexpected failure)"
			}
			fmt.Fprintf(&sb, "  ✗ %-42s %s\n", r.ID, why)
		}
	}
	t.Log(sb.String())

	if p := os.Getenv("AST_COMPAT_MD"); p != "" {
		if err := os.WriteFile(p, []byte(ctMarkdown(order, byGroup)), 0o644); err != nil {
			t.Errorf("write %s: %v", p, err)
		}
	}
}

func ctMarkdown(order []string, byGroup map[string][]ctResult) string {
	var sb strings.Builder
	sb.WriteString("# JS parser compatibility matrix\n\n")
	sb.WriteString("Generated by `AST_COMPAT_MD=COMPAT.md go test -run TestCompat`.\n\n")
	sb.WriteString("| Group | Pass | Fail | Total |\n|---|---:|---:|---:|\n")
	tp, tt := 0, 0
	for _, g := range order {
		p := 0
		for _, r := range byGroup[g] {
			if r.Pass {
				p++
			}
		}
		fmt.Fprintf(&sb, "| %s | %d | %d | %d |\n", g, p, len(byGroup[g])-p, len(byGroup[g]))
		tp += p
		tt += len(byGroup[g])
	}
	fmt.Fprintf(&sb, "| **Total** | **%d** | **%d** | **%d** |\n\n", tp, tt-tp, tt)
	groups := append([]string(nil), order...)
	sort.SliceStable(groups, func(i, j int) bool { return false })
	for _, g := range groups {
		fmt.Fprintf(&sb, "## %s\n\n| | Feature | Note |\n|---|---|---|\n", g)
		for _, r := range byGroup[g] {
			mark, note := "✅", ""
			if !r.Pass {
				mark = "❌"
				note = strings.ReplaceAll(r.Gap, "|", "\\|")
			}
			fmt.Fprintf(&sb, "| %s | %s | %s |\n", mark, strings.ReplaceAll(r.Name, "|", "\\|"), note)
		}
		sb.WriteString("\n")
	}
	return sb.String()
}
