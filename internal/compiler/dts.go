// Declarations of compiled components (task 083, docs/TYPESCRIPT.md
// TS-6.5): `vela --dts` writes Card.d.ts beside Card.js, so that a
// component library published to npm is typed for its consumers.

// ComponentDeclarations prints the declaration file of the component name
// from its type model. The types are copied from the source; the local
// types they reference travel with them and imported ones are imported
// again, with the specifiers the compiled module uses.
func ComponentDeclarations(name, source string, t *analyzer.ComponentTypes) string {
	locals := map[string]*analyzer.TypeDecl{}
	for _, d := range t.Decls {
		locals[d.Name] = d
	}
	imports := map[string]analyzer.TypeImport{}
	for _, imp := range t.Imports {
		imports[imp.Local] = imp
	}
	taken := func(n string) bool {
		_, local := locals[n]
		_, imported := imports[n]
		return local || imported || t.Values[n] || n == name
	}
	typeName := func(suffix string) string {
		n := name + suffix
		for i := 2; taken(n); i++ {
			n = name + "Component" + suffix
			if i > 2 {
				n += strings.Repeat("_", i-2)
			}
		}
		return n
	}
	propsName, eventsName, slotsName := typeName("Props"), typeName("Events"), typeName("Slots")

	params, args, anyArgs := "", "", ""
	if len(t.TypeParams) > 0 {
		params = "<" + t.Generics + ">"
		args = "<" + strings.Join(t.TypeParams, ", ") + ">"
		anyArgs = "<" + strings.TrimSuffix(strings.Repeat("any, ", len(t.TypeParams)), ", ") + ">"
	}

	// The names the public types need, closed over the local declarations.
	var queue []analyzer.TypeRef
	for _, p := range t.Props {
		queue = append(queue, p.Refs...)
	}
	for _, d := range []*analyzer.TypeDecl{t.Events, t.Slots} {
		if d != nil {
			queue = append(queue, d.Refs...)
		}
	}
	usedDecls := map[string]bool{}
	usedImports := map[string]bool{}
	stubTypes, stubValues := map[string]bool{}, map[string]bool{}
	for len(queue) > 0 {
		ref := queue[0]
		queue = queue[1:]
		switch {
		case locals[ref.Name] != nil && !ref.Value:
			if !usedDecls[ref.Name] {
				usedDecls[ref.Name] = true
				queue = append(queue, locals[ref.Name].Refs...)
			}
		case imports[ref.Name].Local != "":
			usedImports[ref.Name] = true
		case t.Values[ref.Name]:
			// A value of the script (a class, `typeof x`): the declaration
			// file cannot name it, so it is any for consumers.
			if ref.Value {
				stubValues[ref.Name] = true
			} else {
				stubTypes[ref.Name] = true
			}
		}
	}

	var b strings.Builder
	b.WriteString("// Generated by vela --dts from " + source + "; do not edit.\n")
	if len(t.TypeParams) == 0 {
		b.WriteString("import type { Component as $$VelaComponent } from '" + runtime.PackageName + "';\n")
	} else {
		b.WriteString("import type { ComponentInstance as $$VelaInstance, Slots as $$VelaSlots } from '" + runtime.PackageName + "';\n")
	}
	for _, imp := range t.Imports {
		if !usedImports[imp.Local] {
			continue
		}
		spec := declarationSpecifier(imp.Source)
		switch imp.Imported {
		case "default":
			b.WriteString("import type " + imp.Local + " from " + quoteTS(spec) + ";\n")
		case "*":
			b.WriteString("import type * as " + imp.Local + " from " + quoteTS(spec) + ";\n")
		default:
			b.WriteString("import type { " + specifierName(imp.Imported, imp.Local) + " } from " + quoteTS(spec) + ";\n")
		}
	}
	b.WriteString("\n")
	for _, n := range sortedKeys(stubTypes) {
		b.WriteString("type " + n + " = any;\n")
	}
	for _, n := range sortedKeys(stubValues) {
		b.WriteString("declare const " + n + ": any;\n")
	}
	for _, d := range t.Decls {
		if !usedDecls[d.Name] {
			continue
		}
		switch {
		case d.JSDoc:
			b.WriteString("type " + d.Name + " = " + d.Text + ";\n")
		case d.Exported:
			b.WriteString("export " + d.Text + "\n")
		default:
			b.WriteString(d.Text + "\n")
		}
	}
	if len(stubTypes)+len(stubValues)+len(usedDecls) > 0 {
		b.WriteString("\n")
	}

	b.WriteString("export interface " + propsName + params + " {\n")
	var bindable []string
	for _, p := range t.Props {
		typ := p.Type
		if typ == "" {
			typ = "any"
		}
		if p.Bindable {
			bindable = append(bindable, quoteTS(p.Name))
			b.WriteString("  /** Bindable: the parent may write `bind:" + p.Name + "`. */\n")
		}
		opt := ""
		if p.Optional {
			opt = "?"
		}
		b.WriteString("  " + propertyName(p.Name) + opt + ": " + indentContinuation(typ) + ";\n")
	}
	b.WriteString("}\n")

	b.WriteString(publicDecl(t.Events, eventsName, params, func() string {
		if t.AnyEvents {
			return "Record<string, any>"
		}
		return objectOf(t.EventNames, "any")
	}))
	b.WriteString(publicDecl(t.Slots, slotsName, params, func() string {
		return objectOf(t.SlotNames, "{}")
	}))

	bindings := "never"
	if len(bindable) > 0 {
		bindings = strings.Join(bindable, " | ")
	}
	b.WriteString("\n")
	if len(t.TypeParams) == 0 {
		b.WriteString("declare const " + name + ": $$VelaComponent<" + propsName + ", " + eventsName + ", " + slotsName + ", " + bindings + ">;\n")
	} else {
		// A generic component: the parent's props choose the type arguments.
		b.WriteString("declare const " + name + ": {\n")
		b.WriteString("  " + params + "(target: Element | DocumentFragment | Comment, props?: " + propsName + args + ", slots?: $$VelaSlots): $$VelaInstance<" + propsName + args + ">;\n")
		b.WriteString("  readonly $$events_def?: " + eventsName + anyArgs + ";\n")
		b.WriteString("  readonly $$slot_def?: " + slotsName + anyArgs + ";\n")
		b.WriteString("  readonly $$bindings_def?: " + bindings + ";\n")
		b.WriteString("};\n")
	}
	b.WriteString("export { " + name + " };\nexport default " + name + ";\n")
	return b.String()
}

// publicDecl prints the events or slots type: the script's declaration
// renamed, or the fallback object type.
func publicDecl(d *analyzer.TypeDecl, name, params string, fallback func() string) string {
	switch {
	case d == nil:
		return "export type " + name + params + " = " + fallback() + ";\n"
	case d.JSDoc:
		return "export type " + name + params + " = " + d.Text + ";\n"
	}
	text := d.Text
	if i := strings.Index(text, d.Name); i >= 0 {
		rest := text[i+len(d.Name):]
		if params != "" && strings.HasPrefix(strings.TrimSpace(rest), "<") {
			params = "" // the declaration has its own type parameters
		}
		text = text[:i] + name + params + rest
	}
	return "export " + text + "\n"
}

// objectOf is an object type with the names as keys of type value.
func objectOf(names []string, value string) string {
	if len(names) == 0 {
		return "{}"
	}
	parts := make([]string, len(names))
	for i, n := range names {
		parts[i] = propertyName(n) + ": " + value
	}
	return "{ " + strings.Join(parts, "; ") + " }"
}

// declarationSpecifier is the specifier of an import in a declaration file
// beside the compiled module: components and .ts modules become .js (whose
// declarations are beside them), and the modules the compiler provides
// become the runtime package, which declares the same names.
func declarationSpecifier(spec string) string {
	if analyzer.IsVelaModule(spec) {
		return runtime.PackageName
	}
	return codegen.RewriteImportPath(spec)
}

func specifierName(imported, local string) string {
	if !isPlainIdentifier(imported) {
		imported = quoteTS(imported)
	}
	if imported == local {
		return local
	}
	return imported + " as " + local
}

func propertyName(n string) string {
	if isPlainIdentifier(n) {
		return n
	}
	return quoteTS(n)
}

func isPlainIdentifier(s string) bool {
	if s == "" || !jsast.IsIdentStart(s[0]) {
		return false
	}
	for i := 1; i < len(s); i++ {
		if !jsast.IsIdentCont(s[i]) {
			return false
		}
	}
	return true
}

func quoteTS(s string) string {
	q, _ := json.Marshal(s)
	return string(q)
}

// indentContinuation indents the lines after the first of a type text that
// spans lines, so it reads as part of its property.
func indentContinuation(s string) string {
	return strings.ReplaceAll(s, "\n", "\n    ")
}

func sortedKeys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
