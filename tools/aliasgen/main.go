// Command aliasgen writes a package main file that re-exports every exported
// top-level identifier of a package under the same name. It keeps package
// main compiling while compiler layers move into internal packages
// (task 037).
//
// Usage: go run ./tools/aliasgen <package dir> <package name> <import path> <output file>
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"sort"
	"strings"
)

func main() {
	if len(os.Args) != 5 {
		fmt.Fprintln(os.Stderr, "usage: aliasgen <package dir> <package name> <import path> <output file>")
		os.Exit(2)
	}
	dir, alias, importPath, output := os.Args[1], os.Args[2], os.Args[3], os.Args[4]
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(fi os.FileInfo) bool { return !strings.HasSuffix(fi.Name(), "_test.go") }, 0)
	if err != nil {
		fail(err)
	}
	var types, funcs, consts, vars []string
	for _, pkg := range pkgs {
		for _, file := range pkg.Files {
			for _, decl := range file.Decls {
				switch d := decl.(type) {
				case *ast.FuncDecl:
					if d.Recv == nil && d.Name.IsExported() {
						if d.Type.TypeParams != nil {
							fail(fmt.Errorf("generic function %s needs a hand-written wrapper", d.Name.Name))
						}
						funcs = append(funcs, d.Name.Name)
					}
				case *ast.GenDecl:
					for _, spec := range d.Specs {
						switch s := spec.(type) {
						case *ast.TypeSpec:
							if !s.Name.IsExported() {
								continue
							}
							if s.TypeParams != nil {
								fail(fmt.Errorf("generic type %s needs a hand-written alias", s.Name.Name))
							}
							types = append(types, s.Name.Name)
						case *ast.ValueSpec:
							for _, name := range s.Names {
								if !name.IsExported() {
									continue
								}
								if d.Tok == token.CONST {
									consts = append(consts, name.Name)
								} else {
									vars = append(vars, name.Name)
								}
							}
						}
					}
				}
			}
		}
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by tools/aliasgen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&out, "// Compatibility names for package %s while the compiler moves out of\n// package main (task 037). New code imports %q directly.\n\n", alias, importPath)
	fmt.Fprintf(&out, "package main\n\nimport %s %q\n\n", alias, importPath)
	block := func(keyword string, names []string) {
		if len(names) == 0 {
			return
		}
		sort.Strings(names)
		fmt.Fprintf(&out, "%s (\n", keyword)
		for _, name := range names {
			fmt.Fprintf(&out, "\t%s = %s.%s\n", name, alias, name)
		}
		fmt.Fprintf(&out, ")\n\n")
	}
	block("type", types)
	block("const", consts)
	block("var", funcs)
	block("var", vars)
	source, err := format.Source(out.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(output, source, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "aliasgen:", err)
	os.Exit(1)
}
