// Generates ssr_runtime/casing_table.go: every code point whose
// toUpperCase() or toLowerCase() in this Node version differs from itself
// (T-6.3c). Context-sensitive final sigma is handled in Go.
// Run: node tools/gen-casing-table.mjs | gofmt > ssr_runtime/casing_table.go
const upper = [];
const lower = [];
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue;
  const s = String.fromCodePoint(cp);
  const u = s.toUpperCase();
  const l = s.toLowerCase();
  if (u !== s) upper.push([cp, u]);
  if (l !== s) lower.push([cp, l]);
}
const goString = (s) => {
  let out = '"';
  for (const ch of s) {
    const cp = ch.codePointAt(0);
    if (cp < 0x80 && ch !== '"' && ch !== '\\') out += ch;
    else if (cp <= 0xffff) out += '\\u' + cp.toString(16).padStart(4, '0');
    else out += '\\U' + cp.toString(16).padStart(8, '0');
  }
  return out + '"';
};
const table = (name, rows) => `var ${name} = map[rune]string{\n` + rows.map(([cp, s]) => `\t0x${cp.toString(16)}: ${goString(s)},`).join('\n') + '\n}\n';
process.stdout.write(`// Code generated by tools/gen-casing-table.mjs from Node ${process.version} (ICU ${process.versions.icu}, Unicode ${process.versions.unicode}). DO NOT EDIT.

package ssr_runtime

// upperCase and lowerCase map every code point whose JavaScript case
// mapping differs from itself to its full mapping (T-6.3c).
${table('upperCase', upper)}
${table('lowerCase', lower)}`);
