// The npm distribution of vela-app (docs/RELEASING.md, the app layer):
// @govela/app has the launcher bin/vela-app.js and depends on one package
// per platform with the binary, of exactly its version. The release
// workflow .github/workflows/release-app.yml builds the binaries into
// packages/app-<os>-<cpu>/bin/.
//
// VELA_UPDATE_APP_PACKAGES=1 go test -run TestAppPackagesAreGenerated .
// rewrites the platform packages.

type appPlatform struct{ GOOS, GOARCH, OS, CPU string }

var appPlatforms = []appPlatform{
	{"linux", "amd64", "linux", "x64"},
	{"linux", "arm64", "linux", "arm64"},
	{"darwin", "amd64", "darwin", "x64"},
	{"darwin", "arm64", "darwin", "arm64"},
	{"windows", "amd64", "win32", "x64"},
}

const appPackageName = "@govela/app"

func (p appPlatform) name() string        { return p.OS + "-" + p.CPU }
func (p appPlatform) packageName() string { return appPackageName + "-" + p.name() }
func (p appPlatform) dir() string         { return "packages/app-" + p.name() }

func (p appPlatform) binary() string {
	if p.OS == "win32" {
		return "bin/vela-app.exe"
	}
	return "bin/vela-app"
}

type npmRepository struct {
	Type      string `json:"type"`
	URL       string `json:"url"`
	Directory string `json:"directory"`
}

type appPlatformManifest struct {
	Name            string        `json:"name"`
	Version         string        `json:"version"`
	Description     string        `json:"description"`
	License         string        `json:"license"`
	Repository      npmRepository `json:"repository"`
	OS              []string      `json:"os"`
	CPU             []string      `json:"cpu"`
	Files           []string      `json:"files"`
	PreferUnplugged bool          `json:"preferUnplugged"`
}

func encodeManifest(t *testing.T, manifest any) []byte {
	t.Helper()
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(manifest); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

func appPackageFiles(t *testing.T, license []byte) map[string][]byte {
	files := map[string][]byte{}
	for _, p := range appPlatforms {
		files[p.dir()+"/package.json"] = encodeManifest(t, appPlatformManifest{
			Name:        p.packageName(),
			Version:     Version,
			Description: "The vela-app binary of Vela App for " + p.name() + ". Installed by " + appPackageName + "; do not depend on it directly.",
			License:     "MIT",
			Repository: npmRepository{
				Type:      "git",
				URL:       "git+https://github.com/elauven/vela.git",
				Directory: p.dir(),
			},
			OS:              []string{p.OS},
			CPU:             []string{p.CPU},
			Files:           []string{p.binary(), "LICENSE"},
			PreferUnplugged: true,
		})
		files[p.dir()+"/README.md"] = []byte("# " + p.packageName() + "\n\n" +
			"The `vela-app` binary of [Vela App](https://github.com/elauven/vela/blob/main/docs/VELA_APP.md)\n" +
			"for " + p.name() + ". It is an optional dependency of `" + appPackageName + "`, which\n" +
			"installs it on this platform only and runs it as `vela-app`; do not\n" +
			"depend on it directly.\n\n" +
			"Generated by the compiler repository (`app/npm_package_test.go`); the\n" +
			"binary is built by the release workflow of the app layer.\n")
		files[p.dir()+"/LICENSE"] = license
	}
	return files
}

func TestAppPackagesAreGenerated(t *testing.T) {
	license, err := os.ReadFile("LICENSE")
	if err != nil {
		t.Fatal(err)
	}
	files := appPackageFiles(t, license)
	update := os.Getenv("VELA_UPDATE_APP_PACKAGES") == "1"
	for name, want := range files {
		file := filepath.Join("..", filepath.FromSlash(name))
		if update {
			if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(file, want, 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		got, err := os.ReadFile(file)
		if err != nil {
			t.Errorf("%s: %v; run VELA_UPDATE_APP_PACKAGES=1 go test -run TestAppPackagesAreGenerated .", name, err)
			continue
		}
		if !bytes.Equal(bytes.ReplaceAll(got, []byte("\r\n"), []byte("\n")), want) {
			t.Errorf("%s is stale; run VELA_UPDATE_APP_PACKAGES=1 go test -run TestAppPackagesAreGenerated .", name)
		}
	}
}

// @govela/app has the version of the layer, runs vela-app and depends on
// every platform package of its version.
func TestAppPackageRunsVelaApp(t *testing.T) {
	data, err := os.ReadFile(filepath.Join("..", "packages", "app", "package.json"))
	if err != nil {
		t.Fatal(err)
	}
	var m struct {
		Version              string            `json:"version"`
		Private              bool              `json:"private"`
		Bin                  map[string]string `json:"bin"`
		Files                []string          `json:"files"`
		OptionalDependencies map[string]string `json:"optionalDependencies"`
	}
	if err := json.Unmarshal(data, &m); err != nil {
		t.Fatal(err)
	}
	if m.Version != Version {
		t.Errorf("packages/app version %s, Version %s", m.Version, Version)
	}
	if m.Private {
		t.Error("packages/app is private")
	}
	if m.Bin["vela-app"] != "bin/vela-app.js" {
		t.Errorf("bin = %v, want vela-app: bin/vela-app.js", m.Bin)
	}
	hasLauncher := false
	for _, f := range m.Files {
		hasLauncher = hasLauncher || f == "bin/vela-app.js"
	}
	if !hasLauncher {
		t.Errorf("files %q lack bin/vela-app.js", m.Files)
	}
	want := map[string]string{}
	for _, p := range appPlatforms {
		want[p.packageName()] = Version
	}
	if !reflect.DeepEqual(m.OptionalDependencies, want) {
		t.Errorf("optionalDependencies = %v, want %v", m.OptionalDependencies, want)
	}
	launcher, err := os.ReadFile(filepath.Join("..", "packages", "app", "bin", "vela-app.js"))
	if err != nil {
		t.Fatal(err)
	}
	for _, p := range appPlatforms {
		if !strings.Contains(string(launcher), "'"+p.name()+"'") {
			t.Errorf("bin/vela-app.js does not list the platform %s", p.name())
		}
	}
}

// The release workflow builds vela-app for every platform and puts each
// binary into its platform package.
func TestAppReleaseWorkflowCoversPlatforms(t *testing.T) {
	data, err := os.ReadFile(filepath.Join("..", ".github", "workflows", "release-app.yml"))
	if err != nil {
		t.Fatal(err)
	}
	workflow := string(data)
	for _, p := range appPlatforms {
		if stage := p.GOOS + "/" + p.GOARCH + ":" + p.name(); !strings.Contains(workflow, stage) {
			t.Errorf("release-app.yml does not build %s into %s (%s)", p.GOOS+"/"+p.GOARCH, p.dir(), stage)
		}
	}
	for _, want := range []string{"tags: ['app/v*']", `npm publish "./$dir"`, "packages/app-* packages/app; do"} {
		if !strings.Contains(workflow, want) {
			t.Errorf("release-app.yml lacks %q", want)
		}
	}
}
