// Package gen scans the routes tree and generates the app root, the client
// and Go route tables (docs/APP.md P-, L- and R- rules). The compiler knows
// nothing about routes (B-2): it compiles the generated VelaApp.vela like
// any other component.
package gen

import (
	"bufio"
	"bytes"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"
)

// Result reports what Generate changed. Paths are relative to the project
// root.
type Result struct {
	Written   []string
	Unchanged []string
	Removed   []string
}

// Load scans the project at root and builds its model.
func Load(root string) (*Model, []Diagnostic) {
	cfg, diags := LoadConfig(root)
	if len(diags) > 0 {
		return nil, diags
	}
	tree, diags := Scan(cfg)
	if len(diags) > 0 {
		return nil, diags
	}
	model, diags := Build(tree)
	if len(diags) > 0 {
		return nil, diags
	}
	return model, nil
}

// Generate writes the generated files of the project at root. It writes
// only files whose content changed, removes stale files it owns (the ones
// with Marker), and never touches a file without the marker. On errors it
// writes nothing.
func Generate(root string) (Result, []Diagnostic) {
	model, diags := Load(root)
	if len(diags) > 0 {
		return Result{}, diags
	}
	outputs, err := model.Outputs()
	if err != nil {
		return Result{}, []Diagnostic{{Code: CodeConfig, Message: err.Error()}}
	}
	for _, out := range outputs {
		if data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(out.Path))); err == nil && !owned(data) {
			diags = append(diags, Diagnostic{File: out.Path, Line: 1, Col: 1, Code: CodeConfig, Message: "the file exists and was not generated by vela-app; it is never overwritten", Help: fmt.Sprintf("remove or move it, or change %q or %q in %s", "out", "goPackage", ConfigFile)})
		}
	}
	if len(diags) > 0 {
		return Result{}, diags
	}
	var result Result
	keep := map[string]bool{}
	for _, out := range outputs {
		keep[out.Path] = true
		file := filepath.Join(root, filepath.FromSlash(out.Path))
		if data, err := os.ReadFile(file); err == nil && bytes.Equal(data, out.Data) {
			result.Unchanged = append(result.Unchanged, out.Path)
			continue
		}
		if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
			return result, []Diagnostic{{File: out.Path, Code: CodeConfig, Message: err.Error()}}
		}
		if err := os.WriteFile(file, out.Data, 0o644); err != nil {
			return result, []Diagnostic{{File: out.Path, Code: CodeConfig, Message: err.Error()}}
		}
		result.Written = append(result.Written, out.Path)
	}
	for _, dir := range []string{model.Config.Out, model.Config.GoPackage} {
		entries, err := os.ReadDir(filepath.Join(root, filepath.FromSlash(dir)))
		if err != nil {
			continue
		}
		for _, entry := range entries {
			rel := path.Join(dir, entry.Name())
			if entry.IsDir() || keep[rel] {
				continue
			}
			file := filepath.Join(root, filepath.FromSlash(rel))
			if data, err := os.ReadFile(file); err == nil && owned(data) {
				if os.Remove(file) == nil {
					result.Removed = append(result.Removed, rel)
				}
			}
		}
	}
	sort.Strings(result.Removed)
	return result, nil
}

// owned reports whether a file carries Marker in its first lines.
func owned(data []byte) bool {
	scanner := bufio.NewScanner(bytes.NewReader(data))
	for i := 0; i < 3 && scanner.Scan(); i++ {
		if strings.Contains(scanner.Text(), Marker) {
			return true
		}
	}
	return false
}
