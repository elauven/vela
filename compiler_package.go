package main

// compiler_package.go — the @govela/compiler npm package and its platform
// packages (task 062), so `npm i -D @govela/compiler` installs the compiler
// without a Go toolchain. The manifests are generated with the compiler
// version; the launcher and the JavaScript API in packages/compiler are
// written by hand, and the release workflow puts the binaries into the
// platform packages.

import (
	"github.com/elauven/vela/runtime"

	"bytes"
	"encoding/json"
	"path"
)

// CompilerPackageName is the npm package of the compiler.
const CompilerPackageName = "@govela/compiler"

// compilerPackageDir is where the main package lives in the repository.
const compilerPackageDir = "packages/compiler"

// compilerPackageSources are the hand-written files of packages/compiler.
var compilerPackageSources = []string{"bin/vela.js", "index.js", "index.d.ts"}

// compilerPlatform is one prebuilt binary: the Go target and the npm
// os/cpu values of the package that carries it.
type compilerPlatform struct {
	GOOS, GOARCH string
	OS, CPU      string
}

// compilerPlatforms are the targets of .github/workflows/release.yml.
var compilerPlatforms = []compilerPlatform{
	{"linux", "amd64", "linux", "x64"},
	{"linux", "arm64", "linux", "arm64"},
	{"darwin", "amd64", "darwin", "x64"},
	{"darwin", "arm64", "darwin", "arm64"},
	{"windows", "amd64", "win32", "x64"},
}

func (p compilerPlatform) name() string { return p.OS + "-" + p.CPU }

// PackageName is the npm package of the platform binary.
func (p compilerPlatform) PackageName() string { return CompilerPackageName + "-" + p.name() }

// Dir is the package directory in the repository.
func (p compilerPlatform) Dir() string { return "packages/compiler-" + p.name() }

// Binary is the binary's path inside the package.
func (p compilerPlatform) Binary() string {
	if p.OS == "win32" {
		return "bin/vela.exe"
	}
	return "bin/vela"
}

func encodePackageJSON(manifest any) ([]byte, error) {
	var out bytes.Buffer
	enc := json.NewEncoder(&out)
	enc.SetEscapeHTML(false) // "node": ">=18"
	enc.SetIndent("", "  ")
	if err := enc.Encode(manifest); err != nil {
		return nil, err
	}
	return out.Bytes(), nil
}

// conditionalExport is one export with its types; "types" must come first.
type conditionalExport struct {
	Types   string `json:"types"`
	Default string `json:"default"`
}

// compilerPackageFiles returns the generated files of every compiler
// package, by repository path.
func compilerPackageFiles() (map[string][]byte, error) {
	files := map[string][]byte{}
	optional := map[string]string{}
	for _, p := range compilerPlatforms {
		optional[p.PackageName()] = runtime.Version
		manifest := struct {
			Name            string   `json:"name"`
			Version         string   `json:"version"`
			Description     string   `json:"description"`
			License         string   `json:"license"`
			OS              []string `json:"os"`
			CPU             []string `json:"cpu"`
			Files           []string `json:"files"`
			PreferUnplugged bool     `json:"preferUnplugged"`
		}{
			Name:            p.PackageName(),
			Version:         runtime.Version,
			Description:     "The Vela compiler binary for " + p.name() + ". Installed by " + CompilerPackageName + "; do not depend on it directly.",
			License:         "MIT",
			OS:              []string{p.OS},
			CPU:             []string{p.CPU},
			Files:           []string{p.Binary(), "LICENSE"},
			PreferUnplugged: true,
		}
		encoded, err := encodePackageJSON(manifest)
		if err != nil {
			return nil, err
		}
		readme := "# " + p.PackageName() + "\n\n" +
			"The Vela compiler binary for " + p.name() + ". Install `" + CompilerPackageName + "`, which\n" +
			"depends on this package for this platform only.\n\n" +
			"The release workflow builds the binary into `" + p.Binary() + "`; the manifest\n" +
			"is generated by the compiler repository; do not edit.\n\n" +
			"License: MIT.\n"
		files[path.Join(p.Dir(), "package.json")] = encoded
		files[path.Join(p.Dir(), "README.md")] = []byte(readme)
		files[path.Join(p.Dir(), "LICENSE")] = licenseText
	}

	manifest := struct {
		Name                 string            `json:"name"`
		Version              string            `json:"version"`
		Description          string            `json:"description"`
		License              string            `json:"license"`
		Type                 string            `json:"type"`
		Bin                  map[string]string `json:"bin"`
		Exports              map[string]any    `json:"exports"`
		Types                string            `json:"types"`
		Files                []string          `json:"files"`
		Engines              map[string]string `json:"engines"`
		OptionalDependencies map[string]string `json:"optionalDependencies"`
	}{
		Name:        CompilerPackageName,
		Version:     runtime.Version,
		Description: "The Vela compiler: single-file components to ES modules, and Go server renderers. Manifest generated by the compiler repository; do not edit.",
		License:     "MIT",
		Type:        "module",
		Bin:         map[string]string{"vela": "bin/vela.js"},
		Exports: map[string]any{
			".":              conditionalExport{Types: "./index.d.ts", Default: "./index.js"},
			"./package.json": "./package.json",
		},
		Types:                "index.d.ts",
		Files:                append(append([]string{}, compilerPackageSources...), "LICENSE"),
		Engines:              map[string]string{"node": ">=18"},
		OptionalDependencies: optional,
	}
	encoded, err := encodePackageJSON(manifest)
	if err != nil {
		return nil, err
	}
	readme := "# " + CompilerPackageName + "\n\n" +
		"The Vela compiler for JavaScript toolchains: `npm i -D " + CompilerPackageName + "` installs\n" +
		"the `vela` command with a prebuilt binary for this platform, no Go\n" +
		"toolchain needed. Install `" + runtime.PackageName + "` of the same version for\n" +
		"bundled applications.\n\n" +
		"```sh\n" +
		"npx vela --project src --out build --runtime-import=bare\n" +
		"npx vela check --project src\n" +
		"```\n\n" +
		"## JavaScript API\n\n" +
		"```js\n" +
		"import { compile, startService } from '" + CompilerPackageName + "';\n\n" +
		"const result = await compile({ path: 'src/App.vela' });\n" +
		"// result.ok, result.js, result.css, result.map, result.diagnostics, result.imports\n\n" +
		"const service = await startService();   // one `vela serve --stdio` process\n" +
		"const a = await service.compile({ path: 'src/App.vela', source, options: { sourcemap: true } });\n" +
		"await service.close();\n" +
		"```\n\n" +
		"Requests, results and options are those of the compiler service protocol\n" +
		"(`docs/TOOLING_PROTOCOL.md` in the compiler repository). `startService`\n" +
		"rejects a binary that speaks another protocol or has another version.\n\n" +
		"Supported platforms: linux x64/arm64, macOS x64/arm64, Windows x64. Set\n" +
		"`VELA_BINARY` to the path of a `vela` binary to use another build.\n\n" +
		"License: MIT.\n"
	files[path.Join(compilerPackageDir, "package.json")] = encoded
	files[path.Join(compilerPackageDir, "README.md")] = []byte(readme)
	files[path.Join(compilerPackageDir, "LICENSE")] = licenseText
	return files, nil
}
